"""
A stack whose only resource is a `database` resource has no app containers, so its generated
docker-compose.app.autogenerated.yml has no services. It must still be a file Compose accepts (#2894):
an empty `services:` key is refused with "services must be a mapping".

Executes the real Starlark through Tilt's interpreter (`tilt alpha tiltfile-result`), then runs
`docker compose config` on the result when Docker is available.
"""

from __future__ import annotations

import shutil
import subprocess

import pytest

from test_compose_project_scoping import TILT_REQUIRED, run_project

pytestmark = [pytest.mark.generator]

BODY = """
load('@DOCKER/compose/compose.star', 'generate_backend_compose_entry', 'generate_app_compose_from_entries')

entry = generate_backend_compose_entry('services/shop', 'shop', {'name': 'orders', 'port': 4001}, {'appType': 'backend', 'stack': 'shop', 'port': 4001})
r = {
    'empty': generate_app_compose_from_entries('services/shop', []),
    'one': generate_app_compose_from_entries('services/shop', [entry]),
}
"""


@TILT_REQUIRED
def test_a_stack_without_containers_writes_an_empty_services_mapping(tmp_path):
    result = run_project(tmp_path, "shop", BODY)
    assert "\nservices: {}\n" in result["empty"]
    # A stack with containers keeps the block form.
    assert "\nservices:\n" in result["one"]
    assert "services: {}" not in result["one"]


@TILT_REQUIRED
@pytest.mark.skipif(shutil.which("docker") is None, reason="docker CLI not installed")
def test_compose_accepts_the_file_of_a_stack_without_containers(tmp_path):
    result = run_project(tmp_path, "shop", BODY)
    compose = tmp_path / "docker-compose.app.autogenerated.yml"
    compose.write_text(result["empty"])
    proc = subprocess.run(
        ["docker", "compose", "-f", str(compose), "config", "-q"], capture_output=True, text=True, timeout=60
    )
    assert proc.returncode == 0, proc.stderr
