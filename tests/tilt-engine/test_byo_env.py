"""
`env` in a bring-your-own service.json becomes the container's Compose environment (#2923).

Before, only `secrets` reached a bring-your-own container, through the git-ignored project .env, so plain configuration
(POSTGRES_DB=invidious, PROXY=socks5://tubehaus:1080) imported from Compose was missing from a fresh clone.

Runs the real Compose generator through Tilt's interpreter (`tilt alpha tiltfile-result`), like test_migrator_compose.py, and
checks with `docker compose config` (when Docker is installed) that Compose reads the values as written and resolves defaults.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
DOCKER_REQUIRED = pytest.mark.skipif(shutil.which("docker") is None, reason="docker CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE_ROOT = REPO_ROOT / "runtime" / "engine"
RESULT_MARKER = "Error in fail: RESULT"
FAIL_MARKER = "MANIFEST ERROR"

LOAD = "load('@ENGINE/topologies/platform/docker/compose/compose.star', 'generate_backend_compose_entry', 'generate_app_compose_from_entries')\n"

COMPOSE_BODY = LOAD + """
companion = {
    'appType': 'bring-your-own', 'stack': 'tube', 'port': 8282, 'image': 'quay.io/invidious/invidious-companion:latest',
    'env': {
        'PROXY': 'socks5://tubehaus:1080',
        'JOBS_YOUTUBE_SESSION_FREQUENCY': '0 * * * *',
        'NOTE': 'a: b # not a comment',
        'PUBLIC_URL': '${TUBEHAUS_URL:-http://localhost:8081}',
    },
    'secrets': {'required': ['SERVER_SECRET_KEY']},
}
plain = {'appType': 'bring-your-own', 'stack': 'tube', 'port': 9000, 'image': 'nginx:alpine'}
backend = {'appType': 'backend', 'stack': 'tube', 'port': 4000, 'env': {'PROXY': 'x'}}
entries = [generate_backend_compose_entry('services/tube', 'tube', {'name': 'companion'}, companion)]
r = {
    'companion': entries[0],
    'plain': generate_backend_compose_entry('services/tube', 'tube', {'name': 'plain'}, plain),
    'backend': generate_backend_compose_entry('services/tube', 'tube', {'name': 'api'}, backend),
    'yaml': generate_app_compose_from_entries('services/tube', entries),
}
"""


def run_tilt(project_root: Path, body: str) -> str:
    (project_root / ".flisk").mkdir(parents=True, exist_ok=True)
    (project_root / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": "env-project"}}))
    tiltfile = project_root / "Tiltfile"
    tiltfile.write_text(body.replace("@ENGINE", str(ENGINE_ROOT)) + "\nfail('RESULT' + encode_json(r))\n")
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(project_root)},
    )
    return proc.stdout + proc.stderr


@pytest.fixture(scope="module")
def project(tmp_path_factory) -> Path:
    return tmp_path_factory.mktemp("env") / "env-project"


@pytest.fixture(scope="module")
def result(project) -> dict:
    if shutil.which("tilt") is None:
        pytest.skip("tilt CLI not installed")
    output = run_tilt(project, COMPOSE_BODY)
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


@TILT_REQUIRED
def test_env_is_written_quoted_after_the_secrets(result):
    entry = result["companion"]

    assert '      - "PROXY=socks5://tubehaus:1080"\n' in entry
    assert '      - "JOBS_YOUTUBE_SESSION_FREQUENCY=0 * * * *"\n' in entry
    assert entry.index("SERVER_SECRET_KEY=") < entry.index('"JOBS_YOUTUBE_SESSION_FREQUENCY=')


@TILT_REQUIRED
def test_only_bring_your_own_containers_read_env(result):
    assert "PROXY" not in result["plain"]
    assert "PROXY" not in result["backend"]


@TILT_REQUIRED
@DOCKER_REQUIRED
def test_compose_reads_the_values_as_written_and_resolves_defaults(result, project):
    stack = project / "services" / "tube"
    (stack / ".autogenerated").mkdir(parents=True, exist_ok=True)
    (stack / "companion" / ".autogenerated").mkdir(parents=True, exist_ok=True)
    (stack / "companion" / ".autogenerated" / ".env.backend.autogenerated").write_text("")
    compose_file = stack / ".autogenerated" / "docker-compose.app.autogenerated.yml"
    compose_file.write_text(result["yaml"])
    proc = subprocess.run(
        ["docker", "compose", "-p", "envproject", "-f", str(compose_file), "config", "--format", "json"],
        capture_output=True,
        text=True,
        timeout=60,
        env={**os.environ, "SERVER_SECRET_KEY": "x", "JWT_SECRET": "x", "DB_PASSWORD": "x"},
    )
    assert proc.returncode == 0, proc.stderr[-2000:]
    environment = json.loads(proc.stdout)["services"]["companion"]["environment"]

    assert environment["PROXY"] == "socks5://tubehaus:1080"
    assert environment["JOBS_YOUTUBE_SESSION_FREQUENCY"] == "0 * * * *"
    assert environment["NOTE"] == "a: b # not a comment"
    assert environment["PUBLIC_URL"] == "http://localhost:8081"


@TILT_REQUIRED
@pytest.mark.parametrize(
    "env, message",
    [
        ("'not an object'", "'env' must be an object"),
        ("{'1BAD': 'x'}", "'env' names must be letters"),
        ("{'A': 1}", "'env.A' must be a string"),
        ("{'A': 'x\\nprivileged: true'}", "'env.A' must not contain line breaks"),
    ],
)
def test_a_bad_env_stops_generation(tmp_path, env, message):
    body = LOAD + (
        "m = {{'appType': 'bring-your-own', 'stack': 'tube', 'port': 9000, 'image': 'nginx:alpine', 'env': {}}}\n"
        "r = generate_backend_compose_entry('services/tube', 'tube', {{'name': 'bad'}}, m)\n"
    ).format(env)
    output = run_tilt(tmp_path / "p", body)

    assert FAIL_MARKER in output and message in output, output[-2000:]
    assert RESULT_MARKER not in output
