"""All eight Vite frontend frameworks share one template (see #4867).

The shared blocks (alias set, HMR port, host, base-path handling) used to be
copied into eight near-identical framework files, so a fix to one silently
missed the other seven. They now live once in
frameworks/vite_template.star and each framework is a data-table entry in
frontend.star. This test generates the dev and build configs for every
framework at once and asserts the shared invariants hold for all of them,
plus that each framework still gets its own plugin and no other framework's.
"""

import json
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.generator]

REPO_ROOT = Path(__file__).resolve().parents[2]
FRONTEND_STAR = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "generators"
    / "vite"
    / "frontend.star"
)
RESULT_MARKER = "Error in fail: RESULT"

FRAMEWORKS = ["react", "vue", "svelte", "preact", "lit", "solid", "qwik", "vanilla"]
# framework -> distinctive text its plugin import/call must carry in both configs
PLUGIN_MARKERS = {
    "react": "@vitejs/plugin-react",
    "vue": "@vitejs/plugin-vue",
    "svelte": "@sveltejs/vite-plugin-svelte",
    "preact": "@preact/preset-vite",
    "lit": "plugins: []",
    "solid": "vite-plugin-solid",
    "qwik": "qwikVite({ csr: true })",
    "vanilla": "plugins: []",
}
ALL_PLUGIN_MARKERS = [
    "@vitejs/plugin-react",
    "@vitejs/plugin-vue",
    "@sveltejs/vite-plugin-svelte",
    "@preact/preset-vite",
    "vite-plugin-solid",
    "@builder.io/qwik/optimizer",
]
# Import line each framework owns (None for the plugin-free lit/vanilla).
OWN_IMPORT = {
    "react": "@vitejs/plugin-react",
    "vue": "@vitejs/plugin-vue",
    "svelte": "@sveltejs/vite-plugin-svelte",
    "preact": "@preact/preset-vite",
    "lit": None,
    "solid": "vite-plugin-solid",
    "qwik": "@builder.io/qwik/optimizer",
    "vanilla": None,
}


def _generate_all(tmp_path: Path) -> dict:
    (tmp_path / ".flisk").mkdir()
    (tmp_path / ".flisk" / "project.json").write_text(
        json.dumps({"project": {"name": "shop"}})
    )
    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(
        f"os.environ['FLISK_PROJECT_ROOT'] = '{tmp_path}'\n"
        + f"load('{FRONTEND_STAR}', 'generate_frontend')\n"
        + "out = {}\n"
        + "def make_write(framework):\n"
        + "    def write(path, content):\n"
        + "        out[framework + '|' + path] = content\n"
        + "    return write\n"
        + f"for framework in {FRAMEWORKS}:\n"
        + "    manifest = {'appType': 'frontend', 'framework': framework, 'appName': 'storefront', 'stack': 'shop', 'port': 3100, '_resource_path': 'apps/storefront'}\n"
        + "    generate_frontend(manifest, write_fn=make_write(framework))\n"
        + "fail('RESULT' + encode_json(out))\n"
    )
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


needs_tilt = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")


def _configs(files: dict, framework: str) -> tuple:
    dev = next(v for k, v in files.items() if k.startswith(framework + "|") and "vite.config.frontend" in k)
    build = next(v for k, v in files.items() if k.startswith(framework + "|") and "vite.config.build" in k)
    return dev, build


@needs_tilt
def test_all_frameworks_share_aliases_hmr_host_and_base_path(tmp_path):
    files = _generate_all(tmp_path)
    assert len(files) == 2 * len(FRAMEWORKS)
    for framework in FRAMEWORKS:
        dev, build = _configs(files, framework)
        for content in (dev, build):
            # Shared alias set, present in both configs.
            assert "'@/autogenerated': resolve(__dirname)" in content, framework
            assert "'@': resolve(__dirname, '../src')" in content, framework
            assert (
                "'set-cookie-parser': resolve(__dirname, '../src/utils/empty-module.js')"
                in content
            ), framework
            # Shared base-path handling: '/storefront' normalizes to '/storefront/'.
            assert "base: '/storefront/'" in content, framework
        # HMR port is always port + 1000; host is 0.0.0.0 in dev.
        assert "port: 3100" in dev, framework
        assert "port: 4100" in dev, framework
        assert "host: '0.0.0.0'" in dev, framework
        assert "mode: 'production'" in build, framework


@needs_tilt
def test_each_framework_keeps_its_own_plugin_and_no_other(tmp_path):
    files = _generate_all(tmp_path)
    for framework in FRAMEWORKS:
        dev, build = _configs(files, framework)
        for content in (dev, build):
            assert PLUGIN_MARKERS[framework] in content, framework
            for marker in ALL_PLUGIN_MARKERS:
                if marker == OWN_IMPORT[framework]:
                    continue
                assert marker not in content, (framework, marker)
