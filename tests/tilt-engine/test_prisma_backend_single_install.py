"""
A generated Prisma backend image used to run a full install in l2_deps_manifest, a second one in l3_production_purger and a
third one (plus `bun add prisma` and a second `prisma generate`) in l3_migration_build, a stage whose only product for a
backend is the pinned Prisma CLI package. That stage cost 60-140 s per API on a cold build (flisk#3710).

The backend now pins the Prisma CLI in the production-install stage it already has, and has no migration stage.
Migrators still build their own.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
GENERATOR = REPO_ROOT / "runtime" / "engine" / "topologies" / "platform" / "docker" / "generators" / "golden_docker_generator_v2.star"
RESULT_MARKER = "Error in fail: RESULT"


def generate(tmp_path: Path, res_type: str, resource_name: str) -> str:
    svc = tmp_path / "services" / "main" / resource_name
    (svc / ".autogenerated").mkdir(parents=True)
    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(
        f"load({json.dumps(str(GENERATOR))}, 'L4_generate_orchestrator')\n"
        f"r = L4_generate_orchestrator('services/main/{resource_name}', res_type={res_type!r}, resource_name={resource_name!r}, "
        "use_prisma=True, use_golden=False)\n"
        "fail('RESULT' + encode_json(r))\n"
    )
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=tmp_path,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(tmp_path)},
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


def run_lines(dockerfile: str, needle: str) -> list[str]:
    return [line for line in dockerfile.splitlines() if line.startswith("RUN") and needle in line]


@TILT_REQUIRED
def test_prisma_backend_has_no_migration_stage(tmp_path):
    dockerfile = generate(tmp_path, "backend", "orders-api")
    assert "AS l3_migration_build" not in dockerfile
    assert "l3_migration_build" not in dockerfile


@TILT_REQUIRED
def test_prisma_backend_runs_one_prisma_pin_and_one_generate(tmp_path):
    dockerfile = generate(tmp_path, "backend", "orders-api")
    assert len(run_lines(dockerfile, "bun add")) == 1  # the pinned prisma CLI
    assert len(run_lines(dockerfile, "prisma generate")) == 1


@TILT_REQUIRED
def test_prisma_backend_runtime_takes_the_cli_from_the_purger_stage(tmp_path):
    dockerfile = generate(tmp_path, "backend", "orders-api")
    copies = [l for l in dockerfile.splitlines() if l.startswith("COPY") and "--from=l3_production_purger" in l]
    assert any("prisma-cli" in l for l in copies), copies


@TILT_REQUIRED
def test_migrator_still_builds_its_own_migration_stage(tmp_path):
    dockerfile = generate(tmp_path, "migrator", "orders-migrator")
    assert "AS l3_migration_build" in dockerfile
