"""Run-time `"port": "auto"` (#4683) in the Starlark engine.

The resolved number lives only in the CLI's machine-local state, never in a generated file. So a generated file
must either stay deterministic (a `${FLISK_SERVICE_<NAME>_PORT:-default}` placeholder) or read the port from the
environment when it executes. Full manifest validation must accept the literal `auto`, or an auto manifest is
reported invalid at load time.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE = REPO_ROOT / "runtime" / "engine"
VALIDATOR = ENGINE / "topologies" / "tilt" / "manifest" / "validator.star"
VITE_BACKEND = ENGINE / "topologies" / "tilt" / "generators" / "vite" / "backend.star"
VITE_FRONTEND = ENGINE / "topologies" / "tilt" / "generators" / "vite" / "frontend.star"
NEXT_DOCKERFILE = ENGINE / "topologies" / "platform" / "docker" / "dockerfile" / "next_dockerfile.star"
COMPOSE = ENGINE / "topologies" / "platform" / "docker" / "compose" / "compose.star"
STATIC_ROUTES = (
    ENGINE / "topologies" / "platform" / "docker" / "networking" / "traefik_static_routes.star"
)
RESULT_MARKER = "RESULT"


def run_starlark(tmp_path: Path, body: str) -> dict:
    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(body + "\nfail('RESULT' + encode_json(r))\n")
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.JSONDecoder().raw_decode(output.split("Error in fail: RESULT", 1)[1].strip())[0]


@TILT_REQUIRED
def test_full_validation_accepts_port_auto(tmp_path: Path):
    # integration.star loads manifests with level='all': the schema stage must accept the literal instead of
    # rejecting it as a non-integer port.
    r = run_starlark(
        tmp_path,
        f"load('{VALIDATOR}', 'ManifestValidator')\n"
        "v = ManifestValidator.validate({'appName': 'orders-api', 'appType': 'backend', 'stack': 'orders', 'port': 'auto'})\n"
        "r = {'valid': v.valid, 'errors': [e.message for e in v.errors]}\n",
    )
    assert r["valid"] is True, r["errors"]


@TILT_REQUIRED
def test_full_validation_still_enforces_numeric_port_ranges(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{VALIDATOR}', 'ManifestValidator')\n"
        "v = ManifestValidator.validate({'appName': 'orders-api', 'appType': 'backend', 'stack': 'orders', 'port': 99999})\n"
        "r = {'valid': v.valid, 'errors': [e.message for e in v.errors]}\n",
    )
    assert r["valid"] is False
    assert any("outside valid range" in message for message in r["errors"])


@TILT_REQUIRED
def test_vite_backend_reads_the_runtime_port(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{VITE_BACKEND}', 'generate_backend')\n"
        "r = {\n"
        "  'auto': generate_backend({'appType': 'backend', 'appName': 'orders-api', 'useViteNode': True, 'port': 'auto'}),\n"
        "  'fixed': generate_backend({'appType': 'backend', 'appName': 'orders-api', 'useViteNode': True, 'port': 4010}),\n"
        "}\n",
    )
    # The server binds the run-time PORT (the native runtime exports it; Compose interpolates it), with the
    # manifest number or the base port as the deterministic fallback.
    assert "port: Number(process.env.PORT) || 4000" in r["auto"]
    assert "port: Number(process.env.PORT) || 4010" in r["fixed"]


@TILT_REQUIRED
def test_vite_frontend_reads_the_runtime_port_and_derives_hmr_from_it(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{VITE_FRONTEND}', 'generate_frontend')\n"
        "r = {\n"
        "  'auto': generate_frontend({'appType': 'frontend', 'appName': 'web', 'stack': 'app', 'framework': 'react', 'port': 'auto'}),\n"
        "  'fixed': generate_frontend({'appType': 'frontend', 'appName': 'web', 'stack': 'app', 'framework': 'react', 'port': 3050}),\n"
        "}\n",
    )
    for config in r.values():
        assert "const serverPort = Number(process.env.PORT) ||" in config
        assert "const hmrPort = serverPort + 1000;" in config
        assert "port: serverPort," in config
        assert "port: hmrPort," in config
    # The generated bytes carry only the deterministic fallback, never the selected number.
    assert "Number(process.env.PORT) || 3000" in r["auto"]
    assert "Number(process.env.PORT) || 3050" in r["fixed"]
    assert "3001" not in r["auto"]
    assert "4050" not in r["fixed"]


@TILT_REQUIRED
def test_next_dockerfile_launches_next_dev_on_the_runtime_port(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{NEXT_DOCKERFILE}', 'generate_next_dockerfile')\n"
        "r = {\n"
        "  'auto': generate_next_dockerfile('services/main/web', '${FLISK_SERVICE_WEB_PORT:-3000}', True),\n"
        "  'fixed': generate_next_dockerfile('services/main/web', 3000, True),\n"
        "}\n",
    )
    # Docker does not expand exec-form arguments: `next dev` reads PORT from the environment instead, the same
    # sh -c form the Python backend template uses.
    assert 'CMD ["sh", "-c", "npx next dev --hostname 0.0.0.0 --port ${PORT:-3000}"]' in r["fixed"]
    assert (
        'CMD ["sh", "-c", "npx next dev --hostname 0.0.0.0 --port ${PORT:-${FLISK_SERVICE_WEB_PORT:-3000}}"]'
        in r["auto"]
    )
    # The image keeps a deterministic ENV PORT (Docker substitutes the unknown variable at build time).
    assert "ENV NODE_ENV=development PORT=${FLISK_SERVICE_WEB_PORT:-3000}" in r["auto"]


@TILT_REQUIRED
def test_frontend_compose_carries_the_runtime_port_into_the_container(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{COMPOSE}', 'generate_frontend_compose')\n"
        "entry = generate_frontend_compose('services/app', 'app', {'name': 'web'},"
        " {'appType': 'frontend', 'stack': 'app', 'framework': 'next', 'port': 'auto',"
        " '_resource_path': 'services/app/web'})\n"
        "r = {'entry': entry}\n",
    )
    # Compose interpolates the placeholder from the environment the CLI exports, overriding the image's ENV PORT,
    # so `next dev` binds the resolved port without the generated file carrying the number.
    assert "- PORT=${FLISK_SERVICE_WEB_PORT:-3000}" in r["entry"]


@TILT_REQUIRED
def test_wake_route_keeps_the_placeholder_the_gateway_resolves_at_proxy_time(tmp_path: Path):
    r = run_starlark(
        tmp_path,
        f"load('{STATIC_ROUTES}', 'generate_static_wake_route')\n"
        "yaml = generate_static_wake_route(\n"
        "    'cold-api', 'analytics-autogenerated',"
        " {'appType': 'backend', 'stack': 'analytics', 'sablier': {'enable': True, 'deferStart': True}},\n"
        "    '${FLISK_SERVICE_COLD_API_PORT:-4000}', 'flisk-wake-gateway', 9999,\n"
        ")\n"
        "r = {'yaml': yaml}\n",
    )
    # The generated route stays deterministic: the gateway reads the resolved number from the woken container's
    # own PORT environment (see the wake-gateway's resolveProxyPort), never from this file.
    assert 'X-Wake-Proxy-Port: "${FLISK_SERVICE_COLD_API_PORT:-4000}"' in r["yaml"]
