"""A service that names its own Dockerfile runs without generation (#2228).

`dockerfile` outside `.autogenerated/` means the user owns the image: config
generation writes only the env file and the YAML mirror (the files Compose
still references), and live-update syncs skip `.autogenerated` paths that are
never written.
"""

from pathlib import Path

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.generator]

REPO = Path(__file__).resolve().parents[2]
MANIFEST_RESOURCE = (
    REPO
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "resources"
    / "orchestrator"
    / "generators"
    / "manifest_resource.star"
)
REGISTRATION = (
    REPO
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "resources"
    / "orchestrator"
    / "apply_compose_resource_registration.star"
)


def _function_source(path: Path, signature: str, next_def: str) -> str:
    source = path.read_text()
    start = source.index(signature)
    return source[start : source.index(next_def, start)]


def test_own_dockerfile_takes_the_minimal_generation_path():
    function = _function_source(
        MANIFEST_RESOURCE,
        "def _generate_all_configs_for_resource(",
        "\ndef _generate_yaml_manifest(",
    )

    fast_path = "or _uses_own_dockerfile(resource_config):"
    env_generation = "_generate_env_file(manifest, backend_manifest, write_file)"
    yaml_generation = "_generate_yaml_manifest(resource_path, manifest, write_file)"
    dockerfile_generation = "GENERATED_CONFIG_FILENAMES['dockerfile_app']"

    assert fast_path in function
    assert function.index(fast_path) < function.index(env_generation)
    assert function.index(env_generation) < function.index(yaml_generation)
    assert function.index(yaml_generation) < function.index("return", function.index(yaml_generation))
    # The generated app Dockerfile is only written on the full path, after the early return.
    assert function.index("return", function.index(yaml_generation)) < function.index(dockerfile_generation)


def test_own_dockerfile_is_any_path_outside_autogenerated():
    helper = _function_source(MANIFEST_RESOURCE, "def _uses_own_dockerfile(", "\ndef _build_generated_file_list(")

    assert "OUTPUT.AUTOGENERATED_FOLDER not in dockerfile_rel_path.split('/')" in helper


def test_generated_file_list_is_empty_for_own_dockerfile():
    function = _function_source(
        MANIFEST_RESOURCE,
        "def _build_generated_file_list(",
        "\ndef _build_config_log_cmd(",
    )

    early_return = "if app_type == 'bring-your-own' or _uses_own_dockerfile(resource_config):"
    assert early_return in function
    assert function.index(early_return) < function.index("files.append")


def test_config_gen_resource_does_not_watch_package_json_for_own_dockerfile():
    source = MANIFEST_RESOURCE.read_text()
    assert (
        "deps=[manifest_path] if manifest.get('appType') == 'bring-your-own' or _uses_own_dockerfile(resource_config)"
        in source
    )


def test_live_update_syncs_skip_autogenerated_paths_for_own_dockerfile():
    source = REGISTRATION.read_text()
    start = source.index("def _register_single_resource(")
    body = source[start : source.index("\n_HEALTHY_SCRIPT", start)]

    assert "if _uses_own_dockerfile(config):" in body
    assert "OUTPUT.AUTOGENERATED_FOLDER not in s.split('/')" in body
    # The filter runs before the sync list is handed to the live-update builder.
    assert body.index("if _uses_own_dockerfile(config):") < body.index("_build_live_update_rules(")


def test_own_dockerfile_detection_matches_generated_dockerfile_rule():
    helper = _function_source(REGISTRATION, "def _uses_own_dockerfile(", "\ndef _image_target(")

    assert "not _uses_generated_dockerfile(config)" in helper
