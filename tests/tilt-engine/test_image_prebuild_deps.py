"""
A service's image is built as soon as its inputs exist, not after the services it depends on are healthy.

Tilt holds a dc_resource's docker_build until every resource_dep is ready, so a chain of `dependsOn` built one image at a
time (a 10-part shop spent 153 s building the last API alone). `image_prebuild_deps` keeps only what the build needs and
`needs_image_prebuild` says when a separate `<name>-image` build step pays off.
"""

from __future__ import annotations

import json
import subprocess

import pytest

from test_dependson_platform_postgres import ORCHESTRATOR, TILT_REQUIRED, run_starlark

pytestmark = [pytest.mark.generator]


@TILT_REQUIRED
def test_prebuild_waits_only_for_what_the_image_build_needs(tmp_path):
    result = run_starlark(
        tmp_path,
        "load('@ORCHESTRATOR/apply_compose_resource_registration.star', 'image_prebuild_deps', 'needs_image_prebuild')\n"
        "deps = ['postgres', 'provision-db-shop', 'golden-layers-build', 'orders-api-config-gen', 'catalog-api-migrator-done', 'catalog-api-healthy']\n"
        "r = {"
        "'deps': image_prebuild_deps(deps), "
        "'verdaccio': image_prebuild_deps(['verdaccio', 'x-config-gen']), "
        "'gated': needs_image_prebuild(deps), "
        "'ungated': needs_image_prebuild(['golden-layers-build', 'x-config-gen']), "
        "'none': needs_image_prebuild([]), "
        "}\n",
    )
    assert result["deps"] == ["golden-layers-build", "orders-api-config-gen"]
    assert result["verdaccio"] == ["verdaccio", "x-config-gen"]
    assert result["gated"] is True
    # Nothing to overlap: the image already builds as early as it can.
    assert result["ungated"] is False
    assert result["none"] is False


def _registered(tmp_path):
    """Register a migrator and an API that depends on it, and return {resource name: [its resource_deps]}."""
    for name in ("api", "migrator"):
        folder = tmp_path / "svc" / name / ".autogenerated"
        folder.mkdir(parents=True)
        (folder / "Dockerfile.app.autogenerated").write_text("FROM alpine\n")
    (tmp_path / "docker-compose.yml").write_text(
        "services:\n  api:\n    image: proj_api:dev\n  migrator:\n    image: proj_migrator:dev\n"
    )
    (tmp_path / "Tiltfile").write_text(
        f"load('{ORCHESTRATOR}', 'register_dc_resources')\n"
        "docker_compose('docker-compose.yml', project_name='proj')\n"
        "for n in ['api-config-gen', 'migrator-config-gen', 'golden-layers-build', 'postgres', 'migrator-done']:\n"
        "    local_resource(n, cmd='true')\n"
        "def cfg(name, deps, app_type):\n"
        "    return {'res_name': name, 'resource_name': name, 'res_deps': deps, 'labels': ['app.' + name], 'replicas': 1,\n"
        "        'syncs': ['src'], 'app_type': app_type, 'dockerfile': '.autogenerated/Dockerfile.app.autogenerated',\n"
        "        'res_path': 'svc/' + name, 'env': {}, 'project_root': '', 'manifest': {}, 'all_services': {}}\n"
        "register_dc_resources([\n"
        "    cfg('migrator', ['postgres', 'golden-layers-build', 'migrator-config-gen'], 'migrator'),\n"
        "    cfg('api', ['postgres', 'golden-layers-build', 'api-config-gen', 'migrator-done'], 'backend'),\n"
        "], 'svc', 'proj', True)\n"
    )
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tmp_path / "Tiltfile")],
        capture_output=True, text=True, timeout=180, cwd=tmp_path,
    )
    assert proc.returncode == 0, proc.stdout[-3000:] + proc.stderr[-3000:]
    manifests = json.loads(proc.stdout)["Manifests"]
    return {m["Name"]: m.get("ResourceDependencies") or [] for m in manifests}


@TILT_REQUIRED
def test_a_service_in_a_dependency_chain_gets_a_parallel_image_build(tmp_path):
    deps = _registered(tmp_path)
    # The image build waits only for its inputs, so it overlaps with the migrator instead of following it.
    assert sorted(deps["api-image"]) == ["api-config-gen", "golden-layers-build"]
    assert sorted(deps["migrator-image"]) == ["golden-layers-build", "migrator-config-gen"]
    # The service itself still waits for everything it declared, and for its prebuilt image.
    assert {"postgres", "migrator-done", "api-image"} <= set(deps["api"])
