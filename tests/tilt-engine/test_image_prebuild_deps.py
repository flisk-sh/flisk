"""
A service's image is built as soon as its inputs exist, not after the services it depends on are healthy.

Tilt holds a dc_resource's docker_build until every resource_dep is ready, so a chain of `dependsOn` built one image at a
time (a 10-part shop spent 153 s building the last API alone). `image_prebuild_deps` keeps only what the build needs and
`needs_image_prebuild` says when a separate `<name>-image` build step pays off.
"""

from __future__ import annotations

import json
import os
import subprocess
import time

import pytest

from test_dependson_platform_postgres import ORCHESTRATOR, TILT_REQUIRED, run_starlark

pytestmark = [pytest.mark.generator]


@TILT_REQUIRED
def test_prebuild_waits_only_for_what_the_image_build_needs(tmp_path):
    result = run_starlark(
        tmp_path,
        f"load('{ORCHESTRATOR.parent.as_posix()}/apply_compose_resource_registration.star', 'image_prebuild_deps', 'needs_image_prebuild')\n"
        "deps = ['postgres', 'provision-db-shop', 'golden-layers-build', 'orders-api-config-gen', 'catalog-api-migrator-done', 'catalog-api-healthy']\n"
        "r = {"
        "'deps': image_prebuild_deps(deps), "
        "'verdaccio': image_prebuild_deps(['verdaccio', 'x-config-gen']), "
        "'gated': needs_image_prebuild(deps), "
        "'ungated': needs_image_prebuild(['golden-layers-build', 'x-config-gen']), "
        "'none': needs_image_prebuild([]), "
        "}\n",
    )
    # Postgres is kept as an ordering dep (#4127); provision-db, the migrator and other services are not.
    assert result["deps"] == ["golden-layers-build", "orders-api-config-gen", "postgres"]
    assert result["verdaccio"] == ["verdaccio", "x-config-gen"]
    assert result["gated"] is True
    # Nothing to overlap: the image already builds as early as it can.
    assert result["ungated"] is False
    assert result["none"] is False


@TILT_REQUIRED
def test_postgres_alone_still_gets_a_separate_image_build(tmp_path):
    # Postgres is an ordering dep of the image build, not an input: a service that waits only for Postgres must still get its
    # `-image` step, or its image would build after Postgres through the dc_resource's own docker_build, as before.
    result = run_starlark(
        tmp_path,
        f"load('{ORCHESTRATOR.parent.as_posix()}/apply_compose_resource_registration.star', 'image_prebuild_deps', 'needs_image_prebuild')\n"
        "deps = ['postgres', 'golden-layers-build', 'x-config-gen']\n"
        "r = {'gated': needs_image_prebuild(deps), 'deps': image_prebuild_deps(deps)}\n",
    )
    assert result["gated"] is True
    assert result["deps"] == ["golden-layers-build", "x-config-gen", "postgres"]


def _registered(tmp_path):
    """Register a migrator and an API that depends on it, and return {resource name: [its resource_deps]}."""
    for name in ("api", "migrator"):
        folder = tmp_path / "svc" / name / ".autogenerated"
        folder.mkdir(parents=True)
        (folder / "Dockerfile.app.autogenerated").write_text("FROM alpine\n")
    (tmp_path / "docker-compose.yml").write_text(
        "services:\n  api:\n    image: flisk_project_api_api:dev\n  migrator:\n    image: flisk_project_migrator_migrator:dev\n"
    )
    (tmp_path / "Tiltfile").write_text(
        f"load('{ORCHESTRATOR.as_posix()}', 'register_dc_resources', 'register_image_retry_gate')\n"
        "docker_compose('docker-compose.yml', project_name='proj')\n"
        "for n in ['api-config-gen', 'migrator-config-gen', 'golden-layers-build', 'postgres', 'migrator-done']:\n"
        "    local_resource(n, cmd='true')\n"
        "def cfg(name, deps, app_type):\n"
        "    return {'res_name': name, 'resource_name': name, 'res_deps': deps, 'labels': ['app.' + name], 'replicas': 1,\n"
        "        'syncs': ['src'], 'app_type': app_type, 'dockerfile': '.autogenerated/Dockerfile.app.autogenerated',\n"
        "        'res_path': 'svc/' + name, 'env': {}, 'project_root': '', 'manifest': {}, 'all_services': {}}\n"
        "configs = [\n"
        "    cfg('migrator', ['postgres', 'golden-layers-build', 'migrator-config-gen'], 'migrator'),\n"
        "    cfg('api', ['postgres', 'golden-layers-build', 'api-config-gen', 'migrator-done'], 'backend'),\n"
        "]\n"
        "register_dc_resources(configs, 'svc', 'proj', True)\n"
        "register_image_retry_gate('svc', configs, True, {})\n"
    )
    return {m["Name"]: m.get("ResourceDependencies") or [] for m in _manifests(tmp_path)}


def _manifests(tmp_path):
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tmp_path / "Tiltfile")],
        capture_output=True, text=True, timeout=180, cwd=tmp_path,
    )
    assert proc.returncode == 0, proc.stdout[-3000:] + proc.stderr[-3000:]
    return json.loads(proc.stdout)["Manifests"]


@TILT_REQUIRED
def test_a_service_in_a_dependency_chain_gets_a_parallel_image_build(tmp_path):
    deps = _registered(tmp_path)
    # The image build waits only for its inputs, so it overlaps with the migrator instead of following it.
    # Postgres is an ordering dep only (#4127): the migrator stays out, so the API image still overlaps the migration.
    assert sorted(deps["api-image"]) == ["api-config-gen", "golden-layers-build", "postgres"]
    assert sorted(deps["migrator-image"]) == ["golden-layers-build", "migrator-config-gen", "postgres"]
    # The service itself still waits for everything it declared, and for its prebuilt image.
    assert {"postgres", "migrator-done", "api-image"} <= set(deps["api"])


# The POSIX `docker` and Windows `docker.cmd` wrappers both call this script, so the generated command can be
# executed on either platform (Tilt emits PowerShell commands on native Windows).
FAKE_DOCKER_PY = """import os
import sys

args = sys.argv[1:]
with open(os.environ['FAKE_DOCKER_LOG'], 'a', encoding='utf-8') as log:
    log.write(' '.join(args) + '\\n')
if args and args[0] == 'build' and os.environ.get('FAKE_BUILD_FAILS'):
    sys.exit(1)
if args and args[0] == 'tag' and os.environ.get('FAKE_TAG_FAILS'):
    sys.exit(1)
"""

FAKE_DOCKER = """#!/bin/sh
exec python "$(dirname "$0")/docker.py" "$@"
"""

FAKE_DOCKER_CMD = '@echo off\r\npython "%~dp0docker.py" %*\r\n'


def _commands(tmp_path):
    """Return the generated command specs for the `-image` step and the api service's own image build."""
    _registered(tmp_path)
    manifests = {m["Name"]: m for m in _manifests(tmp_path)}
    prebuild = manifests["api-image"]["DeployTarget"]["UpdateCmdSpec"]
    details = manifests["api"]["ImageTargets"][0]["BuildDetails"]
    assert details["outputMode"] == "local-docker", details
    return prebuild, details


def _run(tmp_path, spec, **env):
    """Run a generated command with a fake `docker`; return (process, docker calls it made)."""
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir(exist_ok=True)
    (bin_dir / "docker.py").write_text(FAKE_DOCKER_PY)
    (bin_dir / "docker").write_text(FAKE_DOCKER)
    (bin_dir / "docker").chmod(0o755)
    (bin_dir / "docker.cmd").write_text(FAKE_DOCKER_CMD)
    log = tmp_path / "docker.log"
    log.write_text("")
    spec_env = dict(item.split("=", 1) for item in (spec.get("env") or []))
    proc = subprocess.run(
        spec["args"], cwd=tmp_path, capture_output=True, text=True, timeout=60,
        env={**os.environ, **spec_env, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}",
             "FAKE_DOCKER_LOG": str(log), "EXPECTED_REF": "flisk_project_api_api:tilt-build-1", **env},
    )
    return proc, log.read_text().splitlines()


@TILT_REQUIRED
def test_a_prebuilt_image_is_used_as_is_when_nothing_changed(tmp_path):
    prebuild, build = _commands(tmp_path)
    (tmp_path / "svc" / "api" / "src").mkdir()
    (tmp_path / "svc" / "api" / "src" / "main.ts").write_text("1")
    proc, calls = _run(tmp_path, prebuild)
    assert proc.returncode == 0, proc.stderr
    assert [c.split()[0] for c in calls] == ["build"]

    proc, calls = _run(tmp_path, build)
    assert proc.returncode == 0, proc.stderr
    # No second build: the image the `-image` step made gets the tag Tilt expects.
    assert calls == ["tag flisk_project_api_api:dev flisk_project_api_api:tilt-build-1"]
    assert "using it as is" in proc.stdout


@TILT_REQUIRED
def test_a_file_changed_after_the_prebuild_started_builds_again(tmp_path):
    prebuild, build = _commands(tmp_path)
    source = tmp_path / "svc" / "api" / "main.ts"
    source.write_text("1")
    _run(tmp_path, prebuild)
    later = time.time() + 5
    os.utime(source, (later, later))

    proc, calls = _run(tmp_path, build)
    assert proc.returncode == 0, proc.stderr
    assert len(calls) == 1 and calls[0].startswith("build ") and calls[0].split()[-2:] == ["flisk_project_api_api:tilt-build-1", "."], calls
    # A file Tilt does not watch does not count: node_modules changes on every install.
    os.utime(source, (later - 3600, later - 3600))
    (tmp_path / "svc" / "api" / "node_modules").mkdir()
    (tmp_path / "svc" / "api" / "node_modules" / "x.js").write_text("1")
    os.utime(tmp_path / "svc" / "api" / "node_modules" / "x.js", (later, later))
    _, calls = _run(tmp_path, build)
    assert calls == ["tag flisk_project_api_api:dev flisk_project_api_api:tilt-build-1"]


@TILT_REQUIRED
def test_a_failed_or_missing_prebuild_builds_again(tmp_path):
    prebuild, build = _commands(tmp_path)
    # Never prebuilt (for example `tilt trigger api` on a fresh checkout).
    _, calls = _run(tmp_path, build)
    assert [c.split()[0] for c in calls] == ["build"]
    # A prebuild that passed, then one whose only attempt failed: the earlier stamp must not vouch for the image.
    # The first attempt records the failure for the serial retry gate instead of retrying inline (flisk#4226).
    _run(tmp_path, prebuild)
    proc, calls = _run(tmp_path, prebuild, FAKE_BUILD_FAILS="1")
    assert proc.returncode == 0 and [c.split()[0] for c in calls] == ["build"], (proc.stderr, calls)
    marker = tmp_path / "svc/api/.autogenerated/Dockerfile.app.autogenerated.prebuild.failed"
    assert marker.exists()
    _, calls = _run(tmp_path, build)
    assert [c.split()[0] for c in calls] == ["build"]
    # The image is gone (pruned) although the stamp is there: `docker tag` fails, so it builds.
    _run(tmp_path, prebuild)
    proc, calls = _run(tmp_path, build, FAKE_TAG_FAILS="1")
    assert proc.returncode == 0, proc.stderr
    assert [c.split()[0] for c in calls] == ["tag", "build"]


@TILT_REQUIRED
def test_the_service_build_watches_what_docker_build_watched(tmp_path):
    _registered(tmp_path)
    api = {m["Name"]: m for m in _manifests(tmp_path)}["api"]["ImageTargets"][0]
    deps = [os.path.relpath(d, os.path.realpath(tmp_path)).replace(os.sep, "/") for d in api["BuildDetails"]["Deps"]]
    assert {"svc/api", "package.json", "bun.lock"} <= set(deps), deps
    patterns = [p for w in api["FileWatchIgnores"] for p in w.get("patterns") or []]
    # custom_build reads ignore patterns relative to each watched path, so they carry no `svc/api/` prefix.
    assert "node_modules" in patterns and "**/*.prebuild.*" in patterns, patterns
    assert api["LiveUpdateSpec"]["syncs"], api
