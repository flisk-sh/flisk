class TestAgentsMdEndToEnd:
    """End-to-end tests simulating the full generation flow."""
    
    def test_agents_md_generation_simulation(self):
        """Simulate generating AGENTS.md for a sample service."""
        # This simulates what the generator would produce
        
        sample_manifest = {
            "appName": "test-service-backend",
            "appType": "backend",
            "stack": "test",
            "port": 4000,
            "_servicePath": "services/product/test/test-service-backend",
        }
        
        # Simulate the generation logic (in reality this runs in Starlark)
        # We verify the Python equivalent would work
        
        # 1. Extract values from manifest
        app_name = sample_manifest.get("appName", "unknown-service")
        app_type = sample_manifest.get("appType", "backend")
        resource_path = sample_manifest.get("_servicePath", "")
        
        assert app_name == "test-service-backend"
        assert app_type == "backend"
        assert resource_path == "services/product/test/test-service-backend"
        
        # 2. Verify output path construction
        output_path = resource_path + "/.autogenerated/AGENTS.md"
        assert output_path == "services/product/test/test-service-backend/.autogenerated/AGENTS.md"
        
        # 3. Verify content would include service-specific info
        template_vars = {
            "resource_name": app_name,
            "app_type": app_type,
        }
        
        assert template_vars["resource_name"] == "test-service-backend"
        assert template_vars["app_type"] == "backend"
    
    def test_all_required_files_exist(self):
        """Verify all files in the AGENTS.md generator chain exist."""
        root = Path(__file__).parent.parent.parent / "engine" / "topologies"
        
        required_files = [
            root / "tilt" / "generators" / "agents_md.star",
            root / "tilt" / "generators" / "index.star",
            root / "tilt" / "manifest" / "constants.star",
            root / "tilt" / "resources" / "orchestrator" / "generators" / "manifest_resource.star",
        ]
        
        for file_path in required_files:
            assert file_path.exists(), f"Required file missing: {file_path}"


