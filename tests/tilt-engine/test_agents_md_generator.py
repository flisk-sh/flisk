class TestGeneratedAgentsMdContent:
    """Test the content that would be generated by the AGENTS.md generator."""
    
    @pytest.fixture
    def generator_path(self) -> Path:
        """Return path to the agents_md.star generator."""
        return Path(__file__).parent.parent.parent / "engine" / "topologies" / "tilt" / "generators" / "agents_md.star"
    
    @pytest.fixture
    def template_content(self, generator_path: Path) -> str:
        """Extract template content from generator."""
        content = generator_path.read_text()
        
        # Extract TEMPLATE_AGENTS_MD content
        match = re.search(
            r'TEMPLATE_AGENTS_MD = """(.*?)"""',
            content,
            re.DOTALL
        )
        if match:
            return match.group(1)
        return ""
    
    def test_template_has_frontmatter(self, template_content: str):
        """Verify template has YAML frontmatter."""
        assert template_content.startswith("---"), "Should start with YAML frontmatter"
        assert "title:" in template_content, "Should have title in frontmatter"
        assert "description:" in template_content, "Should have description in frontmatter"
        assert "status: autogenerated" in template_content, "Should have autogenerated status"
    
    def test_template_warns_against_modification(self, template_content: str):
        """Verify template clearly warns against modifying autogenerated files."""
        # Should have strong warning language
        warning_patterns = [
            r"DO NOT MODIFY",
            r"will be overwritten",
            r"MACHINE[- ]GENERATED",
            r"NEVER.*write.*edit.*autogenerated",
            r"ALWAYS.*check.*autogenerated",
        ]
        
        for pattern in warning_patterns:
            assert re.search(pattern, template_content, re.IGNORECASE), \
                f"Missing warning pattern: {pattern}"
    
    def test_template_explains_manifest_driven_architecture(self, template_content: str):
        """Verify template explains the manifest-driven pattern."""
        # Should explain the architecture
        assert "service.json" in template_content, "Should reference service.json"
        assert "manifest" in template_content.lower(), "Should explain manifest concept"
        assert "generator" in template_content.lower(), "Should mention generators"
    
    def test_template_lists_all_generated_files(self, template_content: str):
        """Verify template lists all types of generated files."""
        expected_files = [
            "vite.config",
            "tsconfig",
            "Dockerfile",
            "nginx",
            ".env",
            "bunfig",
            ".npmrc",
            "docker-compose",
            "playwright",
            "prisma",
        ]
        
        for file_type in expected_files:
            assert file_type in template_content, \
                f"Should mention {file_type} as generated file type"
    
    def test_template_shows_correct_alternatives(self, template_content: str):
        """Verify template shows correct files to edit instead."""
        # Should have a table or list of alternatives
        alternatives = [
            "service.json",
            "package.json",
            "src/",
        ]
        
        for alt in alternatives:
            assert alt in template_content, f"Should mention {alt} as correct file to edit"
    
    def test_template_has_ai_agent_instructions(self, template_content: str):
        """Verify template has specific instructions for AI agents."""
        # Should have clear AI agent instructions section
        ai_patterns = [
            r"For AI Agents",
            r"CRITICAL INSTRUCTIONS",
            r"write\(\).*edit\(",
            r"skill\(.*autogenerated",
        ]
        
        for pattern in ai_patterns:
            assert re.search(pattern, template_content, re.IGNORECASE), \
                f"Missing AI agent instruction pattern: {pattern}"
    
    def test_template_has_emergency_override_section(self, template_content: str):
        """Verify template explains emergency override procedure."""
        assert "Emergency Override" in template_content, \
            "Should have emergency override section"
        assert "tilt down" in template_content.lower(), \
            "Should mention tilt down for emergency changes"


