"""Regression tests: a frontend's browser API URL must point at its own backend.

Before this fix, `.autogenerated/env.ts` and `.env.frontend.autogenerated` fell back to the
stack-management route (`/api/<stack>-management`), which only serves flisk's own API, so a
frontend's `VITE_API_URL` pointed at the wrong route and its backend calls failed.
"""

from pathlib import Path

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.generator]

REPO_ROOT = Path(__file__).resolve().parents[2]
GENERATORS = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "resources"
    / "orchestrator"
    / "generators"
)
RESOLVER = GENERATORS / "dependencies" / "resolver.star"
ENV_STAR = GENERATORS / "env.star"
FRONTEND_STAR = GENERATORS / "frontend.star"


def _resolver_source() -> str:
    return RESOLVER.read_text()


def test_resolver_routes_backend_through_cli_api_path_rule():
    source = _resolver_source()
    assert 'load("../../../../../platform/docker/networking/traefik_helpers.star", "cli_api_path")' in source
    # Must match the route Traefik serves and `flisk up` prints: /api/<name> with a trailing -api stripped.
    assert "return cli_api_path(backend_name, backend_manifest)" in source


def test_resolver_does_not_return_only_explicit_api_path():
    # The old resolver returned backend_manifest.get("apiPath") and stopped there, so a backend without an
    # explicit apiPath fell back to the stack-management route.
    assert 'return backend_manifest.get("apiPath")' not in _resolver_source()


def test_resolver_finds_backend_through_depends_on_when_backend_name_is_missing():
    source = _resolver_source()
    assert 'manifest.get("dependsOn", [])' in source
    assert '["backend", "mcp", "agent"]' in source


def test_frontend_env_file_uses_backend_route_not_stack_management_route():
    source = ENV_STAR.read_text()
    assert "resolve_backend_api_path(manifest) or api_path" in source
    assert "api_url=frontend_api_url" in source
    # Backends keep the stack-management URL: only the frontend branch changes.
    assert "API_URL={api_url}" not in source.split("if app_type == 'frontend':")[0]


def test_frontend_api_client_and_env_ts_fallback_use_resolved_path():
    source = FRONTEND_STAR.read_text()
    assert source.count("backend_api_path = resolve_backend_api_path(manifest)") == 2
    assert "import.meta.env.VITE_API_URL || 'http://{local_domain}{api_path}'" in source


def test_frontend_without_backend_keeps_stack_management_fallback():
    # resolve_backend_api_path returns None when no backend is found, and every caller then falls back.
    source = _resolver_source()
    assert "if backend_name == None:\n        return None" in source
    assert "api_path = get_api_path(stack, manifest)" in FRONTEND_STAR.read_text()
