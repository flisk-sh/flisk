import re
import sys
from pathlib import Path
from typing import Dict, Any, List

# Add project root to path
PROJECT_ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))


class MockUtils:
    """Mock Utils struct for testing."""
    
    @staticmethod
    def get_template_header(template_type: str, generator_name: str, resource_name: str, output_hint: str) -> str:
        return f"# GENERATED BY Flisk - {template_type} for {resource_name}\n# Generator: {generator_name}\n# {output_hint}"


class MockFileWriter:
    """Mock write_fn that captures written files."""
    
    def __init__(self):
        self.files: Dict[str, str] = {}
    
    def write(self, path: str, content: str) -> None:
        """Mock write_file function."""
        self.files[path] = content
        print(f"  📝 Mock write: {path}")


def extract_template_from_generator() -> str:
    """Extract TEMPLATE_AGENTS_MD from the generator source."""
    generator_path = PROJECT_ROOT / "engine" / "topologies" / "tilt" / "generators" / "agents_md.star"
    content = generator_path.read_text()
    
    match = re.search(r'TEMPLATE_AGENTS_MD = """(.*?)"""', content, re.DOTALL)
    if not match:
        raise ValueError("Could not find TEMPLATE_AGENTS_MD in generator")
    
    return match.group(1)


def simulate_generate_agents_md(manifest: Dict[str, Any], write_fn=None) -> str:
    """
    Simulate the generate_agents_md function in Python.
    
    This mirrors the logic in agents_md.star but in Python for testing.
    """
    resource_path = manifest.get('_servicePath', '')
    app_name = manifest.get('appName', 'unknown-service')
    app_type = manifest.get('appType', 'backend')
    
    # Get template
    template = extract_template_from_generator()
    
    # Generate header
    header = MockUtils.get_template_header(
        'agents_md',
        'AgentsMd.generate()',
        app_name,
        'Output: .autogenerated/AGENTS.md'
    )
    
    # Format template
    timestamp = "2026-04-28 12:00:00"  # Fixed for testing
    content = template.format(
        header=header,
        resource_name=app_name,
        app_type=app_type,
        timestamp=timestamp,
    )
    
    if write_fn:
        output_path = f"{resource_path}/.autogenerated/AGENTS.md"
        write_fn(output_path, content)
    
    return content


def test_backend_service():
    """Test AGENTS.md generation for a backend service."""
    print("\n" + "=" * 70)
    print("🧪 TEST 1: Backend Service (test-api-backend)")
    print("=" * 70)
    
    manifest = {
        "appName": "test-api-backend",
        "appType": "backend",
        "stack": "test",
        "port": 4001,
        "_servicePath": "services/product/test/test-api-backend",
    }
    
    writer = MockFileWriter()
    content = simulate_generate_agents_md(manifest, writer.write)
    
    # Assertions
    assert "test-api-backend" in content, "Service name should appear"
    assert "backend" in content, "App type should appear"
    assert ".autogenerated/" in content, "Should reference .autogenerated folder"
    
    output_path = "services/product/test/test-api-backend/.autogenerated/AGENTS.md"
    assert output_path in writer.files, f"Should write to correct path: {output_path}"
    assert output_path.endswith("AGENTS.md"), "File should be named AGENTS.md"
    
    print(f"\n✅ Backend test passed!")
    print(f"   Output path: {output_path}")
    print(f"   Content length: {len(content)} chars")
    
    return True


