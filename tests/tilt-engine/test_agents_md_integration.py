def test_content_structure():
    """Test that generated content has all required sections."""
    print("\n" + "=" * 70)
    print("🧪 TEST 4: Content Structure Validation")
    print("=" * 70)
    
    manifest = {
        "appName": "structure-test-service",
        "appType": "backend",
        "_servicePath": "services/test",
    }
    
    content = simulate_generate_agents_md(manifest)
    
    required_sections = [
        ("---", "YAML frontmatter start"),
        ("title:", "Title field"),
        ("status: autogenerated", "Autogenerated status"),
        ("# ⚠️ AUTOGENERATED FILES", "Warning header"),
        ("## Why This Folder Exists", "Why section"),
        ("## What Happens If You Modify Files Here", "Consequences section"),
        ("## Where to Make Changes Instead", "Alternatives section"),
        ("## How Regeneration Works", "Architecture section"),
        ("## For AI Agents", "AI agent section"),
        ("## Emergency Override", "Emergency section"),
        ("service.json", "References service.json"),
        ("package.json", "References package.json"),
        ("NEVER", "Critical NEVER instruction"),
        ("ALWAYS", "Best practice ALWAYS instruction"),
        ("Generator Metadata", "Metadata section"),
    ]
    
    all_passed = True
    for pattern, description in required_sections:
        if pattern in content:
            print(f"  ✅ {description}")
        else:
            print(f"  ❌ {description} - missing: '{pattern}'")
            all_passed = False
    
    # Verify list of generated files
    generated_files = [
        "vite.config", "tsconfig", "Dockerfile", "nginx",
        ".env", "bunfig", ".npmrc", "docker-compose",
        "playwright", "prisma"
    ]
    
    for file_type in generated_files:
        if file_type in content:
            print(f"  ✅ Mentions {file_type}")
        else:
            print(f"  ⚠️  Missing mention of {file_type}")
    
    return all_passed


