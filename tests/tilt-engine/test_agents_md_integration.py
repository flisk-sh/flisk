def run_all_tests():
    """Run all integration tests."""
    print("\n" + "=" * 70)
    print("🚀 AGENTS.MD GENERATOR INTEGRATION TESTS")
    print("=" * 70)
    
    tests = [
        ("Backend Service", test_backend_service),
        ("Frontend Service", test_frontend_service),
        ("Migrator Service", test_migrator_service),
        ("Content Structure", test_content_structure),
        ("AI Agent Instructions", test_ai_agent_instructions),
        ("No Write Function", test_no_write_fn),
        ("All Service Types", test_all_services),
    ]
    
    results = []
    for name, test_func in tests:
        try:
            passed = test_func()
            results.append((name, passed))
        except Exception as e:
            print(f"\n💥 ERROR in {name}: {e}")
            import traceback
            traceback.print_exc()
            results.append((name, False))
    
    # Summary
    print("\n" + "=" * 70)
    print("📊 TEST SUMMARY")
    print("=" * 70)
    
    passed_count = sum(1 for _, p in results if p)
    total_count = len(results)
    
    for name, passed in results:
        status = "✅ PASS" if passed else "❌ FAIL"
        print(f"  {status}: {name}")
    
    print(f"\n  Total: {passed_count}/{total_count} tests passed")
    
    if passed_count == total_count:
        print("\n🎉 All tests passed!")
        return 0
    else:
        print(f"\n⚠️  {total_count - passed_count} test(s) failed")
        return 1


if __name__ == "__main__":
    exit_code = run_all_tests()
    sys.exit(exit_code)
