"""
Windows-safe maintenance commands generated by watchers.star (#4032).

The static tests run everywhere. The Tilt tests exercise the generator with both
platform values on any host: maintenance_command() returns the POSIX string or a
PowerShell command list, which is checked as data without running the resource.
"""

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
RUNTIME = REPO_ROOT / "runtime"
WATCHERS = RUNTIME / "engine" / "topologies" / "tilt" / "resources" / "watchers.star"
DOC = REPO_ROOT / "docs" / "design" / "native-windows-runtime-decision.md"

MAINTENANCE = [
    "prune-images",
    "memory-optimizer",
    "auto-prune-dangling",
    "auto-prune-migrator-images",
    "cron-status-init",
    "cron-lint",
    "cron-format",
    "cron-jobs-status-server",
]


def _block(name):
    text = WATCHERS.read_text(encoding="utf-8")
    match = re.search(
        r"local_resource\('" + re.escape(name) + r"',(.*?)\n    \)", text, re.S
    )
    assert match, f"{name} resource not found in watchers.star"
    return match.group(1)


@pytest.mark.parametrize("name", MAINTENANCE)
def test_maintenance_resource_uses_the_platform_command(name):
    block = _block(name)
    assert "maintenance_command(" in block, f"{name} has no platform command"
    assert "IS_NATIVE_WINDOWS" in block, f"{name} does not branch on the host OS"
    if name.startswith(("auto-prune", "cron-lint", "cron-format", "cron-jobs")):
        assert "serve=True" in block, f"{name}'s Windows no-op must stay alive"


def test_no_shell_script_is_executed_by_path():
    for number, line in enumerate(
        WATCHERS.read_text(encoding="utf-8").splitlines(), start=1
    ):
        if ".sh" not in line or line.lstrip().startswith("#"):
            continue
        assert re.search(r"\bbash\s+\./", line), f"line {number} executes a script directly: {line}"


def test_cron_skip_is_documented():
    text = DOC.read_text(encoding="utf-8").lower()
    assert "cron status" in text
    assert "skipped on native windows" in text


TILT_BODY = """
load('@W', 'IS_NATIVE_WINDOWS', 'maintenance_command', 'windows_skip_command')
posix = maintenance_command('probe', 'bash ./a.sh --keep 2', 'a reason', False)
posix_serve = maintenance_command('probe', 'bash ./a.sh', 'a reason', False, True)
win = maintenance_command('probe', 'bash ./a.sh --keep 2', 'needs bash; use WSL2', True)
win_serve = maintenance_command('probe', 'bash ./a.sh', 'needs bash; use WSL2', True, True)
direct = windows_skip_command('probe', 'needs bash; use WSL2')
fail('RESULT' + encode_json({'posix': posix, 'posix_serve': posix_serve, 'win': win, 'win_serve': win_serve, 'direct': direct, 'forced': IS_NATIVE_WINDOWS}))
"""

LOAD_BODY = """
load('@W', 'Watchers')
Watchers.setup_utilities()
Watchers.setup_cron_resources()
fail('RESULT' + encode_json({'loaded': True}))
"""


def _tilt_result(tmp_path: Path, portable: bool = False, body: str = TILT_BODY) -> dict:
    project = tmp_path / "proj"
    (project / ".flisk").mkdir(parents=True)
    (project / ".flisk" / "project.json").write_text(
        json.dumps({"project": {"name": "proj"}}), encoding="utf-8"
    )
    (project / "Tiltfile").write_text(
        body.replace("@W", str(WATCHERS).replace("\\", "/")), encoding="utf-8"
    )
    env = dict(os.environ)
    if portable:
        env["FLISK_WATCHERS_PORTABLE"] = "1"
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(project / "Tiltfile")],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=180,
        cwd=project,
        env=env,
    )
    out = proc.stdout + proc.stderr
    assert "Error in fail: RESULT" in out, out[-3000:]
    return json.loads(out.split("Error in fail: RESULT", 1)[1].strip())


@pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
def test_generated_command_when_not_forced_uses_the_host_os(tmp_path):
    result = _tilt_result(tmp_path)
    assert result["forced"] is (os.name == "nt")
    assert result["posix"] == "bash ./a.sh --keep 2"
    assert result["posix_serve"] == "bash ./a.sh"


@pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
def test_generated_command_on_nt_is_a_skip(tmp_path):
    result = _tilt_result(tmp_path / "forced", portable=True)
    assert result["forced"] is True
    for key in ("win", "win_serve", "direct"):
        command = result[key]
        assert isinstance(command, list)
        assert command[:4] == ["powershell", "-NoProfile", "-NonInteractive", "-Command"]
        assert len(command) == 5
        assert command[4].isascii() and '"' not in command[4]
        assert ".sh" not in command[4]
        assert "needs bash" in command[4]
        assert "use WSL2" in command[4]
    assert "exit 0" in result["win"][4]
    assert "exit 0" in result["direct"][4]
    assert "while ($true)" in result["win_serve"][4]
    assert "Start-Sleep" in result["win_serve"][4]


@pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
def test_all_watchers_resources_load_with_windows_commands(tmp_path):
    result = _tilt_result(tmp_path, portable=True, body=LOAD_BODY)
    assert result == {"loaded": True}
