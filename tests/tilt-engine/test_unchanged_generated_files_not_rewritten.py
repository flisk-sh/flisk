"""
Every generated file under `.autogenerated/` has a snapshot under `.autogenerated/.flisk-contract/` and a copy of the
service's `service.json` beside it, for `flisk config verify`. The engine skipped the generated file when it was
unchanged but rewrote both snapshots on every load, one shell-out each: 201 writes, 2.5 s of a 3.8 s Tiltfile load in
the shop benchmark on a restart where nothing had changed (flisk#4237). An unchanged project must load without writing.

The test writes the files once, makes the service folder read-only, and loads again: any write then fails the load.
Executes the real Starlark through Tilt's interpreter (`tilt alpha tiltfile-result`).
"""

from __future__ import annotations

import os
import stat
import subprocess
from pathlib import Path

import pytest

from test_compose_project_scoping import TILT_REQUIRED

pytestmark = [pytest.mark.generator]

UTILS = Path(__file__).resolve().parents[2] / "runtime/engine/topologies/tilt/common/utils.star"

BODY = """
load('{utils}', 'write_file_if_changed')
write_file_if_changed('services/shop/api/.autogenerated/tsconfig.autogenerated.json', '{{"compilerOptions": {{}}}}')
"""


def load(project_root: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(project_root / "Tiltfile")],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(project_root)},
    )


def set_read_only(root: Path, read_only: bool) -> None:
    for path in [root, *root.rglob("*")]:
        mode = path.stat().st_mode
        path.chmod(mode & ~(stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH) if read_only else mode | stat.S_IWUSR)


@TILT_REQUIRED
def test_loading_an_unchanged_project_writes_no_generated_file(tmp_path):
    project_root = tmp_path / "shop"
    service = project_root / "services/shop/api"
    service.mkdir(parents=True)
    (service / "service.json").write_text('{"name": "api"}\n')
    (project_root / "Tiltfile").write_text(BODY.format(utils=UTILS))

    first = load(project_root)
    assert first.returncode == 0, (first.stdout + first.stderr)[-3000:]
    contract = service / ".autogenerated/.flisk-contract"
    assert (contract / "tsconfig.autogenerated.json").is_file()
    assert (contract / "service.json.source").read_text() == '{"name": "api"}\n'

    set_read_only(service, True)
    try:
        second = load(project_root)
    finally:
        set_read_only(service, False)
    output = second.stdout + second.stderr
    assert second.returncode == 0, output[-3000:]
