"""The API address a built frontend calls is one that exists.

Seen when a coding agent built a shop with Flisk while another project held port 80 (2026-11-10): the page was served
as a static Vite bundle that had no VITE_API_URL in it, so it fell back to `http://api.<project>.localhost/api/<stack>-management`.
That address had no port (the router had moved to 8081) and, with four backends in the stack, no route either.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.fast, pytest.mark.generator]

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE = REPO_ROOT / "runtime" / "engine" / "topologies"
GENERATORS = ENGINE / "tilt" / "resources" / "orchestrator" / "generators"
ENV_STAR = GENERATORS / "env.star"
FRONTEND_STAR = GENERATORS / "frontend.star"
RESOLVER_STAR = GENERATORS / "dependencies" / "resolver.star"
L3_STAR = ENGINE / "platform" / "docker" / "layers" / "l3_builder_layers.star"
RESULT_MARKER = "Error in fail: RESULT"

needs_tilt = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")


def _run(tmp_path: Path, body: str, http_port: str | None = "8081"):
    (tmp_path / ".flisk").mkdir(exist_ok=True)
    (tmp_path / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": "shop"}}))
    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(body)
    # The registry reads FLISK_PROJECT_ROOT while its modules load, so it has to be in the process environment.
    env = {**os.environ, "FLISK_PROJECT_ROOT": str(tmp_path)}
    env.pop("FLISK_HTTP_PORT", None)
    if http_port is not None:
        env["FLISK_HTTP_PORT"] = http_port
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=tmp_path,
        env=env,
    )
    output = proc.stdout + proc.stderr
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


WEB = "{'appType': 'frontend', 'stack': 'main', 'appName': 'web', 'name': 'web', '_resource_path': 'services/main/web'}"


def _frontend_files(tmp_path: Path, http_port: str | None) -> dict:
    return _run(
        tmp_path,
        f"load('{FRONTEND_STAR}', 'FrontendGenerators')\n"
        + "out = {}\n"
        + "def write(path, content):\n    out[path] = content\n"
        + f"manifest = {WEB}\n"
        + "FrontendGenerators.generate_env_ts(manifest, write)\n"
        + "FrontendGenerators.generate_api_client(manifest, write)\n"
        + "fail('RESULT' + encode_json(out))\n",
        http_port,
    )


@needs_tilt
def test_env_ts_and_api_client_fallbacks_carry_a_moved_router_port(tmp_path):
    files = _frontend_files(tmp_path, "8081")
    assert len(files) == 2
    for content in files.values():
        assert "'http://api.shop.localhost:8081/api/" in content


@needs_tilt
@pytest.mark.parametrize("port", ["80", None])
def test_fallbacks_stay_portless_on_port_80(tmp_path, port):
    for content in _frontend_files(tmp_path, port).values():
        assert "'http://api.shop.localhost/api/" in content


@needs_tilt
def test_the_vite_build_stage_gets_the_generated_env_file(tmp_path):
    result = _run(
        tmp_path,
        f"load('{L3_STAR}', 'L3_generate_frontend_builder')\n"
        + "fail('RESULT' + encode_json({'dockerfile': L3_generate_frontend_builder('services/main/web', 'bun run build')}))\n",
    )
    lines = result["dockerfile"].splitlines()
    copy = "COPY services/main/web/.autogenerated/.env.frontend.autogenerated ./.env"
    assert copy in lines
    # Vite reads .env when the build starts, so the file has to be there before the build runs.
    build = next(index for index, line in enumerate(lines) if line.startswith("RUN bun run build"))
    assert lines.index(copy) < build


def _stack_api_path(tmp_path: Path, backends: list[str], web: dict | None = None) -> str:
    for name in backends:
        # services/product/<stack>/<resource> is the registry's default scan root.
        folder = tmp_path / "services" / "product" / "main" / name
        folder.mkdir(parents=True)
        (folder / "service.json").write_text(
            json.dumps({"schemaVersion": 1, "appName": name, "name": name, "appType": "backend", "stack": "main", "port": 4000 + len(name)})
        )
    manifest = {"appType": "frontend", "stack": "main", "appName": "web", "name": "web", "_resource_path": "services/main/web"}
    manifest.update(web or {})
    result = _run(
        tmp_path,
        f"load('{RESOLVER_STAR}', 'resolve_frontend_api_path')\n"
        + f"manifest = decode_json('{json.dumps(manifest)}')\n"
        + "fail('RESULT' + encode_json({'path': resolve_frontend_api_path(manifest, '/api/main-management')}))\n",
    )
    return result["path"]


@needs_tilt
def test_a_frontend_without_a_backend_keeps_the_stack_route_of_a_one_backend_stack(tmp_path):
    assert _stack_api_path(tmp_path, ["orders-api"]) == "/api/main-management"


@needs_tilt
def test_a_frontend_without_a_backend_gets_the_api_root_when_the_stack_route_is_gone(tmp_path):
    # Two routable backends in one stack: the engine drops /api/main-management, and each backend answers at /api/<name>.
    assert _stack_api_path(tmp_path, ["orders-api", "catalog-api"]) == "/api"


@needs_tilt
def test_a_frontend_with_its_own_backend_keeps_that_backend(tmp_path):
    assert _stack_api_path(tmp_path, ["orders-api", "catalog-api"], {"backendName": "orders-api"}) == "/api/orders"
