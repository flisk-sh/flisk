"""
A failed image build is retried once, serially, after the parallel batch (flisk#4226).

The old per-build inline retry let two identical Prisma backends retry at the same time against
one BuildKit cache. The first attempt now records a failure marker and the stack's
`<stack>-image-retry` resource retries marked builds one at a time. Docker is not available on
every host, so the test runs the generated commands with a stub `docker` that plays a scenario.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from test_dependson_platform_postgres import ORCHESTRATOR, TILT_REQUIRED

pytestmark = [pytest.mark.generator]

REPO_ROOT = Path(__file__).resolve().parents[2]

# Cross-platform fake docker: the POSIX `docker` wrapper and the Windows `docker.cmd` wrapper
# both call this script. It fails the build whose -f path contains FAKE_FAIL_ON.
FAKE_DOCKER_PY = """import os
import sys

args = sys.argv[1:]
with open(os.environ['FAKE_DOCKER_LOG'], 'a', encoding='utf-8') as log:
    log.write(' '.join(args) + '\\n')
dockerfile = ''
for index, arg in enumerate(args):
    if index and args[index - 1] == '-f':
        dockerfile = arg
key = dockerfile.replace('/', '_').replace(':', '_')
count = os.path.join(os.environ['FAKE_DOCKER_DIR'], 'count-' + key)
n = 0
if os.path.exists(count):
    with open(count, encoding='utf-8') as handle:
        n = int(handle.read().strip())
n += 1
with open(count, 'w', encoding='utf-8') as handle:
    handle.write(str(n))
fail_on = os.environ['FAKE_FAIL_ON']
attempts = int(os.environ.get('FAKE_FAIL_ATTEMPTS', '1'))
if fail_on in dockerfile and n <= attempts:
    print('ERROR: failed to calculate checksum of ref: snapshot not found', file=sys.stderr)
    sys.exit(1)
"""

FAKE_DOCKER = """#!/bin/sh
exec python "$(dirname "$0")/docker.py" "$@"
"""

FAKE_DOCKER_CMD = '@echo off\r\npython "%~dp0docker.py" %*\r\n'

TILTFILE = f"""
load('{ORCHESTRATOR.as_posix()}', 'register_dc_resources', 'register_image_retry_gate')
docker_compose('docker-compose.yml', project_name='proj')
def cfg(name):
    return {{'res_name': name, 'resource_name': name, 'image_retry_resource': 'saas-image-retry',
        'res_deps': ['golden-layers-build', name + '-config-gen', 'postgres'],
        'labels': ['app.' + name], 'replicas': 1, 'syncs': ['src'], 'app_type': 'backend',
        'dockerfile': '.autogenerated/Dockerfile.app.autogenerated',
        'res_path': 'svc/' + name, 'env': {{}}, 'project_root': '', 'manifest': {{}}, 'all_services': {{}}}}
configs = [cfg('api'), cfg('billing')]
register_dc_resources(configs, 'svc', 'proj', True)
register_image_retry_gate('saas', configs, True, {{}})
"""


def _manifests(tmp_path: Path) -> dict:
    (tmp_path / "docker-compose.yml").write_text(
        "services:\n  api:\n    image: flisk_project_api_api:dev\n"
        "  billing:\n    image: flisk_project_api_billing:dev\n"
    )
    for name in ("api", "billing"):
        folder = tmp_path / "svc" / name / ".autogenerated"
        folder.mkdir(parents=True)
        (folder / "Dockerfile.app.autogenerated").write_text("FROM alpine\n")
    (tmp_path / "Tiltfile").write_text(TILTFILE)
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tmp_path / "Tiltfile")],
        capture_output=True, text=True, timeout=180, cwd=tmp_path,
    )
    assert proc.returncode == 0, proc.stdout[-3000:] + proc.stderr[-3000:]
    return {m["Name"]: m for m in json.loads(proc.stdout)["Manifests"]}


def _commands(tmp_path: Path):
    manifests = _manifests(tmp_path)
    spec = lambda name: manifests[name]["DeployTarget"]["UpdateCmdSpec"]
    return spec("api-image"), spec("billing-image"), spec("saas-image-retry"), manifests


def _run(tmp_path: Path, spec: dict, fail_on: str, attempts: int = 1, env: dict | None = None):
    binary = tmp_path / "bin"
    binary.mkdir(exist_ok=True)
    (binary / "docker.py").write_text(FAKE_DOCKER_PY)
    (binary / "docker").write_text(FAKE_DOCKER)
    (binary / "docker").chmod(0o755)
    # Tilt chooses powershell on native Windows, where PATHEXT resolution needs .cmd.
    (binary / "docker.cmd").write_text(FAKE_DOCKER_CMD)
    calls = tmp_path / "docker.log"
    counts = tmp_path / "counts"
    counts.mkdir(exist_ok=True)
    spec_env = dict(item.split("=", 1) for item in (spec.get("env") or []))
    proc = subprocess.run(
        spec["args"], cwd=tmp_path, capture_output=True, text=True, timeout=60,
        env={
            **os.environ, **spec_env,
            "PATH": f"{binary}{os.pathsep}{os.environ['PATH']}",
            "FAKE_DOCKER_LOG": str(calls), "FAKE_DOCKER_DIR": str(counts),
            "FAKE_FAIL_ON": fail_on, "FAKE_FAIL_ATTEMPTS": str(attempts),
            "EXPECTED_REF": "flisk_project_api_api:tilt-build-1", **(env or {}),
        },
    )
    return proc, [line for line in calls.read_text().splitlines() if line.startswith("build ")]


def _service_of(call: str) -> str:
    return "api" if "svc/api/" in call else "billing"


@TILT_REQUIRED
def test_gate_waits_for_the_batch_and_retries_only_failed_images_once(tmp_path):
    api, billing, gate, manifests = _commands(tmp_path)
    assert sorted(manifests["saas-image-retry"].get("ResourceDependencies") or []) == [
        "api-image", "billing-image",
    ]
    for name in ("api", "billing"):
        assert "saas-image-retry" in (manifests[name].get("ResourceDependencies") or [])

    # Simulate the parallel batch: api's first attempt loses the shared-cache race, billing passes.
    first_api, calls = _run(tmp_path, api, fail_on="svc/api/")
    first_billing, calls = _run(tmp_path, billing, fail_on="svc/api/")
    assert first_api.returncode == 0, first_api.stdout + first_api.stderr
    assert first_billing.returncode == 0, first_billing.stdout + first_billing.stderr
    assert len(calls) == 2
    marker = tmp_path / "svc/api/.autogenerated/Dockerfile.app.autogenerated.prebuild.failed"
    assert marker.exists()

    retried, all_calls = _run(tmp_path, gate, fail_on="svc/api/")
    assert retried.returncode == 0, retried.stdout + retried.stderr
    assert "serially" in retried.stdout
    assert [c.split()[0] for c in all_calls] == ["build"] * 3
    # The retry happens after both first attempts, exactly once, and only for the failed image.
    assert len(all_calls) == 3
    assert _service_of(all_calls[0]) == "api" and _service_of(all_calls[1]) == "billing"
    assert _service_of(all_calls[2]) == "api"
    assert not marker.exists()


@TILT_REQUIRED
def test_gate_fails_when_the_serial_retry_also_fails(tmp_path):
    api, billing, gate, _ = _commands(tmp_path)
    _, calls = _run(tmp_path, api, fail_on="svc/api/", attempts=2)
    _, calls = _run(tmp_path, billing, fail_on="svc/api/")
    failed, calls = _run(tmp_path, gate, fail_on="svc/api/", attempts=2)
    assert failed.returncode != 0, failed.stdout + failed.stderr
    assert "failed again after the serial retry" in failed.stdout
    assert len(calls) == 3
    assert [c.split()[0] for c in calls] == ["build"] * 3


@TILT_REQUIRED
def test_gate_is_a_no_op_when_every_first_attempt_passed(tmp_path):
    api, billing, gate, _ = _commands(tmp_path)
    _, calls = _run(tmp_path, api, fail_on="/nothing/")
    _, calls = _run(tmp_path, billing, fail_on="/nothing/")
    passed, after_gate = _run(tmp_path, gate, fail_on="/nothing/")
    assert passed.returncode == 0, passed.stderr
    assert after_gate == calls  # the gate itself made no docker calls


@pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")
def test_no_inline_retry_is_left_in_the_first_attempt():
    unix = (REPO_ROOT / "runtime/engine/topologies/tilt/resources/orchestrator/apply_compose_resource_registration.star").read_text(encoding="utf-8")
    windows = (REPO_ROOT / "runtime/engine/topologies/tilt/common/windows_scripts.star").read_text(encoding="utf-8")
    assert "retrying once (often a transient BuildKit cache error)" not in unix
    assert "retrying once (often a transient BuildKit cache error)" not in windows
