"""Verdaccio scope routing must follow loader availability, not a non-empty license key.

A key set to any non-empty string must not make generated npmrc/bunfig files point
scopes at a Verdaccio container that the free-tier loader never starts (#3956).
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [
    pytest.mark.generator,
    pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed"),
]

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_STAR = REPO_ROOT / "runtime" / "discovery" / "config.star"
NPMRC_STAR = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "tilt"
    / "generators"
    / "npmrc.star"
)
FREE_LOADER = (
    REPO_ROOT
    / "runtime"
    / "engine"
    / "topologies"
    / "platform"
    / "registries"
    / "verdaccio_loader.star"
)
LOADER_REL_PATH = Path(
    ".flisk/.flisk-out/flisk-cli-ext/engine/topologies/platform/registries/verdaccio_loader.star"
)

# The licensed overlay is private; this stands in for its public signature. It deliberately
# omits the free-stub marker, which is the only signal the config needs to see.
LICENSED_LOADER_STUB = '''# Licensed Verdaccio loader overlay (test stand-in).
def load_verdaccio(should_enable, _root_prefix="", _env_file=None):
    """Starts a real Verdaccio container when the project enables the resource."""
    pass
'''


def _run_generation(tmp_path: Path, loader_source: str) -> str:
    """Generate the package configs through Tilt and return the Tiltfile-result output."""
    out_dir = tmp_path / ".flisk" / ".flisk-out" / "generated"
    out_dir.mkdir(parents=True)
    (out_dir / "spec.master").write_text(
        'OPTIONAL_INFRA_RESOURCES = {\n    "verdaccio": True,\n}\n',
        encoding="utf-8",
    )
    loader_path = tmp_path / LOADER_REL_PATH
    loader_path.parent.mkdir(parents=True)
    loader_path.write_text(loader_source, encoding="utf-8")

    resource_path = tmp_path / "services" / "product" / "demo" / "floor-app"
    (resource_path / ".autogenerated").mkdir(parents=True)

    tiltfile = tmp_path / "Tiltfile"
    tiltfile.write_text(
        "load('{config}', 'GLOBAL_CONFIG')\n"
        "load('{npmrc}', 'PackageConfig')\n"
        "def _write(path, content):\n"
        "    print('GENERATED=' + content)\n"
        "PackageConfig.npmrc(\n"
        "    resource_path='{resource}',\n"
        "    registry_url=GLOBAL_CONFIG['verdaccio_url_docker'],\n"
        "    is_docker=True,\n"
        "    write_fn=_write,\n"
        "    verdaccio_enabled=GLOBAL_CONFIG['verdaccio_enabled'],\n"
        ")\n"
        "PackageConfig.bunfig(\n"
        "    resource_path='{resource}',\n"
        "    registry_url=GLOBAL_CONFIG['verdaccio_url_docker'],\n"
        "    is_docker=True,\n"
        "    write_fn=_write,\n"
        "    verdaccio_enabled=GLOBAL_CONFIG['verdaccio_enabled'],\n"
        ")\n"
        "fail('FLAG=' + str(GLOBAL_CONFIG.get('verdaccio_enabled'))\n"
        "     + ' URL=' + GLOBAL_CONFIG['verdaccio_url_docker'])\n".format(
            config=CONFIG_STAR.as_posix(),
            npmrc=NPMRC_STAR.as_posix(),
            resource=resource_path.as_posix(),
        ),
        encoding="utf-8",
    )

    result = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=180,
        cwd=tmp_path,
        # Any non-empty key must be irrelevant when the free-tier stub is in place.
        env={
            **os.environ,
            "FLISK_PROJECT_ROOT": str(tmp_path),
            "FLISK_LICENSE_KEY": "dummy",
        },
    )
    return result.stdout + result.stderr


def test_key_with_free_loader_does_not_route_scopes(tmp_path: Path) -> None:
    output = _run_generation(tmp_path, FREE_LOADER.read_text(encoding="utf-8"))
    assert "FLAG=False" in output, output[-3000:]
    # The captured output holds both generated package configs.
    assert "verdaccio" not in output.lower()
    assert "@flisk-sh:registry=https://registry.npmjs.org/" in output
    assert "[install.scopes]" not in output


def test_available_loader_keeps_scope_routing(tmp_path: Path) -> None:
    output = _run_generation(tmp_path, LICENSED_LOADER_STUB)
    assert "FLAG=True" in output, output[-3000:]
    url = re.search(r"URL=(\S+)", output)
    assert url, output[-3000:]
    assert f"@flisk-sh:registry={url.group(1)}/" in output
    assert f'"@flisk-sh" = {{ url = "{url.group(1)}/" }}' in output
