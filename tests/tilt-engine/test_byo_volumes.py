"""
`volumes` in a bring-your-own service.json: named volumes kept by `flisk down`, and bind mounts inside the project (#1748).

tubehaus keeps its library in `tubehaus-data:/data`, Postgres in `postgres-data`, and Caddy serves `./web` read-only.
`flisk-import@0.4.1` skipped `volumes` on four of its six services, so the data was gone after every restart.

Runs the real Compose generator through Tilt's interpreter (`tilt alpha tiltfile-result`), like test_migrator_compose.py.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE_ROOT = REPO_ROOT / "runtime" / "engine"
RESULT_MARKER = "Error in fail: RESULT"
FAIL_MARKER = "MANIFEST ERROR"

LOAD = "load('@ENGINE/topologies/platform/docker/compose/compose.star', 'generate_backend_compose_entry', 'generate_app_compose_from_entries')\n"

COMPOSE_BODY = LOAD + """
server = {
    'appType': 'bring-your-own', 'stack': 'tube', 'port': 3010, 'image': 'ghcr.io/biolend83/tubehaus:latest',
    'volumes': [{'source': 'tubehaus-data', 'target': '/data'}, {'source': 'warp-data', 'target': '/var/lib/cloudflare-warp'}],
}
caddy = {
    'appType': 'bring-your-own', 'stack': 'tube', 'port': 8080, 'image': 'caddy:2',
    'volumes': [
        {'source': './Caddyfile', 'target': '/etc/caddy/Caddyfile', 'readOnly': True},
        {'source': '../../../web', 'target': '/srv/web', 'readOnly': True},
        {'source': 'tubehaus-data', 'target': '/library', 'readOnly': True},
    ],
}
plain = {'appType': 'bring-your-own', 'stack': 'tube', 'port': 9000, 'image': 'nginx:alpine'}
backend = {'appType': 'backend', 'stack': 'tube', 'port': 4000, 'volumes': [{'source': 'data', 'target': '/data'}]}
entries = [
    generate_backend_compose_entry('services/tube', 'tube', {'name': 'tubehaus'}, server),
    generate_backend_compose_entry('services/tube', 'tube', {'name': 'caddy'}, caddy),
]
r = {
    'server': entries[0],
    'caddy': entries[1],
    'plain': generate_backend_compose_entry('services/tube', 'tube', {'name': 'plain'}, plain),
    'backend': generate_backend_compose_entry('services/tube', 'tube', {'name': 'api'}, backend),
    'yaml': generate_app_compose_from_entries('services/tube', entries),
}
"""


def run_tilt(tmp_path: Path, body: str) -> str:
    project_root = tmp_path / "volumes-project"
    (project_root / ".flisk").mkdir(parents=True, exist_ok=True)
    (project_root / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": "volumes-project"}}))
    tiltfile = project_root / "Tiltfile"
    tiltfile.write_text(body.replace("@ENGINE", str(ENGINE_ROOT)) + "\nfail('RESULT' + encode_json(r))\n")
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(project_root)},
    )
    return proc.stdout + proc.stderr


@pytest.fixture(scope="module")
def result(tmp_path_factory) -> dict:
    if shutil.which("tilt") is None:
        pytest.skip("tilt CLI not installed")
    output = run_tilt(tmp_path_factory.mktemp("volumes"), COMPOSE_BODY)
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


@TILT_REQUIRED
def test_named_volumes_are_mounted(result):
    assert (
        "    volumes:\n"
        "      - tubehaus-data:/data\n"
        "      - warp-data:/var/lib/cloudflare-warp\n"
    ) in result["server"]


@TILT_REQUIRED
def test_bind_mounts_resolve_from_the_compose_file_to_the_service_directory(result):
    entry = result["caddy"]

    # The Compose file is services/tube/.autogenerated/, three levels below the project root.
    assert "      - ../../../services/tube/caddy/Caddyfile:/etc/caddy/Caddyfile:ro\n" in entry
    # ../../../web from services/tube/caddy is the project's web/ folder.
    assert "      - ../../../web:/srv/web:ro\n" in entry
    assert "      - tubehaus-data:/library:ro\n" in entry


@TILT_REQUIRED
def test_named_volumes_are_declared_once_at_the_top_level_so_flisk_down_keeps_them(result):
    yaml_text = result["yaml"]
    top = yaml_text.split("\nvolumes:\n", 1)[1]

    assert "  tubehaus-data:\n" in top and "  warp-data:\n" in top
    # Two services naming the same volume share it: one declaration.
    assert yaml_text.count("\n  tubehaus-data:\n") == 1


@TILT_REQUIRED
def test_services_without_volumes_are_generated_as_before(result):
    assert "volumes:" not in result["plain"]
    # Only bring-your-own resources read `volumes`; the CLI reports it on other types.
    assert "volumes:" not in result["backend"]


@TILT_REQUIRED
@pytest.mark.parametrize(
    "volumes, message",
    [
        ("[{'source': '../../../../etc', 'target': '/host-etc'}]", "'volumes[0].source' must stay inside the project"),
        ("[{'source': '/etc', 'target': '/etc'}]", "'volumes[0].source' must be a volume name"),
        ("[{'source': 'data\\nprivileged: true', 'target': '/data'}]", "'volumes[0].source' must be a volume name"),
        ("[{'source': 'data', 'target': 'data'}]", "'volumes[0].target' must be an absolute path"),
        ("[{'source': 'a', 'target': '/data'}, {'source': 'b', 'target': '/data'}]", "is mounted twice"),
        ("[{'source': 'data', 'target': '/data', 'readOnly': 'yes'}]", "'volumes[0].readOnly' must be true or false"),
    ],
)
def test_a_bad_volume_stops_generation(tmp_path, volumes, message):
    body = LOAD + (
        "m = {{'appType': 'bring-your-own', 'stack': 'tube', 'port': 9000, 'image': 'nginx:alpine', 'volumes': {}}}\n"
        "r = generate_backend_compose_entry('services/tube', 'tube', {{'name': 'bad'}}, m)\n"
    ).format(volumes)
    output = run_tilt(tmp_path, body)

    assert FAIL_MARKER in output and message in output, output[-2000:]
    assert RESULT_MARKER not in output
