"""
`container.tmpfs` and `envFile` in a bring-your-own service.json.

A Compose stack such as LycheeOrg/Lychee mounts `/tmp` as tmpfs and reads its settings from a `.env` three folders up. Without
these keys `flisk import` could not carry that service over. `envFile` is written in Compose's `required: false` form, so a
`.env` that is not there yet does not stop `docker compose up`.

Runs the real Compose generator through Tilt's interpreter (`tilt alpha tiltfile-result`), like test_byo_container_options.py.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.generator]
TILT_REQUIRED = pytest.mark.skipif(shutil.which("tilt") is None, reason="tilt CLI not installed")

REPO_ROOT = Path(__file__).resolve().parents[2]
ENGINE_ROOT = REPO_ROOT / "runtime" / "engine"
RESULT_MARKER = "Error in fail: RESULT"
FAIL_MARKER = "MANIFEST ERROR"

LOAD = "load('@ENGINE/topologies/platform/docker/compose/compose.star', 'generate_backend_compose_entry')\n"

COMPOSE_BODY = LOAD + """
lychee = {
    'appType': 'bring-your-own', 'stack': 'photos', 'port': 80, 'image': 'ghcr.io/lycheeorg/lychee:latest',
    'envFile': ['../../../.env', './lychee.env'],
    'container': {'tmpfs': ['/tmp:noexec,nosuid,nodev,size=100m', '/run']},
}
plain = {'appType': 'bring-your-own', 'stack': 'photos', 'port': 9000, 'image': 'nginx:alpine'}
backend = {'appType': 'backend', 'stack': 'photos', 'port': 4000, 'envFile': ['../../../.env'], 'container': {'tmpfs': ['/tmp']}}
r = {
    'lychee': generate_backend_compose_entry('services/photos', 'photos', {'name': 'lychee'}, lychee),
    'plain': generate_backend_compose_entry('services/photos', 'photos', {'name': 'plain'}, plain),
    'backend': generate_backend_compose_entry('services/photos', 'photos', {'name': 'api'}, backend),
}
"""


def run_tilt(tmp_path: Path, body: str) -> str:
    project_root = tmp_path / "tmpfs-project"
    (project_root / ".flisk").mkdir(parents=True, exist_ok=True)
    (project_root / ".flisk" / "project.json").write_text(json.dumps({"project": {"name": "tmpfs-project"}}))
    tiltfile = project_root / "Tiltfile"
    tiltfile.write_text(body.replace("@ENGINE", str(ENGINE_ROOT)) + "\nfail('RESULT' + encode_json(r))\n")
    proc = subprocess.run(
        ["tilt", "alpha", "tiltfile-result", "-f", str(tiltfile)],
        capture_output=True,
        text=True,
        timeout=180,
        cwd=project_root,
        env={**os.environ, "FLISK_PROJECT_ROOT": str(project_root)},
    )
    return proc.stdout + proc.stderr


@pytest.fixture(scope="module")
def result(tmp_path_factory) -> dict:
    if shutil.which("tilt") is None:
        pytest.skip("tilt CLI not installed")
    output = run_tilt(tmp_path_factory.mktemp("tmpfs"), COMPOSE_BODY)
    assert RESULT_MARKER in output, output[-3000:]
    return json.loads(output.split(RESULT_MARKER, 1)[1].strip())


@TILT_REQUIRED
def test_tmpfs_becomes_a_compose_tmpfs_list(result):
    assert '    tmpfs:\n      - "/tmp:noexec,nosuid,nodev,size=100m"\n      - "/run"\n' in result["lychee"]


@TILT_REQUIRED
def test_env_files_are_optional_and_relative_to_the_compose_file(result):
    entry = result["lychee"]

    # services/photos/lychee sits three folders under the project; the Compose file is in services/photos/.autogenerated.
    assert "      - path: ../../../.env\n        required: false\n" in entry
    assert "      - path: ../../../services/photos/lychee/lychee.env\n        required: false\n" in entry
    assert entry.index("env_file:") < entry.index("path: ../../../.env") < entry.index("    environment:")


@TILT_REQUIRED
def test_a_service_without_these_keys_is_generated_as_before(result):
    entry = result["plain"]

    assert "    tmpfs:" not in entry
    assert "required: false" not in entry
    assert "    env_file:\n      - ../../../services/photos/plain/.autogenerated/.env.backend.autogenerated\n    environment:\n" in entry


@TILT_REQUIRED
def test_both_are_ignored_on_a_resource_flisk_builds(result):
    # The CLI reports them (containerErrors, envFileErrors); the generator keeps Flisk's own settings.
    assert "    tmpfs:" not in result["backend"]
    assert "required: false" not in result["backend"]


def fails(tmp_path: Path, manifest_extra: str, message: str) -> None:
    body = LOAD + (
        "m = {'appType': 'bring-your-own', 'stack': 'photos', 'port': 9000, 'image': 'nginx:alpine', " + manifest_extra + "}\n"
        "r = generate_backend_compose_entry('services/photos', 'photos', {'name': 'bad'}, m)\n"
    )
    output = run_tilt(tmp_path, body)

    assert FAIL_MARKER in output and message in output, output[-2000:]
    assert RESULT_MARKER not in output


@TILT_REQUIRED
@pytest.mark.parametrize(
    "tmpfs",
    [
        "'/tmp'",
        "['tmp']",
        "['/tmp/../etc']",
        "['/tmp:']",
        "['/tmp:SIZE=1']",
        "['/tmp\\nprivileged: true']",
        "['/tmp:size=1m\\nprivileged: true']",
        "[7]",
    ],
)
def test_a_tmpfs_value_that_could_add_yaml_keys_stops_generation(tmp_path, tmpfs):
    fails(tmp_path, "'container': {'tmpfs': " + tmpfs + "}", "'container.tmpfs'")


@TILT_REQUIRED
@pytest.mark.parametrize(
    "env_file, message",
    [
        ("'.env'", "'envFile' must be a list"),
        ("['/etc/passwd']", "'envFile[0]' must be a relative file path"),
        ("['.env\\nprivileged: true']", "'envFile[0]' must be a relative file path"),
        ("['a b']", "'envFile[0]' must be a relative file path"),
        ("['../../../../.env']", "'envFile[0]' must stay inside the project"),
        ("['../../..']","'envFile[0]' must be a file inside the project"),
        ("[3]", "'envFile[0]' must be a relative file path"),
    ],
)
def test_an_env_file_that_could_add_yaml_keys_or_leave_the_project_stops_generation(tmp_path, env_file, message):
    fails(tmp_path, "'envFile': " + env_file, message)
