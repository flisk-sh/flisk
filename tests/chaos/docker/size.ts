// Size tier: scaffold one resource of every type (and a Prisma backend with its migrator), generate the Dockerfiles and look
// for the patterns that make an image bigger than its contents. Static and fast: no image is built.
//
// A Docker layer stores every file a RUN touches, so a `chown -R` or `chmod -R` over a directory a COPY just added stores that
// directory twice (found on a real agent-stack migrator: 332 MB of node_modules twice in a 1.5 GB image; `COPY --chown` sets the
// owner while copying and costs nothing).
//
//   bun docker/size.ts
import { spawnSync } from "node:child_process";
import {
	mkdirSync,
	readdirSync,
	readFileSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createWorkspace, flisk } from "../graph/project.js";

interface Rule {
	id: string;
	why: string;
	/** The line is a finding. */
	test: (line: string, stage: { installed: boolean }) => boolean;
}

const RULES: Rule[] = [
	{
		id: "recursive-chown-after-copy",
		why: "chown -R / chmod -R over node_modules or /app stores the whole tree again in a new layer; use COPY --chown",
		test: (line) =>
			/\b(chown|chmod)\s+(-\w*R\w*|--recursive)\b[^\n&|;]*(node_modules|\s\/app(\s|$|\/\s))/.test(
				line,
			),
	},
	{
		id: "apk-without-no-cache",
		why: "apk add without --no-cache keeps the package index in the layer",
		test: (line) => /\bapk\s+add\b/.test(line) && !/--no-cache/.test(line),
	},
	{
		id: "apt-without-cleanup",
		why: "apt-get install without removing /var/lib/apt/lists keeps the index in the layer",
		test: (line) =>
			/\bapt-get\s+install\b/.test(line) &&
			!/rm -rf \/var\/lib\/apt\/lists/.test(line),
	},
	{
		id: "copy-all-before-install",
		why: "COPY . . before the dependency install makes every source edit reinstall everything and copies the whole tree",
		test: (line, stage) =>
			/^COPY\s+(--\S+\s+)*\.\s+\.\/?\s*$/.test(line.trim()) && !stage.installed,
	},
];

function dockerfiles(dir: string): string[] {
	const found: string[] = [];
	const walk = (current: string): void => {
		for (const entry of readdirSync(current)) {
			if (
				entry === "node_modules" ||
				entry === ".flisk-contract" ||
				entry === ".flisk"
			)
				continue;
			const path = join(current, entry);
			if (statSync(path).isDirectory()) walk(path);
			else if (entry === "Dockerfile.app.autogenerated") found.push(path);
		}
	};
	walk(dir);
	return found;
}

function main(): void {
	const workspace = createWorkspace();
	const dir = join(workspace.root, "size-project");
	const base = join(workspace.root, "chaosbase");
	flisk(base, [
		"resource",
		"bot",
		"--yes",
		"--type",
		"agent",
		"--stack",
		"main",
	]);
	flisk(base, [
		"resource",
		"tools",
		"--yes",
		"--type",
		"mcp",
		"--stack",
		"main",
	]);
	flisk(base, [
		"resource",
		"db-api",
		"--yes",
		"--type",
		"backend",
		"--stack",
		"main",
		"--feature",
		"prisma",
	]);
	for (const [name, type] of [
		["api", "backend"],
		["web", "frontend"],
		["jobs", "worker"],
	] as const)
		flisk(base, ["resource", name, "--yes", "--type", type, "--stack", "main"]);
	flisk(base, ["config", "regenerate"]);
	const evaluated = flisk(base, ["up", "--dry-run", "--json"]);
	void evaluated;
	const tilt = spawnSync(
		"tilt",
		["alpha", "tiltfile-result", "-f", ".flisk/.flisk-out/Tiltfile"],
		{
			cwd: base,
			env: { ...process.env, FLISK_PROJECT_ROOT: base },
			encoding: "utf-8",
		},
	);
	if (tilt.status !== 0)
		throw new Error(`tilt failed: ${String(tilt.stderr).slice(-400)}`);
	void dir;

	const findings: {
		file: string;
		line: number;
		rule: string;
		why: string;
		text: string;
	}[] = [];
	const files = dockerfiles(join(base, "services"));
	if (files.length === 0)
		throw new Error("no Dockerfile.app.autogenerated found; nothing was scanned");
	for (const file of files) {
		const stage = { installed: false };
		const lines = readFileSync(file, "utf-8").split("\n");
		lines.forEach((text, index) => {
			if (/^FROM\s/.test(text)) stage.installed = false;
			if (/\b(bun|npm|pnpm|yarn)\s+(install|ci|add)\b/.test(text))
				stage.installed = true;
			for (const rule of RULES) {
				if (rule.test(text, stage))
					findings.push({
						file: file.slice(base.length + 1),
						line: index + 1,
						rule: rule.id,
						why: rule.why,
						text: text.trim().slice(0, 140),
					});
			}
		});
	}
	console.log(
		`${files.length} generated Dockerfiles scanned, ${findings.length} findings\n`,
	);
	for (const finding of findings) {
		console.log(
			`[${finding.rule}] ${finding.file}:${finding.line}\n    ${finding.text}\n    ${finding.why}`,
		);
	}
	const reportDir = process.env.CHAOS_REPORT_DIR ?? tmpdir();
	mkdirSync(reportDir, { recursive: true });
	writeFileSync(
		join(reportDir, "docker-size-report.json"),
		JSON.stringify(findings, null, 2),
	);
	process.exit(findings.length > 0 ? 1 : 0);
}

if (import.meta.main) main();
