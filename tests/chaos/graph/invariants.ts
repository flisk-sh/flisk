import { sep } from "node:path";
import {
  badShapes,
  classify,
  closure,
  edges,
  envKey,
  expectedEnvDeps,
  findCycle,
  type Model,
  selfEntries,
  unknownEntries,
} from "./model.js";
import type { TiltGraph, UpPlan } from "./oracles.js";
import type { Touched } from "./project.js";

/**
 * Behaviour that is wrong today and has an issue, but is tolerated by the random runs so they keep looking for new
 * problems. The scenarios in ./scenarios run with every gap off and assert the gap still reproduces, so fixing one fails
 * its scenario until the flag here is flipped too.
 */
export type Gaps = Record<string, boolean>;

export const STRICT: Gaps = {};

/** Today's behaviour on main; each flag that is on has a scenario in ./scenarios proving it still reproduces. Empty: no known gaps. */
export const KNOWN_GAPS: Gaps = {};

export type InvariantId =
  | "tilt-rejected"
  | "tilt-cycle-accepted"
  | "tilt-cycle-unwatched"
  | "tilt-default-enabled"
  | "tilt-missing-service"
  | "tilt-edges"
  | "tilt-focus-closure"
  | "tilt-no-reload"
  | "up-rejected"
  | "up-cycle-accepted"
  | "up-closure"
  | "up-unknown-silent"
  | "verify-unknown-missed"
  | "verify-false-unknown"
  | "verify-cycle-missed"
  | "warm-cold-differ"
  | "env-stale"
  | "env-dep-missing"
  | "env-dep-extra"
  | "env-url-mismatch"
  | "up-shape-accepted"
  | "verify-shape-missed"
  | "verify-shape-noise";

export interface Violation {
  id: InvariantId;
  detail: string;
}

export interface Observation {
  tilt: TiltGraph;
  verify: string[];
  only?: { name: string; up: UpPlan; focus: TiltGraph };
  /** service.json paths written since the previous Tilt evaluation, and what that evaluation watched. */
  reload?: { touched: Touched[]; watched: string[]; daemon: string[] | null };
  /** Each frontend's generated .env.frontend.autogenerated (key -> value), read after Tilt evaluated the Tiltfile. */
  env?: FrontendEnv;
}

export type FrontendEnv = Record<string, Record<string, string>>;

/** The `VITE_<KEY>_API_URL` keys of a frontend env (the dependency lines), as env keys. */
export function dependencyKeys(env: Record<string, string>): string[] {
  return Object.keys(env)
    .map((key) => /^VITE_(.+)_API_URL$/.exec(key)?.[1])
    .filter((key): key is string => Boolean(key))
    .sort();
}

const show = (list: string[]): string => `[${list.join(", ")}]`;
const same = (a: string[], b: string[]): boolean => a.join("\0") === b.join("\0");

function covered(path: string, watched: string[]): boolean {
  return watched.some((entry) => path === entry || path.startsWith(entry + sep));
}

export function check(model: Model, seen: Observation, _gaps: Gaps = STRICT): Violation[] {
  const out: Violation[] = [];
  const fail = (id: InvariantId, detail: string): void => {
    out.push({ id, detail });
  };
  const graph = edges(model);
  const cycle = findCycle(graph);
  const selfOwners = selfEntries(model);
  const refused = cycle ?? (selfOwners.length > 0 ? [selfOwners[0], selfOwners[0]] : null);
  const unknown = unknownEntries(model);
  const broken = badShapes(model);
  // A wrong-typed dependsOn is refused by flisk up before Tilt starts, so what Tilt makes of it is not checked.
  const tiltChecked = broken.length === 0;

  // Tilt keeps self entries out of resource_deps on purpose, so only a real cycle must make it refuse the Tiltfile.
  if (broken.length === 0 && cycle && seen.tilt.ok)
    fail("tilt-cycle-accepted", `Tilt loaded a graph with the cycle ${cycle.join(" -> ")}`);
  // Tilt's own cycle check stops watching the service.json files, so fixing the cycle in the editor never reloads a running Tilt.
  // Our Starlark has to catch the cycle first (an ordinary error keeps every watch).
  if (
    broken.length === 0 &&
    cycle &&
    !seen.tilt.ok &&
    seen.tilt.error.startsWith("cycle detected in resource dependency graph")
  ) {
    fail(
      "tilt-cycle-unwatched",
      `Tilt's own cycle check rejected ${cycle.join(" -> ")}; it stops watching service.json, so fixing it does not reload`,
    );
  }
  if (tiltChecked && !cycle && !seen.tilt.ok)
    fail("tilt-rejected", `Tilt refused an acyclic graph: ${seen.tilt.error}`);
  // A default run (no --focus) enables every service of the enabled stacks; a service named like a release phase must not shrink it.
  if (tiltChecked && !cycle && seen.tilt.ok) {
    const all = Object.keys(model).sort();
    if (!same(seen.tilt.enabled, all)) {
      fail(
        "tilt-default-enabled",
        `a default run enables ${show(seen.tilt.enabled)}, expected ${show(all)}`,
      );
    }
  }
  if (tiltChecked && !cycle && seen.tilt.ok) {
    for (const owner of Object.keys(model).sort()) {
      const actual = seen.tilt.edges[owner];
      if (!actual) fail("tilt-missing-service", `${owner} has no Tilt resource`);
      else if (!same(actual, graph[owner])) {
        fail(
          "tilt-edges",
          `${owner} waits for ${show(actual)} in Tilt, expected ${show(graph[owner])}`,
        );
      }
    }
  }

  if (seen.reload && seen.reload.touched.length > 0) {
    // One watched change is enough: the reload re-reads every service.json, including the unwatched ones. A new service.json
    // is not watched itself; the discovery daemon notices it and rewrites the watched snapshot file.
    const { touched, watched, daemon } = seen.reload;
    const noticed = (change: Touched): boolean =>
      covered(change.path, watched) ||
      (change.kind === "added" && Boolean(daemon?.includes(change.path)));
    if (touched.every((change) => !noticed(change))) {
      const paths = touched.map((change) => `${change.kind} ${change.path}`);
      fail(
        "tilt-no-reload",
        `a running Tilt would not reload: none of ${show(paths)} is watched or seen by the discovery daemon`,
      );
    }
  }

  if (seen.only) {
    const { name, up, focus } = seen.only;
    const want = closure(graph, name);
    if (broken.length > 0) {
      const said = up.messages.some((message) => /array/i.test(message));
      if (up.ok || !said) {
        fail(
          "up-shape-accepted",
          `flisk up --only ${name} did not refuse the non-list dependsOn of ${show(broken)}: ${up.messages.join("; ") || "ok"}`,
        );
      }
    } else if (refused) {
      const said = up.messages.some((message) => /circular|cycle|itself/i.test(message));
      if (up.ok || !said) {
        fail("up-cycle-accepted", `flisk up --only ${name} did not refuse ${refused.join(" -> ")}`);
      }
    } else if (!up.ok) {
      fail("up-rejected", `flisk up --only ${name} refused: ${up.messages.join("; ")}`);
    } else if (!same(up.services, want)) {
      fail(
        "up-closure",
        `flisk up --only ${name} would start ${show(up.services)}, expected ${show(want)}`,
      );
    }
    if (tiltChecked && !cycle && focus.ok && !same(focus.enabled, want)) {
      fail(
        "tilt-focus-closure",
        `Tilt --focus=${name} enables ${show(focus.enabled)}, expected ${show(want)}`,
      );
    }
    if (up.ok && broken.length === 0) {
      for (const { owner, entry } of unknown) {
        if (want.includes(owner) && !up.output.includes(entry)) {
          fail(
            "up-unknown-silent",
            `flisk up --only ${name} says nothing about ${owner} dependsOn "${entry}"`,
          );
        }
      }
    }
  }

  for (const { owner, entry } of unknown) {
    if (!seen.verify.some((message) => message.includes(`"${entry}"`) && message.includes(owner))) {
      fail("verify-unknown-missed", `config verify does not report ${owner} dependsOn "${entry}"`);
    }
  }
  for (const message of seen.verify) {
    const match = /dependsOn "([^"]+)" on (\S+) is not a known/.exec(message);
    if (match && match[2] in model && classify(model, match[2], match[1]) !== "unknown") {
      fail("verify-false-unknown", `config verify calls a valid entry unknown: ${message}`);
    }
  }
  if (refused) {
    if (!seen.verify.some((message) => /circular|cycle|itself/i.test(message))) {
      fail("verify-cycle-missed", `config verify does not report ${refused.join(" -> ")}`);
    }
  }
  for (const owner of broken) {
    const mine = seen.verify.filter((message) => message.includes(owner));
    if (!mine.some((message) => /array|list/i.test(message))) {
      fail("verify-shape-missed", `config verify does not say ${owner} dependsOn is not a list`);
    }
    const noise = mine.filter((message) => /dependsOn "[^"]{1}" on /.test(message));
    if (noise.length > 0 && model[owner].shape === "string") {
      fail("verify-shape-noise", `config verify splits ${owner}'s string dependsOn: ${noise[0]}`);
    }
  }
  if (seen.tilt.ok && seen.env && broken.length === 0) checkEnv(model, seen.env, fail);
  return out;
}

function checkEnv(
  model: Model,
  env: FrontendEnv,
  fail: (id: InvariantId, detail: string) => void,
): void {
  for (const [owner, spec] of Object.entries(model)) {
    const file = env[owner];
    if (spec.kind !== "frontend" || !file) continue;
    const actual = dependencyKeys(file);
    const expected = expectedEnvDeps(model, owner);
    const missing = expected.filter((key) => !actual.includes(key));
    const extra = actual.filter((key) => !expected.includes(key));
    if (missing.length > 0) {
      fail("env-dep-missing", `${owner}'s env has no VITE_*_API_URL for ${show(missing)}`);
    }
    if (extra.length > 0) {
      fail(
        "env-dep-extra",
        `${owner}'s env has VITE_*_API_URL lines for ${show(extra)}, which are not backend-side services it depends on`,
      );
    }
    if (spec.backendName && spec.backendName in model) {
      const dep = file[`VITE_${envKey(spec.backendName)}_API_URL`];
      const route = file.VITE_API_URL;
      if (dep && route && dep !== route) {
        fail(
          "env-url-mismatch",
          `${owner}: VITE_${envKey(spec.backendName)}_API_URL=${dep} but VITE_API_URL=${route}`,
        );
      }
    }
  }
}

/** Tilt names a cycle starting wherever it entered it, so the same cycle reads differently run to run: compare its members. */
function sameCycle(error: string): string {
  const match = /(cycle detected in resource dependency graph|circular dependsOn): (.+)$/.exec(
    error,
  );
  return match ? `${match[1]}: ${[...new Set(match[2].split(" -> "))].sort().join(",")}` : error;
}

/** The same service.json files must give the same graph whether or not earlier runs left generated files behind. */
export function checkWarmCold(
  warm: TiltGraph,
  cold: TiltGraph,
  warmEnv: FrontendEnv = {},
  coldEnv: FrontendEnv = {},
): Violation[] {
  const strip = (graph: TiltGraph) =>
    graph.ok
      ? { ok: true, edges: Object.entries(graph.edges).sort(), enabled: graph.enabled }
      : { ok: false, error: sameCycle(graph.error) };
  const a = JSON.stringify(strip(warm));
  const b = JSON.stringify(strip(cold));
  const out: Violation[] =
    a === b ? [] : [{ id: "warm-cold-differ", detail: `warm ${a}\ncold ${b}` }];
  if (warm.ok && cold.ok) {
    for (const owner of Object.keys(coldEnv)) {
      const w = JSON.stringify(Object.entries(warmEnv[owner] ?? {}).sort());
      const c = JSON.stringify(Object.entries(coldEnv[owner]).sort());
      if (w !== c)
        out.push({
          id: "env-stale",
          detail: `${owner}'s env differs from a fresh copy\nwarm ${w}\ncold ${c}`,
        });
    }
  }
  return out;
}
