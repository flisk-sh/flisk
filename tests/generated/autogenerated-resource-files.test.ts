describe.skipIf(!hasTilt)("autogenerated resource and stack files", () => {
  let parent: string;
  let project: string;

  beforeAll(() => {
    parent = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-autogen-"));
    project = path.join(parent, "hash-proj");
    fs.mkdirSync(project);
    const env: NodeJS.ProcessEnv = {
      ...process.env,
      FLISK_EXTENSION_SOURCE: repoRoot,
      FLISK_QUIET_DEPRECATIONS: "1",
    };
    for (const key of Object.keys(env)) if (key.startsWith("TDK_")) delete env[key];
    const run = (command: string, args: string[]) => {
      const result = spawnSync(command, args, {
        cwd: project,
        env,
        encoding: "utf-8",
        timeout: TILT_TIMEOUT_MS,
      });
      if (result.status !== 0) {
        throw new Error(`${command} ${args.join(" ")} failed:\n${result.stdout}\n${result.stderr}`);
      }
    };
    run("git", ["init", "-q", "."]);
    run("node", [flisk, "project", "--yes"]);
    run("node", [
      flisk,
      "resource",
      "storefront-web",
      "--type",
      "frontend",
      "--stack",
      "store",
      "--yes",
    ]);
    const projectJson = path.join(project, ".flisk", "project.json");
    const config = JSON.parse(fs.readFileSync(projectJson, "utf-8"));
    config.phases.pre_alpha.enabledStacks.push("store");
    fs.writeFileSync(projectJson, JSON.stringify(config, null, 2));
    run("node", [flisk, "config", "regenerate"]);
    run("tilt", [
      "alpha",
      "tiltfile-result",
      "-f",
      ".flisk/.flisk-out/Tiltfile",
      "--",
      "--focus=store",
      "storefront-web",
    ]);
  }, TILT_TIMEOUT_MS * 3);

  afterAll(() => {
    fs.rmSync(parent, { recursive: true, force: true });
  });

  it.each(RESOURCE_FILES)("resource file $file has the expected content and sha256", (golden) => {
    const full = path.join(project, golden.file);
    expect(fs.existsSync(full), `${golden.file} exists`).toBe(true);
    const text = fs.readFileSync(full, "utf-8");
    expect(text.length).toBeGreaterThan(0);
    for (const needle of golden.contains) expect(text).toContain(needle);
    expect(sha256(full)).toBe(golden.sha256);
  });

  it.each(STACK_FILES)("stack file $file has the expected content and sha256", (golden) => {
    const full = path.join(project, golden.file);
    expect(fs.existsSync(full), `${golden.file} exists`).toBe(true);
    const text = fs.readFileSync(full, "utf-8");
    for (const needle of golden.contains) expect(text).toContain(needle);
    expect(sha256(full)).toBe(golden.sha256);
  });

  it("writes exactly the documented set into the service .autogenerated folder", () => {
    const dir = path.join(project, SERVICE);
    const found = fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
      .sort();
    expect(found).toEqual(RESOURCE_FILES.map((g) => path.basename(g.file)).sort());
  });

  it("snapshots every generated file into .flisk-contract with identical bytes", () => {
    const dir = path.join(project, SERVICE);
    for (const golden of RESOURCE_FILES) {
      const name = path.basename(golden.file);
      if (name === "service.yaml") continue; // exempt from the drift comparison
      expect(sha256(path.join(dir, ".flisk-contract", name)), name).toBe(
        sha256(path.join(dir, name)),
      );
    }
    expect(fs.readFileSync(path.join(dir, ".flisk-contract", "service.json.source"), "utf-8")).toBe(
      fs.readFileSync(path.join(project, "services/store/storefront-web/service.json"), "utf-8"),
    );
  });

  it("embeds no absolute path of the machine that generated the files", () => {
    for (const golden of [...RESOURCE_FILES, ...STACK_FILES]) {
      const text = fs.readFileSync(path.join(project, golden.file), "utf-8");
      expect(text, golden.file).not.toContain(parent);
      expect(text, golden.file).not.toContain(os.homedir());
    }
  });
});
