describe("generated project files", () => {
  let projectRoot: string;
  let oldExtensionSource: string | undefined;

  beforeAll(async () => {
    projectRoot = fs.mkdtempSync(path.join(os.tmpdir(), "flisk-generated-hashes-"));
    oldExtensionSource = process.env.FLISK_EXTENSION_SOURCE;
    process.env.FLISK_EXTENSION_SOURCE = repoRoot;
    fs.mkdirSync(path.join(projectRoot, ".flisk"), { recursive: true });
    fs.writeFileSync(
      path.join(projectRoot, ".flisk", "project.json"),
      JSON.stringify({
        version: "1.0",
        project: { name: "hash-proj", version: "1.0.0" },
        phases: {
          pre_alpha: { name: "Pre-Alpha", description: "", enabledStacks: [] },
          alpha: { name: "Alpha", description: "", enabledStacks: [] },
          beta: { name: "Beta", description: "", enabledStacks: [] },
          out_of_scope: { name: "Out of Scope", description: "", enabledStacks: [] },
        },
        optional_infra: {
          monitoring: false,
          elk: false,
          debezium: false,
          golden_image: false,
          verdaccio: false,
        },
        discovery: { paths: ["services/*/*"] },
        overrides: {},
      }),
    );
    await generateMasterConfigs(projectRoot);
  }, 30000);

  afterAll(() => {
    if (oldExtensionSource === undefined) delete process.env.FLISK_EXTENSION_SOURCE;
    else process.env.FLISK_EXTENSION_SOURCE = oldExtensionSource;
    fs.rmSync(projectRoot, { recursive: true, force: true });
  });

  it.each(GENERATED)(
    "$file has the expected content and sha256",
    ({ file, sha256: hash, contains }) => {
      const full = path.join(projectRoot, file);
      expect(fs.existsSync(full), `${file} exists`).toBe(true);
      const text = fs.readFileSync(full, "utf-8");
      expect(text.length).toBeGreaterThan(0);
      for (const needle of contains) expect(text, `${file} contains ${needle}`).toContain(needle);
      expect(sha256(full)).toBe(hash);
    },
  );

  it("writes no generated file beyond the listed ones outside the vendored extension", () => {
    const vendored = path.join(projectRoot, ".flisk", ".flisk-out", "flisk-cli-ext");
    const found = walk(projectRoot)
      .filter((file) => !file.startsWith(vendored + path.sep))
      .map((file) => path.relative(projectRoot, file).split(path.sep).join("/"))
      .filter((file) => file !== ".flisk/project.json")
      .sort();
    expect(found).toEqual(GENERATED.map((entry) => entry.file).sort());
  });

  it("keeps the project root .tiltignore identical to the one in .flisk-out", () => {
    expect(sha256(path.join(projectRoot, ".tiltignore"))).toBe(
      sha256(path.join(projectRoot, ".flisk", ".flisk-out", ".tiltignore")),
    );
  });

  it("copies the docker templates byte for byte from the source tree", () => {
    const sourceDir = path.join(
      repoRoot,
      "runtime",
      "shared-platform-engineering",
      "docker-templates",
    );
    const copiedDir = path.join(projectRoot, "shared-platform-engineering", "docker-templates");
    const sources = fs
      .readdirSync(sourceDir)
      .filter((name) => fs.statSync(path.join(sourceDir, name)).isFile());
    expect(sources.length).toBeGreaterThan(0);
    for (const name of sources) {
      expect(sha256(path.join(copiedDir, name)), name).toBe(sha256(path.join(sourceDir, name)));
    }
  });

  it("vendors every non-test extension file with the same sha256 as its runtime/ source", () => {
    const vendored = path.join(projectRoot, ".flisk", ".flisk-out", "flisk-cli-ext");
    expect(sha256(path.join(vendored, "Tiltfile"))).toBe(sha256(resolveTiltfile(repoRoot)));
    let compared = 1;
    for (const dir of EXTENSION_DIRS) {
      const sourceDir = resolveExtensionDir(repoRoot, dir);
      const expected = walk(sourceDir).filter((file) => !isTestFile(file));
      expect(expected.length, `${dir} has source files`).toBeGreaterThan(0);
      for (const source of expected) {
        const copy = path.join(vendored, dir, path.relative(sourceDir, source));
        expect(fs.existsSync(copy), `${dir}/${path.relative(sourceDir, source)} vendored`).toBe(
          true,
        );
        expect(sha256(copy)).toBe(sha256(source));
        compared++;
      }
      expect(walk(path.join(vendored, dir)).length).toBe(expected.length);
    }
    expect(compared).toBeGreaterThan(100);
  });
});
