# Run one examples/byo/<name> service through a real `tdk up` and check it answers through Traefik.
# Needs Docker, Tilt, and a built CLI (cli/dist). Uses an isolated throwaway project with unique
# names and random alternate ports, and removes only the containers and networks carrying its own
# unique project name (it never calls `tdk down`, which can touch other projects' containers).
#
# Unlike verify-byo-example.sh, which runs the image alone, this gives the service TDK's DATABASE_URL
# and Postgres, so it is the check for apps that need a database.
#
# Usage: tests/e2e/resource-types/bring-your-own/verify-byo-tdk.sh <name> [health-path]     (default health path /health)
set -euo pipefail

name="${1:?usage: verify-byo-tdk.sh <name> [health-path]}"
health="${2:-/health}"
root="$(cd "$(dirname "$0")/../../../.." && pwd)"
src="$root/examples/byo/$name"
[ -d "$src" ] || { echo "no such example: $src" >&2; exit 2; }

# Truncate the name, not the PID: a long example name would otherwise cut the PID off, so every run reuses one project and its Postgres volume.
base="svc${name//[^a-z0-9]/}"
pid="$$"
proj="${base:0:$((24 - ${#pid}))}$pid"
work="$(mktemp -d)/$proj"
mkdir -p "$work"
http_port=$((30000 + RANDOM % 2000))
tdk() { command "${TDK_BIN:-tdk}" "$@"; }

cleanup() {
  pkill -f "tilt up.*$proj" >/dev/null 2>&1 || true
  docker rm -f $(docker ps -aq --filter "name=$proj") >/dev/null 2>&1 || true
  docker network ls --format '{{.Name}}' | grep "^${proj}" | xargs -r docker network rm >/dev/null 2>&1 || true
  # Tilt also tags the build as <project>_<stack>_<resource>:tilt-<hash>, so remove every tag of this run's own repository, not just :dev.
  docker images --format '{{.Repository}}:{{.Tag}}' | grep -E "^${proj}_" | xargs -r docker rmi -f >/dev/null 2>&1 || true   # the image `tdk up` built for this run only
  # TDK also builds per-project "golden layer" base images named <project>-l1 ... -l4-*; they are unique to this run.
  docker images --format '{{.Repository}}:{{.Tag}}' | grep -E "^${proj}-l[0-9]+" | xargs -r docker rmi -f >/dev/null 2>&1 || true
}
trap cleanup EXIT

cd "$work"
git init -q .
tdk project --yes >/dev/null
printf '\nTDK_HTTP_PORT=%s\nTDK_HTTPS_PORT=%s\nTDK_POSTGRES_PORT=%s\n' \
  "$http_port" "$((32000 + RANDOM % 2000))" "$((34000 + RANDOM % 2000))" >> .env
mkdir -p "services/app/$proj"
cp -R "$src/." "services/app/$proj/"
rm -f "services/app/$proj/README.md"
(cd "services/app/$proj" && tdk resource "$proj" --type bring-your-own --stack app \
  --register-existing --dockerfile ./Dockerfile --health-path "$health" --yes >/dev/null)
nohup "${TDK_BIN:-tdk}" up app >"$work/up.log" 2>&1 &

url="http://127.0.0.1:$http_port/api/$proj$health"
status=000
for _ in $(seq 1 "${VERIFY_WAIT_SECONDS:-600}"); do
  status="$(curl -s -o /dev/null -m 3 -w '%{http_code}' -H "Host: api.$proj.localhost" "$url" || true)"
  [ "$status" = "200" ] && break
  sleep 1
done

if [ "$status" = "200" ]; then
  echo "PASS $name: through tdk up and Traefik, GET /api/$proj$health -> 200 ($(curl -s -m 3 -H "Host: api.$proj.localhost" "$url" | head -c 80))"
else
  echo "FAIL $name: GET /api/$proj$health -> $status" >&2
  docker logs "${proj}-app-autogenerated-$proj-1" 2>&1 | tail -20 >&2 || true
  exit 1
fi
