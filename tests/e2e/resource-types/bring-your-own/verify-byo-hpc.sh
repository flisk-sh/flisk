# GPU and HPC options in a bring-your-own `container` block, through a real `flisk up`.
# Needs Docker, Tilt, and a built CLI (cli/dist). Uses an isolated throwaway project with unique names and alternate ports,
# and removes only the containers, networks and images carrying its own unique project name.
#
# Checks, in order:
#   1. `flisk config verify` accepts cpus, memory, ipc and shmSize, and refuses a bad gpus value.
#   2. The container started by `flisk up` has the CPU and memory limits, the host IPC namespace and the /dev/shm size from
#      service.json instead of Flisk's defaults (0.5 CPU, 512M), and answers its health route through Traefik.
#   3. With `gpus` set, the generated Compose file reserves NVIDIA devices and `docker compose config` accepts it. On a host
#      with the NVIDIA runtime the container must also carry the device request; elsewhere Docker refusing the nvidia driver
#      shows the request reached it.
#
# Usage: tests/e2e/resource-types/bring-your-own/verify-byo-hpc.sh
set -euo pipefail

root="$(cd "$(dirname "$0")/../../../.." && pwd)"
proj="hpc$$"
work="$(mktemp -d)/$proj"
mkdir -p "$work"
flisk() { command "${FLISK_BIN:-flisk}" "$@"; }
res="$proj"
wait_seconds=${VERIFY_WAIT_SECONDS:-240}

up_pid=""
cleanup() {
  # Stop the background flisk up first: when a check fails early it is still starting Tilt and containers.
  [ -n "$up_pid" ] && kill "$up_pid" >/dev/null 2>&1 || true
  sleep 1
  pkill -f "tilt up.*$proj" >/dev/null 2>&1 || true
  docker rm -f $(docker ps -aq --filter "name=$proj") >/dev/null 2>&1 || true
  docker network ls --format '{{.Name}}' | grep "^${proj}" | xargs -r docker network rm >/dev/null 2>&1 || true
  docker images --format '{{.Repository}}:{{.Tag}}' | grep -E "^${proj}(_|-l[0-9]+)" | xargs -r docker rmi -f >/dev/null 2>&1 || true
}
trap cleanup EXIT
fail() { echo "FAIL hpc: $*" >&2; [ -f "$work/up.log" ] && tail -30 "$work/up.log" >&2; exit 1; }

# Set service.json's `container` block to the JSON given.
set_container() { # <json>
  # Through the environment: under Bun's node shim, `node -e` arguments do not reach process.argv intact.
  SERVICE_JSON="$work/services/app/$res/service.json" CONTAINER_JSON="$1" node -e 'const fs=require("fs"); const f=process.env.SERVICE_JSON; const m=JSON.parse(fs.readFileSync(f,"utf8")); m.container=JSON.parse(process.env.CONTAINER_JSON); fs.writeFileSync(f, JSON.stringify(m,null,2)+"\n")'
}

cd "$work"
git init -q .
flisk project --yes >/dev/null
http_port=$((30000 + RANDOM % 2000))
printf '\nFLISK_HTTP_PORT=%s\nFLISK_HTTPS_PORT=%s\nFLISK_POSTGRES_PORT=%s\n' \
  "$http_port" "$((32000 + RANDOM % 2000))" "$((34000 + RANDOM % 2000))" >> .env
mkdir -p "services/app/$res/www"
echo ok > "services/app/$res/www/health"
cat > "services/app/$res/Dockerfile" <<'DOCKERFILE'
FROM busybox:1.36
COPY www /www
CMD httpd -f -p "${PORT:-4500}" -h /www
DOCKERFILE
(cd "services/app/$res" && flisk resource "$res" --type bring-your-own --stack app \
  --register-existing --dockerfile ./Dockerfile --health-path /health --yes >/dev/null)

# 1. config verify: the options a model server needs are accepted, a bad GPU count is refused.
set_container '{"gpus": 0}'
if flisk config verify --json >"$work/verify-bad.json" 2>&1; then fail "config verify accepted container.gpus = 0"; fi
grep -q 'container.gpus' "$work/verify-bad.json" || fail "config verify did not name container.gpus: $(cat "$work/verify-bad.json")"
set_container '{"cpus": "1.5", "memory": "768m", "ipc": "host", "shmSize": "128mb"}'
flisk config verify --json >"$work/verify.json" 2>&1 || fail "config verify refused the HPC options: $(cat "$work/verify.json")"
echo "PASS config verify accepts cpus, memory, ipc and shmSize and refuses gpus: 0"

# 2. A real container with those limits.
nohup "${FLISK_BIN:-flisk}" up app >"$work/up.log" 2>&1 &
up_pid=$!
container="${proj}-app-autogenerated-$res-1"
url="http://127.0.0.1:$http_port/api/$res/health"
status=000
for _ in $(seq 1 "$wait_seconds"); do
  status="$(curl -s -o /dev/null -m 3 -w '%{http_code}' -H "Host: api.$proj.localhost" "$url" || true)"
  [ "$status" = "200" ] && break
  sleep 1
done
[ "$status" = "200" ] || fail "GET /api/$res/health through Traefik returned $status"
limits="$(docker inspect -f '{{.HostConfig.NanoCpus}} {{.HostConfig.Memory}} {{.HostConfig.IpcMode}} {{.HostConfig.ShmSize}}' "$container")"
want="1500000000 805306368 host 134217728"
[ "$limits" = "$want" ] || fail "container has NanoCpus/Memory/IpcMode/ShmSize '$limits', wanted '$want'"
echo "PASS container answers through Traefik with 1.5 CPUs, 768m memory, host IPC and a 128mb /dev/shm ($limits)"

# 3. GPUs: the running Tiltfile picks up the service.json change and regenerates the stack's Compose file.
compose_file="$(grep -rl -- "$container\|  $res:" .flisk/.flisk-out --include='docker-compose*.yml' 2>/dev/null | head -1 || true)"
[ -n "$compose_file" ] || compose_file="$(find . -name 'docker-compose.app.autogenerated.yml' -not -path './node_modules/*' | head -1)"
[ -n "$compose_file" ] || fail "no generated Compose file for the app stack"
set_container '{"gpus": "all", "cpus": "1.5", "memory": "768m", "ipc": "host"}'
for _ in $(seq 1 120); do grep -q 'driver: nvidia' "$compose_file" && break; sleep 1; done
grep -q 'driver: nvidia' "$compose_file" || fail "$compose_file has no NVIDIA device reservation after setting gpus"
docker compose --env-file "$work/.env" -f "$compose_file" config --quiet 2>"$work/compose-config.err" \
  || fail "docker compose config refused the generated file: $(cat "$work/compose-config.err")"
echo "PASS the generated Compose file reserves every NVIDIA GPU and docker compose config accepts it"

if docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q nvidia; then
  for _ in $(seq 1 "$wait_seconds"); do
    requests="$(docker inspect -f '{{json .HostConfig.DeviceRequests}}' "$container" 2>/dev/null || true)"
    case "$requests" in *nvidia*) break ;; esac
    sleep 1
  done
  case "$requests" in *nvidia*) echo "PASS container carries the NVIDIA device request ($requests)" ;;
    *) fail "container has DeviceRequests '$requests', expected the nvidia driver" ;; esac
else
  echo "SKIP live GPU container: this Docker host has no NVIDIA runtime"
fi
