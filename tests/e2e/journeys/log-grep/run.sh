set -euo pipefail
SUITE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../../lib/lib.sh
source "$SUITE_DIR/../../lib/lib.sh"
e2e_init log-grep loggrepe2e
SERVICE="${PROJECT}-api"
RESOURCES=("$SERVICE")

fixture_hashes() {
  node - "$DIR" <<'JS'
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = process.argv[2], files = [];
function walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.isFile() && (file.includes('/.flisk/.flisk-out/') || file.includes('/.autogenerated/'))) files.push(file);
  }
}
walk(path.join(root, '.flisk/.flisk-out'));
walk(path.join(root, 'services'));
for (const file of files.sort()) console.log(path.relative(root,file), crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'));
JS
}

scaffold_logs() { # native or docker; edits only user-owned source/config, never generated runtime files
  e2e_cleanup
  local runtime=local
  [ "$1" = docker ] && runtime=docker
  (cd "$SUITE_ROOT" && flisk create "$PROJECT" --runtime "$runtime" --frontend none --backend hono --extras none --yes) >"$OUT/create-$1.out" 2>"$OUT/create-$1.err"
  node - "$DIR" "$1" "$SERVICE" <<'JS'
const fs = require('node:fs'), path = require('node:path');
const root = process.argv[2], native = process.argv[3] === 'native';
const project = path.join(root,'.flisk/project.json'), p = JSON.parse(fs.readFileSync(project));
p.capabilities = {gateway:false,database:false};
// Feed source configuration to the CLI; it owns all writes under .flisk/.
fs.writeFileSync(path.join(root,'fixture-project.json'), JSON.stringify(p,null,2)+'\n');
const service = path.join(root, native ? 'api' : 'services/app/'+process.argv[4], 'service.json'), s = JSON.parse(fs.readFileSync(service));
if (native) {
  s.command = 'node fixture.cjs';
  fs.writeFileSync(path.join(path.dirname(service),'fixture.cjs'), "console.log('before');console.log('ERROR target');console.log('after');console.log('quiet');require('node:http').createServer((q,s)=>s.end('ok')).listen(process.env.PORT);\n");
} else {
  // This log emitter serves no HTTP; its readiness contract is a command, not a route.
  delete s.healthCheckPath;
  s.appType = 'bring-your-own';
  s.type = 'bring-your-own';
  s.image = 'alpine:latest';
  s.exposeViaProxy = false;
  s.container = {command:['sh','-c', "printf 'before\\nERROR target\\nafter\\nquiet\\n'; exec tail -f /dev/null"]};
  s.healthCheck = {command:['true']};
}
fs.writeFileSync(service, JSON.stringify(s,null,2)+'\n');
JS
  run configure project --config-file fixture-project.json --force --yes --no-agent-skills
  [ "$RC" -eq 0 ] || die "fixture project configuration failed"
  run regenerate config regenerate --json
  [ "$RC" -eq 0 ] || die "config regenerate failed"
  run verify config verify --json
  [ "$RC" -eq 0 ] || die "config verify failed"
  assert check "$OUT/verify.out" "j.data.valid === true" "generated config is valid"
  fixture_hashes >"$OUT/$1-before.sha256"
  run regenerate-again config regenerate --json
  [ "$RC" -eq 0 ] || die "second regenerate failed"
  fixture_hashes >"$OUT/$1-again.sha256"
  cmp "$OUT/$1-before.sha256" "$OUT/$1-again.sha256"
}

logs_ready() { (cd "$DIR" && flisk logs --service "$SERVICE" --source runtime --json) | jq -e '.data.lines | any(.text | contains("quiet"))'; }
service_ready() { status_json | jq -e --arg name "$SERVICE" '.data.resources | any(.name == $name and .status == "ready")'; }

check_logs() { # run after the fixture is ready; also used for deliberate-break evidence
  run matches logs --service "$SERVICE" --source runtime --since 5m --tail 100 --grep error --context 1 --json
  [ "$RC" -eq 0 ] || die "matching logs failed"
  assert check "$OUT/matches.out" "JSON.stringify(j.data.lines.map(l=>[l.text,l.match])) === JSON.stringify([['before',false],['ERROR target',true],['after',false]])" "smart-case matches and exact context"
  run text logs --service "$SERVICE" --grep ERROR
  [ "$RC" -eq 0 ] || die "text logs failed"
  grep -q "^$SERVICE *| ERROR target$" "$OUT/text.out" || die "text lacks service prefix"
  run empty logs --grep never-a-match --json
  [ "$RC" -eq 0 ] || die "no-match must succeed"
  assert check "$OUT/empty.out" "j.data.lines.length === 0" "no matches is empty"
  run literal logs --grep '.' --json
  [ "$RC" -eq 0 ] || die "literal meta-character pattern must succeed"
  assert check "$OUT/literal.out" "j.data.lines.length === 0" "meta-characters match as literal text"
  local calls
  calls=$(jq -nc --arg service "$SERVICE" '[{"tool":"logs","arguments":{"services":[$service],"source":"runtime","grep":"error","context":1}},{"tool":"logs","arguments":{"grep":"never-a-match"}}]')
  mcp_session grep "$calls"
  mcp_structured grep 0
  assert check "$OUT/grep.0.json" "j.data.lines.length === 3 && j.data.lines[1].match === true && j.data.lines[0].match === false" "MCP delegates grep and context"
  mcp_structured grep 1
  assert check "$OUT/grep.1.json" "j.data.lines.length === 0" "MCP no-match succeeds"
}

check_generated_and_logs() {
  # Startup may create runtime files; only the read-only logs calls must leave these unchanged.
  run post-up-regenerate config regenerate --json
  [ "$RC" -eq 0 ] || die "post-up regenerate failed"
  run post-up-verify config verify --json
  [ "$RC" -eq 0 ] || die "post-up verify failed"
  assert check "$OUT/post-up-verify.out" "j.data.valid === true && j.data.diffs.length === 0 && j.errors.length === 0" "post-up generated config is valid"
  fixture_hashes >"$OUT/$1-running.sha256"
  run post-up-regenerate-again config regenerate --json
  [ "$RC" -eq 0 ] || die "post-up second regenerate failed"
  fixture_hashes >"$OUT/$1-regenerated.sha256"
  cmp "$OUT/$1-running.sha256" "$OUT/$1-regenerated.sha256"
  check_logs
  fixture_hashes >"$OUT/$1-after-logs.sha256"
  cmp "$OUT/$1-regenerated.sha256" "$OUT/$1-after-logs.sha256"
}

LG1() {
  scaffold_logs native
  start_stack ""
  poll_until "native emitter writes all fixture lines" 90 logs_ready
  poll_until "native emitter is ready" 90 service_ready
  check_generated_and_logs native
  run down down
  [ "$RC" -eq 0 ] || die "native cleanup failed"
}

LG2() {
  scaffold_logs docker
  start_stack app
  poll_until "Docker/Tilt emitter writes all fixture lines" "$READY_TIMEOUT" logs_ready
  poll_until "Docker/Tilt emitter is ready" "$READY_TIMEOUT" service_ready
  check_generated_and_logs docker
  run verify-after config verify --json
  [ "$RC" -eq 0 ] || die "post-up config verify failed"
  assert check "$OUT/verify-after.out" "j.data.valid === true" "config remains valid after up"
  run down down
  [ "$RC" -eq 0 ] || die "Docker cleanup failed"
}

e2e_main "$@"
