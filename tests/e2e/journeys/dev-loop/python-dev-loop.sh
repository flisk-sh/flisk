# Time the Python development loop through a real `flisk up` (#683): first start, a later start with a warm image, and save-to-ready after
# a one-line change to main.py, then the same change under a plain `uvicorn --reload` for comparison. Prints numbers; it is a measurement,
# not a gate, so it only fails when the service never comes up or an edit is never served.
#
# Needs Docker, Tilt, python3, uv (for the uvicorn baseline) and a built CLI (cli/dist). Uses an isolated throwaway project with a unique
# name and random alternate ports, and removes only the containers, networks and images carrying its own name (it never calls
# `flisk down`, which can touch other projects' containers).
#
# Usage: tests/e2e/journeys/dev-loop/python-dev-loop.sh [edits]     (default 5)
#   VERIFY_WAIT_SECONDS   how long to wait for a start (default 900)
set -euo pipefail

edits="${1:-5}"
root="$(cd "$(dirname "$0")/../../../.." && pwd)"
proj="pyloop$$"
work="$(mktemp -d)/$proj"
mkdir -p "$work"
http_port=$((30000 + RANDOM % 2000))
tilt_port=$((10400 + RANDOM % 500))
export FLISK_EXTENSION_SOURCE="$root"
flisk() { node "$root/cli/bin/flisk.js" "$@"; }

uvicorn_pid=""
cleanup() {
  [ -n "$uvicorn_pid" ] && kill "$uvicorn_pid" >/dev/null 2>&1 || true
  pkill -f "tilt up.*/${proj}/" >/dev/null 2>&1 || true
  docker rm -f $(docker ps -aq --filter "name=^${proj}[-_]") >/dev/null 2>&1 || true
  docker network ls --format '{{.Name}}' | grep -E "^${proj}_" | xargs -r docker network rm >/dev/null 2>&1 || true
  docker volume ls --format '{{.Name}}' | grep -E "^${proj}-" | xargs -r docker volume rm >/dev/null 2>&1 || true
  docker images --format '{{.Repository}}:{{.Tag}}' | grep -E "^(${proj}_|${proj}-l[0-9]+)" | xargs -r docker rmi -f >/dev/null 2>&1 || true
}
trap cleanup EXIT

cd "$work"
git init -q .
flisk project --yes >/dev/null 2>&1
printf '\nFLISK_HTTP_PORT=%s\nFLISK_HTTPS_PORT=%s\nFLISK_POSTGRES_PORT=%s\n' \
  "$http_port" "$((32000 + RANDOM % 2000))" "$((34000 + RANDOM % 2000))" >> .env
flisk resource api --type backend --language python --stack "$proj" --yes >/dev/null
svc="services/$proj/api"
health="/api/api/health"
route="/api/api/"
host="api.$proj.localhost"
container="${proj}-${proj}-autogenerated-api-1"

wait_healthy() {
  local status=000
  for _ in $(seq 1 "${VERIFY_WAIT_SECONDS:-900}"); do
    status="$(curl -s -o /dev/null -m 3 -w '%{http_code}' -H "Host: $host" "http://127.0.0.1:$http_port$health" || true)"
    [ "$status" = "200" ] && return 0
    sleep 1
  done
  echo "FAIL: GET $health -> $status after ${VERIFY_WAIT_SECONDS:-900}s" >&2
  tail -30 "$work/up.log" >&2 || true
  return 1
}

start_up() {
  local label="$1" started
  started="$(date +%s)"
  TILT_PORT="$tilt_port" nohup node "$root/cli/bin/flisk.js" up "$proj" >"$work/up-$label.log" 2>&1 &
  cp "$work/up-$label.log" "$work/up.log" 2>/dev/null || true
  wait_healthy
  echo "$label start: $(( $(date +%s) - started ))s from launching flisk up to the first 200 through Traefik"
}

echo "machine: $(uname -sm), load average $(uptime | sed 's/.*load averages*: //')"
start_up first
echo "image: $(docker inspect -f '{{.Config.Image}}' "$container"), process: $(docker top "$container" -o pid,args | sed -n 2p | cut -c1-80)"

echo
echo "== edit loop through flisk up =="
python3 "$root/tests/e2e/journeys/dev-loop/python-dev-loop-probe.py" "$work/$svc/src/main.py" "$http_port" "$host" "$route" "$container" "$edits"

# Warm start: stop this project's own containers and Tilt, keep the image, start again.
pkill -f "tilt up.*/${proj}/" >/dev/null 2>&1 || true
docker rm -f $(docker ps -aq --filter "name=^${proj}[-_]") >/dev/null 2>&1 || true
sleep 3
echo
start_up warm
pkill -f "tilt up.*/${proj}/" >/dev/null 2>&1 || true
docker rm -f $(docker ps -aq --filter "name=^${proj}[-_]") >/dev/null 2>&1 || true

echo
echo "== the same edit loop under plain uvicorn --reload =="
base_port=$((36000 + RANDOM % 2000))
(cd "$work/$svc" && PORT="$base_port" nohup uvx --python 3.12 --with fastapi --with uvicorn uvicorn main:app --app-dir src --port "$base_port" --reload --reload-dir src >"$work/uvicorn.log" 2>&1) &
uvicorn_pid=$!
for _ in $(seq 1 120); do
  [ "$(curl -s -o /dev/null -m 2 -w '%{http_code}' "http://127.0.0.1:$base_port/health" || true)" = "200" ] && break
  sleep 1
done
python3 "$root/tests/e2e/journeys/dev-loop/python-dev-loop-probe.py" "$work/$svc/src/main.py" "$base_port" localhost "/" - "$edits"
