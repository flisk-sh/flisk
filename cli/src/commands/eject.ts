import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import chalk from "chalk";
import { Command } from "commander";
import { addYesOption, confirmOrCancel, handleDryRun } from "../utils/command-helpers.js";
import { errorFactories, FliskError, runCommand } from "../utils/errors.js";
import { type JsonCommandResult, runJsonCommand } from "../utils/json-command.js";
import { findProjectRoot } from "../utils/paths.js";

// Same location `flisk up` hands to Tilt (see getTiltfilePath in utils/tilt.ts), relative to the project root.
export const TILTFILE_RELATIVE_PATH = ".flisk/.flisk-out/Tiltfile";
export const TILT_UP_COMMAND = `tilt up -f ${TILTFILE_RELATIVE_PATH} -- --focus=<stack>`;

export const EJECTED_CONTENT = `# Ejected from Flisk

\`flisk eject\` wrote this file and nothing else. It did not copy, move or generate anything, and it did
not remove Flisk. What exists is what Flisk had already generated, and that is still Flisk-owned output.

## Where the generated files are

- \`.flisk/.flisk-out/\` holds the Tiltfile and the engine it loads (\`flisk-cli-ext/\`). It is git-ignored.
  \`flisk config regenerate\` rewrites the master files in it.
- The per-service Compose files (\`services/<stack>/<name>/.autogenerated/\`), the golden-layer
  Dockerfile and the Traefik file (\`.flisk/.flisk-out/\`) are written by Tilt when it runs, not by
  \`flisk eject\`. Until Tilt has run they do not exist. They are git-ignored too.
- Your own Dockerfiles, \`service.json\` files and source code are untouched.

## Running the stack without the flisk CLI

There is no Tiltfile at the project root, so a plain \`tilt up\` does not find one. Flisk runs:

    ${TILT_UP_COMMAND}

from the project root (\`<stack>\` is a stack name under \`services/\`; without \`--focus\` the Tiltfile
falls back to its default phase). The Tiltfile still reads \`.flisk/project.json\` and the
\`service.json\` files, so those must stay. \`flisk up\` also does steps before Tilt starts (it chooses
host ports and exports them to Tilt); running Tilt by hand skips them.

## Cleaning up

Optional to delete later: this file, and \`.flisk/\` plus the \`service.json\` files if you stop using Flisk.
Deleting them also removes what the Tiltfile needs.

To go back to Flisk: install it and run \`flisk config regenerate\`.
`;

/** What `flisk eject --json` reports. `created`: EJECTED.md was written by this run (in a dry run: would be). */
export interface EjectReport {
  dryRun: boolean;
  created: boolean;
  ejectedFile: string;
  generatedFiles: string[];
  userFiles: string[];
  tiltUpCommand: string;
}

export const ejectCommand = addYesOption(new Command("eject"))
  .description(
    "Write EJECTED.md describing the generated Tilt files (copies and generates nothing; they stay in .flisk/.flisk-out/)",
  )
  .option(
    "--dry-run",
    "List the generated files and what would be written, without changing the project",
    false,
  )
  .option("--json", "Print one JSON envelope on stdout; implies --yes", false)
  .action(async (options) => {
    const action = async (): Promise<JsonCommandResult> => {
      const projectRoot = findProjectRoot();
      if (!projectRoot) {
        throw errorFactories.notInProject();
      }
      const generatedPaths = [".flisk/.flisk-out"];
      const presentPaths = generatedPaths.filter((path) => existsSync(join(projectRoot, path)));
      const files = presentPaths.flatMap((path) => {
        const absolutePath = join(projectRoot, path);
        if (statSync(absolutePath).isFile()) return [path];
        try {
          return readdirSync(absolutePath, { recursive: true }).map((entry) =>
            join(path, entry.toString()),
          );
        } catch {
          return [path];
        }
      });
      if (!existsSync(join(projectRoot, ".flisk", ".flisk-out", "Tiltfile"))) {
        throw new FliskError(
          "Generated Tilt files are missing. Run `flisk project --yes` before ejecting.",
          ["flisk project --yes", "flisk eject"],
        );
      }
      const rootTiltfile = join(projectRoot, "Tiltfile");
      const userTiltfile = existsSync(rootTiltfile) ? ["Tiltfile"] : [];
      const ejectedPath = join(projectRoot, "EJECTED.md");
      const willCreate = existsSync(ejectedPath) ? [] : ["EJECTED.md"];
      const report = (dryRun: boolean): JsonCommandResult => ({
        data: {
          dryRun,
          created: willCreate.length > 0,
          ejectedFile: "EJECTED.md",
          generatedFiles: files,
          userFiles: userTiltfile,
          tiltUpCommand: TILT_UP_COMMAND,
        } satisfies EjectReport,
      });

      // eject's plan is a file list, not the standard "Dry run - ..." pair, so it supplies its own printer.
      if (
        handleDryRun(options, "", "", () => {
          console.log("Generated files, left where they are (git-ignored):");
          for (const path of files) console.log(`  ${path}`);
          if (userTiltfile.length > 0) {
            console.log("Root Tiltfile, left where it is (not generated, not git-ignored):");
            for (const path of userTiltfile) console.log(`  ${path}`);
          }
          console.log("Files written:");
          for (const path of willCreate) console.log(`  ${path}`);
          if (willCreate.length === 0) console.log("  (none)");
        })
      ) {
        return report(true);
      }

      if (
        !options.yes &&
        !options.json &&
        !(await confirmOrCancel(
          "Write EJECTED.md? (Generated files stay in .flisk/.flisk-out/; nothing is copied or moved.)",
        ))
      ) {
        return { data: null };
      }

      if (existsSync(ejectedPath)) {
        console.log(
          chalk.green(
            "EJECTED.md already exists and was left unchanged. Nothing was copied, moved or generated.",
          ),
        );
      } else {
        writeFileSync(ejectedPath, EJECTED_CONTENT, { flag: "wx" });
        console.log(chalk.green("Wrote EJECTED.md. Nothing was copied, moved or generated."));
      }
      console.log(
        "Generated files stay in .flisk/.flisk-out/ (git-ignored) and still need Flisk inputs.",
      );
      console.log(`Run from the project root: ${TILT_UP_COMMAND}`);
      console.log(
        "Replace <stack> with a stack name under services/, or omit --focus to use the Tiltfile's default phase.",
      );
      console.log("Read EJECTED.md");
      return report(false);
    };

    if (options.json) {
      await runJsonCommand("EJECT_FAILED", "flisk eject", action);
      return;
    }
    await runCommand(action);
  });
