import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { createTempDir, parseEnvelope, runFlisk } from "../../test-support/index.js";

/** `config regenerate` writes the master files; a service's compose and Dockerfile come from `flisk up`. */
describe("flisk config regenerate with generated service files older than service.json", () => {
  function projectWithStaleCompose(): string {
    const dir = createTempDir("regenerate-stale");
    expect(runFlisk(["project", "--yes", "--no-agent-skills"], { cwd: dir }).status).toBe(0);
    expect(runFlisk(["resource", "api", "--yes", "--stack", "main"], { cwd: dir }).status).toBe(0);
    const service = join(dir, "services/main/api");
    const generated = join(service, ".autogenerated");
    mkdirSync(join(generated, ".flisk-contract"), { recursive: true });
    writeFileSync(join(generated, "docker-compose.app.autogenerated.yml"), "services: {}\n");
    // The snapshot `flisk up` took of the service.json it generated from; the file has changed since.
    const manifest = JSON.parse(readFileSync(join(service, "service.json"), "utf-8"));
    writeFileSync(
      join(generated, ".flisk-contract", "service.json.source"),
      readFileSync(join(service, "service.json"), "utf-8"),
    );
    manifest.secrets = { required: ["TEAM_TAYLOR_WEBHOOK_SECRET"] };
    writeFileSync(join(service, "service.json"), JSON.stringify(manifest, null, 2));
    return dir;
  }

  it("says which services `flisk up` still has to rewrite", () => {
    const dir = projectWithStaleCompose();
    const result = runFlisk(["config", "regenerate"], { cwd: dir });
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("services/main/api/service.json");
    expect(result.stdout).toMatch(/flisk up/);
  });

  it("lists them in --json as staleServiceOutputs", () => {
    const dir = projectWithStaleCompose();
    const envelope = parseEnvelope(
      runFlisk(["config", "regenerate", "--json"], { cwd: dir }).stdout,
    );
    expect(envelope.data.staleServiceOutputs).toEqual(["services/main/api/service.json"]);
  });

  it("stays quiet when nothing is stale", () => {
    const dir = createTempDir("regenerate-fresh");
    runFlisk(["project", "--yes", "--no-agent-skills"], { cwd: dir });
    runFlisk(["resource", "api", "--yes", "--stack", "main"], { cwd: dir });
    const result = runFlisk(["config", "regenerate"], { cwd: dir });
    expect(result.stdout).not.toMatch(/older service\.json/);
    const envelope = parseEnvelope(
      runFlisk(["config", "regenerate", "--json"], { cwd: dir }).stdout,
    );
    expect(envelope.data.staleServiceOutputs).toEqual([]);
  });
});

describe("a name in both secrets and params", () => {
  it("is reported by config verify and flisk up --dry-run, and does not stop either", () => {
    const dir = createTempDir("secret-vs-param");
    runFlisk(["project", "--yes", "--no-agent-skills"], { cwd: dir });
    runFlisk(["resource", "api", "--yes", "--stack", "main"], { cwd: dir });
    const file = join(dir, "services/main/api/service.json");
    const manifest = JSON.parse(readFileSync(file, "utf-8"));
    manifest.secrets = { optional: ["ADMIN_PASSWORD"] };
    manifest.params = { ADMIN_PASSWORD: "changeme" };
    writeFileSync(file, JSON.stringify(manifest, null, 2));
    runFlisk(["config", "regenerate"], { cwd: dir });

    const verify = parseEnvelope(runFlisk(["config", "verify", "--json"], { cwd: dir }).stdout);
    expect(JSON.stringify(verify.data.warnings)).toContain("params.ADMIN_PASSWORD");
    const up = runFlisk(["up", "--dry-run"], { cwd: dir });
    expect(up.status).toBe(0);
    expect(`${up.stdout}${up.stderr}`).toContain("params.ADMIN_PASSWORD");
  });
});
