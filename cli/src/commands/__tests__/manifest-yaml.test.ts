import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const converter = join(repoRoot, "engine", "topologies", "tilt", "manifest", "json_to_yaml.py");

const hasPyYaml = spawnSync("python3", ["-c", "import yaml"], { encoding: "utf-8" }).status === 0;
if (process.env.TDK_REQUIRE_TILT === "1" && !hasPyYaml) {
  throw new Error("python3 with PyYAML is required for the manifest YAML converter tests in CI.");
}

const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

function convert(manifest: Record<string, unknown>) {
  const dir = mkdtempSync(join(tmpdir(), "flisk-manifest-yaml-"));
  dirs.push(dir);
  const file = join(dir, "service.json");
  writeFileSync(file, JSON.stringify(manifest));
  return spawnSync("python3", [converter, file], { encoding: "utf-8" });
}

// `.autogenerated/service.yaml` mirrors service.json and is generated, so it must not be a second copy of a secret.
describe.skipIf(!hasPyYaml)("service.json to service.yaml converter", { timeout: 30_000 }, () => {
  it("does not copy jwtSecret into the generated YAML", () => {
    const result = convert({
      appName: "orders-api",
      appType: "backend",
      port: 4000,
      jwtSecret: "a-real-secret-that-must-not-leak",
    });
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).not.toContain("a-real-secret-that-must-not-leak");
    expect(result.stdout).not.toContain("jwtSecret");
  });

  it("writes the same YAML for the same manifest, so regenerating it does not change the file", async () => {
    const manifest = { appName: "orders-api", appType: "backend", port: 4000 };
    const first = convert(manifest);
    await new Promise((resolve) => setTimeout(resolve, 1100));
    const second = convert(manifest);
    expect(first.status, first.stderr).toBe(0);
    expect(second.stdout).toBe(first.stdout);
  });

  it("gives different manifests different uids", () => {
    const uid = (port: number) =>
      /uid: (\S+)/.exec(convert({ appName: "orders-api", appType: "backend", port }).stdout)?.[1];
    expect(uid(4000)).toBeTruthy();
    expect(uid(4000)).not.toBe(uid(4001));
  });

  it("still carries everything else, including the names in secrets", () => {
    const result = convert({
      appName: "orders-api",
      appType: "backend",
      port: 4000,
      jwtSecret: "x",
      secrets: { required: ["STRIPE_KEY"] },
    });
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("appName: orders-api");
    expect(result.stdout).toContain("STRIPE_KEY");
  });
});
