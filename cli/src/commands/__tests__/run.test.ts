import { type SpawnSyncReturns, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { createTempDir } from "../../test-support/index.js";
import { FliskError } from "../../utils/errors.js";
import { composeProjectFor, resolveRunTarget, runningContainer } from "../run.js";

const CLI = join(dirname(fileURLToPath(import.meta.url)), "../../../bin/flisk.js");

/** A project with one local-process service `api` (env GREETING, port 4567) and the project .env. */
function nativeProject(): string {
  const root = createTempDir();
  mkdirSync(join(root, ".flisk"), { recursive: true });
  writeFileSync(
    join(root, ".flisk", "project.json"),
    JSON.stringify({ project: { name: "Run-Test" } }),
  );
  writeFileSync(join(root, ".env"), "FROM_DOT_ENV=yes\n");
  const dir = join(root, "services", "app", "api");
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "service.json"),
    JSON.stringify({
      schemaVersion: 1,
      appName: "api",
      appType: "backend",
      stack: "app",
      command: "node server.js",
      port: 4567,
      env: { GREETING: "hi" },
    }),
  );
  return root;
}

function docker(stdout: string, status = 0): (args: string[]) => SpawnSyncReturns<string> {
  return () => ({ stdout, stderr: "", status, pid: 1, output: [], signal: null });
}

function flisk(root: string, args: string[]) {
  return spawnSync(process.execPath, [CLI, "run", ...args], { cwd: root, encoding: "utf-8" });
}

describe("flisk run (#2872)", () => {
  it("names the stack's Compose project the way the engine does, lowercased like Docker", () => {
    expect(composeProjectFor("Run-Test", "app")).toBe("run-test-app-autogenerated");
  });

  it("finds the running container of a Compose service by its labels", () => {
    expect(runningContainer("p-app-autogenerated", "api", docker("abc123\n"))).toBe("abc123");
    expect(runningContainer("p-app-autogenerated", "api", docker(""))).toBeNull();
    expect(() => runningContainer("p", "api", docker("", 1))).toThrow(FliskError);
  });

  it("refuses an unknown service with the names it knows, and a missing command", () => {
    const root = nativeProject();
    expect(() => resolveRunTarget(root, "web", ["true"])).toThrow(/No service named "web"/);
    try {
      resolveRunTarget(root, "web", ["true"]);
    } catch (error) {
      expect((error as FliskError).suggestions).toContain("Services: api");
    }
    expect(() => resolveRunTarget(root, "api", [])).toThrow(/Give the command to run after --/);
  });

  it("runs a local-process service's command from its folder with the project .env, its env and PORT", () => {
    const root = nativeProject();
    const target = resolveRunTarget(root, "api", ["printenv", "GREETING"]);
    expect(target).toMatchObject({
      service: "api",
      runtime: "native",
      file: "printenv",
      args: ["GREETING"],
      cwd: join(root, "services", "app", "api"),
    });
    expect(target.env).toMatchObject({ GREETING: "hi", PORT: "4567", FROM_DOT_ENV: "yes" });
  });

  it("passes the command's exit code through, and --json reports it with the output", () => {
    const root = nativeProject();
    const plain = flisk(root, [
      "api",
      "--",
      "sh",
      "-c",
      'echo "$GREETING:$PORT:$FROM_DOT_ENV"; exit 7',
    ]);
    expect(plain.status).toBe(7);
    expect(plain.stdout).toContain("hi:4567:yes");

    const json = flisk(root, ["api", "--json", "--", "sh", "-c", "echo out; echo err >&2; exit 3"]);
    expect(json.status).toBe(3);
    const envelope = JSON.parse(json.stdout.trim().split("\n").at(-1) as string);
    expect(envelope).toEqual({
      schemaVersion: 1,
      data: {
        service: "api",
        runtime: "native",
        command: ["sh", "-c", "echo out; echo err >&2; exit 3"],
        exitCode: 3,
        stdout: "out\n",
        stderr: "err\n",
      },
      errors: [],
    });
  });

  it("reports an unknown service as RUN_FAILED in --json", () => {
    const root = nativeProject();
    const result = flisk(root, ["nope", "--json", "--", "true"]);
    expect(result.status).toBe(1);
    const envelope = JSON.parse(result.stdout.trim().split("\n").at(-1) as string);
    expect(envelope.errors[0]).toMatchObject({ code: "RUN_FAILED" });
    expect(envelope.errors[0].message).toContain('No service named "nope"');
  });
});
