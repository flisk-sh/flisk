import { beforeEach, describe, expect, it } from "vitest";
import {
  createTempDir,
  createTempProject,
  parseEnvelope,
  runCommandInProcess,
} from "../../test-support/index.js";
import { configCommand } from "../config.js";

const projectJson = {
  version: "1.0",
  project: { name: "explain", version: "1.0.0" },
  phases: Object.fromEntries(
    ["pre_alpha", "alpha", "beta", "out_of_scope"].map((phase) => [
      phase,
      { name: phase, description: "", enabledStacks: [] },
    ]),
  ),
  optional_infra: {
    monitoring: false,
    elk: false,
    debezium: false,
    golden_image: false,
    verdaccio: false,
  },
  discovery: { paths: ["services/*/*"] },
};

const apiService = { appType: "backend", port: 4000 };

const explainJson = (root: string, file: string) =>
  runCommandInProcess(configCommand, ["explain", file, "--json"], root);

beforeEach(() => {
  // Commander keeps option values on each subcommand between parseAsync calls, so clear them before every case.
  const explain = configCommand.commands.find((sub) => sub.name() === "explain");
  for (const option of explain?.options ?? []) {
    explain?.setOptionValue(option.attributeName(), undefined);
  }
});

describe("config explain: Flisk-generated service outputs", () => {
  it("reports a hand-edited .autogenerated file as generated and blocking flisk up", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
      files: {
        "services/api/.autogenerated/app.ts": "edited by hand\n",
        "services/api/.autogenerated/.flisk-contract/app.ts": "generated\n",
      },
    });

    const result = await explainJson(root, "services/api/.autogenerated/app.ts");

    expect(result.status).toBeUndefined();
    expect(parseEnvelope(result.stdout)).toEqual({
      schemaVersion: 1,
      data: expect.objectContaining({
        file: "services/api/.autogenerated/app.ts",
        ownership: "generated",
        source: "services/api/service.json",
        driftOnUp: "blocks-up",
        isEditedNow: true,
      }),
      errors: [],
    });
    const data = parseEnvelope(result.stdout).data;
    expect(data.next).toContain("Edit services/api/service.json instead, then run `flisk up`.");
    expect(data.next).toContain("Keep a hand edit on purpose with `flisk up --ignore-drift`.");
  });

  it("reports an untouched .autogenerated file as generated, not edited now, but still blocking", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
      files: {
        "services/api/.autogenerated/app.ts": "generated\n",
        "services/api/.autogenerated/.flisk-contract/app.ts": "generated\n",
      },
    });

    const result = await explainJson(root, "services/api/.autogenerated/app.ts");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "generated",
      driftOnUp: "blocks-up",
      isEditedNow: false,
    });
  });

  it("reports drift as unknown when Flisk has no snapshot of the file", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
      files: { "services/api/.autogenerated/app.ts": "generated\n" },
    });

    const result = await explainJson(root, "services/api/.autogenerated/app.ts");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "generated",
      driftOnUp: "unknown",
    });
  });

  it("reports service.yaml as generated and exempt from the hand-edit check", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
      files: { "services/api/.autogenerated/service.yaml": "name: api\n" },
    });

    const result = await explainJson(root, "services/api/.autogenerated/service.yaml");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "generated",
      source: "services/api/service.json",
      driftOnUp: "none",
    });
  });

  it("reports ownership as unknown when the .autogenerated folder has no service.json beside it", async () => {
    const root = createTempProject({
      projectJson,
      files: { "services/orphan/.autogenerated/app.ts": "generated\n" },
    });

    const result = await explainJson(root, "services/orphan/.autogenerated/app.ts");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "unknown",
      source: null,
      driftOnUp: "unknown",
    });
  });

  it("reports a project output as generated from .flisk/project.json and not blocking flisk up", async () => {
    const root = createTempProject({
      projectJson,
      files: { Tiltfile: "# generated\n" },
    });

    const result = await explainJson(root, "Tiltfile");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      file: "Tiltfile",
      ownership: "generated",
      source: ".flisk/project.json",
      driftOnUp: "none",
    });
  });
});

describe("config explain: files whose path alone does not settle ownership", () => {
  it("reports a root .tiltignore without Flisk's marker as user-owned", async () => {
    const root = createTempProject({ projectJson, files: { ".tiltignore": "node_modules\n" } });

    const result = await explainJson(root, ".tiltignore");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "user-owned",
      driftOnUp: "none",
      source: null,
    });
  });

  it("reports a root .tiltignore with Flisk's marker as generated from project.json", async () => {
    const root = createTempProject({
      projectJson,
      files: { ".tiltignore": "# SYSTEM-GENERATED BY Flisk CLI\n" },
    });

    const result = await explainJson(root, ".tiltignore");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "generated",
      source: ".flisk/project.json",
    });
  });

  it("reports package.json as user-owned, since Flisk never overwrites it", async () => {
    const root = createTempProject({ projectJson, files: { "package.json": "{}\n" } });

    const result = await explainJson(root, "package.json");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      ownership: "user-owned",
      driftOnUp: "none",
    });
  });
});

describe("config explain: path resolution", () => {
  it("resolves the file against the current directory, not the project root", async () => {
    const root = createTempProject({
      projectJson,
      files: { "services/api/src/index.ts": "export {};\n" },
    });

    const result = await runCommandInProcess(
      configCommand,
      ["explain", "src/index.ts", "--json"],
      `${root}/services/api`,
    );

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      file: "services/api/src/index.ts",
      ownership: "user-owned",
    });
  });
});

describe("config explain: user-owned files", () => {
  it("reports a file outside the generated-path allowlist as user-owned", async () => {
    const root = createTempProject({
      projectJson,
      files: { "services/api/src/index.ts": "export {};\n" },
    });

    const result = await explainJson(root, "services/api/src/index.ts");

    expect(parseEnvelope(result.stdout).data).toMatchObject({
      file: "services/api/src/index.ts",
      ownership: "user-owned",
      source: null,
      driftOnUp: "none",
      isEditedNow: false,
      next: ["Edit it directly."],
    });
  });
});

describe("config explain: failure cases", () => {
  it("fails with a structured error when the file does not exist", async () => {
    const root = createTempProject({ projectJson });

    const result = await explainJson(root, "missing.txt");

    expect(result.status).toBe(1);
    const envelope = parseEnvelope(result.stdout);
    expect(envelope.data).toBeNull();
    expect(envelope.errors).toEqual([
      expect.objectContaining({
        code: "COMMAND_FAILED",
        message: "File not found: missing.txt",
      }),
    ]);
  });

  it("fails when the file is outside the project", async () => {
    const root = createTempProject({ projectJson });

    const result = await explainJson(root, "../outside.txt");

    expect(result.status).toBe(1);
    expect(parseEnvelope(result.stdout).errors[0]).toMatchObject({
      message: "../outside.txt is outside the project",
    });
  });

  it("fails when the path is a directory", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
    });

    const result = await explainJson(root, "services/api");

    expect(result.status).toBe(1);
    expect(parseEnvelope(result.stdout).errors[0]).toMatchObject({
      message: "Not a file: services/api",
    });
  });

  it("emits a null-data envelope outside a project", async () => {
    const root = createTempDir();

    const result = await explainJson(root, "package.json");

    expect(result.status).toBe(1);
    const envelope = parseEnvelope(result.stdout);
    expect(envelope.data).toBeNull();
    expect(envelope.errors).toHaveLength(1);
  });
});

describe("config explain: human output", () => {
  it("says a generated file blocks flisk up and lists the next steps", async () => {
    const root = createTempProject({
      projectJson,
      resources: { api: apiService },
      files: {
        "services/api/.autogenerated/app.ts": "edited by hand\n",
        "services/api/.autogenerated/.flisk-contract/app.ts": "generated\n",
      },
    });

    const result = await runCommandInProcess(
      configCommand,
      ["explain", "services/api/.autogenerated/app.ts"],
      root,
    );

    expect(result.status).toBeUndefined();
    expect(result.stdout).toContain("Ownership: generated");
    expect(result.stdout).toContain("Source: services/api/service.json");
    expect(result.stdout).toContain("Edited now: yes");
    expect(result.stdout).toContain(
      "Editing it blocks flisk up: yes, until the edit is removed or --ignore-drift is passed",
    );
    expect(result.stdout).toContain("Next:");
  });

  it("says a user-owned file is not blocked by flisk up", async () => {
    const root = createTempProject({
      projectJson,
      files: { "services/api/src/index.ts": "export {};\n" },
    });

    const result = await runCommandInProcess(
      configCommand,
      ["explain", "services/api/src/index.ts"],
      root,
    );

    expect(result.stdout).toContain("Ownership: user-owned");
    expect(result.stdout).toContain("Editing it blocks flisk up: no");
  });
});
