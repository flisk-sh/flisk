/**
 * Checks the project's minimum and exact pinned CLI version.
 * Shared with `flisk up` so both commands report the same message and fix.
 */
export function checkFliskVersion(currentVersion: string = getPackageVersion()): CheckResult {
  const projectRoot = findProjectRoot();
  if (!projectRoot) {
    return {
      name: "Flisk version",
      didPass: true,
      isSkipped: true,
      message: "Not in a project - skipping Flisk version check",
    };
  }

  const version = evaluateFliskVersion(projectRoot, currentVersion);
  const warning = version.deprecationWarning ? `\nWarning: ${version.deprecationWarning}` : "";

  if (version.status === "none") {
    return {
      name: "Flisk version",
      didPass: true,
      isSkipped: true,
      message: `flisk ${currentVersion} (no minFliskVersion or pinnedFliskVersion in .flisk/project.json)${warning}`,
    };
  }

  if (version.status !== "ok") {
    return {
      name: "Flisk version",
      didPass: false,
      message: `${version.message}${warning}`,
      fix: version.fix,
    };
  }

  const requirement =
    version.source === "pin"
      ? `matches pinnedFliskVersion ${version.required}`
      : `meets minFliskVersion ${version.required}`;

  return {
    name: "Flisk version",
    didPass: true,
    isWarning: Boolean(version.deprecationWarning),
    message: `flisk ${currentVersion} ${requirement}${warning}`,
  };
}

/** A CLI older than the latest release is a warning, never a failure; an unreachable registry is skipped (#4119). */
export async function checkLatestFliskVersion(
  currentVersion: string = getPackageVersion(),
  lookup: () => Promise<string | null> = () => fetchLatestVersion(),
): Promise<CheckResult> {
  const latest = await lookup();
  if (!latest) {
    return {
      name: "Latest Flisk version",
      didPass: true,
      isSkipped: true,
      message: "Could not read the latest version (offline, CI, or slow registry) - skipping",
    };
  }
  if (isOlderVersion(currentVersion, latest)) {
    return {
      name: "Latest Flisk version",
      didPass: true,
      isWarning: true,
      message: `flisk ${currentVersion} is older than the latest release ${latest}`,
      fix: "Run: flisk upgrade (or npx @flisk-sh/flisk@latest demo)",
    };
  }
  return {
    name: "Latest Flisk version",
    didPass: true,
    message: `flisk ${currentVersion} is up to date`,
  };
}

/**
 * Tilt only builds resources under `discovery.paths`, but the CLI finds every service.json,
 * so a resource outside them is listed and given a URL by `flisk up` yet never started.
 */
export function checkResourceDiscovery(): CheckResult {
  const projectRoot = findProjectRoot() ?? process.cwd();
  const patterns = readDiscoveryPaths(projectRoot);
  const stranded = discoverResourcesFromRoot(projectRoot).filter(
    (resource) => !isPathDiscovered(projectRoot, resource.path, patterns),
  );

  if (stranded.length === 0) {
    return {
      name: "Resource Discovery",
      didPass: true,
      message: `All resources are covered by discovery.paths ${JSON.stringify(patterns)}`,
    };
  }

  const list = stranded
    .map((resource) => normalize(relative(projectRoot, resource.path)))
    .join(", ");
  return {
    name: "Resource Discovery",
    didPass: false,
    message: `${formatCount(stranded.length, "resource")} outside discovery.paths ${JSON.stringify(patterns)}: ${list}. \`flisk up\` will not start them`,
    fix: "Move each under services/<stack>/<name>, or add a matching pattern to discovery.paths in .flisk/project.json and run: flisk config regenerate",
  };
}

/**
 * `.autogenerated/` is written by `flisk up`, so a resource without it has simply not been generated yet.
 * That is a warning, not a failure: `flisk doctor` is also run before the first `flisk up`.
 */
/** Regular files under `.autogenerated/`, nested ones included, without the `.flisk-contract` bookkeeping directory. */
function listGeneratedFiles(root: string): string[] {
  const files: string[] = [];
  const collect = (dir: string, relativeDir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (relativeDir === "" && entry.name === ".flisk-contract") continue;
      const relativeFile = relativeDir === "" ? entry.name : `${relativeDir}/${entry.name}`;
      if (entry.isDirectory()) collect(join(dir, entry.name), relativeFile);
      else if (entry.isFile()) files.push(relativeFile);
    }
  };
  collect(root, "");
  return files.sort();
}

export function checkGeneratedFiles(strict = false): CheckResult {
  const projectRoot = findProjectRoot() ?? process.cwd();
  const resources = discoverResourcesFromRoot(projectRoot).filter(
    (resource) => (resource.config?.appType ?? resource.type) !== "library",
  );

  if (resources.length === 0) {
    return {
      name: "Generated Files",
      didPass: true,
      isSkipped: true,
      message: "No resources to check",
    };
  }

  const lines: string[] = [];
  const missing: string[] = [];
  for (const resource of resources) {
    const label = normalize(relative(projectRoot, resource.path));
    const dir = join(resource.path, AUTOGENERATED_DIR);
    const files = existsSync(dir) ? listGeneratedFiles(dir) : [];
    if (files.length === 0) {
      missing.push(label);
      lines.push(`${label}: no ${AUTOGENERATED_DIR}/ files`);
    } else {
      lines.push(`${label}: ${files.join(", ")}`);
    }
  }

  if (missing.length === 0) {
    return {
      name: "Generated Files",
      didPass: true,
      message: `${formatCount(resources.length, "resource")} with generated files:\n    ${lines.join("\n    ")}`,
    };
  }

  return {
    name: "Generated Files",
    didPass: false,
    isWarning: !strict,
    message: `${missing.length} of ${formatCount(resources.length, "resource")} not generated yet:\n    ${lines.join("\n    ")}`,
    fix: "Run `flisk up` to generate them (it needs Docker, Compose and Tilt). `flisk config verify` checks the project-level files only.",
  };
}

