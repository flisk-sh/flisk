import { renderToString } from "ink";
import { createElement } from "react";
import { describe, expect, it } from "vitest";
import type { ResourceMetadata } from "../types/index.js";
import { ServiceIssues } from "./ServiceIssues.js";

const base: ResourceMetadata = {
  name: "api",
  type: "backend",
  createdAt: "2026-10-07T00:00:00.000Z",
  lastModified: "2026-10-07T00:00:00.000Z",
  dependencies: [],
  hasDockerfile: true,
  hasTiltfile: false,
  hasDockerCompose: false,
  autogeneratedFiles: [],
  status: "unknown",
};
const render = (resources: ResourceMetadata[]) =>
  renderToString(createElement(ServiceIssues, { resources }), { columns: 80 });

describe("ServiceIssues", () => {
  it("names the failed dependency of a service that is not ready", () => {
    const out = render([{ ...base, status: "error", statusReason: "db failed" }]);
    expect(out).toContain("api: db failed");
  });

  it("prints nothing when every service is ready or has no reason", () => {
    const out = render([
      { ...base, name: "web", status: "ready" },
      { ...base, name: "idle", status: "unknown" },
    ]);
    expect(out.trim()).toBe("");
  });
});
