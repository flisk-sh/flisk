import { renderToString } from "ink";
import { createElement, type ReactElement } from "react";
import { describe, expect, it } from "vitest";
import { createHelpHint, LoadingScreen } from "../../commands/ui.js";
import type {
  DiscoveredResource,
  DiscoveredStack,
  FileNode,
  ResourceMetadata,
  StackMetadata,
} from "../../types/index.js";
import {
  formatUiKeyHint,
  formatUiKeyNames,
  TABS,
  UI_KEYMAP,
  type UiKeymapId,
} from "../../utils/ui-keymap.js";
import { AccessibleTooltip } from "../Accessible.js";
import { BaseTooltip } from "../BaseTooltip.js";
import { DetailPanel } from "../DetailPanel.js";
import { FileTree } from "../FileTree.js";
import { ResourceTable } from "../ResourceTable.js";
import { TabBar } from "../TabBar.js";
import { TUIHeader } from "../TUIHeader.js";
import { createTUITheme, TUIThemeContext } from "../ui-theme.js";

// ASCII mode is for terminals that cannot draw anything else, so one stray glyph (a check mark, a box line, an info sign)
// breaks the whole frame. This keeps every character of every covered frame in the printable ASCII range.
const asciiTheme = createTUITheme(false, { NO_COLOR: "1" });

const inAsciiMode = (element: ReactElement): string =>
  renderToString(createElement(TUIThemeContext.Provider, { value: asciiTheme }, element), {
    columns: 100,
  });

const nonAscii = (text: string): string[] =>
  [...text].filter((char) => char !== "\n" && (char < " " || char > "~"));

const expectAscii = (text: string): void => {
  expect(nonAscii(text), `non-ASCII characters in:\n${text}`).toEqual([]);
};

const resource = (name: string, status: ResourceMetadata["status"]): ResourceMetadata => ({
  name,
  stack: "shop",
  type: "backend",
  createdAt: "2026-10-06T12:34:56.000Z",
  lastModified: "2026-10-06T12:34:56.000Z",
  dependencies: [],
  hasDockerfile: true,
  hasTiltfile: false,
  hasDockerCompose: false,
  autogeneratedFiles: [],
  status,
});

const service: DiscoveredResource = {
  name: "orders-api",
  path: "services/shop/orders-api",
  configPath: "services/shop/orders-api/service.json",
  stack: "shop",
  port: 4000,
  type: "backend",
};

const stack: DiscoveredStack = {
  name: "shop",
  description: "Shop services",
  resources: [service],
  resourceCount: 1,
};

const stackMetadata: StackMetadata = {
  name: "shop",
  resourceCount: 2,
  createdAt: "2026-10-06T12:34:56.000Z",
  lastModified: "2026-10-06T12:34:56.000Z",
  resources: [resource("orders-api", "ready"), resource("worker", "pending")],
  overallStatus: "healthy",
};

const fileNodes: FileNode[] = [
  {
    name: "autogenerated",
    path: "autogenerated",
    type: "directory",
    children: (["docker", "tilt", "config", "prisma", "generated", "unknown"] as const).map(
      (fileType) => ({
        name: `${fileType}-file`,
        path: `autogenerated/${fileType}-file`,
        type: "file" as const,
        fileType,
      }),
    ),
  },
  { name: "empty", path: "empty", type: "directory", children: [] },
];

describe("ASCII mode only draws printable ASCII", () => {
  it("renders the test helper's own check correctly", () => {
    expect(nonAscii("plain text\n[i] ok")).toEqual([]);
    expect(nonAscii("ℹ ✓ │")).toEqual(["ℹ", "✓", "│"]);
  });

  it("covers the loading screen and the header", () => {
    expectAscii(inAsciiMode(createElement(LoadingScreen, { animated: false })));
    expectAscii(
      inAsciiMode(
        createElement(TUIHeader, {
          projectRoot: "example",
          resourceCount: 2,
          terminalWidth: 80,
          version: "1.0.0",
        }),
      ),
    );
  });

  it.each(TABS.map((tab) => tab.id))("covers the tab bar with %s active", (activeTab) => {
    expectAscii(
      inAsciiMode(createElement(TabBar, { activeTab, onTabChange: () => {}, terminalWidth: 100 })),
    );
  });

  it("covers the resource table", () => {
    expectAscii(
      inAsciiMode(
        createElement(ResourceTable, {
          resources: [
            resource("orders-api", "ready"),
            resource("worker", "pending"),
            resource("broken", "error"),
          ],
          maxWidth: 100,
        }),
      ),
    );
  });

  it.each([
    ["a service", { stack: null, service }],
    ["a stack", { stack, service: null, stackMetadata }],
  ])("covers the detail panel for %s", (_name, props) => {
    expectAscii(inAsciiMode(createElement(DetailPanel, { ...props, visible: true })));
  });

  it("covers the file tree with every file type, an open and a closed folder", () => {
    expectAscii(
      inAsciiMode(
        createElement(FileTree, {
          nodes: fileNodes,
          selectedPath: "autogenerated/docker-file",
          onSelect: () => {},
        }),
      ),
    );
  });

  it("covers the tooltip with and without a shortcut", () => {
    expectAscii(
      inAsciiMode(
        createElement(BaseTooltip, { content: "Tip text", visible: true, prefix: "[i] " }),
      ),
    );
    expectAscii(
      inAsciiMode(
        createElement(BaseTooltip, { content: "Tip text", shortcut: "r", visible: true }),
      ),
    );
  });

  it("covers the accessible tooltip, which swaps its info sign for [i]", () => {
    expectAscii(
      inAsciiMode(createElement(AccessibleTooltip, { content: "Tip text", visible: true })),
    );
  });

  describe("footer and key hints", () => {
    const tabs = TABS.map((tab) => tab.id);

    it.each(tabs)("composes an ASCII-only footer for the %s tab", (tab) => {
      for (const selectedStack of [null, "shop"]) {
        for (const selectedService of [null, "orders-api"]) {
          for (const showEnabledOnly of [false, true]) {
            expectAscii(createHelpHint(tab, selectedStack, selectedService, showEnabledOnly, true));
          }
        }
      }
    });

    it("keeps the Unicode footer Unicode, so the ASCII check above can fail", () => {
      expect(nonAscii(createHelpHint("overview", null, null, false, false))).not.toEqual([]);
    });

    it.each(UI_KEYMAP.map((entry) => [entry.id]))("writes %s in ASCII", (id) => {
      expectAscii(formatUiKeyNames(id as UiKeymapId, true));
      expectAscii(formatUiKeyHint(id as UiKeymapId, undefined, true));
    });
  });
});
