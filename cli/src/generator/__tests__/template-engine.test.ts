function writeProjectJson(projectRoot: string, config: unknown): void {
  fs.mkdirSync(path.join(projectRoot, ".tdk"), { recursive: true });
  fs.writeFileSync(path.join(projectRoot, ".tdk", "project.json"), JSON.stringify(config));
}

