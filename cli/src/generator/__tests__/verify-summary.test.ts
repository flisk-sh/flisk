import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { createTempProject } from "../../test-support/index.js";
import { VERIFY_DIFF_LINE_LIMIT, verifyMasterConfigs } from "../template-engine.js";

const projectJson = {
  version: "1.0",
  project: { name: "verify-summary", version: "1.0.0" },
  phases: Object.fromEntries(
    ["pre_alpha", "alpha", "beta", "out_of_scope"].map((phase) => [
      phase,
      { name: phase, description: "", enabledStacks: [] },
    ]),
  ),
  optional_infra: {
    monitoring: false,
    elk: false,
    debezium: false,
    golden_image: false,
    verdaccio: false,
  },
  discovery: { paths: ["services/*/*"] },
};

/** A generated project with five missing master files and one edited master file (#4205). */
const driftedProject = () =>
  createTempProject({ projectJson, generated: { "spec.master": "# old\n" } });

const EXPECTED_FILES = [
  ".flisk/.flisk-out/TILT_TECH_STACK.star",
  ".flisk/.flisk-out/TILT_RESOURCE_DEFAULTS.star",
  ".flisk/.flisk-out/spec.master",
  ".flisk/.flisk-out/Tiltfile",
  ".flisk/.flisk-out/.tiltignore",
  ".tiltignore",
];

describe("config verify summary before diffs (#4205)", () => {
  it("names every drifted file with its state and line counts, without any file bodies", () => {
    const result = verifyMasterConfigs(driftedProject());

    expect(result.state).toBe("generated");
    expect(result.valid).toBe(false);
    expect(result.diffs.map((entry) => entry.file).sort()).toEqual([...EXPECTED_FILES].sort());
    expect(result.errors.filter((error) => error.startsWith("Missing file:"))).toHaveLength(5);
    for (const entry of result.diffs) {
      expect(entry.state).toBe(entry.file.endsWith("spec.master") ? "different" : "missing");
      expect(entry.linesAdded).toBeGreaterThan(0);
      expect(entry.linesRemoved).toBe(entry.state === "missing" ? 0 : 1);
      expect(entry.diff).toBeUndefined();
      expect(entry.truncated).toBeUndefined();
    }
    // Every error line stays in the report even though the diffs are summaries.
    expect(result.errors.join("\n")).toContain("Missing file: .flisk/.flisk-out/Tiltfile");
    expect(result.errors.join("\n")).toContain("Out of sync: .flisk/.flisk-out/spec.master");
    expect(result.diffLineLimit).toBe(VERIFY_DIFF_LINE_LIMIT);
  });

  it("returns a diff only for the named file", () => {
    const result = verifyMasterConfigs(driftedProject(), {
      diffFiles: [".flisk/.flisk-out/.tiltignore"],
    });
    const withDiff = result.diffs.filter((entry) => entry.diff !== undefined);

    expect(withDiff.map((entry) => entry.file)).toEqual([".flisk/.flisk-out/.tiltignore"]);
    expect(withDiff[0]?.diff).toContain("--- a/.flisk/.flisk-out/.tiltignore");
    expect(withDiff[0]?.diff).toContain(`@@ -1,0 +1,${withDiff[0]?.linesAdded} @@`);
    expect(result.diffs).toHaveLength(EXPECTED_FILES.length);
  });

  it("accepts a bare file name and caps a long diff with a truncation note", () => {
    const root = driftedProject();
    fs.writeFileSync(
      path.join(root, ".tiltignore"),
      [
        "# SYSTEM-GENERATED BY Flisk CLI - DO NOT EDIT",
        ...Array.from({ length: 300 }, (_, i) => `line-${i}`),
        "",
      ].join("\n"),
    );

    const result = verifyMasterConfigs(root, { diffFiles: [".tiltignore"] });
    const entry = result.diffs.find((item) => item.file === ".tiltignore");

    // A bare name matches every reported file with that name (root and generated .tiltignore).
    expect(result.diffs.filter((item) => item.diff !== undefined)).toHaveLength(2);
    expect(entry?.state).toBe("different");
    expect(entry?.linesRemoved).toBe(301);
    expect(entry?.truncated).toBe(true);
    expect(entry?.diff).toContain(`truncated after ${VERIFY_DIFF_LINE_LIMIT} diff lines`);
    expect(entry?.diff?.split("\n").length).toBeLessThanOrEqual(VERIFY_DIFF_LINE_LIMIT + 4);
  });

  it("warns when a requested diff file is not part of the report", () => {
    const result = verifyMasterConfigs(driftedProject(), { diffFiles: ["nope.txt"] });
    expect(result.warnings).toContain(
      "Diff requested for nope.txt, but that file is not reported as drifted",
    );
  });
});
