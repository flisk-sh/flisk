/**
 * Type guard to validate if an unknown value is a valid ProjectConfig.
 *
 * NOTE: The `as` assertions below are INTENTIONAL and SAFE:
 * - We've already verified `typeof value === 'object'` and `value !== null`
 * - TypeScript doesn't automatically narrow `{}` to `Record<string, unknown>`
 * - Each assertion is immediately followed by property type checks
 * - This pattern is standard for deep object validation in type guards
 */
function hasPhaseShape(value: unknown, fieldName: "enabledStacks" | "services"): boolean {
  if (!value || typeof value !== "object") return false;
  const phases = value as Record<string, unknown>;
  for (const phaseName of ["pre_alpha", "alpha", "beta", "out_of_scope"]) {
    const phase = phases[phaseName];
    if (!phase || typeof phase !== "object") return false;
    if (!Array.isArray((phase as Record<string, unknown>)[fieldName])) return false;
  }
  return true;
}

/** `capabilities` in project.json: an object whose every value is a boolean. */
function isCapabilityMap(value: unknown): boolean {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  return Object.values(value).every((flag) => typeof flag === "boolean");
}

function normalizeProjectConfig(value: unknown): ProjectConfig | null {
  if (!value || typeof value !== "object") {
    return null;
  }

  // Safe to assert as Record after null and object type checks
  const config = value as Record<string, unknown>;

  if (typeof config.version !== "string") {
    return null;
  }

  if (!config.project || typeof config.project !== "object") {
    return null;
  }
  const project = config.project as Record<string, unknown>;
  if (typeof project.name !== "string" || typeof project.version !== "string") {
    return null;
  }

  let phases: ProjectConfig["phases"] | null = null;
  if (hasPhaseShape(config.phases, "enabledStacks")) {
    phases = config.phases as ProjectConfig["phases"];
  } else if (hasPhaseShape(config.stacks, "services")) {
    const legacyStacks = config.stacks as NonNullable<ProjectConfig["stacks"]>;
    phases = {
      pre_alpha: {
        name: legacyStacks.pre_alpha.name,
        description: legacyStacks.pre_alpha.description,
        enabledStacks: legacyStacks.pre_alpha.services,
      },
      alpha: {
        name: legacyStacks.alpha.name,
        description: legacyStacks.alpha.description,
        enabledStacks: legacyStacks.alpha.services,
      },
      beta: {
        name: legacyStacks.beta.name,
        description: legacyStacks.beta.description,
        enabledStacks: legacyStacks.beta.services,
      },
      out_of_scope: {
        name: legacyStacks.out_of_scope.name,
        description: legacyStacks.out_of_scope.description,
        enabledStacks: legacyStacks.out_of_scope.services,
      },
    };
  }

  if (!phases) {
    return null;
  }

  if (!config.optional_infra || typeof config.optional_infra !== "object") {
    return null;
  }
  const optionalInfra = config.optional_infra as Record<string, unknown>;
  if (
    typeof optionalInfra.monitoring !== "boolean" ||
    typeof optionalInfra.elk !== "boolean" ||
    typeof optionalInfra.debezium !== "boolean" ||
    typeof optionalInfra.golden_image !== "boolean" ||
    typeof optionalInfra.verdaccio !== "boolean"
  ) {
    return null;
  }

  if (!config.discovery || typeof config.discovery !== "object") {
    return null;
  }
  const discovery = config.discovery as Record<string, unknown>;
  if (!Array.isArray(discovery.paths)) {
    return null;
  }

  // A capability is a boolean: `"gateway": "false"` would not match `=== false` and leave Traefik on, so refuse the file.
  if (config.capabilities !== undefined && !isCapabilityMap(config.capabilities)) {
    return null;
  }
  let repos: RepoConfig[] | undefined;
  if (config.repos !== undefined) {
    if (!Array.isArray(config.repos)) {
      return null;
    }
    repos = [];
    for (const item of config.repos) {
      if (
        !item ||
        typeof item !== "object" ||
        typeof item.url !== "string" ||
        typeof item.dir !== "string" ||
        !item.url.trim() ||
        !item.dir.trim() ||
        (item.branch !== undefined && typeof item.branch !== "string")
      ) {
        return null;
      }
      repos.push({
        url: item.url.trim(),
        dir: item.dir.trim(),
        ...(typeof item.branch === "string" && item.branch.trim()
          ? { branch: item.branch.trim() }
          : {}),
      });
    }
  }

  const capabilities = config.capabilities as ProjectConfig["capabilities"];

  return {
    version: config.version,
    project: config.project as ProjectConfig["project"],
    phases,
    always_enabled_infra: config.always_enabled_infra as string[] | undefined,
    optional_infra: config.optional_infra as ProjectConfig["optional_infra"],
    discovery: config.discovery as ProjectConfig["discovery"],
    overrides: config.overrides as ProjectConfig["overrides"],
    orchestration: config.orchestration as ProjectConfig["orchestration"],
    ...(capabilities ? { capabilities } : {}),
    ...(repos ? { repos } : {}),
  };
}

/** The project has no .flisk/project.json yet, as opposed to one that exists but is unreadable or invalid. */
export class ProjectConfigNotFoundError extends FliskError {}

/**
 * Reads, parses, and normalizes `.flisk/project.json` from the given project root.
 *
 * The file is read directly instead of being existence-checked first: `fs.existsSync` swallows
 * filesystem errors and reports an inaccessible config as missing, which hides the real reason.
 * Only a missing file (`ENOENT`) means "not found"; every other read failure keeps its reason.
 *
 * @param projectRoot - Root directory of the Flisk project.
 * @returns The validated and normalized {@link ProjectConfig}.
 */
export function readProjectConfig(projectRoot: string): ProjectConfig {
  const projectJsonPath = path.join(projectRoot, ".flisk", PROJECT_JSON);

  // A project.json that exists but cannot be read, parsed or validated stays a plain Error: `flisk config verify --json`
  // documents it as a structured INTERNAL error with exit code 2 (docs/reference/machine-readable-cli.md).
  let jsonContent: string;
  try {
    jsonContent = fs.readFileSync(projectJsonPath, "utf-8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException | undefined)?.code === "ENOENT") {
      throw new ProjectConfigNotFoundError(
        `Project config not found: ${projectJsonPath}. Run 'flisk project --yes' first.`,
        ["flisk project --yes"],
      );
    }
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(`Could not read project.json at ${projectJsonPath}: ${reason}`);
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(jsonContent);
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(`Could not parse project.json at ${projectJsonPath}: ${reason}`);
  }

  const projectConfig = normalizeProjectConfig(parsed);
  if (!projectConfig) {
    throw new Error(
      "Invalid project.json: missing or invalid required fields. " +
        "Expected: version (string), project (object with name/version), " +
        "phases (object with pre_alpha/alpha/beta/out_of_scope enabledStacks), " +
        "optional_infra (object with boolean flags), " +
        "discovery (object with paths array), " +
        "capabilities (optional object of booleans), " +
        "repos (optional array of { url, dir, branch? } with non-empty url and dir)",
    );
  }

  return projectConfig;
}

// Sablier ("sablier: {enable: true}" on a resource's own service.json) is
// Premium, but unlike Verdaccio below, this is NOT the enforcement - it's a
// friendly heads-up. The real gate is that engine/.../sablier_container_cycle.star
// in this (public) repo is a free-tier stub that always returns disabled; the
// working implementation only exists in the private flisk-cli-extensions/premium/
// bundle, applied by vendorFliskExtension()'s applyPremiumOverlay() below when a
// license grants it. Forking this repo and deleting a license check (as you
// could with Verdaccio/DDD) gets you nothing here, because there's no check to
// delete - the actual code simply isn't present without the overlay. This just
// tells a confused free-tier user why their `sablier` block silently does
// nothing, instead of leaving them to guess.
async function warnIfSablierUnlicensed(projectRoot: string): Promise<void> {
  const resources = discoverResourcesFromRoot(projectRoot).filter(
    (r) => r.config?.sablier?.enable === true,
  );
  if (resources.length === 0) return;

  const granted = await hasSablierLicense(projectRoot);
  if (granted) return;

  console.warn(
    `⚠️  Sablier (on-demand scaling) is a Premium feature - no valid license key found. ` +
      `${resources.length} resource${resources.length === 1 ? " has" : "s have"} a \`sablier\` block, ` +
      "but it will have no effect without a license. Set FLISK_LICENSE_KEY to a key that grants it, " +
      "or remove the `sablier` block from the affected service.json file(s) to silence this warning.",
  );
}

function ensureRootWorkspaceManifest(projectRoot: string, projectConfig: ProjectConfig): boolean {
  const packageJsonPath = assertFliskGeneratedPath(projectRoot, PACKAGE_JSON);
  if (fs.existsSync(packageJsonPath)) {
    return false;
  }

  const manifest = {
    name: projectConfig.project.name || path.basename(projectRoot),
    version: projectConfig.project.version || "1.0.0",
    private: true,
    type: "module",
    workspaces: projectConfig.discovery.paths,
  };

  writeTextFile(packageJsonPath, `${JSON.stringify(manifest, null, 2)}\n`);
  return true;
}

export interface GenerateMasterConfigsOptions {
  /**
   * Overwrite a root .tiltignore that carries Flisk's generated header but was edited by hand.
   * Set by `flisk config regenerate`, the explicit "discard hand edits" command. A root
   * .tiltignore without the header belongs to the team and is never overwritten.
   */
  discardHandEdits?: boolean;
  /** Suppress progress lines on stdout, for callers that print machine output (`flisk up --json`). */
  quiet?: boolean;
  /** In-memory overrides for project configuration during generation. */
  configOverrides?: Partial<ProjectConfig>;
}

export async function generateMasterConfigs(
  projectRoot: string,
  options: GenerateMasterConfigsOptions = {},
): Promise<void> {
  let projectConfig = readProjectConfig(projectRoot);
  if (options.configOverrides) {
    projectConfig = {
      ...projectConfig,
      ...options.configOverrides,
      capabilities: {
        ...projectConfig.capabilities,
        ...options.configOverrides.capabilities,
      },
    };
  }

  // Refuse before writing anything: a service.json value with a line break or YAML syntax would add keys to the generated compose
  // file (GHSA-phgf-pww4-7jxc).
  const unsafeFields = discoverServiceManifestPaths(projectRoot).flatMap((manifestPath) =>
    generatedFieldErrorsForFile(
      manifestPath,
      path.relative(projectRoot, manifestPath).split(path.sep).join("/"),
    ),
  );
  if (unsafeFields.length > 0) {
    throw new FliskError(
      `Refusing to generate config from unsafe service.json values:\n${unsafeFields.map((error) => `  ${error}`).join("\n")}`,
      [
        "Remove the quotes, newlines or control characters from those values",
        "Check every service.json with: flisk config verify",
      ],
    );
  }

  await warnIfSablierUnlicensed(projectRoot);

  if (ensureRootWorkspaceManifest(projectRoot, projectConfig) && !options.quiet) {
    console.log("✓ Generated: package.json (workspace root)");
  }

  // Verdaccio is Premium, but unlike the old posture here, this is NOT the
  // enforcement - it's a friendly heads-up. The real gate is that
  // engine/topologies/platform/registries/verdaccio_loader.star in this
  // (public) repo is a free-tier stub that always skips; the working loader
  // only exists in the private flisk-cli-extensions/premium/ bundle, applied
  // by vendorFliskExtension()'s applyPremiumOverlay() below when a license
  // grants it. Forking this repo and deleting a license check gets you
  // nothing, because there's no check left to delete - the actual code
  // simply isn't present without the overlay. This just tells a confused
  // free-tier user why enabling Verdaccio silently did nothing, instead of
  // leaving them to guess.
  const verdaccioInPhase = Object.values(projectConfig.phases).some((phase) =>
    phase.enabledStacks.includes("verdaccio"),
  );
  if (projectConfig.optional_infra.verdaccio || verdaccioInPhase) {
    const granted = await hasVerdaccioLicense(projectRoot);
    if (!granted) {
      console.warn(
        "⚠️  Verdaccio is a Premium feature - no valid license key found. It's enabled in " +
          "this project's config, but will have no effect without a license. Set FLISK_LICENSE_KEY " +
          "to a key that grants it, or run `flisk config disable-infra verdaccio` to silence this warning.",
      );
    }
  }

  const outputDir = path.join(projectRoot, ".flisk", ".flisk-out");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const engine = new TemplateEngine();
  const files = engine.generateAll(projectConfig, { projectRoot });

  for (const filename of ALL_GENERATED_FILES) {
    const content = files[filename];
    const filePath = assertFliskGeneratedPath(
      projectRoot,
      path.join(".flisk", ".flisk-out", filename),
    );
    writeTextFileAtomic(filePath, content);
    if (!options.quiet) console.log(`✓ Generated: .flisk/.flisk-out/${filename}`);
  }

  if (
    isDatabaseCapabilityEnabled(projectConfig) &&
    isStackFeatureEnabledInStacks(projectConfig.phases, DATABASE_MANAGEMENT_FEATURE)
  ) {
    const composePath = assertFliskGeneratedPath(
      projectRoot,
      path.join("services", "platform", DATABASE_MANAGEMENT_FEATURE, DOCKER_COMPOSE_FILE),
    );
    const composeDir = path.dirname(composePath);
    fs.mkdirSync(composeDir, { recursive: true });
    writeTextFileAtomic(composePath, generateDatabaseManagementCompose(projectConfig));
    if (!options.quiet) {
      console.log("✓ Generated: services/platform/database-management/docker-compose.yml");
    }
  }

  // Copy .tiltignore to project root so Tilt uses it
  const tiltignoreSource = path.join(outputDir, TILTIGNORE_FILE);
  const tiltignoreTarget = assertFliskGeneratedPath(projectRoot, TILTIGNORE_FILE);
  if (fs.existsSync(tiltignoreSource)) {
    if (!fs.existsSync(tiltignoreTarget)) {
      fs.copyFileSync(tiltignoreSource, tiltignoreTarget);
      if (!options.quiet) console.log(`✓ Copied: .tiltignore → project root`);
    } else if (options.discardHandEdits) {
      // Only a file Flisk wrote (it carries the header) may be restored; one without the
      // header is the team's own and `verifyMasterConfigs` reports it as a warning.
      const current = fs.readFileSync(tiltignoreTarget, "utf-8");
      if (
        current.includes(FLISK_GENERATED_MARKER) &&
        current !== fs.readFileSync(tiltignoreSource, "utf-8")
      ) {
        fs.copyFileSync(tiltignoreSource, tiltignoreTarget);
        if (!options.quiet) {
          console.log("✓ Restored: .tiltignore → project root (hand edits discarded)");
        }
      }
    }
  }

  const copiedAssets = ensureProjectRuntimeAssets(projectRoot);
  if (!options.quiet) {
    for (const asset of copiedAssets) {
      console.log(`✓ Copied: ${asset} → project root`);
    }
  }

  await vendorFliskExtension(projectRoot, { quiet: options.quiet });

  if (!options.quiet) {
    console.log("");
    console.log("💡 To start Tilt: flisk up");
  }
}

// The generated Tiltfile loads the Flisk Tilt extension (engine, discovery,
// specs, ext starlark modules). The extension repo may stay private, so we
// vendor a working copy into .flisk/.flisk-out/flisk-cli-ext/ at generation time.
// This makes `flisk up` work offline and on any machine - no hardcoded paths,
// no dependency on a private GitHub repo.
// The engine's own unit tests (for example wake-gateway/decide.test.ts, which imports bun:test) are
// not needed to run a stack. Vendoring them under .flisk/.flisk-out makes a Node project's test runner
// (Vitest, Jest) discover them and fail, so they are left out of the vendored copy.
const TEST_FILE_PATTERN = /\.(?:test|spec)\.[cm]?[jt]sx?$/;

export function isTestFile(filePath: string): boolean {
  return TEST_FILE_PATTERN.test(filePath);
}

function removeVendoredTestFiles(dir: string): void {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      removeVendoredTestFiles(entryPath);
    } else if (isTestFile(entryPath)) {
      fs.rmSync(entryPath, { force: true });
    }
  }
}

const FLISK_EXTENSION_DIRS: readonly string[] = EXTENSION_DIRS;
const PROJECT_RUNTIME_ASSET_DIRS = [["shared-platform-engineering", "docker-templates"]] as const;
const REQUIRED_DOCKER_TEMPLATE_FILES = [
  "install-deps.sh",
  "bun-hoisted-symlink-fix.sh",
  "prisma-bun-client-link-fix.sh",
  "prisma-normalize-client.sh",
] as const;

// Walk up from this module's own location looking for a directory that has
// both Tiltfile and engine/ next to it - true when cli/ and engine/ ship
// together in the same repo (the public flisk layout, where a plain
// `git clone` + `bun run` needs zero extra config to find the engine).
function findSelfContainedEngineRoot(): string | null {
  let dir = import.meta.dirname || process.cwd();
  for (let i = 0; i < 6; i++) {
    if (hasExtensionLayout(dir)) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

function hasDockerTemplates(sourceRoot: string): boolean {
  return fs.existsSync(path.join(resolveSharedPlatformDir(sourceRoot), "docker-templates"));
}

export function findCliAssetRoot(): string | null {
  let dir = import.meta.dirname || process.cwd();
  for (let i = 0; i < 8; i++) {
    if (hasDockerTemplates(dir)) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }

  const exeDir = path.dirname(process.execPath);
  const candidates = [
    path.join(exeDir, "flisk-cli"),
    path.join(process.cwd(), "node_modules", "@flisk-sh", "flisk"),
  ];

  return candidates.find(hasDockerTemplates) ?? null;
}

export function ensureProjectRuntimeAssets(projectRoot: string): string[] {
  const sourceRoot = findCliAssetRoot();
  const copied: string[] = [];

  if (!sourceRoot) {
    console.warn(
      "⚠️  Flisk runtime assets not found - generated Dockerfiles may fail. " +
        "Reinstall or upgrade Flisk, then re-run `flisk project`.",
    );
    return copied;
  }

  for (const parts of PROJECT_RUNTIME_ASSET_DIRS) {
    const source = path.join(resolveSharedPlatformDir(sourceRoot), ...parts.slice(1));
    const target = assertFliskGeneratedPath(projectRoot, path.join(...parts));
    if (!fs.existsSync(source)) {
      continue;
    }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.cpSync(source, target, { recursive: true });
    copied.push(parts.join("/"));
  }

  for (const file of REQUIRED_DOCKER_TEMPLATE_FILES) {
    const filePath = path.join(
      projectRoot,
      "shared-platform-engineering",
      "docker-templates",
      file,
    );
    if (!fs.existsSync(filePath)) {
      console.warn(`⚠️  Missing runtime asset after copy: ${filePath}`);
    }
  }

  return copied;
}

function defaultTemplatesDir(): string {
  const currentDir = import.meta.dirname || path.dirname(new URL(import.meta.url).pathname);
  return path.join(currentDir, "..", "..", "templates");
}

/**
 * Where `flisk up` and `flisk config regenerate` copy the Flisk extension from, in order; the first with the extension layout
 * wins.
 */
function extensionSourceCandidates(projectRoot: string): string[] {
  // Source resolution order:
  //   1. $FLISK_EXTENSION_SOURCE (explicit override)
  //   2. Self-contained repo (engine/ ships next to cli/ - public flisk)
  //   3. Executable-adjacent checkout (bundled installs)
  //   4. Relative ../flisk-cli sibling (monorepo maintainer layout)
  const sources: string[] = [];
  if (process.env.FLISK_EXTENSION_SOURCE) {
    sources.push(process.env.FLISK_EXTENSION_SOURCE);
  }
  const selfContainedRoot = findSelfContainedEngineRoot();
  if (selfContainedRoot) {
    sources.push(selfContainedRoot);
  }
  // process.execPath is the compiled binary's own path when running as a
  // standalone executable (what we actually need here). In dev mode it's
  // the bun CLI's own path instead (e.g. ~/.bun/bin/bun) - harmless, that
  // candidate just won't match anything and falls through to the next
  // one. Note: process.executablePath is not a real property on Node or
  // Bun's process object - it was always undefined, silently falling
  // back to cwd() instead of the binary's real location.
  const exeDir = path.dirname(process.execPath);
  sources.push(path.join(exeDir, "flisk-cli"));
  sources.push(path.join(projectRoot, "..", "flisk-cli"));
  return sources;
}

/**
 * The vendored engine records what it was copied from, so `flisk up` can tell that the installed CLI now ships a different
 * engine or different templates (an upgrade, or a checkout on another commit) and regenerate .flisk/.flisk-out/ (#2899).
 */
const ENGINE_FINGERPRINT_FILE = ".source-fingerprint";

function hashTree(hash: ReturnType<typeof createHash>, root: string, dir: string): void {
  if (!fs.existsSync(dir)) return;
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      hashTree(hash, root, entryPath);
    } else if (entry.isFile() && !isTestFile(entryPath)) {
      hash.update(path.relative(root, entryPath).split(path.sep).join("/"));
      hash.update("\0");
      hash.update(fs.readFileSync(entryPath));
      hash.update("\0");
    }
  }
}

/** Hash of the CLI version, the templates, and the extension files vendoring copies from `sourceRoot`. */
export function engineSourceFingerprint(
  sourceRoot: string,
  templatesDir = defaultTemplatesDir(),
): string {
  const hash = createHash("sha256");
  hash.update(`flisk ${getPackageVersion()}\0`);
  hash.update(fs.readFileSync(resolveTiltfile(sourceRoot)));
  for (const dir of FLISK_EXTENSION_DIRS) {
    hashTree(hash, sourceRoot, resolveExtensionDir(sourceRoot, dir));
  }
  hashTree(hash, templatesDir, templatesDir);
  return hash.digest("hex");
}

/**
 * True when .flisk/.flisk-out/ was generated from another engine or other templates than this CLI ships: the vendored copy's
 * fingerprint differs, or it has none (vendored by a Flisk from before the fingerprint). False when nothing is vendored yet, or
 * this CLI has no extension to vendor (then regenerating would change nothing).
 */
export function isVendoredEngineStale(projectRoot: string): boolean {
  const vendoredDir = path.join(projectRoot, ".flisk", ".flisk-out", "flisk-cli-ext");
  if (!fs.existsSync(vendoredDir)) return false;
  const sourceRoot = extensionSourceCandidates(projectRoot).find(
    (candidate) => candidate && hasExtensionLayout(candidate),
  );
  if (!sourceRoot) return false;
  const stampPath = path.join(vendoredDir, ENGINE_FINGERPRINT_FILE);
  const recorded = fs.existsSync(stampPath) ? fs.readFileSync(stampPath, "utf-8").trim() : "";
  return recorded !== engineSourceFingerprint(sourceRoot);
}

async function vendorFliskExtension(
  projectRoot: string,
  options: { quiet?: boolean } = {},
): Promise<void> {
  const vendoredDir = assertFliskGeneratedPath(
    projectRoot,
    path.join(".flisk", ".flisk-out", "flisk-cli-ext"),
  );
  const sources = extensionSourceCandidates(projectRoot);

  // An explicit override that fails the layout check is skipped below; say why instead of silently falling
  // back to a different copy of the extension.
  const override = process.env.FLISK_EXTENSION_SOURCE;
  if (override && fs.existsSync(override) && !hasExtensionLayout(override)) {
    console.warn(
      `⚠️  FLISK_EXTENSION_SOURCE is not a usable Flisk extension and is ignored:\n   ${describeLayoutProblems(override)}`,
    );
  }

  let sourceRoot = "";
  for (const candidate of sources) {
    if (candidate && hasExtensionLayout(candidate)) {
      sourceRoot = candidate;
      break;
    }
  }

  if (!sourceRoot) {
    // A candidate that has some extension entries but fails the layout check is a stale or half-migrated tree.
    const broken = sources
      .filter((candidate) => candidate && fs.existsSync(candidate))
      .map((candidate) => ({ candidate, report: inspectExtensionLayout(candidate) }))
      .filter(({ report }) => report.kind === "mixed" || report.missing.length < 5);
    console.warn(
      "⚠️  Flisk extension not found - set FLISK_EXTENSION_SOURCE to its checkout path " +
        "and re-run `flisk project` (or `flisk config regenerate`) to vendor it before `flisk up`." +
        broken
          .map(({ candidate, report }) => `\n   ${describeLayoutProblems(candidate, report)}`)
          .join(""),
    );
    return;
  }

  if (!fs.existsSync(vendoredDir)) {
    fs.mkdirSync(vendoredDir, { recursive: true });
  }
  fs.copyFileSync(resolveTiltfile(sourceRoot), path.join(vendoredDir, "Tiltfile"));
  for (const dir of FLISK_EXTENSION_DIRS) {
    // A project vendored by an older Flisk already holds test files; cpSync only adds, so drop them.
    removeVendoredTestFiles(path.join(vendoredDir, dir));
    fs.cpSync(resolveExtensionDir(sourceRoot, dir), path.join(vendoredDir, dir), {
      recursive: true,
      filter: (source) => !isTestFile(source),
    });
  }
  writeTextFileAtomic(
    path.join(vendoredDir, ENGINE_FINGERPRINT_FILE),
    `${engineSourceFingerprint(sourceRoot)}\n`,
  );
  if (!options.quiet) console.log(`✓ Vendored Flisk extension → .flisk/.flisk-out/flisk-cli-ext/`);

  // Best-effort: if FLISK_LICENSE_KEY is set and grants any paid resource,
  // overlay the premium bundle over the stub files just vendored above.
  // No-ops silently (beyond a warning) if there's no key, the fetch
  // fails, or nothing's granted - the free engine already works fine on
  // its own.
  try {
    const { applyPremiumOverlay } = await import("./extension-fetch.js");
    await applyPremiumOverlay(projectRoot, vendoredDir);
  } catch (err) {
    console.warn(`⚠️  Premium overlay skipped: ${(err as Error).message}`);
  }
}

export const FLISK_GENERATED_MARKER = "SYSTEM-GENERATED BY Flisk CLI";

export function verifyMasterConfigs(
  projectRoot: string,
  options?: { manifestPaths?: string[]; skipManifestValidation?: boolean },
): {
  valid: boolean;
  errors: string[];
  warnings: string[];
  diffs: Array<{ file: string; diff: string }>;
  /** Generated service files (project-relative) whose content differs from their Flisk snapshot, i.e. edited by hand. */
  handEdited: string[];
} {
  const errors: string[] = [];
  const warnings: string[] = [];
  const diffs: Array<{ file: string; diff: string }> = [];
  const handEdited: string[] = [];

  const addDrift = (displayPath: string, actual: string | undefined, expected: string) => {
    if (actual === expected) return;
    errors.push(
      `${actual === undefined ? "Missing file" : "Out of sync"}: ${displayPath} (run 'flisk config regenerate')`,
    );
    diffs.push({
      file: displayPath,
      diff: createUnifiedDiff(displayPath, actual ?? "", expected),
    });
  };

  const projectConfig = readProjectConfig(projectRoot);
  const engine = new TemplateEngine();
  const expectedFiles = engine.generateAll(projectConfig, { projectRoot });

  const outputDir = path.join(projectRoot, ".flisk", ".flisk-out");

  for (const filename of ALL_GENERATED_FILES) {
    const expectedContent = expectedFiles[filename];
    const filePath = path.join(outputDir, filename);

    addDrift(
      `.flisk/.flisk-out/${filename}`,
      fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf-8") : undefined,
      expectedContent,
    );
  }

  // `flisk project` never overwrites a root .tiltignore the repo already has, so one
  // without Flisk's header belongs to the team: it is not drift.
  const rootTiltIgnore = path.join(projectRoot, TILTIGNORE_FILE);
  const rootTiltIgnoreText = fs.existsSync(rootTiltIgnore)
    ? fs.readFileSync(rootTiltIgnore, "utf-8")
    : undefined;
  if (rootTiltIgnoreText !== undefined && !rootTiltIgnoreText.includes(FLISK_GENERATED_MARKER)) {
    warnings.push(".tiltignore: not generated by Flisk, left as is");
  } else {
    addDrift(TILTIGNORE_FILE, rootTiltIgnoreText, expectedFiles[TILTIGNORE_FILE]);
  }

  const manifestPaths = options?.manifestPaths ?? discoverServiceManifestPaths(projectRoot);
  for (const manifestPath of manifestPaths) {
    const displayPath = path.relative(projectRoot, manifestPath).split(path.sep).join("/");
    if (!options?.skipManifestValidation) {
      const validation = validateServiceManifestFile(manifestPath, displayPath);
      errors.push(...validation.errors);
      warnings.push(...validation.warnings);
    }
    const generated = verifyGeneratedResourceFiles(projectRoot, manifestPath);
    errors.push(...generated.errors);
    handEdited.push(...generated.handEdited);
  }

  return { valid: errors.length === 0, errors, warnings, diffs, handEdited };
}

function createUnifiedDiff(file: string, actual: string, expected: string): string {
  const oldLines = actual.replace(/\n$/, "").split("\n");
  const newLines = expected.replace(/\n$/, "").split("\n");
  const lines = [
    `--- a/${file}`,
    `+++ b/${file}`,
    `@@ -1,${oldLines.length} +1,${newLines.length} @@`,
  ];
  for (const line of oldLines) lines.push(`-${line}`);
  for (const line of newLines) lines.push(`+${line}`);
  return lines.join("\n");
}

// Top-level `.autogenerated/` entries that have no Flisk snapshot: the contract directory itself, and service.yaml, the
// discovery shadow of service.json that the Tilt extension writes for every manifest. A service whose folder holds only
// these (a `database` resource) has no generated outputs to verify.
const UNSNAPSHOTTED_ENTRIES = new Set([".flisk-contract", "service.yaml"]);

/**
 * Services whose generated files (the app compose, the Dockerfile) were written from an older service.json than the one on disk,
 * as project-relative service.json paths. `flisk config regenerate` rewrites only the master files; these are written by
 * `flisk up`, which is also what `flisk config verify` asks for.
 */
export function staleServiceOutputs(projectRoot: string): string[] {
  const stale: string[] = [];
  for (const manifestPath of discoverServiceManifestPaths(projectRoot)) {
    const generatedDir = path.join(path.dirname(manifestPath), AUTOGENERATED_DIR);
    if (!fs.existsSync(generatedDir)) continue;
    const snapshot = path.join(generatedDir, ".flisk-contract", "service.json.source");
    let isStale = false;
    try {
      isStale = fs.readFileSync(snapshot, "utf-8") !== fs.readFileSync(manifestPath, "utf-8");
    } catch {
      // No snapshot: verify reports it the same way, and only when generated files exist.
      isStale = fs.readdirSync(generatedDir).some((entry) => !UNSNAPSHOTTED_ENTRIES.has(entry));
    }
    if (isStale) stale.push(path.relative(projectRoot, manifestPath).split(path.sep).join("/"));
  }
  return stale;
}

function verifyGeneratedResourceFiles(
  projectRoot: string,
  serviceJsonPath: string,
): { errors: string[]; handEdited: string[] } {
  const serviceDir = path.dirname(serviceJsonPath);
  const generatedDir = path.join(serviceDir, AUTOGENERATED_DIR);
  if (!fs.existsSync(generatedDir)) return { errors: [], handEdited: [] };

  const generatedFiles: Array<{ fullPath: string; relativeFile: string }> = [];
  const collect = (directory: string, relativeDir = ""): void => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      if (relativeDir === "" && UNSNAPSHOTTED_ENTRIES.has(entry.name)) continue;
      const relativeFile = path.join(relativeDir, entry.name);
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) collect(fullPath, relativeFile);
      else if (entry.isFile()) generatedFiles.push({ fullPath, relativeFile });
    }
  };
  collect(generatedDir);
  if (generatedFiles.length === 0) return { errors: [], handEdited: [] };

  const contractDir = path.join(generatedDir, ".flisk-contract");
  const sourceSnapshot = path.join(contractDir, "service.json.source");
  const errors: string[] = [];
  const handEdited: string[] = [];
  if (!fs.existsSync(sourceSnapshot)) {
    errors.push(
      path.relative(projectRoot, sourceSnapshot) +
        ": generated-file contract snapshot is missing (run flisk up to regenerate)",
    );
  } else if (
    fs.readFileSync(sourceSnapshot, "utf-8") !== fs.readFileSync(serviceJsonPath, "utf-8")
  ) {
    errors.push(
      path.relative(projectRoot, serviceJsonPath) +
        ": service.json changed since generated outputs were written (run flisk up)",
    );
  }

  for (const generated of generatedFiles) {
    const snapshotPath = path.join(contractDir, generated.relativeFile);
    const display = path.relative(projectRoot, generated.fullPath);
    if (!fs.existsSync(snapshotPath)) {
      errors.push(`${display}: generated-file snapshot is missing (run flisk up to regenerate)`);
    } else if (
      fs.readFileSync(generated.fullPath, "utf-8") !== fs.readFileSync(snapshotPath, "utf-8")
    ) {
      // Windows path.relative uses backslashes; report project-relative paths with forward slashes everywhere.
      handEdited.push(display.split(path.sep).join("/"));
      errors.push(
        `${display}: generated file differs from its Flisk snapshot (run flisk up to regenerate)`,
      );
    }
  }
  return { errors, handEdited };
}
