export class TemplateEngine {
  private templatesDir: string;

  constructor(templatesDir?: string) {
    this.templatesDir = templatesDir || defaultTemplatesDir();
  }

  // Backslashes must be escaped before quotes, or a value ending in a backslash escapes the closing quote.
  private quoteStarlarkString(s: string): string {
    return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }

  private formatStarlarkValue(val: JsonValue): string {
    if (val === null || val === undefined) {
      return "None";
    }
    if (typeof val === "string") {
      return this.quoteStarlarkString(val);
    }
    if (typeof val === "boolean") {
      return val ? "True" : "False";
    }
    if (typeof val === "number") {
      return String(val);
    }
    if (Array.isArray(val)) {
      const items = val.map((item) => this.formatStarlarkValue(item));
      return `[${items.join(", ")}]`;
    }
    if (typeof val === "object") {
      const entries = Object.entries(val).map(([key, v]) => {
        return `${this.quoteStarlarkString(key)}: ${this.formatStarlarkValue(v)}`;
      });
      return `{${entries.join(", ")}}`;
    }
    return String(val);
  }

  private helpers(): TemplateHelpers {
    return {
      starlark: { raw: true, fn: (value) => this.formatStarlarkValue(value as JsonValue) },
      starlarkArray: {
        raw: true,
        fn: (value) => {
          if (!Array.isArray(value)) return "[]";
          return `[${value.map((item) => this.formatStarlarkValue(item)).join(", ")}]`;
        },
      },
      json: { raw: false, fn: (value) => JSON.stringify(value) },
    };
  }

  buildContext(
    projectConfig: ProjectConfig,
    options: { projectRoot?: string } = {},
  ): GeneratorContext {
    const dbEnabled = isDatabaseCapabilityEnabled(projectConfig);
    const gatewayEnabled = isGatewayEnabled(projectConfig);
    // A capability that is off is dropped from the phases as well as from always_enabled_infra: a phase entry reaches
    // RESOURCE_DEFAULTS in the Tiltfile and would start the container anyway.
    const isProvisioned = (name: string): boolean =>
      (dbEnabled || name !== DATABASE_MANAGEMENT_FEATURE) &&
      (gatewayEnabled || !GATEWAY_RESOURCE_NAMES.includes(name));
    const phases = dedupePhaseEnabledStacks(projectConfig.phases);
    if (!dbEnabled || !gatewayEnabled) {
      for (const key of Object.keys(phases) as (keyof ProjectConfig["phases"])[]) {
        phases[key] = {
          ...phases[key],
          enabledStacks: phases[key].enabledStacks.filter(isProvisioned),
        };
      }
    }
    const alwaysEnabledInfra = (
      projectConfig.always_enabled_infra ?? [...DEFAULT_ALWAYS_ENABLED_INFRA]
    ).filter(isProvisioned);

    return {
      version: PLATFORM_STANDARDS.version,
      tech: PLATFORM_STANDARDS.tech,
      ports: PLATFORM_STANDARDS.ports,
      health: PLATFORM_STANDARDS.health,
      naming: PLATFORM_STANDARDS.naming,
      traefik: PLATFORM_STANDARDS.traefik,
      filewatchIgnores: [...PLATFORM_STANDARDS.filewatchIgnores],
      serviceTypes: PLATFORM_STANDARDS.serviceTypes,
      paths: PLATFORM_STANDARDS.paths,
      discovery: {
        scanIntervalSeconds: PLATFORM_STANDARDS.discovery.scanIntervalSeconds,
        maxManifestsPerRoot: PLATFORM_STANDARDS.discovery.maxManifestsPerRoot,
        paths: projectConfig.discovery.paths,
      },
      docker: PLATFORM_STANDARDS.docker,
      runtime: PLATFORM_STANDARDS.runtime,
      project: projectConfig.project,
      phases,
      alwaysEnabledInfra,
      optionalInfra: projectConfig.optional_infra,
      serviceDescriptions: RESOURCE_DESCRIPTIONS,
      infraDescriptions: INFRA_DESCRIPTIONS,
      orchestration: projectConfig.orchestration,
      ...(options.projectRoot ? { projectRoot: options.projectRoot } : {}),
    };
  }

  private loadTemplate(templateName: string): (context: unknown) => string {
    const templatePath = path.join(this.templatesDir, `${templateName}.hbs`);
    const templateSource = fs.existsSync(templatePath)
      ? fs.readFileSync(templatePath, "utf-8")
      : getEmbeddedTemplates()[templateName];
    if (!templateSource) {
      throw new FliskError(`Template not found: ${templatePath}`, [
        "Reinstall the CLI: npm install -g @flisk-sh/flisk",
        "Check the installed package with: flisk runtime",
      ]);
    }
    return compileTemplate(templateSource, this.helpers());
  }

  generateTechStack(context: GeneratorContext): string {
    const template = this.loadTemplate(TECH_STACK_FILE);
    return template(context);
  }

  generateServiceDefaults(context: GeneratorContext): string {
    const template = this.loadTemplate(RESOURCE_DEFAULTS_FILE);
    return template(context);
  }

  generateSpecMaster(context: GeneratorContext): string {
    const template = this.loadTemplate("spec.master");
    return template(context);
  }

  generateTiltfile(context: GeneratorContext): string {
    const userTiltfile = wrappedTiltfilePath(context.orchestration, context.projectRoot);
    if (userTiltfile) return renderTiltfileWrapper(context.project.name, userTiltfile);
    const template = this.loadTemplate("Tiltfile");
    return template(context);
  }

  generateTiltIgnore(context: GeneratorContext): string {
    const template = this.loadTemplate(".tiltignore");
    return template(context);
  }

  /** `projectRoot` is the project the files are generated for, when there is one on disk. */
  generateAll(
    projectConfig: ProjectConfig,
    options: { projectRoot?: string } = {},
  ): Record<GeneratedFileName, string> {
    const context = this.buildContext(projectConfig, options);

    return {
      "TILT_TECH_STACK.star": this.generateTechStack(context),
      "TILT_RESOURCE_DEFAULTS.star": this.generateServiceDefaults(context),
      "spec.master": this.generateSpecMaster(context),
      Tiltfile: this.generateTiltfile(context),
      // Key must stay the literal: Record<GeneratedFileName, ...> requires it.
      ".tiltignore": this.generateTiltIgnore(context),
    };
  }
}

/** The header line that marks .flisk/.flisk-out/Tiltfile as a wrapper written by renderTiltfileWrapper. */
const TILTFILE_WRAPPER_MARKER = '# Source: .flisk/project.json (orchestration.source = "tiltfile")';

/**
 * The project's own Tiltfile when .flisk/project.json sets `orchestration.source` to "tiltfile" (`flisk import tiltfile`),
 * relative to the project root (or absolute), or null when Flisk generates the whole Tiltfile itself. The path is used as
 * stored (backslashes become slashes), and defaults to `Tiltfile` when it is missing or empty.
 *
 * With `projectRoot`, a path that resolves through a symlink into the project's .flisk/ directory is refused as well. Without
 * it the check is lexical only and reads nothing from disk.
 */
export function wrappedTiltfilePath(
  orchestration: ProjectConfig["orchestration"] | undefined,
  projectRoot?: string,
): string | null {
  if (orchestration?.source !== "tiltfile") return null;
  const raw = typeof orchestration.path === "string" ? orchestration.path : "";
  const tiltfilePath = path.posix.normalize((raw || "Tiltfile").replace(/\\/g, "/"));
  if ([...tiltfilePath].some((char) => char === '"' || char.charCodeAt(0) < 0x20)) {
    throw new FliskError(
      `orchestration.path in .flisk/project.json has a quote or control character: ${JSON.stringify(tiltfilePath)}`,
      ["Rename the Tiltfile, then run: flisk import tiltfile <path> --force"],
    );
  }
  const isInsideFliskDir =
    tiltfilePath === ".flisk" ||
    tiltfilePath.startsWith(".flisk/") ||
    (projectRoot !== undefined && resolvesInsideFliskDir(projectRoot, tiltfilePath));
  if (isInsideFliskDir) {
    throw new FliskError(
      `orchestration.path in .flisk/project.json points inside .flisk/ (${tiltfilePath}), where Flisk writes its generated files`,
      ["Point it at your own Tiltfile: flisk import tiltfile <path> --force"],
    );
  }
  return tiltfilePath;
}

/**
 * The real path of `target`, also when it does not exist yet: existing parts go through realpath, and a dangling symlink is
 * followed to where it points, so a link to a file Flisk has not generated yet still resolves to that file.
 */
function realPathOfExistingPart(target: string, linkHops = 0): string {
  const resolved = path.resolve(target);
  if (fs.existsSync(resolved)) return fs.realpathSync(resolved);
  const parent = path.dirname(resolved);
  if (parent === resolved) return resolved;
  const realParent = realPathOfExistingPart(parent, linkHops);
  const candidate = path.join(realParent, path.basename(resolved));
  let linkTarget: string | undefined;
  try {
    if (fs.lstatSync(candidate).isSymbolicLink()) linkTarget = fs.readlinkSync(candidate);
  } catch {
    linkTarget = undefined;
  }
  if (linkTarget === undefined || linkHops >= 40) return candidate;
  return realPathOfExistingPart(path.resolve(realParent, linkTarget), linkHops + 1);
}

/** True when `tiltfilePath`, followed through symlinks, is the project's .flisk/ directory or inside it. */
function resolvesInsideFliskDir(projectRoot: string, tiltfilePath: string): boolean {
  const fliskDir = realPathOfExistingPart(path.join(projectRoot, ".flisk"));
  const target = realPathOfExistingPart(path.resolve(projectRoot, tiltfilePath));
  const relative = path.relative(fliskDir, target);
  const isOutside =
    relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative);
  return !isOutside;
}

/**
 * True when .flisk/project.json makes the project's own Tiltfile its orchestration source (`flisk import tiltfile`), so
 * `flisk up` runs Tilt with the wrapper. False when there is no readable project.json.
 */
export function isTiltfileOrchestration(projectRoot: string): boolean {
  try {
    return readProjectConfig(projectRoot).orchestration?.source === "tiltfile";
  } catch {
    return false;
  }
}

/**
 * True when .flisk/.flisk-out/Tiltfile does not match what project.json selects, so `flisk up` has to regenerate it before
 * starting Tilt: project.json wraps the project's own Tiltfile but the generated one is not that wrapper (missing, or
 * generated before `flisk import tiltfile`), or the generated one is a wrapper but project.json no longer selects one.
 */
export function isWrappedTiltfileStale(projectRoot: string): boolean {
  let projectConfig: ProjectConfig;
  try {
    projectConfig = readProjectConfig(projectRoot);
  } catch {
    return false;
  }
  const userTiltfile = wrappedTiltfilePath(projectConfig.orchestration, projectRoot);
  const generatedPath = path.join(projectRoot, ".flisk", ".flisk-out", "Tiltfile");
  const current = fs.existsSync(generatedPath) ? fs.readFileSync(generatedPath, "utf-8") : "";
  if (!userTiltfile) return current.split(/\r?\n/).includes(TILTFILE_WRAPPER_MARKER);
  return current !== renderTiltfileWrapper(projectConfig.project.name, userTiltfile);
}

/**
 * The Tiltfile `flisk up` runs when the project brings its own. It only includes that file, so Tilt runs it unchanged and Flisk
 * never writes to it. It sits in .flisk/.flisk-out/ like the generated one, so `tilt up -f .flisk/.flisk-out/Tiltfile`, the
 * port-owner check and `flisk down` work as before.
 */
function renderTiltfileWrapper(projectName: string, tiltfilePath: string): string {
  const includePath = path.posix.isAbsolute(tiltfilePath) ? tiltfilePath : `../../${tiltfilePath}`;
  return `#!/usr/bin/env starlark
# -*- coding: utf-8 -*-
# =============================================================================
# ${projectName} - TILT ENTRYPOINT (wraps ${tiltfilePath})
# =============================================================================
# SYSTEM-GENERATED BY Flisk CLI - DO NOT EDIT
${TILTFILE_WRAPPER_MARKER}
# Regenerate with: flisk config regenerate
# =============================================================================
# \`flisk import tiltfile\` registered ${tiltfilePath} as this project's
# orchestration source, so \`flisk up\` runs it as it is. Flisk never writes
# to it: edit it as usual. Relative paths in it resolve from its own folder.

# This file is in .flisk/.flisk-out/, so the project root is two levels up.
os.environ['FLISK_PROJECT_ROOT'] = config.main_dir + "/../.."

include(${JSON.stringify(includePath)})
`;
}

// spec.master.hbs emits one Starlark dict entry per enabledStacks[] item, so a
// duplicate name in project.json (e.g. from the interactive wizard offering
// the same service as both a core feature and a discovered stack) becomes a
// duplicate dict key, which fails Starlark parsing at `flisk up`. Dedupe here
// so a bad project.json can't break generation.
function dedupePhaseEnabledStacks(phases: ProjectConfig["phases"]): ProjectConfig["phases"] {
  const deduped = { ...phases };
  for (const key of Object.keys(deduped) as (keyof ProjectConfig["phases"])[]) {
    deduped[key] = {
      ...deduped[key],
      enabledStacks: Array.from(new Set(deduped[key].enabledStacks)),
    };
  }
  return deduped;
}

