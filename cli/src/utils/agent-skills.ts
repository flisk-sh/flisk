import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadTemplate } from "../generator/template-engine.js";

// The agent skills `flisk project` writes into a new project, so a coding agent opened there knows how to build and run
// the app with Flisk. Copies of .claude/skills/<name>/SKILL.md, shipped in cli/templates/agent-skills (a test keeps
// them identical).
export const PROJECT_AGENT_SKILLS = [
  "flisk-build",
  "flisk-recipe-starters",
  "flisk-recipe-shop",
  "flisk-recipe-saas",
  "flisk-recipe-ai-agent",
  "flisk-recipe-blog",
  "flisk-doctor",
  "flisk-up",
  "flisk-resource",
  "flisk-status",
  "flisk-troubleshoot",
  "flisk-agent-ops",
] as const;

// Claude Code reads .claude/skills; Codex, Cursor and other agents read .agents/skills.
export const AGENT_SKILL_DIRS = [".claude/skills", ".agents/skills"] as const;

const DOCS_URL = "https://github.com/flisk-sh/flisk/blob/main/docs/";

export const PROJECT_AGENTS_MD = `# AGENTS.md

This project runs on [Flisk](https://github.com/flisk-sh/flisk). To build or run something here, follow the Flisk skills in \`.agents/skills\` (Claude Code: \`.claude/skills\`), starting with \`flisk-build\`.

- Add a service: \`flisk resource <name> --type <frontend|backend|worker|agent|mcp> --stack <stack> --yes\`
- Start it: \`flisk up <stack>\`, then check every URL from \`flisk networks\`
- When something fails: \`flisk doctor\`, then \`flisk logs -s <service>\`
- Do not hand-write Dockerfiles, Compose files or Tiltfiles, and do not edit \`.autogenerated/\`: change \`service.json\` instead.
`;

// In the repository the skills link to docs/ with relative paths; in a user's project those point nowhere.
export function rewriteSkillLinks(markdown: string): string {
  return markdown.replace(/\]\((?:\.\.\/)+docs\//g, `](${DOCS_URL}`);
}

/** The skill files Flisk ships for the given skill directories: a root-relative path and its contents. */
export function agentSkillFiles(
  dirs: readonly string[] = AGENT_SKILL_DIRS,
): Array<{ rel: string; contents: string }> {
  const files: Array<{ rel: string; contents: string }> = [];
  for (const name of PROJECT_AGENT_SKILLS) {
    const contents = rewriteSkillLinks(loadTemplate(`agent-skills/${name}/SKILL.md`));
    for (const dir of dirs) {
      files.push({ rel: path.join(dir, name, "SKILL.md"), contents });
    }
  }
  return files;
}

/**
 * Write the Flisk agent skills and an AGENTS.md into a project. Never overwrites: a file that already exists is left
 * as it is, so a user's own edits survive `flisk project` running again. Returns the paths written, relative to the
 * project root.
 */
export function installAgentSkills(projectRoot: string): string[] {
  const written: string[] = [];
  for (const { rel, contents } of agentSkillFiles()) {
    const target = path.join(projectRoot, rel);
    if (existsSync(target)) continue;
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, contents);
    written.push(rel);
  }
  const agentsMd = path.join(projectRoot, "AGENTS.md");
  if (!existsSync(agentsMd)) {
    writeFileSync(agentsMd, PROJECT_AGENTS_MD);
    written.push("AGENTS.md");
  }
  return written;
}
