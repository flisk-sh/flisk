const RESOURCE_JSON_FILENAME = SERVICE_JSON;

function findServiceJsonFiles(
  dir: string,
  maxDepth: number = 5,
  currentDepth: number = 0,
): string[] {
  const results: string[] = [];

  if (currentDepth > maxDepth) {
    return results;
  }

  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);

    if (entry.isDirectory()) {
      if (shouldSkipDirectory(entry.name)) continue;
      results.push(...findServiceJsonFiles(fullPath, maxDepth, currentDepth + 1));
    } else if (entry.isFile() && entry.name === RESOURCE_JSON_FILENAME) {
      results.push(fullPath);
    }
  }

  return results;
}

export function discoverServiceManifestPaths(projectRoot: string): string[] {
  return findServiceJsonFiles(projectRoot);
}

function shouldSkipDirectory(name: string): boolean {
  return includes(SKIP_DIRECTORIES, name) || name.startsWith(".");
}

function isValidResourceConfig(value: unknown): value is ResourceConfig {
  if (!value || typeof value !== "object") return false;
  const config = value as Record<string, unknown>;
  // Accept runtime, appType, or type (for backward compatibility with existing service.json files)
  const hasRuntimeOrAppType =
    typeof config.runtime === "string" ||
    typeof config.appType === "string" ||
    typeof config.type === "string";
  return typeof config.appName === "string" && hasRuntimeOrAppType;
}

// Discovery may be invoked more than once per process,
// so remember what was already printed and show each warning once.
const printedWarnings = new Set<string>();

export function resetPrintedServiceWarnings(): void {
  printedWarnings.clear();
}

class InvalidServiceJsonError extends Error {
  constructor(readonly reason: string) {
    super(reason);
    this.name = "InvalidServiceJsonError";
  }
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

function parseResource(serviceJsonPath: string): DiscoveredResource {
  let content: string;
  try {
    content = fs.readFileSync(serviceJsonPath, "utf-8");
  } catch (error) {
    throw new InvalidServiceJsonError(`could not read file: ${errorMessage(error)}`);
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(content);
  } catch (error) {
    throw new InvalidServiceJsonError(`invalid JSON: ${errorMessage(error)}`);
  }

  if (!isValidResourceConfig(parsed)) {
    throw new InvalidServiceJsonError("missing required fields (appName, runtime or appType)");
  }

  const invalidRoutePathFields = getInvalidServiceRoutePathFields(parsed);
  if (invalidRoutePathFields.length > 0) {
    throw new InvalidServiceJsonError(
      invalidRoutePathFields.map((field) => `${field}: expected a string`).join("; "),
    );
  }

  const unsafeFields = validateGeneratedStringFields(
    parsed as Record<string, unknown>,
    serviceJsonPath,
  );
  if (unsafeFields.length > 0) throw new InvalidServiceJsonError(unsafeFields.join("; "));

  const parsedConfig = parsed as unknown as ResourceConfig;
  for (const warning of validateServiceManifest(parsed, serviceJsonPath).warnings) {
    // The warning names the file and field and says what is wrong (unknown, deprecated, ignored), so do not prefix it.
    if (printedWarnings.has(warning)) continue;
    printedWarnings.add(warning);
    console.warn(`⚠️  ${warning}`);
  }
  const config: ResourceConfig = {
    ...parsedConfig,
    appType: (parsedConfig.appType ||
      (parsedConfig as unknown as { type?: string }).type) as ResourceConfig["appType"],
  };
  const resourceDir = dirname(serviceJsonPath);

  return {
    name: config.appName,
    path: resourceDir,
    configPath: serviceJsonPath,
    config,
    stack: config.stack,
    port: config.port,
    type: config.appType,
  };
}

export function discoverResourcesWithProblems(projectRoot: string): {
  resources: DiscoveredResource[];
  problems: DiscoveryProblem[];
} {
  const serviceJsonPaths = findServiceJsonFiles(projectRoot);
  const resources: DiscoveredResource[] = [];
  const problems: DiscoveryProblem[] = [];

  for (const path of serviceJsonPaths) {
    try {
      resources.push(parseResource(path));
    } catch (error) {
      problems.push({
        path,
        reason: error instanceof InvalidServiceJsonError ? error.reason : errorMessage(error),
      });
    }
  }

  return { resources, problems };
}

export function warnAboutSkippedFiles(problems: DiscoveryProblem[]): void {
  for (const problem of problems) {
    const warning = `skipped ${problem.path}: ${problem.reason}`;
    if (printedWarnings.has(warning)) continue;
    printedWarnings.add(warning);
    console.warn(`⚠️  ${warning}`);
  }
}

export function discoverResourcesFromRoot(projectRoot: string): DiscoveredResource[] {
  const { resources, problems } = discoverResourcesWithProblems(projectRoot);
  warnAboutSkippedFiles(problems);
  return resources;
}

export function discoverResources(): DiscoveredResource[] {
  const projectRoot = findProjectRoot();

  if (!projectRoot) {
    throw errorFactories.notInProject();
  }

  return discoverResourcesFromRoot(projectRoot);
}

export function discoverResourcesStrict(discovered?: {
  resources: DiscoveredResource[];
  problems: DiscoveryProblem[];
}): DiscoveredResource[] {
  let result = discovered;
  if (!result) {
    const projectRoot = findProjectRoot();
    if (!projectRoot) {
      throw errorFactories.notInProject();
    }
    result = discoverResourcesWithProblems(projectRoot);
  }

  if (result.problems.length > 0) {
    throw new Error(
      result.problems
        .map((problem) => `Invalid service.json at ${problem.path}: ${problem.reason}`)
        .join("\n"),
    );
  }

  return result.resources;
}

/**
 * Unique, sorted `stack` values across discovered service.json files under `projectRoot`.
 * Tilt's discovery groups services by this same field (see tdk-cli-extensions
 * discovery_orchestrator.star), so these are the names that must appear in a
 * stack's `services` list in .tdk/project.json for that group to be enabled.
 */
export function discoverStackNames(
  projectRoot: string,
  resources?: DiscoveredResource[],
): string[] {
  const resourcesToScan = resources ?? discoverResourcesFromRoot(projectRoot);
  return getAllStacks(resourcesToScan);
}

export function getAllStacks(resources?: DiscoveredResource[]): string[] {
  const resourcesToScan = resources || discoverResources();
  const stacks = new Set<string>();

  for (const resource of resourcesToScan) {
    if (resource.stack) {
      stacks.add(resource.stack);
    }
  }

  return Array.from(stacks).sort();
}

export function discoverStacks(
  resources: DiscoveredResource[] = discoverResources(),
): DiscoveredStack[] {
  const stackMap = new Map<string, DiscoveredResource[]>();

  for (const resource of resources) {
    if (resource.stack) {
      const stackResources = stackMap.get(resource.stack);
      if (stackResources) {
        stackResources.push(resource);
      } else {
        stackMap.set(resource.stack, [resource]);
      }
    }
  }

  const stacks: DiscoveredStack[] = [];
  for (const [name, stackResources] of stackMap) {
    stacks.push({
      name,
      description: formatCount(stackResources.length, "resource"),
      resources: stackResources,
      resourceCount: stackResources.length,
    });
  }

  return stacks.sort((a, b) => a.name.localeCompare(b.name));
}

export function getResourcesForStack(
  stackName: string,
  resources?: DiscoveredResource[],
): DiscoveredResource[] {
  const allResources = resources ?? discoverResources();
  return allResources.filter((r) => r.stack === stackName);
}

export function stackExists(stackName: string, resources?: DiscoveredResource[]): boolean {
  const resourcesToSearch = resources ?? discoverResources();
  return resourcesToSearch.some((resource) => resource.stack === stackName);
}

/**
 * Cache TTL in milliseconds
 */
const CACHE_TTL_MS = 5000;

const resourcesCache = new Cache<ResourceMetadata>({ ttlMs: CACHE_TTL_MS });
const stacksCache = new Cache<StackMetadata>({ ttlMs: CACHE_TTL_MS });
const cacheValidator = createCacheValidator(CACHE_TTL_MS);

export function clearMetadataCache(): void {
  resourcesCache.clear();
  stacksCache.clear();
  cacheValidator.reset();
}

function detectFileType(filename: string, content?: string): FileType {
  if (filename === "Dockerfile" || filename.startsWith("docker-compose")) {
    return "docker";
  }
  if (filename === "Tiltfile" || filename.endsWith(".star")) {
    return "tilt";
  }
  if (filename === "vite.config.ts" || filename === "tsconfig.json" || filename === PACKAGE_JSON) {
    return "config";
  }
  if (filename === "schema.prisma" || filename.includes("migration")) {
    return "prisma";
  }
  if (content) {
    const firstLines = content.split("\n").slice(0, 10).join("\n");
    if (firstLines.includes("GENERATED BY TDK") || firstLines.includes("AUTOGENERATED")) {
      return "generated";
    }
  }
  return "unknown";
}

export function getResourceMetadata(resource: DiscoveredResource): ResourceMetadata {
  const cacheKey = resource.configPath;

  if (cacheValidator.isValid()) {
    const cached = resourcesCache.get(cacheKey);
    if (cached) {
      return cached;
    }
  }

  const resourceDir = resource.path;

  const stats = statSync(resource.configPath);
  const createdAt = stats.mtime.toISOString();
  const lastModified = stats.mtime.toISOString();

  const autogeneratedFiles = discoverAutogeneratedFiles(resourceDir);
  const hasDockerfile = existsSync(join(resourceDir, "Dockerfile"));
  const hasTiltfile = existsSync(join(resourceDir, "Tiltfile"));
  const hasDockerCompose =
    existsSync(join(resourceDir, DOCKER_COMPOSE_FILE)) ||
    existsSync(join(resourceDir, "docker-compose.yaml"));

  const configType = resource.config?.appType;
  let type: ResourceType = configType || "backend";
  if (!configType) {
    if (resource.name.includes("frontend")) {
      type = "frontend";
    } else if (
      resource.name.includes("sdk") ||
      resource.name.includes("lib") ||
      resource.name.includes("infra")
    ) {
      type = "library";
    }
  }

  const metadata: ResourceMetadata = {
    name: resource.name,
    stack: resource.stack,
    type,
    port: resource.config?.port,
    createdAt,
    lastModified,
    dependencies: resource.config?.dependsOn ?? [],
    hasDockerfile,
    hasTiltfile,
    hasDockerCompose,
    autogeneratedFiles,
    status: "unknown",
  };

  resourcesCache.set(cacheKey, metadata);
  cacheValidator.markUpdated();

  return metadata;
}

function discoverAutogeneratedFiles(resourceDir: string): AutogeneratedFile[] {
  const files: AutogeneratedFile[] = [];

  for (const pattern of AUTOGENERATED_FILE_PATTERNS) {
    const filePath = join(resourceDir, pattern);
    if (existsSync(filePath)) {
      const stats = statSync(filePath);
      const content = readFileSync(filePath, "utf-8");

      files.push({
        name: pattern,
        path: filePath,
        type: detectFileType(pattern, content),
        size: stats.size,
        lastModified: stats.mtime.toISOString(),
      });
    }
  }

  const prismaDir = join(resourceDir, "prisma");
  if (existsSync(prismaDir)) {
    const entries = readdirSync(prismaDir);
    for (const entry of entries) {
      if (entry === "schema.prisma" || entry.includes("migration")) {
        const filePath = join(prismaDir, entry);
        const stats = statSync(filePath);
        files.push({
          name: `prisma/${entry}`,
          path: filePath,
          type: "prisma",
          size: stats.size,
          lastModified: stats.mtime.toISOString(),
        });
      }
    }
  }

  return files.sort((a, b) => a.name.localeCompare(b.name));
}

export function getStackMetadata(stack: DiscoveredStack): StackMetadata {
  const cacheKey = stack.name;

  if (cacheValidator.isValid()) {
    const cached = stacksCache.get(cacheKey);
    if (cached) {
      return cached;
    }
  }

  const resourcesMetadata = stack.resources.map((r) => getResourceMetadata(r));
  const timestamps = resourcesMetadata.map((r) => new Date(r.createdAt).getTime());
  const earliestTimestamp = Math.min(...timestamps);
  const latestTimestamp = Math.max(...timestamps);

  const overallStatus = deriveStackStatus(resourcesMetadata.map((r) => r.status));

  const metadata: StackMetadata = {
    name: stack.name,
    resourceCount: resourcesMetadata.length,
    createdAt: new Date(earliestTimestamp).toISOString(),
    lastModified: new Date(latestTimestamp).toISOString(),
    resources: resourcesMetadata,
    overallStatus,
  };

  stacksCache.set(cacheKey, metadata);
  cacheValidator.markUpdated();

  return metadata;
}
