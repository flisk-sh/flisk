import { existsSync, readFileSync, statSync } from "node:fs";
import { isAbsolute, join, relative, resolve, sep } from "node:path";
import {
  FLISK_GENERATED_MARKER,
  ProjectConfigNotFoundError,
  verifyMasterConfigs,
} from "../generator/template-engine.js";
import {
  AUTOGENERATED_DIR,
  PACKAGE_JSON,
  PROJECT_JSON,
  SERVICE_JSON,
  TILTIGNORE_FILE,
} from "./constants.js";
import { FliskError } from "./errors.js";
import { isFliskGeneratedPath } from "./generated-paths.js";

/** Snapshot directory `flisk up` writes next to a service's `.autogenerated/` outputs. */
const CONTRACT_DIR = ".flisk-contract";

/** Generated service file that is exempt from the hand-edit check. */
const SERVICE_YAML = "service.yaml";

export type ConfigFileOwnership = "generated" | "user-owned" | "unknown";

/** What editing the file does on `flisk up`: blocked by the drift gate, not checked, or not decidable. */
export type ConfigFileDrift = "blocks-up" | "none" | "unknown";

export interface ConfigFileExplanation {
  /** Project-relative path with forward slashes. */
  file: string;
  ownership: ConfigFileOwnership;
  reason: string;
  /** Project-relative input the file is generated from, or null when Flisk does not record one. */
  source: string | null;
  driftOnUp: ConfigFileDrift;
  /** True when the file currently differs from its snapshot, so `flisk up` would refuse. */
  isEditedNow: boolean;
  /** Suggested next steps, in order. */
  next: string[];
}

/**
 * Explains one project file using the generated-path allowlist and the hand-edit check that `flisk up` runs.
 * `file` resolves against the current directory, as shell paths do. Throws a FliskError for a path outside the
 * project, a missing file, or a directory.
 */
export function explainConfigFile(projectRoot: string, file: string): ConfigFileExplanation {
  const absolute = resolve(file);
  const rel = relative(projectRoot, absolute).split(sep).join("/");
  if (rel === "" || rel === ".." || rel.startsWith("../") || isAbsolute(rel)) {
    throw new FliskError(`${file} is outside the project`, ["Pass a file inside the project root"]);
  }
  if (!existsSync(absolute)) {
    throw new FliskError(`File not found: ${rel}`, ["Check the path and try again"]);
  }
  if (!statSync(absolute).isFile()) {
    throw new FliskError(`Not a file: ${rel}`, ["Pass a file, not a directory"]);
  }

  const isEditedNow = isHandEditedNow(projectRoot, rel);
  if (!isFliskGeneratedPath(rel)) {
    return userOwned(rel, isEditedNow);
  }

  const segments = rel.split("/");
  const autogenIndex = segments.indexOf(AUTOGENERATED_DIR);
  if (autogenIndex >= 0) {
    return explainServiceOutput(projectRoot, rel, segments, autogenIndex, isEditedNow);
  }
  // The allowlist names these paths, but the path alone does not show who wrote the file. Flisk creates
  // package.json only when it is missing and never overwrites an existing one, so it is the user's to edit.
  if (rel === PACKAGE_JSON) {
    return {
      file: rel,
      ownership: "user-owned",
      reason:
        "Flisk creates package.json only when it is missing and never overwrites an existing one.",
      source: null,
      driftOnUp: "none",
      isEditedNow,
      next: ["Edit it directly."],
    };
  }
  // A root .tiltignore without Flisk's marker belongs to the team, and Flisk leaves it in place.
  if (
    rel === TILTIGNORE_FILE &&
    !readFileSync(absolute, "utf-8").includes(FLISK_GENERATED_MARKER)
  ) {
    return {
      file: rel,
      ownership: "user-owned",
      reason: "This .tiltignore has no Flisk generated marker, so Flisk leaves it in place.",
      source: null,
      driftOnUp: "none",
      isEditedNow,
      next: ["Edit it directly."],
    };
  }
  if (isProjectOutput(rel)) {
    return {
      file: rel,
      ownership: "generated",
      reason: "Generated from .flisk/project.json.",
      source: `.flisk/${PROJECT_JSON}`,
      driftOnUp: "none",
      isEditedNow,
      next: [
        `Edit .flisk/${PROJECT_JSON} instead.`,
        "`flisk config regenerate` rewrites this file from project.json and discards edits.",
      ],
    };
  }
  return {
    file: rel,
    ownership: "generated",
    reason: "Written by Flisk; this file does not record the input it is generated from.",
    source: null,
    driftOnUp: "none",
    isEditedNow,
    next: ["Do not edit it; Flisk writes it when it generates outputs."],
  };
}

function userOwned(rel: string, isEditedNow: boolean): ConfigFileExplanation {
  const base = { file: rel, ownership: "user-owned" as const, isEditedNow };
  if (rel === `.flisk/${PROJECT_JSON}`) {
    return {
      ...base,
      reason: "Flisk input: the project config that generated outputs are built from.",
      source: null,
      driftOnUp: "none",
      next: ["Edit it, then run `flisk config regenerate`."],
    };
  }
  if (rel.split("/").pop() === SERVICE_JSON) {
    return {
      ...base,
      reason: "Flisk input: the service manifest that generated service files are built from.",
      source: null,
      driftOnUp: "none",
      next: ["Edit it, then run `flisk up` to regenerate the service's outputs."],
    };
  }
  return {
    ...base,
    reason: "Not in Flisk's generated-file allowlist, so Flisk does not write it.",
    source: null,
    driftOnUp: "none",
    next: ["Edit it directly."],
  };
}

function explainServiceOutput(
  projectRoot: string,
  rel: string,
  segments: string[],
  autogenIndex: number,
  isEditedNow: boolean,
): ConfigFileExplanation {
  const serviceDir = segments.slice(0, autogenIndex).join("/");
  const source = serviceDir ? `${serviceDir}/${SERVICE_JSON}` : SERVICE_JSON;
  if (!existsSync(join(projectRoot, source))) {
    return {
      file: rel,
      ownership: "unknown",
      reason: `${AUTOGENERATED_DIR}/ has no ${SERVICE_JSON} beside it, so Flisk cannot tell which input produces this file.`,
      source: null,
      driftOnUp: "unknown",
      isEditedNow,
      next: ["Find where the file came from before editing it."],
    };
  }

  const inside = segments.slice(autogenIndex + 1);
  if (inside[0] === CONTRACT_DIR) {
    return {
      file: rel,
      ownership: "generated",
      reason: "Flisk's snapshot of the generated files; `flisk up` reads it to detect hand edits.",
      source,
      driftOnUp: "none",
      isEditedNow,
      next: ["Do not edit it; Flisk writes it when it generates outputs."],
    };
  }
  const insidePath = inside.join("/");
  if (insidePath === SERVICE_YAML) {
    return {
      file: rel,
      ownership: "generated",
      reason:
        "Runtime discovery file written by the Tilt extension; exempt from the hand-edit check.",
      source,
      driftOnUp: "none",
      isEditedNow,
      next: [`Do not edit it; edit ${source} instead.`],
    };
  }

  const snapshot = join(projectRoot, serviceDir, AUTOGENERATED_DIR, CONTRACT_DIR, insidePath);
  if (!existsSync(snapshot)) {
    return {
      file: rel,
      ownership: "generated",
      reason: `Generated from ${source}. Flisk has no snapshot of this file, so it cannot tell whether an edit would block flisk up.`,
      source,
      driftOnUp: "unknown",
      isEditedNow,
      next: ["Run `flisk up` to write the snapshots, then explain the file again."],
    };
  }
  return {
    file: rel,
    ownership: "generated",
    reason: `Generated from ${source}.`,
    source,
    driftOnUp: "blocks-up",
    isEditedNow,
    next: [
      `Edit ${source} instead, then run \`flisk up\`.`,
      "Discard a hand edit with `flisk config regenerate`.",
      "Keep a hand edit on purpose with `flisk up --ignore-drift`.",
    ],
  };
}

function isProjectOutput(rel: string): boolean {
  return (
    rel.startsWith(".flisk/.flisk-out/") ||
    rel === "Tiltfile" ||
    /^TILT_[^/]+\.star$/.test(rel) ||
    rel === TILTIGNORE_FILE
  );
}

/** The same hand-edit list `flisk up` blocks on, so explain and the gate cannot disagree. */
function isHandEditedNow(projectRoot: string, rel: string): boolean {
  try {
    return verifyMasterConfigs(projectRoot).handEdited.includes(rel);
  } catch (error) {
    if (error instanceof ProjectConfigNotFoundError) return false;
    throw error;
  }
}
