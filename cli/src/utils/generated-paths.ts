import { existsSync, lstatSync } from "node:fs";
import { isAbsolute, normalize, relative, sep } from "node:path";
import { AUTOGENERATED_DIR, PACKAGE_JSON, TILTIGNORE_FILE } from "./constants.js";

/** Reviewed Flisk-owned destinations written by `flisk config regenerate` or Tilt generation. */
export const TDK_GENERATED_PATH_ALLOWLIST = [
  `${AUTOGENERATED_DIR}/**`,
  ".tdk/.tdk-out/**",
  "Tiltfile",
  "TILT_*.star",
  TILTIGNORE_FILE,
  `${PACKAGE_JSON} (create only)`,
  "shared-platform-engineering/docker-templates/**",
  "services/platform/database-management/docker-compose.yml",
  "product_autogenerated_resource_manifests/**",
  "product_autogenerated_services_list/**",
] as const;

export function isTdkGeneratedPath(path: string): boolean {
  const normalized = normalize(path).split(sep).join("/");
  if (isAbsolute(path) || normalized === ".." || normalized.startsWith("../")) return false;
  if (
    normalized.split("/").includes(AUTOGENERATED_DIR) ||
    normalized.startsWith(".tdk/.tdk-out/") ||
    normalized === "shared-platform-engineering/docker-templates" ||
    normalized.startsWith("shared-platform-engineering/docker-templates/") ||
    normalized.startsWith("product_autogenerated_resource_manifests/") ||
    normalized.startsWith("product_autogenerated_services_list/")
  ) {
    return true;
  }
  return (
    normalized === "Tiltfile" ||
    /^TILT_[^/]+\.star$/.test(normalized) ||
    normalized === TILTIGNORE_FILE ||
    normalized === PACKAGE_JSON ||
    normalized === "services/platform/database-management/docker-compose.yml"
  );
}

export function assertTdkGeneratedPath(projectRoot: string, path: string): string {
  const absolute = isAbsolute(path) ? normalize(path) : normalize(`${projectRoot}/${path}`);
  const projectRelative = relative(projectRoot, absolute).split(sep).join("/");
  if (!isTdkGeneratedPath(projectRelative)) {
    throw new Error(
      `Refusing to write outside Flisk's generated-file allowlist: ${projectRelative}`,
    );
  }
  let cursor = projectRoot;
  for (const segment of projectRelative.split("/")) {
    cursor = normalize(`${cursor}/${segment}`);
    if (existsSync(cursor) && lstatSync(cursor).isSymbolicLink()) {
      throw new Error(
        `Refusing to write through a symbolic link in generated path: ${projectRelative}`,
      );
    }
  }
  return absolute;
}
