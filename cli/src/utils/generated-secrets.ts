import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { DiscoveredResource } from "../types/index.js";
import { parseEnv } from "./env-validator.js";

/** `secrets.generate` (#3140): { NAME: "hex:N" | "base64:N" }, N bytes of random data. */
export const GENERATE_MIN_BYTES = 8;
export const GENERATE_MAX_BYTES = 128;
const NAME_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/;

export interface GenerateSpec {
  format: "hex" | "base64";
  bytes: number;
}

/** Parses "hex:32" / "base64:32"; returns a message when the spec is bad. */
export function parseGenerateSpec(spec: unknown): GenerateSpec | string {
  const match = typeof spec === "string" ? /^(hex|base64):(\d+)$/.exec(spec) : null;
  if (!match) return `${JSON.stringify(spec)} is not a spec: use "hex:N" or "base64:N"`;
  const bytes = Number(match[2]);
  if (bytes < GENERATE_MIN_BYTES || bytes > GENERATE_MAX_BYTES)
    return `${JSON.stringify(spec)}: N must be between ${GENERATE_MIN_BYTES} and ${GENERATE_MAX_BYTES} bytes`;
  return { format: match[1] as GenerateSpec["format"], bytes };
}

export function isGenerateName(name: string): boolean {
  return NAME_PATTERN.test(name);
}

/** The valid `secrets.generate` entries of a manifest; invalid ones are reported by `secretsErrors`, not here. */
export function generateEntries(
  manifest: Record<string, unknown> | undefined,
): Map<string, GenerateSpec> {
  const out = new Map<string, GenerateSpec>();
  const generate = (manifest?.secrets as { generate?: unknown } | undefined)?.generate;
  if (!generate || typeof generate !== "object" || Array.isArray(generate)) return out;
  for (const [name, spec] of Object.entries(generate)) {
    const parsed = parseGenerateSpec(spec);
    if (isGenerateName(name) && typeof parsed !== "string") out.set(name, parsed);
  }
  return out;
}

export function generateSecretValue(spec: GenerateSpec): string {
  return randomBytes(spec.bytes).toString(spec.format);
}

/**
 * Appends every `secrets.generate` name that the env file lacks, once, with a random value. An existing line is never changed
 * or reordered, a new file is created with mode 0600, and a value set in the shell is left alone. Returns the names added (with
 * `dryRun`, the names that would be); the values are never returned, printed or logged.
 */
export function ensureGeneratedSecrets(
  projectRoot: string,
  resources: DiscoveredResource[],
  options: { envFilePath?: string; env?: NodeJS.ProcessEnv; dryRun?: boolean } = {},
): string[] {
  const wanted = new Map<string, GenerateSpec>();
  for (const resource of resources)
    for (const [name, spec] of generateEntries(resource.config as Record<string, unknown>))
      if (!wanted.has(name)) wanted.set(name, spec);
  if (wanted.size === 0) return [];

  const path = options.envFilePath ?? join(projectRoot, ".env");
  const exists = existsSync(path);
  const content = exists ? readFileSync(path, "utf-8") : "";
  const present = parseEnv(content);
  const env = options.env ?? process.env;
  const missing = [...wanted.keys()].filter(
    (name) => !present.has(name) && !(env[name] ?? "").trim(),
  );
  if (missing.length === 0 || options.dryRun) return missing;

  const lines = missing.map(
    (name) => `${name}=${generateSecretValue(wanted.get(name) as GenerateSpec)}`,
  );
  const header =
    "# Generated by Flisk (secrets.generate): created once, never overwritten. Keep out of git.";
  const lead = content === "" || content.endsWith("\n") ? "" : "\n";
  const block = `${lead}${content === "" ? "" : "\n"}${header}\n${lines.join("\n")}\n`;
  if (exists) appendFileSync(path, block);
  else writeFileSync(path, block, { mode: 0o600 });
  return missing;
}
