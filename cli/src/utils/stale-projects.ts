export type CommandRunner = (command: string, args: string[]) => string;

const defaultRun: CommandRunner = (command, args) =>
  execFileSync(command, args, { encoding: "utf-8", stdio: "pipe", windowsHide: true });

export interface StaleProject {
  name: string;
  recordedPath: string;
  containers: string[];
  volumes: string[];
  networks: string[];
  /** Golden layer tags and service images (`repository:tag`), found for projects recorded by `flisk up`. */
  images: string[];
  /**
   * True for a project `flisk up` recorded, whose objects were matched by their exact names. Only these can be pruned:
   * the others are any Compose project whose folder is gone, which need not be Flisk's.
   */
  recorded: boolean;
  containerCount: number;
  volumeCount: number;
  networkCount: number;
  imageCount: number;
  estimatedSizeBytes: number;
  estimatedSize: string;
  cleanupCommand: string;
}

export interface StaleProjectsReport {
  staleProjects: StaleProject[];
  totalContainers: number;
  totalVolumes: number;
  totalNetworks: number;
  totalImages: number;
  totalProjects: number;
  totalSizeBytes: number;
  totalSize: string;
}

export function parseSizeToBytes(sizeStr: string): number {
  if (!sizeStr) return 0;
  const virtualMatch = /virtual\s+([0-9.]+\s*[A-Za-z]+)/i.exec(sizeStr);
  const target = virtualMatch ? virtualMatch[1] : sizeStr.split(/\s*\(/)[0]?.trim();
  if (!target) return 0;
  const match = /^([0-9.]+)\s*([A-Za-z]+)$/.exec(target);
  if (!match) return 0;
  const num = parseFloat(match[1]);
  if (Number.isNaN(num)) return 0;
  const unit = match[2].toLowerCase();
  if (unit === "b") return num;
  if (unit === "kb" || unit === "k" || unit === "kib") return num * 1024;
  if (unit === "mb" || unit === "m" || unit === "mib") return num * 1024 * 1024;
  if (unit === "gb" || unit === "g" || unit === "gib") return num * 1024 * 1024 * 1024;
  if (unit === "tb" || unit === "t" || unit === "tib") return num * 1024 * 1024 * 1024 * 1024;
  return num;
}

export function extractProjectRootFromWorkingDir(workingDir: string): string {
  const norm = workingDir.replace(/\\/g, "/");
  const fliskOutIdx = norm.indexOf("/.flisk/.flisk-out");
  if (fliskOutIdx > 0) {
    return norm.slice(0, fliskOutIdx);
  }
  const autoIdx = norm.lastIndexOf("/.autogenerated");
  if (autoIdx > 0) {
    const beforeAuto = norm.slice(0, autoIdx);
    const servicesIdx = beforeAuto.indexOf("/services/");
    if (servicesIdx > 0) {
      return beforeAuto.slice(0, servicesIdx);
    }
    return beforeAuto;
  }
  return norm;
}

export function isPathStale(
  path: string,
  pathChecker: (p: string) => boolean = existsSync,
): boolean {
  if (!path) return false;
  if (pathChecker(path)) return false;
  const root = extractProjectRootFromWorkingDir(path);
  if (pathChecker(root)) return false;
  return true;
}

/**
 * Discovers projects whose recorded directory no longer exists on disk, but whose Docker containers,
 * volumes, or networks remain (#3119).
 *
 * Strictly read-only: never deletes any Docker resource or file.
 */
interface ProjectEntry {
  name: string;
  recordedPath: string;
  containers: string[];
  volumes: string[];
  networks: string[];
  images: string[];
  totalBytes: number;
}

export function findStaleProjects(options?: {
  commandRunner?: CommandRunner;
  pathChecker?: (p: string) => boolean;
  /** Projects recorded by `flisk up` (default: ~/.flisk/projects). */
  records?: ProjectRecord[];
  /** Whether a folder still holds the project (default: reads its .flisk/project.json). */
  holds?: (root: string, name: string) => boolean;
}): StaleProjectsReport {
  const runner = options?.commandRunner ?? defaultRun;

  const dockerOutputCache = new Map<string, string>();
  const cachedDocker: DockerRun = (args) => {
    const key = JSON.stringify(args);
    const cached = dockerOutputCache.get(key);
    if (cached !== undefined) return cached;
    const output = runner("docker", args);
    dockerOutputCache.set(key, output);
    return output;
  };

  const pathChecker = options?.pathChecker ?? existsSync;
  const records = options?.records ?? readProjectRecords();
  const holds = options?.holds ?? folderHoldsProject;

  const projectsByName = new Map<string, ProjectEntry>();
  // Docker objects already attributed to a recorded project, so the label scans below do not list them twice.
  const claimed = new Set<string>();

  const getOrCreate = (name: string, recordedPath: string) => {
    let p = projectsByName.get(name);
    if (!p) {
      p = {
        name,
        recordedPath,
        containers: [],
        volumes: [],
        networks: [],
        images: [],
        totalBytes: 0,
      };
      projectsByName.set(name, p);
    }
    if (!p.recordedPath && recordedPath) {
      p.recordedPath = recordedPath;
    }
    return p;
  };

  // 0. Projects recorded by `flisk up` whose folders are all gone. Volumes carry no folder, so after `flisk down` (no
  // containers left) this is the only way to tell a deleted project's database volume from a stopped project's.
  const knownNames = records.map((record) => record.name);
  // Kept apart from projectsByName so the label scans below can never add a non-Flisk object to a project --prune deletes.
  const recordedEntries: ProjectEntry[] = [];
  for (const record of records) {
    if (!isRecordStale(record, holds)) continue;
    const found = listProjectArtifacts(record.name, { stacks: record.stacks, knownNames }, (args) =>
      cachedDocker(args),
    );
    recordedEntries.push({
      name: record.name,
      recordedPath: record.roots[record.roots.length - 1] ?? "",
      containers: found.containers,
      volumes: found.volumes,
      networks: found.networks,
      images: found.images,
      totalBytes: 0,
    });
    for (const name of [...found.containers, ...found.volumes, ...found.networks])
      claimed.add(name);
  }

  // 1. Containers
  try {
    const containerOutput = cachedDocker([
      "ps",
      "-a",
      "--format",
      '{{.ID}}\t{{.Names}}\t{{.Size}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of containerOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [id, names, size, composeProject, composeDir, fliskProject, fliskDir] =
        line.split("\t");
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;
      if (!workingDir && !projectName) continue;
      if (claimed.has(names ?? "")) continue;

      const recordedPath = workingDir ? extractProjectRootFromWorkingDir(workingDir.trim()) : "";
      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        const containerLabel = names || id || "container";
        if (!entry.containers.includes(containerLabel)) {
          entry.containers.push(containerLabel);
        }
        if (size) {
          entry.totalBytes += parseSizeToBytes(size.trim());
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  // 2. Volumes
  try {
    const volumeOutput = cachedDocker([
      "volume",
      "ls",
      "--format",
      '{{.Name}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of volumeOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [volName, composeProject, composeDir, fliskProject, fliskDir] = line.split("\t");
      if (claimed.has(volName ?? "")) continue;
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;

      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const recordedPath = extractProjectRootFromWorkingDir(workingDir.trim());
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        if (!entry.volumes.includes(volName)) {
          entry.volumes.push(volName);
        }
      } else if (projectName && projectsByName.has(projectName)) {
        const entry = projectsByName.get(projectName);
        if (entry && !entry.volumes.includes(volName)) {
          entry.volumes.push(volName);
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  // 3. Networks
  try {
    const networkOutput = cachedDocker([
      "network",
      "ls",
      "--format",
      '{{.Name}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of networkOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [netName, composeProject, composeDir, fliskProject, fliskDir] = line.split("\t");
      if (claimed.has(netName ?? "")) continue;
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;

      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const recordedPath = extractProjectRootFromWorkingDir(workingDir.trim());
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        if (!entry.networks.includes(netName)) {
          entry.networks.push(netName);
        }
      } else if (projectName && projectsByName.has(projectName)) {
        const entry = projectsByName.get(projectName);
        if (entry && !entry.networks.includes(netName)) {
          entry.networks.push(netName);
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  const staleProjects: StaleProject[] = [];
  let totalContainers = 0;
  let totalVolumes = 0;
  let totalNetworks = 0;
  let totalImages = 0;
  let totalSizeBytes = 0;

  const entries = [
    ...recordedEntries.map((entry) => ({ entry, recorded: true })),
    ...[...projectsByName.values()].map((entry) => ({ entry, recorded: false })),
  ].sort((a, b) => a.entry.name.localeCompare(b.entry.name));
  for (const { entry: p, recorded } of entries) {
    // Only report as stale if there is at least one container, volume, or network
    if (
      p.containers.length === 0 &&
      p.volumes.length === 0 &&
      p.networks.length === 0 &&
      p.images.length === 0
    ) {
      continue;
    }
    totalContainers += p.containers.length;
    totalVolumes += p.volumes.length;
    totalNetworks += p.networks.length;
    totalImages += p.images.length;
    totalSizeBytes += p.totalBytes;

    staleProjects.push({
      name: p.name,
      recordedPath: p.recordedPath,
      containers: p.containers,
      volumes: p.volumes,
      networks: p.networks,
      images: p.images,
      recorded,
      containerCount: p.containers.length,
      volumeCount: p.volumes.length,
      networkCount: p.networks.length,
      imageCount: p.images.length,
      estimatedSizeBytes: p.totalBytes,
      estimatedSize: formatBytes(p.totalBytes),
      // The folder is gone, so `flisk down` cannot run for it. --prune only deletes projects Flisk recorded; another
      // Compose project may not be Flisk's at all, so its owner decides.
      cleanupCommand: recorded
        ? "flisk projects --stale --prune"
        : `docker compose -p ${p.name} down`,
    });
  }

  return {
    staleProjects,
    totalContainers,
    totalVolumes,
    totalNetworks,
    totalImages,
    totalProjects: staleProjects.length,
    totalSizeBytes,
    totalSize: formatBytes(totalSizeBytes),
  };
}

export interface PrunedStaleProject {
  name: string;
  removed: ProjectArtifacts;
  kept: PurgeResult["kept"];
}

/**
 * Deletes what {@link findStaleProjects} listed for each stale project `flisk up` recorded: containers, then volumes,
 * networks and images. Unrecorded ones are left alone and named in `skipped`. A project whose objects were all removed
 * is also dropped from the `flisk up` record, so it is not reported again.
 */
export function pruneStaleProjects(
  staleProjects: StaleProject[],
  options: { docker?: DockerRun; forget?: (name: string) => void } = {},
): { projects: PrunedStaleProject[]; skipped: string[] } {
  const forget = options.forget ?? ((name: string) => forgetProject(name));
  const projects: PrunedStaleProject[] = [];
  for (const project of staleProjects.filter((stale) => stale.recorded)) {
    const result = removeProjectArtifacts(
      {
        containers: project.containers,
        volumes: project.volumes,
        networks: project.networks,
        images: project.images,
      },
      options.docker,
    );
    if (result.kept.length === 0) {
      try {
        forget(project.name);
      } catch {
        // The record only decides what is reported; a stale record lists nothing once Docker holds nothing.
      }
    }
    projects.push({ name: project.name, removed: result.removed, kept: result.kept });
  }
  return {
    projects,
    skipped: staleProjects.filter((stale) => !stale.recorded).map((stale) => stale.name),
  };
}
