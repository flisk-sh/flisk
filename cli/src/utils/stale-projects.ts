import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { formatBytes } from "./formatting.js";

export type CommandRunner = (command: string, args: string[]) => string;

const defaultRun: CommandRunner = (command, args) =>
  execFileSync(command, args, { encoding: "utf-8", stdio: "pipe", windowsHide: true });

export interface StaleProject {
  name: string;
  recordedPath: string;
  containers: string[];
  volumes: string[];
  networks: string[];
  containerCount: number;
  volumeCount: number;
  networkCount: number;
  estimatedSizeBytes: number;
  estimatedSize: string;
  cleanupCommand: string;
}

export interface StaleProjectsReport {
  staleProjects: StaleProject[];
  totalContainers: number;
  totalVolumes: number;
  totalNetworks: number;
  totalProjects: number;
  totalSizeBytes: number;
  totalSize: string;
}

export function parseSizeToBytes(sizeStr: string): number {
  if (!sizeStr) return 0;
  const virtualMatch = /virtual\s+([0-9.]+\s*[A-Za-z]+)/i.exec(sizeStr);
  const target = virtualMatch ? virtualMatch[1] : sizeStr.split(/\s*\(/)[0]?.trim();
  if (!target) return 0;
  const match = /^([0-9.]+)\s*([A-Za-z]+)$/.exec(target);
  if (!match) return 0;
  const num = parseFloat(match[1]);
  if (Number.isNaN(num)) return 0;
  const unit = match[2].toLowerCase();
  if (unit === "b") return num;
  if (unit === "kb" || unit === "k" || unit === "kib") return num * 1024;
  if (unit === "mb" || unit === "m" || unit === "mib") return num * 1024 * 1024;
  if (unit === "gb" || unit === "g" || unit === "gib") return num * 1024 * 1024 * 1024;
  if (unit === "tb" || unit === "t" || unit === "tib") return num * 1024 * 1024 * 1024 * 1024;
  return num;
}

export function extractProjectRootFromWorkingDir(workingDir: string): string {
  const norm = workingDir.replace(/\\/g, "/");
  const fliskOutIdx = norm.indexOf("/.flisk/.flisk-out");
  if (fliskOutIdx > 0) {
    return norm.slice(0, fliskOutIdx);
  }
  const autoIdx = norm.lastIndexOf("/.autogenerated");
  if (autoIdx > 0) {
    const beforeAuto = norm.slice(0, autoIdx);
    const servicesIdx = beforeAuto.indexOf("/services/");
    if (servicesIdx > 0) {
      return beforeAuto.slice(0, servicesIdx);
    }
    return beforeAuto;
  }
  return norm;
}

export function isPathStale(
  path: string,
  pathChecker: (p: string) => boolean = existsSync,
): boolean {
  if (!path) return false;
  if (pathChecker(path)) return false;
  const root = extractProjectRootFromWorkingDir(path);
  if (pathChecker(root)) return false;
  return true;
}

/**
 * Discovers projects whose recorded directory no longer exists on disk, but whose Docker containers,
 * volumes, or networks remain (#3119).
 *
 * Strictly read-only: never deletes any Docker resource or file.
 */
export function findStaleProjects(options?: {
  commandRunner?: CommandRunner;
  pathChecker?: (p: string) => boolean;
}): StaleProjectsReport {
  const runner = options?.commandRunner ?? defaultRun;
  const pathChecker = options?.pathChecker ?? existsSync;

  const projectsByName = new Map<
    string,
    {
      name: string;
      recordedPath: string;
      containers: string[];
      volumes: string[];
      networks: string[];
      totalBytes: number;
    }
  >();

  const getOrCreate = (name: string, recordedPath: string) => {
    let p = projectsByName.get(name);
    if (!p) {
      p = {
        name,
        recordedPath,
        containers: [],
        volumes: [],
        networks: [],
        totalBytes: 0,
      };
      projectsByName.set(name, p);
    }
    if (!p.recordedPath && recordedPath) {
      p.recordedPath = recordedPath;
    }
    return p;
  };

  // 1. Containers
  try {
    const containerOutput = runner("docker", [
      "ps",
      "-a",
      "--format",
      '{{.ID}}\t{{.Names}}\t{{.Size}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of containerOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [id, names, size, composeProject, composeDir, fliskProject, fliskDir] =
        line.split("\t");
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;
      if (!workingDir && !projectName) continue;

      const recordedPath = workingDir ? extractProjectRootFromWorkingDir(workingDir.trim()) : "";
      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        const containerLabel = names || id || "container";
        if (!entry.containers.includes(containerLabel)) {
          entry.containers.push(containerLabel);
        }
        if (size) {
          entry.totalBytes += parseSizeToBytes(size.trim());
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  // 2. Volumes
  try {
    const volumeOutput = runner("docker", [
      "volume",
      "ls",
      "--format",
      '{{.Name}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of volumeOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [volName, composeProject, composeDir, fliskProject, fliskDir] = line.split("\t");
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;

      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const recordedPath = extractProjectRootFromWorkingDir(workingDir.trim());
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        if (!entry.volumes.includes(volName)) {
          entry.volumes.push(volName);
        }
      } else if (projectName && projectsByName.has(projectName)) {
        const entry = projectsByName.get(projectName);
        if (entry && !entry.volumes.includes(volName)) {
          entry.volumes.push(volName);
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  // 3. Networks
  try {
    const networkOutput = runner("docker", [
      "network",
      "ls",
      "--format",
      '{{.Name}}\t{{.Label "com.docker.compose.project"}}\t{{.Label "com.docker.compose.project.working_dir"}}\t{{.Label "sh.flisk.project"}}\t{{.Label "sh.flisk.project.dir"}}',
    ]);
    for (const line of networkOutput.split(/\r?\n/)) {
      if (!line.trim()) continue;
      const [netName, composeProject, composeDir, fliskProject, fliskDir] = line.split("\t");
      const workingDir = fliskDir || composeDir;
      const projectName = fliskProject || composeProject;

      if (workingDir && isPathStale(workingDir.trim(), pathChecker)) {
        const recordedPath = extractProjectRootFromWorkingDir(workingDir.trim());
        const projKey = projectName || recordedPath;
        const entry = getOrCreate(projKey, recordedPath);
        if (!entry.networks.includes(netName)) {
          entry.networks.push(netName);
        }
      } else if (projectName && projectsByName.has(projectName)) {
        const entry = projectsByName.get(projectName);
        if (entry && !entry.networks.includes(netName)) {
          entry.networks.push(netName);
        }
      }
    }
  } catch {
    // Docker unavailable or failed
  }

  const staleProjects: StaleProject[] = [];
  let totalContainers = 0;
  let totalVolumes = 0;
  let totalNetworks = 0;
  let totalSizeBytes = 0;

  for (const p of [...projectsByName.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    // Only report as stale if there is at least one container, volume, or network
    if (p.containers.length === 0 && p.volumes.length === 0 && p.networks.length === 0) {
      continue;
    }
    totalContainers += p.containers.length;
    totalVolumes += p.volumes.length;
    totalNetworks += p.networks.length;
    totalSizeBytes += p.totalBytes;

    staleProjects.push({
      name: p.name,
      recordedPath: p.recordedPath,
      containers: p.containers,
      volumes: p.volumes,
      networks: p.networks,
      containerCount: p.containers.length,
      volumeCount: p.volumes.length,
      networkCount: p.networks.length,
      estimatedSizeBytes: p.totalBytes,
      estimatedSize: formatBytes(p.totalBytes),
      cleanupCommand: `flisk down --purge`,
    });
  }

  return {
    staleProjects,
    totalContainers,
    totalVolumes,
    totalNetworks,
    totalProjects: staleProjects.length,
    totalSizeBytes,
    totalSize: formatBytes(totalSizeBytes),
  };
}
