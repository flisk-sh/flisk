import { describe, expect, it } from "vitest";
import {
  type DockerRun,
  listProjectArtifacts,
  ownerOf,
  removeProjectArtifacts,
} from "../project-purge.js";

/** A fake `docker` that answers the list calls from fixed output and logs every call. */
function fakeDocker(output: {
  containers?: string[];
  volumes?: string[];
  networks?: string[];
  images?: string[];
  fail?: (args: string[]) => string | undefined;
}): { docker: DockerRun; calls: string[][] } {
  const calls: string[][] = [];
  const docker: DockerRun = (args) => {
    calls.push(args);
    const failure = output.fail?.(args);
    if (failure) throw Object.assign(new Error("docker failed"), { stderr: `${failure}\nmore` });
    if (args[0] === "ps") return (output.containers ?? []).join("\n");
    if (args[0] === "volume" && args[1] === "ls") return (output.volumes ?? []).join("\n");
    if (args[0] === "network" && args[1] === "ls") return (output.networks ?? []).join("\n");
    if (args[0] === "images") return (output.images ?? []).join("\n");
    return "";
  };
  return { docker, calls };
}

describe("ownerOf", () => {
  it("gives a prefix to the longest known name", () => {
    expect(ownerOf("shop_admin_web_app", "_", ["shop", "shop_admin"])).toBe("shop_admin");
    expect(ownerOf("shop_main_api", "_", ["shop", "shop_admin"])).toBe("shop");
    expect(ownerOf("shopping_main_api", "_", ["shop"])).toBeUndefined();
  });

  it("matches underscored names for Docker objects named with underscores", () => {
    const underscore = (name: string) => name.replace(/-/g, "_");
    expect(ownerOf("my_shop_main_api", "_", ["my-shop"], underscore)).toBe("my-shop");
  });
});

describe("listProjectArtifacts", () => {
  const { docker } = fakeDocker({
    containers: [
      "shop_postgres\tshop-database-management",
      "shop-main-autogenerated-api-1\tshop-main-autogenerated",
      "shop_admin_postgres\tshop-admin-database-management",
      "shop-admin-web-autogenerated-app-1\tshop-admin-web-autogenerated",
      "unrelated\t",
    ],
    volumes: [
      "shop-database-management_shop_postgres_data\tshop-database-management",
      "shop-main-autogenerated_uploads\tshop-main-autogenerated",
      "shop-admin-database-management_shop_admin_postgres_data\tshop-admin-database-management",
      "shop-admin-messaging_shop_admin_nats_data\tshop-admin-messaging",
      "shop-staging_cache\tshop-staging",
      "shop_cache\t",
      "0c351a8afe09f1f7980c903afc2098bee7995b9ac4e007afe70325dd43bfe102\t",
    ],
    networks: ["shop_backend", "shop_traefik-public", "shop_admin_backend", "bridge"],
    images: [
      "shop-l1:latest",
      "shop-l4-backend-node:latest",
      "shop-l3-migrator:latest",
      "shop-lounge:latest",
      "shop_main_api:dev",
      "shop_main_api:tilt-885d7474e253569a",
      "shop_main-db-migrator:dev",
      "shop-admin-l1:latest",
      "shop_admin_web_app:dev",
      "shop_other_api:dev",
      "postgres:16-alpine",
      "<none>:<none>",
    ],
  });

  it("finds this project's containers, volumes, networks and images by their exact names", () => {
    expect(listProjectArtifacts("shop", { stacks: ["main"] }, docker)).toEqual({
      containers: ["shop_postgres", "shop-main-autogenerated-api-1"],
      volumes: ["shop-database-management_shop_postgres_data", "shop-main-autogenerated_uploads"],
      networks: ["shop_traefik-public", "shop_backend"],
      images: [
        "shop-l1:latest",
        "shop-l4-backend-node:latest",
        "shop-l3-migrator:latest",
        "shop_main_api:dev",
        "shop_main_api:tilt-885d7474e253569a",
        "shop_main-db-migrator:dev",
      ],
    });
  });

  it("never claims the database of a longer-named project, even one nothing recorded", () => {
    // Regression: ownership was a name prefix narrowed by recorded names, so an unrecorded `shop-admin` lost its data.
    const found = listProjectArtifacts("shop", { stacks: ["main"], knownNames: [] }, docker);

    expect(found.volumes.filter((volume) => volume.startsWith("shop-admin"))).toEqual([]);
    expect(found.containers.filter((name) => name.includes("admin"))).toEqual([]);
    expect(found.volumes).not.toContain("shop-staging_cache");
  });

  it("finds the wake-gateway image of this project only, not one of a project named like a prefix", () => {
    const { docker: gatewayDocker } = fakeDocker({
      images: [
        "foo-traefik-wake-gateway:latest",
        "foo2-traefik-wake-gateway:latest",
        "foo-bar-traefik-wake-gateway:latest",
      ],
    });
    expect(listProjectArtifacts("foo", { stacks: ["main"] }, gatewayDocker).images).toEqual([
      "foo-traefik-wake-gateway:latest",
    ]);
  });

  it("never claims a volume without a Compose project label, or an image that only shares the prefix", () => {
    const found = listProjectArtifacts("shop", { stacks: ["main"] }, docker);
    expect(found.volumes).not.toContain("shop_cache");
    expect(found.images).not.toContain("shop-lounge:latest");
    expect(found.images).not.toContain("shop_other_api:dev");
  });

  it("gives an ambiguous service image to the longest recorded name", () => {
    const stacks = ["admin"];
    expect(listProjectArtifacts("shop", { stacks }, docker).images).toContain(
      "shop_admin_web_app:dev",
    );
    expect(
      listProjectArtifacts("shop", { stacks, knownNames: ["shop-admin"] }, docker).images,
    ).not.toContain("shop_admin_web_app:dev");
  });

  it("without known stacks still finds the shared infrastructure and golden images", () => {
    const found = listProjectArtifacts("shop", { stacks: [] }, docker);
    expect(found.volumes).toEqual(["shop-database-management_shop_postgres_data"]);
    expect(found.images).toEqual([
      "shop-l1:latest",
      "shop-l4-backend-node:latest",
      "shop-l3-migrator:latest",
    ]);
  });

  it("lists nothing when docker fails", () => {
    const failing: DockerRun = () => {
      throw new Error("Cannot connect to the Docker daemon");
    };
    expect(listProjectArtifacts("shop", { stacks: [] }, failing)).toEqual({
      containers: [],
      volumes: [],
      networks: [],
      images: [],
    });
  });
});

describe("removeProjectArtifacts", () => {
  it("removes containers before volumes, networks and images, untagging images without --force", () => {
    const { docker, calls } = fakeDocker({});
    const result = removeProjectArtifacts(
      { containers: ["c1"], volumes: ["v1"], networks: ["n1"], images: ["shop-l1:latest"] },
      docker,
    );

    expect(calls).toEqual([
      ["rm", "-f", "c1"],
      ["volume", "rm", "v1"],
      ["network", "rm", "n1"],
      ["image", "rm", "shop-l1:latest"],
    ]);
    expect(result.removed).toEqual({
      containers: ["c1"],
      volumes: ["v1"],
      networks: ["n1"],
      images: ["shop-l1:latest"],
    });
    expect(result.kept).toEqual([]);
  });

  it("keeps going past an object Docker refuses, and reports the first line of why", () => {
    const { docker } = fakeDocker({
      fail: (args) => (args[2] === "v1" ? "Error: volume is in use - [abc]" : undefined),
    });
    const result = removeProjectArtifacts(
      { containers: [], volumes: ["v1", "v2"], networks: [], images: [] },
      docker,
    );

    expect(result.removed.volumes).toEqual(["v2"]);
    expect(result.kept).toEqual([
      { kind: "volumes", name: "v1", reason: "Error: volume is in use - [abc]" },
    ]);
  });
});
