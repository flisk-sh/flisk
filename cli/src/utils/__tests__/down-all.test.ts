import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it, vi } from "vitest";
import {
  discoverRunningStacks,
  isFliskUpCommand,
  type RunningStack,
  stopRunningStack,
} from "../down-all.js";

const ps = [
  " 100 /usr/bin/tilt up -f /work/shop/.flisk/.flisk-out/Tiltfile -- --focus=api web",
  " 101 tilt up -f /gone/blog/.flisk/.flisk-out/Tiltfile",
  " 102 /usr/local/bin/flisk up",
  " 103 vim /work/shop/.flisk/.flisk-out/Tiltfile",
  " 104 tilt down -f /work/shop/.flisk/.flisk-out/Tiltfile",
  " 105 tilt up -f /work/plain/Tiltfile",
  " 106 node /usr/local/bin/flisk down --all",
].join("\n");

const dockerPs = [
  "shop\t/work/shop/.flisk/.flisk-out\tapi\t0.0.0.0:3000->3000/tcp\tshop_api\t\t",
  "shop\t/work/shop/services/web/.autogenerated\tweb\t:5173->5173/tcp\tshop_web\t\t",
  "blog\t/gone/blog/.flisk/.flisk-out\tapi\t0.0.0.0:4000->4000/tcp\tblog_api\t\t",
  // A hand-written Compose project in an ordinary folder is never a Flisk stack.
  "other\t/work/foreign/compose\tapi\t0.0.0.0:9999->80/tcp\tother_api\t\t",
].join("\n");

function nativeState(pid: number) {
  return {
    pid,
    startedAt: "2026-11-19T00:00:00.000Z",
    services: {
      api: { pid: 201, port: 3000, url: "http://localhost:3000" },
      web: { pid: 202, port: 5173 },
    },
  };
}

function discoveryDeps() {
  return {
    platform: "darwin" as const,
    commandRunner: () => ps,
    docker: () => dockerPs,
    cwdOf: (pid: number) => (pid === 102 ? "/work/local" : undefined),
    readNative: (root: string) => (root === "/work/local" ? nativeState(102) : null),
    nativeAlive: async () => true,
    folderExists: (path: string) => path !== "/gone/blog" && path !== "/gone/stranger",
    records: [],
  };
}

describe("down --all discovery", () => {
  it("lists local and Docker stacks with their folders, services and ports, including a missing folder", async () => {
    const stacks = await discoverRunningStacks(discoveryDeps());

    expect(stacks).toEqual([
      {
        folder: "/gone/blog",
        runtime: "docker",
        services: ["api"],
        ports: [4000],
        stacks: [],
        missingFolder: true,
        tiltfile: "/gone/blog/.flisk/.flisk-out/Tiltfile",
        tiltPids: [101],
        composeProjects: ["blog"],
      },
      {
        folder: "/work/local",
        runtime: "local",
        services: ["api", "web"],
        ports: [3000, 5173],
        stacks: [],
        missingFolder: false,
        tiltPids: [],
        composeProjects: [],
        supervisorPid: 102,
      },
      {
        folder: "/work/shop",
        runtime: "docker",
        services: ["api", "web"],
        ports: [3000, 5173],
        stacks: ["api", "web"],
        missingFolder: false,
        tiltfile: "/work/shop/.flisk/.flisk-out/Tiltfile",
        tiltPids: [100],
        composeProjects: ["shop"],
      },
    ]);
  });

  it("reports nothing when no process and no container is running", async () => {
    const stacks = await discoverRunningStacks({
      ...discoveryDeps(),
      commandRunner: () => "",
      docker: () => {
        throw new Error("docker is not running");
      },
    });
    expect(stacks).toEqual([]);
  });

  it("finds a live native run at a recorded folder when no process command is visible", async () => {
    const alive = vi.fn(async () => true);
    const stacks = await discoverRunningStacks({
      ...discoveryDeps(),
      platform: "win32",
      commandRunner: () => "",
      docker: () => {
        throw new Error("docker is not running");
      },
      cwdOf: () => undefined,
      readNative: (root) => (root === "/work/recorded" ? nativeState(777) : null),
      nativeAlive: alive,
      records: [
        { name: "local", roots: ["/work/recorded"], stacks: [], updatedAt: "2026-11-19T00:00:00Z" },
      ],
    });

    expect(stacks).toEqual([
      {
        folder: "/work/recorded",
        runtime: "local",
        services: ["api", "web"],
        ports: [3000, 5173],
        stacks: [],
        missingFolder: false,
        tiltPids: [],
        composeProjects: [],
        supervisorPid: 777,
      },
    ]);
    expect(alive).toHaveBeenCalledOnce();
  });

  it("ignores editors, tilt down, plain Tiltfiles and other flisk subcommands", async () => {
    expect(isFliskUpCommand("/usr/local/bin/flisk down --all")).toBe(false);
    expect(isFliskUpCommand("vim /work/shop/.flisk/.flisk-out/Tiltfile")).toBe(false);
    expect(isFliskUpCommand("bun /opt/flisk/dist/index.js up --json")).toBe(true);
    expect(isFliskUpCommand("/usr/local/bin/flisk up --json")).toBe(true);
    const stacks = await discoverRunningStacks(discoveryDeps());
    expect(stacks.map((stack) => stack.folder)).not.toContain("/work/plain");
  });

  it("does not adopt a deleted Compose folder that Flisk never recorded", async () => {
    const stacks = await discoverRunningStacks({
      ...discoveryDeps(),
      commandRunner: () => "",
      docker: () =>
        "foreign\t/gone/stranger/.flisk/.flisk-out\tapi\t0.0.0.0:9999->80/tcp\tstranger_api\t\t",
    });
    expect(stacks).toEqual([]);
  });
});

function dockerStack(folder: string, tiltfile?: string): RunningStack {
  return {
    folder,
    runtime: "docker",
    services: ["api"],
    ports: [3000],
    stacks: [],
    missingFolder: false,
    ...(tiltfile ? { tiltfile, tiltPids: [101] } : { tiltPids: [] }),
    composeProjects: ["shop"],
  };
}

describe("down --all stopping", () => {
  it("stops only this Tilt and its Compose projects, leaving generated files untouched", async () => {
    const root = mkdtempSync(join(tmpdir(), "flisk-down-all-generated-"));
    const tiltfile = join(root, ".flisk", ".flisk-out", "Tiltfile");
    const composeFile = join(root, "services", "api", ".autogenerated", "compose.yaml");
    mkdirSync(join(root, ".flisk", ".flisk-out"), { recursive: true });
    mkdirSync(join(root, "services", "api", ".autogenerated"), { recursive: true });
    writeFileSync(tiltfile, "# generated Tiltfile\n");
    writeFileSync(composeFile, "services: {}\n");
    const digest = (file: string) => createHash("sha256").update(readFileSync(file)).digest("hex");
    const before = [digest(tiltfile), digest(composeFile)];
    const stopTilt = vi.fn(() => [101]);
    const stopCompose = vi.fn(() => ({ stopped: ["shop"], failed: [] }));
    const waitForTilt = vi.fn(async () => true);

    try {
      const result = await stopRunningStack(dockerStack(root, tiltfile), {
        platform: "darwin",
        commandRunner: () => "",
        stopTilt,
        stopCompose,
        waitForTilt,
      });

      expect(result).toEqual({ ok: true, stopped: ["tilt up (pid 101)", "compose shop"] });
      expect(stopTilt).toHaveBeenCalledWith(tiltfile, "darwin", expect.any(Function));
      expect(stopCompose).toHaveBeenCalledWith(root, expect.any(Function));
      expect(waitForTilt).toHaveBeenCalledWith(tiltfile);
      expect([digest(tiltfile), digest(composeFile)]).toEqual(before);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("stops a stack whose folder is gone without recreating it", async () => {
    const folder = join(tmpdir(), `flisk-down-all-gone-${Date.now()}`);
    expect(existsSync(folder)).toBe(false);
    const stopCompose = vi.fn(() => ({ stopped: ["blog"], failed: [] }));

    const result = await stopRunningStack(
      { ...dockerStack(folder, `${folder}/.flisk/.flisk-out/Tiltfile`), missingFolder: true },
      {
        platform: "darwin",
        commandRunner: () => "",
        stopTilt: () => [101],
        stopCompose,
        waitForTilt: async () => true,
      },
    );

    expect(result.ok).toBe(true);
    expect(stopCompose).toHaveBeenCalledWith(folder, expect.any(Function));
    expect(existsSync(folder)).toBe(false);
  });

  it("stops a local run through stopNativeRun, never through Tilt or Compose", async () => {
    const stopNative = vi.fn(async () => ({
      wasRunning: true,
      services: ["api"],
      supervisorPid: 102,
    }));
    const stack: RunningStack = {
      folder: "/work/local",
      runtime: "local",
      services: ["api"],
      ports: [3000],
      stacks: [],
      missingFolder: false,
      tiltPids: [],
      composeProjects: [],
      supervisorPid: 102,
    };

    const result = await stopRunningStack(stack, { stopNative });

    expect(result).toEqual({
      ok: true,
      stopped: ["local api", "flisk up (pid 102)"],
    });
    expect(stopNative).toHaveBeenCalledWith("/work/local");
  });
});
