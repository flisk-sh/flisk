const viteSpaFrameworks = Object.values(FRONTEND_FRAMEWORKS).filter(
  (provider) => (provider.kind ?? "vite-spa") === "vite-spa",
);

describe("every Vite frontend in the registry can run on the host", () => {
  it("declares its Vite setup, so no framework needs the engine for its config", () => {
    expect(viteSpaFrameworks.length).toBeGreaterThanOrEqual(9);
    for (const provider of viteSpaFrameworks) {
      expect(provider.vite, `${provider.id} has no vite setup`).toBeDefined();
    }
  });

  it.each(viteSpaFrameworks.map((provider) => [provider.id, provider] as const))(
    "%s: the plugin it imports is one of its own dependencies",
    (_id, provider) => {
      for (const statement of provider.vite?.imports ?? []) {
        const module = /from '([^']+)'/.exec(statement)?.[1] ?? "";
        const declared = { ...provider.dependencies, ...provider.devDependencies };
        const root = module.startsWith("@")
          ? module.split("/").slice(0, 2).join("/")
          : module.split("/")[0];
        expect(Object.keys(declared), `${provider.id} imports ${module}`).toContain(root);
      }
    },
  );

  it("writes a plain config: the framework plugin, one port, and no engine files", () => {
    const config = renderLocalViteConfig(FRONTEND_FRAMEWORKS.react as never, { port: 3456 });
    expect(config).toContain("import react from '@vitejs/plugin-react';");
    expect(config).toContain("plugins: [react()]");
    expect(config).toContain("process.env.PORT ?? 3456");
    // Flisk watches this exact port, so Vite must not quietly move to the next free one.
    expect(config).toContain("strictPort: true");
    expect(config).not.toMatch(/autogenerated|resolve\(__dirname/);
    expect(config).not.toContain("proxy");
  });

  it("proxies the backend when there is one", () => {
    const config = renderLocalViteConfig(FRONTEND_FRAMEWORKS.vue as never, {
      port: 3000,
      proxyTarget: "http://localhost:4001",
    });
    expect(config).toContain("'/health': { target: 'http://localhost:4001'");
  });

  it("refuses a framework without a Vite setup instead of writing a broken config", () => {
    expect(() => renderLocalViteConfig({ id: "x", label: "X" } as never, { port: 3000 })).toThrow(
      /no Vite setup/,
    );
  });
});

const contentOf = (tasks: FileGenerationTask[], filename: string) =>
  (tasks.find((task) => task.filename === filename)?.content ?? {}) as Record<string, unknown>;

describe("applyLocalScaffold", () => {
  const scaffold = (): FileGenerationTask[] => [
    {
      type: "json",
      filename: "service.json",
      content: {
        build: { dockerfile: "Dockerfile" },
        dev: { command: "bun run dev" },
        healthCheckPath: "/health",
      },
      description: "",
      emoji: "",
    },
    {
      type: "json",
      filename: "package.json",
      content: {
        scripts: {
          predev: "x",
          prebuild: "y",
          dev: "vite --config .autogenerated/a.ts",
          build: "b",
        },
      },
      description: "",
      emoji: "",
    },
    { type: "text", filename: "Dockerfile", content: "FROM bun", description: "", emoji: "" },
  ];

  it("drops the Dockerfile, writes a vite config, and points service.json at an npm script", () => {
    const tasks = scaffold();
    const command = applyLocalScaffold({
      resourceName: "web",
      resourceType: "frontend",
      port: 3000,
      tasks,
      frontendFramework: FRONTEND_FRAMEWORKS.react,
    });
    expect(command).toBe("npm run dev");
    expect(tasks.map((task) => task.filename)).toEqual([
      "service.json",
      "package.json",
      "vite.config.ts",
    ]);
    const service = contentOf(tasks, "service.json");
    expect(service.command).toBe("npm run dev");
    expect(service).not.toHaveProperty("build");
    expect(service).not.toHaveProperty("dev");
    const scripts = contentOf(tasks, "package.json").scripts as Record<string, string>;
    expect(scripts.dev).toBe("vite");
    expect(scripts).not.toHaveProperty("predev");
    expect(scripts).not.toHaveProperty("prebuild");
  });

  it("a server framework keeps its own dev script and probes the root on the host", () => {
    const tasks = scaffold();
    contentOf(tasks, "service.json").healthCheckPath = "/web/health";
    applyLocalScaffold({
      resourceName: "web",
      resourceType: "frontend",
      port: 3000,
      tasks,
      frontendFramework: FRONTEND_FRAMEWORKS.next,
    });
    expect(tasks.some((task) => task.filename === "vite.config.ts")).toBe(false);
    expect(contentOf(tasks, "service.json").healthCheckPath).toBe("/");
  });

  it("a language that owns its runtime runs its own dev command", () => {
    const tasks = scaffold().filter((task) => task.filename !== "package.json");
    const command = applyLocalScaffold({
      resourceName: "api",
      resourceType: "backend",
      port: 4000,
      tasks,
      backendLanguage: { id: "go", label: "Go", devCommand: "go run .", installHint: "" },
    });
    expect(command).toBe("go run .");
  });
});

describe("flisk resource --local (the real CLI)", () => {
  let dir: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "flisk-resource-local-"));
    runFlisk(["project", "--yes"], { cwd: dir, timeout: 60_000 });
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it("scaffolds a Vite frontend that needs no Docker, Tilt or generated files", () => {
    const run = runFlisk(
      [
        "resource",
        "web",
        "--type",
        "frontend",
        "--framework",
        "vue",
        "--path",
        "web",
        "--stack",
        "app",
        "--local",
        "--yes",
      ],
      { cwd: dir, timeout: 120_000 },
    );
    expect(run.status, run.stdout + run.stderr).toBe(0);
    const web = join(dir, "web");
    expect(existsSync(join(web, "Dockerfile"))).toBe(false);
    expect(readFileSync(join(web, "vite.config.ts"), "utf8")).toContain("vue()");
    const scripts = JSON.parse(readFileSync(join(web, "package.json"), "utf8")).scripts;
    expect(scripts.dev).toBe("vite");
    expect(JSON.stringify(scripts)).not.toContain("autogenerated");
    expect(JSON.parse(readFileSync(join(web, "service.json"), "utf8")).command).toBe("npm run dev");
  });

  it("without --local the scaffold is the same Docker one as before", () => {
    const run = runFlisk(
      [
        "resource",
        "web",
        "--type",
        "frontend",
        "--framework",
        "react",
        "--path",
        "web",
        "--stack",
        "app",
        "--yes",
      ],
      { cwd: dir, timeout: 120_000 },
    );
    expect(run.status, run.stdout + run.stderr).toBe(0);
    expect(existsSync(join(dir, "web", "Dockerfile"))).toBe(true);
    expect(existsSync(join(dir, "web", "vite.config.ts"))).toBe(false);
    const scripts = JSON.parse(readFileSync(join(dir, "web", "package.json"), "utf8")).scripts;
    expect(scripts.dev).toContain("autogenerated");
  });

  it("refuses --local for a resource that is neither a frontend nor a backend", () => {
    const run = runFlisk(["resource", "jobs", "--type", "worker", "--local", "--yes"], {
      cwd: dir,
      timeout: 60_000,
    });
    expect(run.status).not.toBe(0);
    expect(run.stdout + run.stderr).toContain("--local applies to frontend and backend");
  });
});

describe("localResourcePort", () => {
  it("moves past a port something on this computer really listens on, and past ports other resources hold", async () => {
    // A real socket on a port the OS chose, standing in for "4000 is already taken by another program".
    const busy = createServer();
    await new Promise<void>((resolve) => busy.listen(0, "localhost", resolve));
    const address = busy.address();
    const port = typeof address === "object" && address ? address.port : 0;
    try {
      expect(await isPortListening(port)).toBe(true);
      const picked = await localResourcePort(port, false, [port + 1], isPortListening);
      expect(picked).toBeGreaterThan(port + 1);
      // An explicit --port is kept as given, busy or not.
      expect(await localResourcePort(port, true, [], isPortListening)).toBe(port);
    } finally {
      await new Promise((resolve) => busy.close(resolve));
    }
  });
});
