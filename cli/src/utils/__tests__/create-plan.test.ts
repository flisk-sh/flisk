import { describe, expect, it } from "vitest";
import {
  asksBackend,
  asksExtras,
  asksFrontend,
  asksRuntime,
  buildCreatePlan,
  CREATE_DEFAULTS,
  CREATE_KINDS,
  CREATE_STACK,
  type CreateAnswers,
  describeAnswers,
  describeParts,
  describeRequirements,
  isTemplateKind,
  isValidProjectName,
  parseExtras,
  runsLocally,
} from "../create-plan.js";

function answers(patch: Partial<CreateAnswers> = {}): CreateAnswers {
  return { name: "shop", ...CREATE_DEFAULTS, runtime: "docker", ...patch };
}

const localAnswers = (patch: Partial<CreateAnswers> = {}) =>
  answers({ runtime: "local", ...patch });

const argsOf = (patch: Partial<CreateAnswers>) =>
  buildCreatePlan(answers(patch)).map((step) => step.args ?? []);

describe("the default is a local app", () => {
  it("web + local is the default answer set", () => {
    expect(CREATE_DEFAULTS).toMatchObject({ kind: "web", runtime: "local" });
  });

  it("a local web app is one step that writes a Vite + React project, and runs no command", () => {
    const steps = buildCreatePlan(localAnswers());
    expect(steps).toHaveLength(1);
    expect(steps[0]?.args).toBeUndefined();
    const paths = (steps[0]?.files ?? []).map((file) => file.path);
    expect(paths).toEqual(
      expect.arrayContaining([
        "package.json",
        "vite.config.ts",
        "index.html",
        "tsconfig.json",
        "src/main.tsx",
        "src/App.tsx",
        ".gitignore",
        "service.json",
        "README.md",
      ]),
    );
  });

  it("writes no Docker, Compose, Tilt or generated-file artifacts", () => {
    const paths = buildCreatePlan(localAnswers()).flatMap((s) =>
      (s.files ?? []).map((f) => f.path),
    );
    for (const path of paths) {
      expect(path).not.toMatch(/dockerfile|compose|tiltfile|autogenerated|\.flisk\//i);
    }
  });

  it("starts with npm and needs no infrastructure: service.json names an npm script", () => {
    const file = buildCreatePlan(localAnswers(), { api: 4000, web: 3456 })[0]?.files?.find(
      (f) => f.path === "service.json",
    );
    expect(file?.json).toMatchObject({
      appName: "shop",
      appType: "frontend",
      command: "npm run dev",
      port: 3456,
      schemaVersion: 1,
    });
    expect(file?.json).not.toHaveProperty("build");
    expect(file?.json).not.toHaveProperty("dependsOn");
  });

  it("the README tells the reader the exact commands and that no Docker is needed", () => {
    const readme = buildCreatePlan(localAnswers())[0]?.files?.find((f) => f.path === "README.md");
    expect(readme?.text).toContain("npm install");
    expect(readme?.text).toContain("npm run dev");
    expect(readme?.text).toContain("no Docker, no Tilt, no database");
    expect(readme?.text).toContain("flisk create --runtime docker");
  });

  it("a local API is a plain Node server with an npm script", () => {
    const steps = buildCreatePlan(localAnswers({ kind: "api" }), { api: 4321, web: 3000 });
    const paths = (steps[0]?.files ?? []).map((f) => f.path);
    expect(paths).toEqual(
      expect.arrayContaining(["package.json", "server.mjs", "service.json", "README.md"]),
    );
    expect(paths).not.toContain("vite.config.ts");
    const manifest = steps[0]?.files?.find((f) => f.path === "service.json")?.json;
    expect(manifest).toMatchObject({ appType: "backend", command: "node server.mjs", port: 4321 });
  });

  it("ignores framework and extras answers on the local route", () => {
    const withExtras = buildCreatePlan(
      localAnswers({ frontend: "vue", backend: "express", extras: ["queue", "redis"] }),
    );
    expect(withExtras).toEqual(buildCreatePlan(localAnswers()));
  });

  it("says it needs Node and npm only", () => {
    expect(describeRequirements(localAnswers())).toMatch(/Node\.js and npm only/);
    expect(describeRequirements(localAnswers())).toMatch(/No Docker, no Tilt, no database/);
  });
});

describe("the Docker route", () => {
  it("builds a website and an API from the defaults", () => {
    expect(argsOf({})).toEqual([
      ["project", "--yes"],
      [
        "resource",
        "shop-api",
        "--type",
        "backend",
        "--framework",
        "hono",
        "--stack",
        "app",
        "--yes",
      ],
      [
        "resource",
        "shop-web",
        "--type",
        "frontend",
        "--framework",
        "react",
        "--stack",
        "app",
        "--yes",
      ],
    ]);
  });

  it("leaves out the website when the person picks none", () => {
    const steps = argsOf({ frontend: "none" });
    expect(steps).toHaveLength(2);
    expect(steps.flat()).not.toContain("frontend");
  });

  it("an API kind never adds a website, whatever the frontend answer says", () => {
    const steps = argsOf({ kind: "api", frontend: "vue" });
    expect(steps.flat()).not.toContain("frontend");
    expect(steps.flat()).not.toContain("vue");
  });

  it("adds one resource per extra, with the right type and framework", () => {
    const steps = argsOf({ extras: ["queue", "redis", "worker", "mcp", "agent"] });
    const stepFor = (name: string) => steps.find((s) => s[1] === name);
    expect(stepFor("shop-queue")).toContain("nats");
    expect(stepFor("shop-queue")?.[3]).toBe("queue");
    expect(stepFor("shop-redis")?.slice(3, 6)).toEqual(["database", "--framework", "redis"]);
    expect(stepFor("shop-worker")?.[3]).toBe("worker");
    expect(stepFor("shop-tools")?.[3]).toBe("mcp");
    expect(stepFor("shop-agent")?.[3]).toBe("agent");
  });

  it("puts every generated resource in the same stack and never asks a question", () => {
    for (const step of argsOf({ extras: ["queue", "worker"] })) {
      if (step[0] !== "resource") continue;
      expect(step[step.indexOf("--stack") + 1]).toBe(CREATE_STACK);
      expect(step).toContain("--yes");
    }
  });

  it("says it needs Docker, Tilt and Bun", () => {
    expect(describeRequirements(answers())).toMatch(/Docker, Tilt and Bun/);
  });
});

describe("starter kinds", () => {
  it("a template kind is one project command into the named folder", () => {
    expect(argsOf({ kind: "saas" })).toEqual([["project", "saas", "--path", "shop", "--yes"]]);
    expect(argsOf({ kind: "agent" })).toEqual([
      ["project", "agent-stack", "--path", "shop", "--yes"],
    ]);
    expect(argsOf({ kind: "swarm" })).toEqual([["project", "swarm", "--path", "shop", "--yes"]]);
    expect(argsOf({ kind: "ecommerce" })).toEqual([
      ["project", "ecommerce", "--path", "shop", "--yes"],
    ]);
  });

  it("runs a template in the current folder and generated parts inside the project", () => {
    expect(buildCreatePlan(answers({ kind: "saas" })).every((s) => !s.inProject)).toBe(true);
    expect(buildCreatePlan(answers({ kind: "web" })).every((s) => s.inProject)).toBe(true);
  });

  it("every kind and runtime produces a non-empty plan", () => {
    for (const kind of CREATE_KINDS) {
      for (const runtime of ["local", "docker"] as const) {
        expect(buildCreatePlan(answers({ kind, runtime }))).not.toHaveLength(0);
      }
    }
  });

  it("only the swarm starter runs locally among the starters", () => {
    const local = CREATE_KINDS.filter(
      (kind) => isTemplateKind(kind) && runsLocally({ kind, runtime: "docker" }),
    );
    expect(local).toEqual(["swarm"]);
  });
});

describe("which questions a kind asks", () => {
  it("asks how to run it only for a web app and an API", () => {
    expect(CREATE_KINDS.filter(asksRuntime)).toEqual(["web", "api"]);
  });

  it("asks frameworks and extras only on the Docker route", () => {
    for (const kind of CREATE_KINDS) {
      expect(asksFrontend(kind, "local")).toBe(false);
      expect(asksBackend(kind, "local")).toBe(false);
      expect(asksExtras(kind, "local")).toBe(false);
    }
    expect(CREATE_KINDS.filter((kind) => asksFrontend(kind, "docker"))).toEqual(["web"]);
    expect(CREATE_KINDS.filter((kind) => asksBackend(kind, "docker"))).toEqual(["web", "api"]);
    expect(CREATE_KINDS.filter((kind) => asksExtras(kind, "docker"))).toEqual(["web", "api"]);
  });

  it("treats the four starters as templates", () => {
    expect(CREATE_KINDS.filter(isTemplateKind)).toEqual(["saas", "agent", "swarm", "ecommerce"]);
  });

  it("the summary lists only what the kind and route use", () => {
    expect(describeAnswers(answers({ kind: "saas" }))).toEqual(["name: shop", "kind: saas"]);
    expect(describeAnswers(localAnswers())).toEqual(["name: shop", "kind: web", "runtime: local"]);
    expect(describeAnswers(answers({ extras: ["queue"] }))).toContain("extras: queue");
  });

  it("describes the parts a plan creates", () => {
    expect(describeParts(localAnswers(), buildCreatePlan(localAnswers()))).toMatch(/Vite \+ React/);
    expect(describeParts(answers({ kind: "saas" }), [])).toBe("the saas starter");
    const docker = answers({ extras: ["queue"] });
    expect(describeParts(docker, buildCreatePlan(docker))).toBe("shop-api, shop-web, shop-queue");
  });
});

describe("isValidProjectName", () => {
  it.each(["app", "my-app", "shop2", "a-b-c"])("accepts %s", (name) => {
    expect(isValidProjectName(name)).toBe(true);
  });
  it.each(["", "My_App", "-app", "app-", "a--b", "2app", "has space", "x".repeat(49), "../evil"])(
    "rejects %j",
    (name) => {
      expect(isValidProjectName(name)).toBe(false);
    },
  );
});

describe("parseExtras", () => {
  it("parses a list, trims and drops repeats", () => {
    expect(parseExtras("queue, worker,queue")).toEqual({ extras: ["queue", "worker"] });
  });
  it("names the first unknown extra and the valid ones", () => {
    const result = parseExtras("queue,kafka");
    expect(result).toHaveProperty("error");
    expect((result as { error: string }).error).toContain('"kafka"');
    expect((result as { error: string }).error).toContain("queue, worker, mcp, agent, redis");
  });
});
