import type { SpawnSyncReturns } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
  collectSidecarDependents,
  composeProjectName,
  DEFAULT_MCP_CLI_TIMEOUT_MS,
  type DockerRunner,
  parseEnabledTiltResourceNames,
  RESTART_TIMEOUT_MS,
  resolveRestartCliTimeoutMs,
  resolveRestartSequenceCliTimeoutMs,
  restartContainer,
} from "../container-restart.js";
import { FliskError } from "../errors.js";

/** A project whose .flisk/project.json names the project, like a real Flisk project. */
function project(projectName?: string): string {
  const root = mkdtempSync(join(tmpdir(), "flisk-container-restart-"));
  mkdirSync(join(root, ".flisk"), { recursive: true });
  writeFileSync(
    join(root, ".flisk", "project.json"),
    JSON.stringify(projectName ? { project: { name: projectName } } : {}),
  );
  return root;
}

function dockerResult(extra: Partial<SpawnSyncReturns<string>> = {}): SpawnSyncReturns<string> {
  return {
    stdout: "",
    stderr: "",
    status: 0,
    pid: 1,
    output: [],
    signal: null,
    ...extra,
  } as SpawnSyncReturns<string>;
}

/** A runner that answers `docker ps` with the given ids and everything else with success. */
function runnerWithContainers(ids: string[], restart: Partial<SpawnSyncReturns<string>> = {}) {
  const run = vi.fn<DockerRunner>().mockImplementation((args) => {
    if (args[0] === "ps")
      return dockerResult({
        stdout: ids.join("\n") + (ids.length ? "\n" : ""),
      });
    return dockerResult(restart);
  });
  return run;
}

let roots: string[] = [];

beforeEach(() => {
  roots = [];
});

afterEach(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
  vi.restoreAllMocks();
});

describe("composeProjectName", () => {
  it("names the stack's Compose project as the engine does, lowercased", () => {
    const root = project("Flisk-Clean_76574");
    roots.push(root);
    expect(composeProjectName(root, "main")).toBe("flisk-clean_76574-main-autogenerated");
  });

  it("falls back to the engine's default when project.json is missing or unreadable", () => {
    const root = project();
    roots.push(root);
    expect(composeProjectName(root, "shop")).toBe("flisk-project-shop-autogenerated");

    const bare = mkdtempSync(join(tmpdir(), "flisk-container-restart-bare-"));
    roots.push(bare);
    expect(composeProjectName(bare, "shop")).toBe("flisk-project-shop-autogenerated");
  });
});

describe("restartContainer", () => {
  it("finds the labelled container and restarts it, with no build or tilt trigger", () => {
    const root = project("clean");
    roots.push(root);
    const run = runnerWithContainers(["cid-api-1"]);

    const result = restartContainer(root, "main", "api", run);

    expect(result).toEqual({ exitCode: 0, stdout: "", stderr: "" });
    expect(run).toHaveBeenCalledTimes(2);
    expect(run).toHaveBeenNthCalledWith(
      1,
      [
        "ps",
        "-a",
        "-q",
        "--filter",
        "label=com.docker.compose.project=clean-main-autogenerated",
        "--filter",
        "label=com.docker.compose.service=api",
        "--filter",
        "label=com.docker.compose.oneoff=False",
      ],
      { timeoutMs: RESTART_TIMEOUT_MS },
    );
    expect(run).toHaveBeenNthCalledWith(2, ["restart", "cid-api-1"], {
      timeoutMs: RESTART_TIMEOUT_MS,
    });
    const all = run.mock.calls.flatMap(([args]) => args);
    expect(all).not.toContain("build");
    expect(all).not.toContain("up");
    expect(all).not.toContain("trigger");
    expect(all).not.toContain("compose");
  });

  it("restarts a web/frontend resource the same way as a backend resource", () => {
    const root = project("clean");
    roots.push(root);
    const run = runnerWithContainers(["cid-web-1"]);

    restartContainer(root, "main", "web", run);

    expect(run).toHaveBeenNthCalledWith(
      1,
      [
        "ps",
        "-a",
        "-q",
        "--filter",
        "label=com.docker.compose.project=clean-main-autogenerated",
        "--filter",
        "label=com.docker.compose.service=web",
        "--filter",
        "label=com.docker.compose.oneoff=False",
      ],
      { timeoutMs: RESTART_TIMEOUT_MS },
    );
    expect(run).toHaveBeenNthCalledWith(2, ["restart", "cid-web-1"], {
      timeoutMs: RESTART_TIMEOUT_MS,
    });
  });

  it("uses the resource's stack so a resource in another stack is not touched", () => {
    const root = project("clean");
    roots.push(root);
    const run = runnerWithContainers(["cid"]);

    restartContainer(root, "admin", "api", run);

    expect(run).toHaveBeenNthCalledWith(
      1,
      [
        "ps",
        "-a",
        "-q",
        "--filter",
        "label=com.docker.compose.project=clean-admin-autogenerated",
        "--filter",
        "label=com.docker.compose.service=api",
        "--filter",
        "label=com.docker.compose.oneoff=False",
      ],
      { timeoutMs: RESTART_TIMEOUT_MS },
    );
  });

  it("restarts every container returned for the service label", () => {
    const root = project();
    roots.push(root);
    const run = runnerWithContainers(["cid-1", "cid-2"]);

    restartContainer(root, "main", "api", run);

    expect(run).toHaveBeenNthCalledWith(2, ["restart", "cid-1", "cid-2"], {
      timeoutMs: RESTART_TIMEOUT_MS,
    });
  });

  it("includes stopped containers (an exited one-shot worker is started again)", () => {
    const root = project();
    roots.push(root);
    const run = runnerWithContainers(["cid-exited"]);

    restartContainer(root, "main", "worker", run);

    expect(run.mock.calls[0]?.[0]).toContain("-a");
    expect(run).toHaveBeenNthCalledWith(2, ["restart", "cid-exited"], {
      timeoutMs: RESTART_TIMEOUT_MS,
    });
  });

  it("returns Docker's output on success", () => {
    const root = project();
    roots.push(root);
    const run = runnerWithContainers(["cid"], { stdout: "cid\n" });

    const result = restartContainer(root, "main", "api", run);

    expect(result.stdout).toBe("cid\n");
  });

  it("throws a FliskError with a start hint when no labelled container exists", () => {
    const root = project();
    roots.push(root);
    const run = runnerWithContainers([]);
    let error: unknown;
    try {
      restartContainer(root, "main", "api", run);
    } catch (err) {
      error = err;
    }

    expect(error).toBeInstanceOf(FliskError);
    expect((error as FliskError).message).toMatch(/No container for api/);
    expect((error as FliskError).suggestions).toContain("Start the stack first with: flisk up");
    expect(run).toHaveBeenCalledTimes(1);
  });

  it("throws a FliskError with Docker's message when the lookup fails", () => {
    const root = project();
    roots.push(root);
    const run = vi.fn<DockerRunner>().mockReturnValue(
      dockerResult({
        status: 1,
        stderr: "Cannot connect to the Docker daemon",
      }),
    );

    expect(() => restartContainer(root, "main", "api", run)).toThrow(
      /Could not find containers for api: Cannot connect to the Docker daemon/,
    );
    expect(run).toHaveBeenCalledTimes(1);
  });

  it("throws a FliskError with Docker's message when the restart fails", () => {
    const root = project();
    roots.push(root);
    const run = vi
      .fn<DockerRunner>()
      .mockImplementation((args) =>
        args[0] === "ps"
          ? dockerResult({ stdout: "cid\n" })
          : dockerResult({ status: 1, stderr: "permission denied" }),
      );

    expect(() => restartContainer(root, "main", "api", run)).toThrow(
      /Could not restart api: permission denied/,
    );
  });

  it("falls back to stdout and then a generic message when both streams are empty", () => {
    const root = project();
    roots.push(root);
    const fromStdout = vi
      .fn<DockerRunner>()
      .mockImplementation((args) =>
        args[0] === "ps"
          ? dockerResult({ stdout: "cid\n" })
          : dockerResult({ status: 1, stdout: "restart error on stdout" }),
      );
    expect(() => restartContainer(root, "main", "api", fromStdout)).toThrow(
      /Could not restart api: restart error on stdout/,
    );

    const silent = vi
      .fn<DockerRunner>()
      .mockImplementation((args) =>
        args[0] === "ps" ? dockerResult({ stdout: "cid\n" }) : dockerResult({ status: 1 }),
      );
    expect(() => restartContainer(root, "main", "api", silent)).toThrow(/docker exited 1/);
  });

  it("throws a FliskError when docker cannot be spawned", () => {
    const root = project();
    roots.push(root);
    const run = vi.fn<DockerRunner>().mockReturnValue(
      dockerResult({
        error: Object.assign(new Error("spawn docker ENOENT"), {
          code: "ENOENT",
        }),
        status: null,
      }),
    );

    expect(() => restartContainer(root, "main", "api", run)).toThrow(
      /Could not find containers for api: spawn docker ENOENT/,
    );
  });

  it("has a bounded timeout so a stuck Docker call cannot hang the command", () => {
    expect(RESTART_TIMEOUT_MS).toBeGreaterThan(0);
    expect(RESTART_TIMEOUT_MS).toBeLessThanOrEqual(120_000);
  });

  it("keeps container lookup bounded and extends restart timeout from stopGracePeriod", () => {
    const root = project();
    roots.push(root);
    const run = runnerWithContainers(["cid"]);

    restartContainer(root, "main", "worker", run, { stopGracePeriod: "1m30s" });

    expect(run).toHaveBeenNthCalledWith(
      1,
      [
        "ps",
        "-a",
        "-q",
        "--filter",
        "label=com.docker.compose.project=flisk-project-main-autogenerated",
        "--filter",
        "label=com.docker.compose.service=worker",
        "--filter",
        "label=com.docker.compose.oneoff=False",
      ],
      { timeoutMs: RESTART_TIMEOUT_MS },
    );
    expect(run).toHaveBeenNthCalledWith(2, ["restart", "cid"], {
      timeoutMs: 140_000,
    });
  });

  it("computes the MCP CLI timeout above Tilt probe, lookup, and configured stopGracePeriod", () => {
    expect(resolveRestartCliTimeoutMs()).toBeGreaterThanOrEqual(DEFAULT_MCP_CLI_TIMEOUT_MS);
    expect(resolveRestartCliTimeoutMs()).toBe(140_000);
    expect(resolveRestartCliTimeoutMs("3m")).toBe(310_000);
  });

  it("collects nested sidecarOf containers in host-before-sidecar order and sums MCP timeouts", () => {
    const sidecars = collectSidecarDependents(
      [
        {
          name: "tubehaus",
          path: "/p/t",
          configPath: "/p/t/service.json",
          stack: "tube",
          config: { appType: "bring-your-own" },
        } as never,
        {
          name: "nested",
          path: "/p/n",
          configPath: "/p/n/service.json",
          stack: "tube",
          config: {
            appType: "bring-your-own",
            sidecarOf: "bgutil",
            container: { stopGracePeriod: "2m" },
          },
        } as never,
        {
          name: "bgutil",
          path: "/p/b",
          configPath: "/p/b/service.json",
          stack: "tube",
          config: { appType: "bring-your-own", sidecarOf: "tubehaus" },
        } as never,
      ],
      "tubehaus",
    );
    expect(sidecars.map((r) => r.name)).toEqual(["bgutil", "nested"]);
    expect(resolveRestartSequenceCliTimeoutMs([undefined, undefined, "2m"])).toBe(490_000);
  });

  it("extracts enabled resource names from tilt uiresources JSON while excluding Disabled items", () => {
    expect(parseEnabledTiltResourceNames("")).toBeNull();
    expect(parseEnabledTiltResourceNames("NAME")).toBeNull();
    expect(
      parseEnabledTiltResourceNames(
        JSON.stringify({
          items: [
            { metadata: { name: "tubehaus" } },
            { metadata: { name: "bgutil" }, status: { disableStatus: { state: "Enabled" } } },
            {
              metadata: { name: "bgutil-helper" },
              status: { disableStatus: { state: "Disabled" } },
            },
          ],
        }),
      ),
    ).toEqual(new Set(["tubehaus", "bgutil"]));
  });
});
