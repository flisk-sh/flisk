import { describe, expect, it } from "vitest";
import {
  belongsToProject,
  type ContainerState,
  checkCrashLoopingContainers,
  crashLoopHint,
  type DockerRun,
  isCrashLooping,
} from "../doctor-crashloop.js";

const NOW = Date.parse("2026-10-16T12:00:00Z");
const state = (over: Partial<ContainerState>): ContainerState => ({
  name: "c",
  restartCount: 0,
  status: "running",
  startedAt: "2026-10-16T11:59:00Z",
  exitCode: 0,
  ...over,
});

describe("belongsToProject", () => {
  it("matches the project's compose projects in either spelling, not a prefix-sharing project", () => {
    expect(belongsToProject("it_ai_search_database", "it-ai-search")).toBe(true);
    expect(belongsToProject("it-ai-search-people-autogenerated", "it-ai-search")).toBe(true);
    expect(belongsToProject("it_ai_search", "it-ai-search")).toBe(true);
    expect(belongsToProject("it_ai_searching_x", "it-ai-search")).toBe(false);
    expect(belongsToProject("umami_backend", "it-ai-search")).toBe(false);
  });
});

describe("isCrashLooping", () => {
  it("flags a restarting container and a recent loop, not old history", () => {
    expect(isCrashLooping(state({ status: "restarting" }), NOW)).toBe(true);
    expect(isCrashLooping(state({ restartCount: 2932 }), NOW)).toBe(true);
    expect(
      isCrashLooping(
        state({
          restartCount: 6,
          status: "exited",
          exitCode: 1,
          finishedAt: "2026-10-16T11:58:00Z",
        }),
        NOW,
      ),
    ).toBe(true);
    // Stopped long ago, or cleanly: old history, not a loop.
    expect(
      isCrashLooping(
        state({
          restartCount: 2932,
          status: "exited",
          exitCode: 1,
          finishedAt: "2026-09-01T00:00:00Z",
        }),
        NOW,
      ),
    ).toBe(false);
    expect(
      isCrashLooping(
        state({
          restartCount: 6,
          status: "exited",
          exitCode: 0,
          finishedAt: "2026-10-16T11:58:00Z",
        }),
        NOW,
      ),
    ).toBe(false);
    expect(isCrashLooping(state({ restartCount: 4 }), NOW)).toBe(false);
    expect(isCrashLooping(state({ restartCount: 9, startedAt: "2026-10-10T00:00:00Z" }), NOW)).toBe(
      false,
    );
  });
});

describe("crashLoopHint", () => {
  it("names a missing database", () => {
    expect(crashLoopHint('error: database "umami_umami" does not exist', state({}))).toContain(
      'database "umami_umami"',
    );
  });
  it("hints at a missing module, an unreachable dependency and OOM", () => {
    expect(crashLoopHint("Error: Cannot find module 'x'", state({}))).toContain("module");
    expect(crashLoopHint("connect ECONNREFUSED 10.0.0.2:5432", state({}))).toContain("dependency");
    expect(crashLoopHint("", state({ exitCode: 137 }))).toContain("memory");
  });
  it("hints at a missing environment variable only when the logs say so", () => {
    expect(crashLoopHint("Error: DATABASE_URL is not set", state({}))).toContain(
      "environment variable",
    );
    expect(crashLoopHint("environment variable JWT_SECRET missing", state({}))).toContain(
      "environment variable",
    );
    // A Node crash that merely mentions undefined and env is not a missing variable.
    expect(
      crashLoopHint("TypeError: Cannot read properties of undefined (reading 'env')", state({})),
    ).toBeNull();
  });
  it("gives no hint when the logs do not say", () => {
    expect(crashLoopHint("something odd", state({}))).toBeNull();
  });
});

function docker(map: Record<string, string | Error>): DockerRun {
  return async (args) => {
    const hit = map[args[0] ?? ""];
    if (hit instanceof Error) throw hit;
    if (hit === undefined) throw new Error(`unexpected ${args.join(" ")}`);
    return hit;
  };
}

describe("checkCrashLoopingContainers", () => {
  it("reports a project container restarted thousands of times with logs and a hint, redacting secrets", async () => {
    const result = await checkCrashLoopingContainers(
      "umami",
      ["s3cret"],
      docker({
        ps: "a1\tumami_backend\nb2\tother_backend\n",
        inspect: "/umami-app-1\t2932\trunning\t2026-10-16T11:59:00Z\t1\n",
        logs: 'password s3cret\nerror: database "umami_umami" does not exist\n',
      }),
      NOW,
    );
    expect(result.didPass).toBe(false);
    expect(result.message).toContain("umami-app-1: running, restarted 2932 times");
    expect(result.message).toContain('database "umami_umami" does not exist');
    expect(result.message).not.toContain("s3cret");
    expect(result.fix).toContain("database provisioning");
  });

  it("only inspects this project's containers", async () => {
    let inspected: string[] = [];
    const run: DockerRun = async (args) => {
      if (args[0] === "ps") return "a1\tumami_backend\nb2\tother_backend\n";
      inspected = args.slice(3);
      return "/x\t0\trunning\t2026-10-16T11:59:00Z\t0\n";
    };
    const result = await checkCrashLoopingContainers("umami", [], run, NOW);
    expect(inspected).toEqual(["a1"]);
    expect(result.didPass).toBe(true);
  });

  it("skips without Docker or without project containers", async () => {
    expect(
      (await checkCrashLoopingContainers("p", [], docker({ ps: new Error("x") }))).isSkipped,
    ).toBe(true);
    expect((await checkCrashLoopingContainers("p", [], docker({ ps: "" }))).isSkipped).toBe(true);
  });

  it("skips when a container disappears between ps and inspect", async () => {
    const result = await checkCrashLoopingContainers(
      "p",
      [],
      docker({ ps: "a\tp_x\n", inspect: new Error("No such object") }),
    );
    expect(result.isSkipped).toBe(true);
  });
});
