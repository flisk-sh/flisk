import { describe, expect, it } from "vitest";
import {
  extractProjectRootFromWorkingDir,
  findStaleProjects,
  isPathStale,
  parseSizeToBytes,
} from "../stale-projects.js";

describe("parseSizeToBytes", () => {
  it("parses plain byte and unit sizes", () => {
    expect(parseSizeToBytes("500B")).toBe(500);
    expect(parseSizeToBytes("10KB")).toBe(10 * 1024);
    expect(parseSizeToBytes("15.5MB")).toBe(15.5 * 1024 * 1024);
    expect(parseSizeToBytes("2GB")).toBe(2 * 1024 * 1024 * 1024);
    expect(parseSizeToBytes("0B")).toBe(0);
    expect(parseSizeToBytes("")).toBe(0);
  });

  it("prefers virtual container sizes when present", () => {
    expect(parseSizeToBytes("12MB (virtual 1.5GB)")).toBe(1.5 * 1024 * 1024 * 1024);
    expect(parseSizeToBytes("0B (virtual 500MB)")).toBe(500 * 1024 * 1024);
  });
});

describe("extractProjectRootFromWorkingDir", () => {
  it("extracts root from .flisk/.flisk-out directories", () => {
    expect(
      extractProjectRootFromWorkingDir("/Users/sunny/worktrees/agent-1/.flisk/.flisk-out"),
    ).toBe("/Users/sunny/worktrees/agent-1");
  });

  it("extracts root from service autogenerated directories", () => {
    expect(
      extractProjectRootFromWorkingDir(
        "/Users/sunny/worktrees/agent-1/services/web/.autogenerated",
      ),
    ).toBe("/Users/sunny/worktrees/agent-1");
  });

  it("returns plain path when not in an autogenerated subdirectory", () => {
    expect(extractProjectRootFromWorkingDir("/Users/sunny/projects/my-app")).toBe(
      "/Users/sunny/projects/my-app",
    );
  });
});

describe("isPathStale", () => {
  it("returns true when neither path nor project root exists", () => {
    const existing = new Set(["/existing/project"]);
    const checker = (p: string) => existing.has(p);

    expect(isPathStale("/deleted/project/.flisk/.flisk-out", checker)).toBe(true);
    expect(isPathStale("/existing/project/.flisk/.flisk-out", checker)).toBe(false);
  });
});

describe("findStaleProjects", () => {
  it("discovers stale projects whose directory is missing and groups resources", () => {
    const existingDirs = new Set(["/live/project"]);
    const pathChecker = (p: string) => existingDirs.has(p);

    const fakeDocker = (command: string, args: string[]) => {
      if (args[0] === "ps") {
        return [
          // Stale project container
          "c1\tstale-web-1\t10MB (virtual 100MB)\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          // Live project container (should be ignored)
          "c2\tlive-web-1\t5MB (virtual 50MB)\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
          // Stale project second container
          "c3\tstale-worker-1\t5MB (virtual 50MB)\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      if (args[0] === "volume") {
        return [
          "stale-proj_data\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          "live-proj_data\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      if (args[0] === "network") {
        return [
          "stale-proj_default\tstale-proj\t/deleted/worktree-1/.flisk/.flisk-out\t\t",
          "live-proj_default\tlive-proj\t/live/project/.flisk/.flisk-out\t\t",
        ].join("\n");
      }
      return "";
    };

    const report = findStaleProjects({
      commandRunner: fakeDocker,
      pathChecker,
    });

    expect(report.totalProjects).toBe(1);
    expect(report.staleProjects).toHaveLength(1);

    const proj = report.staleProjects[0];
    expect(proj.name).toBe("stale-proj");
    expect(proj.recordedPath).toBe("/deleted/worktree-1");
    expect(proj.containers).toEqual(["stale-web-1", "stale-worker-1"]);
    expect(proj.volumes).toEqual(["stale-proj_data"]);
    expect(proj.networks).toEqual(["stale-proj_default"]);
    expect(proj.containerCount).toBe(2);
    expect(proj.volumeCount).toBe(1);
    expect(proj.networkCount).toBe(1);
    expect(proj.estimatedSizeBytes).toBe(150 * 1024 * 1024);
    expect(proj.cleanupCommand).toBe("flisk down --purge");
  });

  it("returns an empty report when all projects are active", () => {
    const existingDirs = new Set(["/live/project"]);
    const fakeDocker = (command: string, args: string[]) => {
      if (args[0] === "ps") {
        return "c1\tlive-web-1\t10MB\tlive-proj\t/live/project/.flisk/.flisk-out\t\t";
      }
      return "";
    };

    const report = findStaleProjects({
      commandRunner: fakeDocker,
      pathChecker: (p) => existingDirs.has(p),
    });

    expect(report.totalProjects).toBe(0);
    expect(report.staleProjects).toEqual([]);
    expect(report.totalContainers).toBe(0);
  });

  it("handles docker errors gracefully without crashing", () => {
    const failingDocker = () => {
      throw new Error("Cannot connect to the Docker daemon");
    };

    const report = findStaleProjects({
      commandRunner: failingDocker,
    });

    expect(report.totalProjects).toBe(0);
    expect(report.staleProjects).toEqual([]);
  });
});
