import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  type DockerRun,
  findForeignContainerOwners,
  findOtherRecordedFolders,
  purgeOwnerRefusal,
  upOwnerRefusal,
} from "../project-owner.js";
import type { ProjectRecord } from "../project-registry.js";

let base: string;

beforeEach(() => {
  base = realpathSync(mkdtempSync(join(tmpdir(), "flisk-owner-")));
});

afterEach(() => {
  rmSync(base, { recursive: true, force: true });
});

/** Creates `<base>/<folder>` as a Flisk project named `name`. */
function project(folder: string, name: string): string {
  const root = join(base, folder);
  mkdirSync(join(root, ".flisk"), { recursive: true });
  writeFileSync(join(root, ".flisk", "project.json"), JSON.stringify({ project: { name } }));
  return root;
}

/** A fake `docker ps -a` that prints one `name<TAB>composeProject<TAB>workingDir` line per container. */
function psOutput(containers: [string, string, string][]): DockerRun {
  return () => containers.map((row) => row.join("\t")).join("\n");
}

describe("findForeignContainerOwners", () => {
  it("names the other folder whose containers carry this project's Compose names (#3961)", () => {
    const a = project("a/shop", "shop");
    const b = project("b/shop", "shop");
    const docker = psOutput([
      [
        "shop_postgres",
        "shop-database-management",
        join(a, "services", "platform", "database-management"),
      ],
      ["shop_traefik", "shop-traefik", join(a, ".flisk", ".flisk-out")],
      ["shop-main-autogenerated-api-1", "shop-main-autogenerated", join(a, "services", "main")],
    ]);

    const owners = findForeignContainerOwners("shop", ["main"], b, docker);

    expect(owners).toEqual([
      {
        root: a,
        containers: ["shop_postgres", "shop_traefik", "shop-main-autogenerated-api-1"],
      },
    ]);
  });

  it("finds nothing when the containers belong to this folder", () => {
    const a = project("a/shop", "shop");
    const docker = psOutput([
      [
        "shop_postgres",
        "shop-database-management",
        join(a, "services", "platform", "database-management"),
      ],
    ]);

    expect(findForeignContainerOwners("shop", ["main"], a, docker)).toEqual([]);
  });

  it("treats the same folder reached through a symlink as this folder", () => {
    const a = project("a/shop", "shop");
    const docker = psOutput([["shop_traefik", "shop-traefik", join(a, ".flisk", ".flisk-out")]]);

    expect(findForeignContainerOwners("shop", [], join(a, ".", "services", ".."), docker)).toEqual(
      [],
    );
  });

  it("ignores a folder that is gone, so a leftover of a deleted project can be replaced", () => {
    const b = project("b/shop", "shop");
    const docker = psOutput([
      ["shop_postgres", "shop-database-management", join(base, "deleted", "shop", "services")],
    ]);

    expect(findForeignContainerOwners("shop", [], b, docker)).toEqual([]);
  });

  it("ignores a folder that now holds a project with another name", () => {
    const a = project("a/shop", "renamed");
    const b = project("b/shop", "shop");
    const docker = psOutput([["shop_traefik", "shop-traefik", join(a, ".flisk", ".flisk-out")]]);

    expect(findForeignContainerOwners("shop", [], b, docker)).toEqual([]);
  });

  it("ignores containers of other Compose projects and containers without a folder label", () => {
    const a = project("a/shop", "shop");
    const b = project("b/shop", "shop");
    const docker = psOutput([
      ["shop-admin_postgres", "shop-admin-database-management", join(a, "services")],
      ["unlabelled", "shop-traefik", ""],
      ["other-stack", "shop-billing-autogenerated", join(a, "services")],
    ]);

    expect(findForeignContainerOwners("shop", ["main"], b, docker)).toEqual([]);
  });

  it("finds nothing when Docker cannot be read", () => {
    const b = project("b/shop", "shop");
    const docker: DockerRun = () => {
      throw new Error("Cannot connect to the Docker daemon");
    };

    expect(findForeignContainerOwners("shop", [], b, docker)).toEqual([]);
  });
});

describe("findOtherRecordedFolders", () => {
  const record = (name: string, roots: string[]): ProjectRecord => ({
    name,
    roots,
    stacks: [],
    updatedAt: "",
  });

  it("lists the other recorded folders that still hold the project", () => {
    const a = project("a/shop", "shop");
    const b = project("b/shop", "shop");

    expect(findOtherRecordedFolders("shop", b, () => [record("shop", [a, b])])).toEqual([a]);
  });

  it("skips folders that are deleted or renamed, and records of other names", () => {
    const a = project("a/shop", "renamed");
    const b = project("b/shop", "shop");
    const gone = join(base, "gone", "shop");

    expect(
      findOtherRecordedFolders("shop", b, () => [record("shop", [a, gone, b]), record("x", [a])]),
    ).toEqual([]);
  });

  it("finds nothing when the project has no record", () => {
    const b = project("b/shop", "shop");

    expect(findOtherRecordedFolders("shop", b, () => [])).toEqual([]);
  });
});

describe("refusal messages", () => {
  it("up names the folder, the containers and both ways out", () => {
    const refusal = upOwnerRefusal("shop", [{ root: "/a/shop", containers: ["shop_postgres"] }]);

    expect(refusal?.message).toContain('"shop"');
    expect(refusal?.message).toContain("/a/shop");
    expect(refusal?.message).toContain("shop_postgres");
    expect(refusal?.suggestions.join("\n")).toContain("project.name");
    expect(refusal?.suggestions.join("\n")).toContain("cd /a/shop && flisk down");
  });

  it("up has nothing to say without another owner", () => {
    expect(upOwnerRefusal("shop", [])).toBeUndefined();
  });

  it("purge says nothing was removed and lists each folder once", () => {
    const refusal = purgeOwnerRefusal(
      "shop",
      [{ root: "/a/shop", containers: ["shop_postgres"] }],
      ["/a/shop", "/c/shop"],
    );

    expect(refusal?.message).toContain("Nothing was removed.");
    expect(refusal?.message.match(/\/a\/shop/g)).toHaveLength(1);
    expect(refusal?.message).toContain("/c/shop");
  });

  it("purge has nothing to say when no other folder uses the project", () => {
    expect(purgeOwnerRefusal("shop", [], [])).toBeUndefined();
  });
});
