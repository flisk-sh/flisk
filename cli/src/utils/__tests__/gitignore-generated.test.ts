import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { generateMasterConfigs } from "../../generator/template-engine.js";
import { ensureGeneratedRootIgnored, GENERATED_ROOT_BLOCK_START } from "../gitignore-generated.js";

const roots: string[] = [];
const GENERATED = "# SYSTEM-GENERATED BY Flisk CLI - DO NOT EDIT\n";

function git(root: string, ...args: string[]): void {
  execFileSync("git", ["-c", "user.email=t@example.com", "-c", "user.name=t", ...args], {
    cwd: root,
    stdio: "ignore",
  });
}

function write(root: string, path: string, content: string): void {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
}

/** A repository with what `flisk project` leaves in the root. */
function repo(options: { git?: boolean } = {}): string {
  const root = mkdtempSync(join(tmpdir(), "flisk-gitignore-generated-"));
  roots.push(root);
  if (options.git !== false) git(root, "init", "-q");
  write(
    root,
    ".flisk/project.json",
    JSON.stringify({ project: { name: "app" }, discovery: { paths: ["services/*/*"] } }),
  );
  write(
    root,
    "package.json",
    `${JSON.stringify(
      {
        name: "app",
        version: "1.0.0",
        private: true,
        type: "module",
        workspaces: ["services/*/*"],
      },
      null,
      2,
    )}\n`,
  );
  write(root, ".tiltignore", GENERATED);
  write(root, "shared-platform-engineering/docker-templates/a.sh", "#!/bin/sh\n");
  write(root, "services/platform/database-management/docker-compose.yml", GENERATED);
  write(root, "services/platform/messaging/docker-compose.yml", "services: {}\n");
  return root;
}

const gitignore = (root: string) => readFileSync(join(root, ".gitignore"), "utf-8");

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe("generated root files go into .gitignore (#3030)", () => {
  it("writes one marked block with the generated files, root-anchored", () => {
    const root = repo();
    write(root, ".gitignore", "node_modules/\n");
    const added = ensureGeneratedRootIgnored(root);
    expect(added).toEqual(
      expect.arrayContaining([
        "package.json",
        "bun.lock",
        ".tiltignore",
        "shared-platform-engineering/",
        "services/platform/database-management/docker-compose.yml",
      ]),
    );
    const text = gitignore(root);
    expect(text.startsWith("node_modules/\n")).toBe(true);
    expect(text).toContain(GENERATED_ROOT_BLOCK_START);
    expect(text).toContain("/package.json\n");
    expect(text).toContain("/shared-platform-engineering/\n");
    // The messaging compose file is the team's own: never ignored.
    expect(text).not.toContain("messaging");
    expect(
      execFileSync("git", ["status", "--short"], { cwd: root, encoding: "utf-8" }),
    ).not.toContain("package.json");
  });

  it("never ignores a path git tracks", () => {
    const root = repo();
    git(root, "add", "package.json", ".tiltignore");
    const added = ensureGeneratedRootIgnored(root);
    expect(added).not.toContain("package.json");
    expect(added).not.toContain(".tiltignore");
    expect(added).toContain("shared-platform-engineering/");
    expect(gitignore(root)).not.toContain("/package.json");
  });

  it("never ignores a package.json or .tiltignore the team wrote", () => {
    const root = repo();
    write(root, "package.json", JSON.stringify({ name: "app", dependencies: { left: "1.0.0" } }));
    write(root, ".tiltignore", "# ours\nnode_modules\n");
    const added = ensureGeneratedRootIgnored(root);
    expect(added).not.toContain("package.json");
    expect(added).not.toContain("bun.lock");
    expect(added).not.toContain(".tiltignore");
  });

  it("leaves an existing block alone, so a deleted line stays deleted", () => {
    const root = repo();
    ensureGeneratedRootIgnored(root);
    const edited = gitignore(root).replace("/shared-platform-engineering/\n", "");
    writeFileSync(join(root, ".gitignore"), edited);
    expect(ensureGeneratedRootIgnored(root)).toEqual([]);
    expect(gitignore(root)).toBe(edited);
  });

  it("writes nothing outside a git work tree", () => {
    const root = repo({ git: false });
    // The temp directory may itself sit in a repository; only assert when it does not.
    const added = ensureGeneratedRootIgnored(root);
    if (added.length === 0) expect(() => gitignore(root)).toThrow();
  });

  it("flisk config generation adds the block in a repository", async () => {
    const root = repo();
    rmSync(join(root, "package.json"));
    rmSync(join(root, ".flisk", "project.json"));
    write(
      root,
      ".flisk/project.json",
      JSON.stringify({
        version: "1.0.0",
        project: { name: "app", version: "1.0.0" },
        phases: {
          pre_alpha: { name: "a", description: "a", enabledStacks: [] },
          alpha: { name: "a", description: "a", enabledStacks: [] },
          beta: { name: "a", description: "a", enabledStacks: [] },
          out_of_scope: { name: "a", description: "a", enabledStacks: [] },
        },
        optional_infra: {
          monitoring: false,
          elk: false,
          debezium: false,
          golden_image: false,
          verdaccio: false,
        },
        discovery: { paths: ["services/*/*"] },
      }),
    );
    await generateMasterConfigs(root, { quiet: true });
    const text = gitignore(root);
    expect(text).toContain(GENERATED_ROOT_BLOCK_START);
    expect(text).toContain("/package.json\n");
    expect(text).toContain("/shared-platform-engineering/\n");
  });
});
