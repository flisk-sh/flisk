import { describe, expect, it, vi } from "vitest";
import {
  DOCKER_STATS_ARGS,
  PS_ARGS,
  sampleServiceUsage,
  type UsageCommandRunner,
} from "../service-usage.js";

function fakePs(output: string): UsageCommandRunner {
  const runner = vi.fn(async (command: string, args: string[]) => {
    expect(command).toBe("ps");
    expect(args).toEqual(PS_ARGS);
    return output;
  });
  return runner;
}

describe("sampleServiceUsage", () => {
  it("reports one process from its own process group", async () => {
    const runner = fakePs("  4242  20480  12.5\n");

    expect(
      await sampleServiceUsage([{ name: "api", pid: 4242 }], {
        platform: "linux",
        runner,
      }),
    ).toEqual({
      api: { cpuPercent: 12.5, rssBytes: 20480 * 1024, processes: 1 },
    });
    expect(runner).toHaveBeenCalledTimes(1);
  });

  it("sums child processes in the same group and ignores other groups", async () => {
    const runner = fakePs(" 4242 20480 10.0\n 4242 8192 2.5\n 9999 1024 99.0\n");

    expect(
      await sampleServiceUsage([{ name: "api", pid: 4242 }], {
        platform: "darwin",
        runner,
      }),
    ).toEqual({
      api: { cpuPercent: 12.5, rssBytes: (20480 + 8192) * 1024, processes: 2 },
    });
    expect(runner).toHaveBeenCalledTimes(1);
  });

  it("returns null for a stopped service whose group is absent from ps", async () => {
    const runner = fakePs(" 9999 1024 99.0\n");

    expect(
      await sampleServiceUsage([{ name: "api", pid: 4242 }], {
        platform: "linux",
        runner,
      }),
    ).toEqual({ api: null });
    expect(runner).toHaveBeenCalledTimes(1);
  });

  it("returns null for every service on Windows without spawning anything", async () => {
    const runner = vi.fn(() => {
      throw new Error("no process should be spawned on Windows");
    });

    expect(
      await sampleServiceUsage(
        [
          { name: "api", pid: 4242 },
          { name: "db", docker: true, service: "db" },
        ],
        { platform: "win32", runner },
      ),
    ).toEqual({ api: null, db: null });
    expect(runner).not.toHaveBeenCalled();
  });

  it("does not call any command when there are no targets", async () => {
    const runner = vi.fn();

    expect(await sampleServiceUsage([], { platform: "linux", runner })).toEqual({});
    expect(runner).not.toHaveBeenCalled();
  });

  it("leaves a local service null when ps fails", async () => {
    const runner = vi.fn(async () => {
      throw new Error("ps not found");
    });

    expect(
      await sampleServiceUsage([{ name: "api", pid: 4242 }], {
        platform: "linux",
        runner,
      }),
    ).toEqual({ api: null });
    expect(runner).toHaveBeenCalledTimes(1);
  });

  it("maps one docker stats call to each container's CPU, resident memory and PIDs", async () => {
    const runner = vi.fn(async (command: string, args: string[]) => {
      expect(command).toBe("docker");
      expect(args).toEqual(DOCKER_STATS_ARGS);
      return [
        "shop-autogenerated-orders-api-1\t12.5%\t42MiB / 1GiB\t3",
        "shop-autogenerated-orders-web-1\t1.25%\t10MiB / 1GiB\t1",
        "other-orders-api-1\t99%\t1GiB / 1GiB\t9",
        "shop-invoices-1\t0%\t1024kB / 1GiB\t",
      ].join("\n");
    });

    expect(
      await sampleServiceUsage(
        [
          {
            name: "orders-api",
            docker: true,
            service: "orders-api",
            composeProject: "shop-autogenerated",
          },
          {
            name: "orders-web",
            docker: true,
            service: "orders-web",
            composeProject: "shop-autogenerated",
          },
          { name: "invoices", docker: true, service: "invoices", composeProject: "shop" },
          { name: "missing", docker: true, service: "missing", composeProject: "shop" },
        ],
        { platform: "linux", runner },
      ),
    ).toEqual({
      "orders-api": { cpuPercent: 12.5, rssBytes: 42 * 1024 ** 2, processes: 3 },
      "orders-web": { cpuPercent: 1.3, rssBytes: 10 * 1024 ** 2, processes: 1 },
      invoices: { cpuPercent: 0, rssBytes: 1024 * 1000, processes: null },
      missing: null,
    });
    expect(runner).toHaveBeenCalledTimes(1);
  });

  it("matches a mixed native run's container by its recorded name", async () => {
    const runner = vi.fn(async () => "flisk-shop-postgres\t2.5%\t64MiB / 1GiB\t4\n");

    expect(
      await sampleServiceUsage([{ name: "postgres", container: "flisk-shop-postgres" }], {
        platform: "linux",
        runner,
      }),
    ).toEqual({ postgres: { cpuPercent: 2.5, rssBytes: 64 * 1024 ** 2, processes: 4 } });
    expect(runner).toHaveBeenCalledTimes(1);
  });
});
