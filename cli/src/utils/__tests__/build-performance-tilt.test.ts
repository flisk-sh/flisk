import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { evaluateStarlark, tiltAvailable } from "../../test-support/index.js";

// Behaviour of the Starlark planners that `flisk up` runs at Tiltfile load: the frontend build plan and the
// Tilt build concurrency. They run under Tilt's own Starlark interpreter, so these tests spawn Tilt.
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const framePlan = join(
  repoRoot,
  "engine/topologies/platform/docker/build/frontend_build_plan.star",
);
const concurrency = join(repoRoot, "engine/topologies/tilt/resources/build_concurrency.star");
const hasTilt = tiltAvailable();

/** Runs a Tiltfile body in a scratch project and returns the JSON value it wrote to `out.json`. */
function evaluate(file: string, body: string, files: Record<string, string> = {}): unknown {
  const result = evaluateStarlark(file, {
    args: `${body}\nlocal('cat > out.json', quiet = True, stdin = encode_json(RESULT))\n`,
    files,
  });
  if (result.status !== 0) throw new Error(`tilt failed: ${result.stderr || result.stdout}`);
  return JSON.parse(readFileSync(join(result.dir, "out.json"), "utf-8"));
}

const pkg = (scripts: Record<string, string>) => JSON.stringify({ name: "web", scripts });

describe.skipIf(!hasTilt)("frontend build plan", () => {
  const plan = (scripts: Record<string, string> | null) => {
    const files: Record<string, string> =
      scripts === null ? {} : { "web/package.json": pkg(scripts) };
    return evaluate(
      framePlan,
      `load(${JSON.stringify(framePlan)}, "frontend_build_plan")
RESULT = frontend_build_plan("web/package.json")`,
      files,
    ) as { build_cmd: string; typecheck: boolean; typecheck_cmd: string };
  };

  it("moves a non-emitting type-check out of the image and runs vite directly", () => {
    expect(plan({ build: "tsc --noEmit && vite build" })).toEqual({
      build_cmd: "bunx vite build",
      typecheck: true,
      typecheck_cmd: "bunx tsc --noEmit",
    });
  });

  it("keeps extra vite flags and a generated config the image copies", () => {
    const result = plan({
      build:
        "tsc --noEmit && vite build --mode production --config .autogenerated/vite.config.build.autogenerated.ts",
    });
    expect(result.build_cmd).toBe(
      "bunx vite build --mode production --config .autogenerated/vite.config.build.autogenerated.ts",
    );
    expect(result.typecheck).toBe(true);
  });

  it("keeps a plain emitting tsc in the image (its output may be used)", () => {
    expect(
      plan({
        build: "tsc && vite build --config .autogenerated/vite.config.build.autogenerated.ts",
      }),
    ).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
  });

  it("does not use a custom config the image does not copy", () => {
    expect(plan({ build: "tsc --noEmit && vite build --config vite.config.ts" }).typecheck).toBe(
      false,
    );
    expect(plan({ build: "tsc --noEmit && vite build --config=vite.config.ts" }).typecheck).toBe(
      false,
    );
  });

  it("leaves any other script unchanged", () => {
    expect(plan({ build: "vite build" }).typecheck).toBe(false);
    expect(plan({ build: "tsc --noEmit && vite build && node scripts/post.js" }).typecheck).toBe(
      false,
    );
    expect(plan({ build: "tsc -b && vite build" }).typecheck).toBe(false);
  });

  it("falls back to the default build when there is no build script or no package.json", () => {
    expect(plan({ start: "vite" })).toEqual({
      build_cmd: "bun run build",
      typecheck: false,
      typecheck_cmd: "",
    });
    expect(plan(null)).toEqual({ build_cmd: "bun run build", typecheck: false, typecheck_cmd: "" });
  });
});

describe.skipIf(!hasTilt)("Tilt build concurrency", () => {
  const max = (cpus: number, memoryBytes: number) =>
    evaluate(
      concurrency,
      `load(${JSON.stringify(concurrency)}, "compute_max_parallel_builds")
RESULT = compute_max_parallel_builds(${cpus}, ${memoryBytes})`,
    ) as number;
  const GIB = 1024 ** 3;

  it("reserves two CPUs and about 1.5 GiB per build, clamped to 3..8", () => {
    expect(max(8, Math.round(8.3 * GIB))).toBe(5); // memory allows 5
    expect(max(4, 16 * GIB)).toBe(3); // 2 CPUs left, clamped up to the minimum
    expect(max(32, 64 * GIB)).toBe(8); // plenty of room, clamped down to the maximum
    expect(max(12, 8 * GIB)).toBe(5); // memory is the limit
  });

  it("falls back to the minimum when the engine reports no CPUs or memory", () => {
    expect(max(0, 0)).toBe(3);
    expect(max(1, 64 * GIB)).toBe(3); // fewer CPUs than the reserve
    expect(max(32, GIB)).toBe(3); // less than one build's memory
  });

  it("rounds memory down to whole builds at the boundary", () => {
    expect(max(32, 6 * GIB)).toBe(4); // exactly four 1.5 GiB builds
    expect(max(32, 6 * GIB - 1)).toBe(3); // one byte short of four
    expect(max(10, 64 * GIB)).toBe(8); // CPUs give exactly the maximum
  });
});

describe("Tilt build concurrency wiring", () => {
  // The override and the engine-unavailable branches run only inside a live Tilt load (they call update_settings),
  // so these checks pin the source they depend on.
  const source = readFileSync(concurrency, "utf-8");

  it("reads TDK_MAX_PARALLEL_BUILDS first and accepts only a positive integer", () => {
    expect(source).toContain("os.environ.get('TDK_MAX_PARALLEL_BUILDS'");
    expect(source).toContain("_is_positive_int(override)");
  });

  it("keeps Tilt's default and says why when docker info cannot be read", () => {
    expect(source).toContain("if resources == None:");
    expect(source).toContain("Tilt default (docker info unavailable");
  });

  it("calls update_settings exactly once", () => {
    expect(source.match(/update_settings\(/g)).toHaveLength(1);
  });
});
