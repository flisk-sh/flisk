import { mkdirSync, mkdtempSync, rmSync, symlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, normalize } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  assertFliskGeneratedPath,
  FLISK_GENERATED_PATH_ALLOWLIST,
  isFliskGeneratedPath,
} from "../generated-paths.js";

describe("Flisk generated-file allowlist", () => {
  let tempRoot = "";

  afterEach(() => {
    if (tempRoot) {
      rmSync(tempRoot, { recursive: true, force: true });
      tempRoot = "";
    }
  });

  describe("FLISK_GENERATED_PATH_ALLOWLIST constant", () => {
    it("exports the frozen allowlist patterns", () => {
      expect(FLISK_GENERATED_PATH_ALLOWLIST).toBeDefined();
      expect(Array.isArray(FLISK_GENERATED_PATH_ALLOWLIST)).toBe(true);
      expect(FLISK_GENERATED_PATH_ALLOWLIST.length).toBeGreaterThan(0);
      expect(FLISK_GENERATED_PATH_ALLOWLIST).toContain("Tiltfile");
      expect(FLISK_GENERATED_PATH_ALLOWLIST).toContain("TILT_*.star");
    });
  });

  describe("isFliskGeneratedPath", () => {
    it("allows owned generated directories and project Tilt files", () => {
      const allowedPaths = [
        "services/shop/api/.autogenerated/Dockerfile.app.autogenerated",
        ".autogenerated/config.json",
        "nested/sub/.autogenerated/manifest.yaml",
        ".flisk/.flisk-out/Tiltfile",
        ".flisk/.flisk-out/sub/deep/output.star",
        "Tiltfile",
        "TILT_RESOURCE.star",
        "TILT_01_backend.star",
        "TILT_infrastructure_shared.star",
        ".tiltignore",
        "package.json",
        "shared-platform-engineering/docker-templates",
        "shared-platform-engineering/docker-templates/install-deps.sh",
        "shared-platform-engineering/docker-templates/node/Dockerfile",
        "services/platform/database-management/docker-compose.yml",
        "product_autogenerated_resource_manifests/manifest.json",
        "product_autogenerated_resource_manifests/deep/resource.star",
        "product_autogenerated_services_list/services.json",
        "product_autogenerated_services_list/sub/list.json",
      ];

      for (const path of allowedPaths) {
        expect(isFliskGeneratedPath(path)).toBe(true);
      }
    });

    it.runIf(process.platform === "win32")("handles Windows backslash paths correctly", () => {
      expect(
        isFliskGeneratedPath("services\\shop\\api\\.autogenerated\\Dockerfile.app.autogenerated"),
      ).toBe(true);
      expect(isFliskGeneratedPath(".flisk\\.flisk-out\\Tiltfile")).toBe(true);
      expect(
        isFliskGeneratedPath("shared-platform-engineering\\docker-templates\\install-deps.sh"),
      ).toBe(true);
      expect(
        isFliskGeneratedPath("services\\platform\\database-management\\docker-compose.yml"),
      ).toBe(true);
    });

    it("rejects project source and path traversal", () => {
      expect(isFliskGeneratedPath("services/shop/api/src/index.ts")).toBe(false);
      expect(isFliskGeneratedPath("../src/index.ts")).toBe(false);
      expect(isFliskGeneratedPath("..")).toBe(false);
      expect(isFliskGeneratedPath("../..")).toBe(false);
      expect(isFliskGeneratedPath("/tmp/project/.autogenerated/file.ts")).toBe(false);
      if (process.platform === "win32") {
        expect(isFliskGeneratedPath("C:/project/.autogenerated/file.ts")).toBe(false);
      }
    });

    it("rejects non-matching TILT files and non-allowlisted filenames", () => {
      expect(isFliskGeneratedPath("TILT_file.txt")).toBe(false);
      expect(isFliskGeneratedPath("TILT_sub/nested.star")).toBe(false);
      expect(isFliskGeneratedPath("prefix_TILT_file.star")).toBe(false);
      expect(isFliskGeneratedPath("Tiltfile.bak")).toBe(false);
      expect(isFliskGeneratedPath("docker-compose.yml")).toBe(false);
      expect(isFliskGeneratedPath("services/shop/service.json")).toBe(false);
      expect(isFliskGeneratedPath(".flisk/project.json")).toBe(false);
      expect(isFliskGeneratedPath("node_modules/pkg/index.js")).toBe(false);
    });
  });

  describe("assertFliskGeneratedPath", () => {
    it("resolves an allowed path under the project root and rejects an unowned destination", () => {
      const projectRoot = "/tmp/project";
      expect(assertFliskGeneratedPath(projectRoot, ".autogenerated/file.ts")).toBe(
        normalize(`${projectRoot}/.autogenerated/file.ts`),
      );
      expect(assertFliskGeneratedPath(projectRoot, "Tiltfile")).toBe(
        normalize(`${projectRoot}/Tiltfile`),
      );
      expect(assertFliskGeneratedPath(projectRoot, ".flisk/.flisk-out/out.star")).toBe(
        normalize(`${projectRoot}/.flisk/.flisk-out/out.star`),
      );
      expect(() => assertFliskGeneratedPath(projectRoot, "src/index.ts")).toThrow(
        /outside Flisk's generated-file allowlist/,
      );
      expect(() => assertFliskGeneratedPath(projectRoot, "services/shop/service.json")).toThrow(
        /outside Flisk's generated-file allowlist/,
      );
    });

    it("accepts an absolute path that is inside project root and allowlisted", () => {
      const projectRoot = "/tmp/project";
      const absPath = normalize(`${projectRoot}/.autogenerated/file.ts`);
      expect(assertFliskGeneratedPath(projectRoot, absPath)).toBe(absPath);
    });

    it("rejects path traversal attempting to escape project root", () => {
      const projectRoot = "/tmp/project";
      expect(() => assertFliskGeneratedPath(projectRoot, "../outside/file.ts")).toThrow(
        /outside Flisk's generated-file allowlist/,
      );
      expect(() =>
        assertFliskGeneratedPath(projectRoot, "services/../../outside/.autogenerated/file.ts"),
      ).toThrow(/outside Flisk's generated-file allowlist/);
    });

    it("rejects an allowlisted path that traverses a project symlink", (ctx) => {
      tempRoot = mkdtempSync(join(tmpdir(), "flisk-generated-path-"));
      const outside = mkdtempSync(join(tmpdir(), "flisk-generated-outside-"));
      mkdirSync(join(tempRoot, "services"), { recursive: true });

      try {
        try {
          symlinkSync(outside, join(tempRoot, "services", "shop"), "junction");
        } catch (err: unknown) {
          const code = (err as NodeJS.ErrnoException).code;
          if (code === "EPERM" || code === "EACCES" || code === "ENOTSUP") {
            ctx.skip(`symlink creation is not permitted on ${process.platform} (${code})`);
            return;
          }
          throw err;
        }

        expect(() =>
          assertFliskGeneratedPath(tempRoot, "services/shop/api/.autogenerated/Dockerfile.app"),
        ).toThrow(/symbolic link/);
      } finally {
        rmSync(join(tempRoot, "services", "shop"), { force: true });
        rmSync(outside, { recursive: true, force: true });
      }
    });
  });
});
