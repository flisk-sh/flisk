# Native Windows equivalent of check-lib-publish.sh. Not run on a real Windows machine yet.
# Exit code: 0 = rebuild needed, 1 = sources unchanged, skip.
param([Parameter(Mandatory = $true)][string]$LibPath, [string]$Registry = 'http://localhost:4873')

$ErrorActionPreference = 'Continue'
$WorkspaceRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
if ([IO.Path]::IsPathRooted($LibPath)) { $LibAbs = $LibPath } else { $LibAbs = Join-Path $WorkspaceRoot $LibPath }
$CacheDir = Join-Path $LibAbs '.tilt-cache'
New-Item -ItemType Directory -Force -Path $CacheDir | Out-Null

$PackageJson = Join-Path $LibAbs 'package.json'
if (-not (Test-Path -LiteralPath $PackageJson -PathType Leaf)) {
  Write-Output ('package.json not found at ' + $PackageJson)
  exit 0
}
$pkg = Get-Content -LiteralPath $PackageJson -Raw | ConvertFrom-Json
$PackageName = $pkg.name
$PackageVersion = $pkg.version

function Get-SourceHash([string]$lib) {
  $ts = Join-Path $lib '.autogenerated\tsconfig.autogenerated.json'
  if (-not (Test-Path -LiteralPath $ts -PathType Leaf)) { $ts = Join-Path $lib 'tsconfig.json' }
  $files = @()
  $src = Join-Path $lib 'src'
  if (Test-Path -LiteralPath $src) { $files += Get-ChildItem -LiteralPath $src -Recurse -File | ForEach-Object { $_.FullName } }
  $files += (Join-Path $lib 'package.json')
  $files += $ts
  $sha = [Security.Cryptography.SHA256]::Create()
  $ms = New-Object IO.MemoryStream
  foreach ($f in ($files | Sort-Object { $_ -replace '\\', '/' })) {
    if (Test-Path -LiteralPath $f -PathType Leaf) { $b = [IO.File]::ReadAllBytes($f); $ms.Write($b, 0, $b.Length) }
  }
  return (($sha.ComputeHash($ms.ToArray()) | ForEach-Object { $_.ToString('x2') }) -join '')
}

$HashFile = Join-Path $CacheDir 'source-hash.txt'
$Current = Get-SourceHash $LibAbs
if (Test-Path -LiteralPath $HashFile -PathType Leaf) {
  $Cached = (Get-Content -LiteralPath $HashFile -Raw).Trim()
  if ($Current -eq $Cached) {
    Write-Output ($PackageName + '@' + $PackageVersion + ' sources unchanged (hash match) - skipping build')
    exit 1
  }
  Write-Output ($PackageName + '@' + $PackageVersion + ' sources changed - rebuilding')
} else {
  Write-Output ($PackageName + '@' + $PackageVersion + ' no cached hash found - initial build')
}
Write-Output ('Building ' + $PackageName + '@' + $PackageVersion + '...')
exit 0
