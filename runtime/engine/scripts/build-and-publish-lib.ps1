# Native Windows equivalent of build-and-publish-lib.sh. Not run on a real Windows machine yet.
# The source hash is hashed over file bytes sorted by path, like the shell version, but both
# versions keep their own cache file content (do not share .tilt-cache between hosts).
param(
  [Parameter(Mandatory = $true)][string]$LibPath,
  [string]$Registry = 'http://localhost:4873',
  [Parameter(Mandatory = $true)][string]$PackageName,
  [string]$ConsumerPaths = ''
)

$ErrorActionPreference = 'Continue'
$ScriptDir = $PSScriptRoot
$WorkspaceRoot = (Resolve-Path (Join-Path $ScriptDir '..\..')).Path
if ([IO.Path]::IsPathRooted($LibPath)) { $LibAbs = $LibPath } else { $LibAbs = Join-Path $WorkspaceRoot $LibPath }
$CacheDir = Join-Path $LibAbs '.tilt-cache'

& (Join-Path $ScriptDir 'check-lib-publish.ps1') -LibPath $LibAbs -Registry $Registry
if ($LASTEXITCODE -ne 0) { exit 0 }

Set-Location -LiteralPath $LibAbs

function Test-Registry([string]$url) {
  try { Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 -Uri ($url.TrimEnd('/') + '/-/ping') | Out-Null; return $true } catch { return $false }
}
function Get-Npmrc([string]$registry) {
  $c = @()
  if ($registry -like '*host.docker.internal*') { $c += 'autogenerated\.npmrc.docker.autogenerated'; $c += '.npmrc.docker' }
  $c += 'autogenerated\.npmrc.autogenerated'; $c += '.npmrc'; $c += '.npmrc.docker'
  foreach ($rel in $c) { $p = Join-Path $LibAbs $rel; if (Test-Path -LiteralPath $p -PathType Leaf) { return $p } }
  return ''
}
function Invoke-BunInstall([string]$npmrc, [string]$registry) {
  $env:npm_config_registry = $registry
  if ($PackageName -like '@*/*') { Set-Item -Path ('Env:npm_config_' + $PackageName.Split('/')[0] + ':registry') -Value $registry }
  if ($npmrc) { $env:NPM_CONFIG_USERCONFIG = $npmrc } else { Remove-Item Env:NPM_CONFIG_USERCONFIG -ErrorAction SilentlyContinue }
  $code = 1
  for ($attempt = 1; $attempt -le 3; $attempt++) {
    bun install
    $code = $LASTEXITCODE
    if ($code -eq 0) { return 0 }
    if ($attempt -lt 3) { Write-Output ('bun install failed (attempt ' + $attempt + '/3), retrying...'); Start-Sleep -Seconds ($attempt * 2) }
  }
  return $code
}

$Effective = $Registry.TrimEnd('/')
if (-not (Test-Registry $Effective)) {
  foreach ($fb in @('http://localhost:4873', 'http://verdaccio.localhost:4873')) {
    if (Test-Registry $fb) { Write-Output ('Registry ' + $Effective + ' is unreachable, falling back to ' + $fb); $Effective = $fb; break }
  }
}

Write-Output 'Installing dependencies...'
$code = Invoke-BunInstall (Get-Npmrc $Effective) $Effective
if ($code -ne 0) {
  $retry = ''
  foreach ($fb in @('http://localhost:4873', 'http://verdaccio.localhost:4873', 'https://registry.npmjs.org')) {
    if (($fb -ne $Effective) -and (Test-Registry $fb)) { $retry = $fb; break }
  }
  if (-not $retry) { exit $code }
  Write-Output ('bun install failed, retrying with fallback registry ' + $retry)
  $code = Invoke-BunInstall (Get-Npmrc $retry) $retry
  $Effective = $retry
  if ($code -ne 0) { exit $code }
}

Write-Output 'Building package...'
$pkgText = Get-Content -LiteralPath (Join-Path $LibAbs 'package.json') -Raw
if ($pkgText -match '"build":') {
  bun run build
} elseif (Test-Path -LiteralPath '.autogenerated/tsconfig.autogenerated.json') {
  bunx tsc -p .autogenerated/tsconfig.autogenerated.json --declaration --declarationMap --rootDir src --outDir dist
} else {
  bunx tsc -p tsconfig.json --declaration --declarationMap --rootDir src --outDir dist
}
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Output 'Linking package...'
bun link
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Output 'Publishing to registry...'
$env:npm_config_registry = $Effective
if ($PackageName -like '@*/*') { Set-Item -Path ('Env:npm_config_' + $PackageName.Split('/')[0] + ':registry') -Value $Effective }
npm unpublish --force --registry $Effective *> $null
npm publish --registry $Effective --fetch-retries=1 --fetch-timeout=10000 --fetch-retry-mintimeout=1000 --fetch-retry-maxtimeout=5000
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

# Mark the successful build: reuse the hash function of the check script by running it in a child scope.
New-Item -ItemType Directory -Force -Path $CacheDir | Out-Null
$hashScript = {
  param($lib)
  $ts = Join-Path $lib '.autogenerated\tsconfig.autogenerated.json'
  if (-not (Test-Path -LiteralPath $ts -PathType Leaf)) { $ts = Join-Path $lib 'tsconfig.json' }
  $files = @()
  $src = Join-Path $lib 'src'
  if (Test-Path -LiteralPath $src) { $files += Get-ChildItem -LiteralPath $src -Recurse -File | ForEach-Object { $_.FullName } }
  $files += (Join-Path $lib 'package.json'); $files += $ts
  $ms = New-Object IO.MemoryStream
  foreach ($f in ($files | Sort-Object { $_ -replace '\\', '/' })) { if (Test-Path -LiteralPath $f -PathType Leaf) { $b = [IO.File]::ReadAllBytes($f); $ms.Write($b, 0, $b.Length) } }
  (([Security.Cryptography.SHA256]::Create().ComputeHash($ms.ToArray()) | ForEach-Object { $_.ToString('x2') }) -join '')
}
[IO.File]::WriteAllText((Join-Path $CacheDir 'source-hash.txt'), ((& $hashScript $LibAbs) + "`n"), (New-Object Text.UTF8Encoding($false)))

if ($ConsumerPaths) {
  foreach ($consumer in ($ConsumerPaths -split ',')) {
    if ($consumer) {
      Write-Output ('Linking to consumer: ' + $consumer)
      Push-Location -LiteralPath (Join-Path $WorkspaceRoot $consumer)
      bun link $PackageName
      Pop-Location
    }
  }
}
Write-Output ($PackageName + ' build and publish complete')
exit 0
