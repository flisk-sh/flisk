// Pure helpers of the shop benchmark runner: contract loading and validation, the W1-W7 file scan and the report.
import fs from "node:fs";
import path from "node:path";

export const DEFAULT_PATHS = {
  products: "/api/products",
  orders: "/api/orders",
  payments: "/api/payments",
  notifications: "/api/notifications",
  storefront: "/",
  admin: "/admin/",
};

// Wiring heuristics. A contract can replace the two tool specific ones under `wiring`.
const DEFAULT_WIRING = {
  // files that are the hand-written run/infra config of the tool, as globs relative to the work folder (W7)
  configFiles: [],
  // W4: lines that make a service wait for the database or queue
  waitsOnHealthy:
    "service_healthy|service_completed_successfully|dependsOn|resource_deps|depends_on",
  // W5: health checks declared in the config files
  healthChecks: "healthcheck|healthCheckPath|HEALTHCHECK|healthCheck",
};

const TEXT_EXT =
  /\.(ts|js|mjs|json|ya?ml|toml|sql|html|conf|md|sh|star)$|(^|\/)(Dockerfile|Tiltfile)[^/]*$/;
const SKIP_DIR = new Set([
  "node_modules",
  ".git",
  ".flisk",
  ".flisk-out",
  ".autogenerated",
  ".agents",
  ".claude",
  "dist",
]);

export function loadCompetitors(benchDir) {
  const dir = path.join(benchDir, "competitors");
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const id of fs.readdirSync(dir).sort()) {
    const file = path.join(dir, id, "bench.json");
    if (!fs.existsSync(file)) continue;
    const c = JSON.parse(fs.readFileSync(file, "utf8"));
    out.push({
      ...c,
      id: c.id ?? id,
      dir: path.join(dir, id),
      folder: id,
      paths: { ...DEFAULT_PATHS, ...(c.paths ?? {}) },
      wiring: { ...DEFAULT_WIRING, ...(c.wiring ?? {}) },
    });
  }
  return out;
}

export function validateContract(c) {
  const errs = [];
  if (!/^[a-z0-9][a-z0-9-]*$/.test(c.id)) errs.push(`id "${c.id}" must be kebab-case`);
  if (c.id !== c.folder) errs.push(`id "${c.id}" must equal its folder name "${c.folder}"`);
  if (!c.name) errs.push("name is required");
  for (const k of ["start", "stop", "base"])
    if (typeof c[k] !== "string" || !c[k]) errs.push(`${k} is required (a string)`);
  if (!Array.isArray(c.health) || c.health.length === 0)
    errs.push("health must list at least one URL");
  else
    for (const h of c.health)
      if (!/^https?:\/\//.test(h)) errs.push(`health URL must start with http: ${h}`);
  if (c.requires && !Array.isArray(c.requires))
    errs.push("requires must be an array of command names");
  return errs;
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIR.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (TEXT_EXT.test(p) && fs.statSync(p).size < 512 * 1024) out.push(p);
  }
  return out;
}

export function globToRegex(g) {
  // Placeholders (NUL, which a glob never holds) keep the single-`*` step from rewriting the output of the `**` steps.
  const re = g
    .replace(/[.+^${}()|[\]\\]/g, "\\$&")
    .replace(/\*\*\//g, "\0A")
    .replace(/\*\*/g, "\0B")
    .replace(/\*/g, "[^/]*")
    .replaceAll("\0A", "(?:.*/)?")
    .replaceAll("\0B", ".*");
  // The glob comes from a bench.json in this repository (reviewed in the pull request that adds it), and every regex
  // metacharacter except `*` is escaped above, so this is not attacker input.
  return new RegExp(`^${re}$`); // nosemgrep: javascript.lang.security.audit.detect-non-literal-regexp.detect-non-literal-regexp
}

const count = (text, re) => (text.match(re) ?? []).length;

/**
 * W1-W7 read from files. The shared shop code is scanned once for every tool (it is the same code), the tool's own folder
 * (after setup, so generated project files count) for everything the tool adds. Counts, not verdicts.
 */
export function scanWiring(workDir, benchDir, c) {
  const shopDir = path.join(benchDir, "shop");
  const shop = walk(shopDir).map((f) => ({
    f,
    rel: path.relative(shopDir, f),
    text: fs.readFileSync(f, "utf8"),
    shared: true,
  }));
  const own = walk(workDir).map((f) => ({
    f,
    rel: path.relative(workDir, f),
    text: fs.readFileSync(f, "utf8"),
    shared: false,
  }));
  const all = [...shop, ...own].filter((x) => x.rel !== "bench.json");
  const w = c.wiring;
  const isWeb = (x) =>
    /(^|\/)(storefront|admin|web)\//.test(x.rel) && /\.(html|js|ts|mjs)$/.test(x.rel);
  const isMigrationPath = (x) => /migrat|\.sql$|(^|\/)db\//i.test(x.rel);
  const isServiceCode = (x) =>
    /\.(ts|js|mjs)$/.test(x.rel) &&
    /(^|\/)(catalog|orders|payments|notifications|fulfilment|[a-z-]+-api)\//.test(x.rel) &&
    !/test/.test(x.rel);
  const configRes = (w.configFiles ?? []).map(globToRegex);
  const config = own.filter((x) => configRes.some((r) => r.test(x.rel)));
  return {
    // W1: web code calls an API at a hardcoded host:port
    W1: all
      .filter(isWeb)
      .reduce(
        (n, x) => n + count(x.text, /https?:\/\/(?:localhost|127\.0\.0\.1|[a-z][\w-]*):\d+/g),
        0,
      ),
    // W2: a migration runs from a service's own start-up (outside the migrator and the migration files)
    W2: all
      .filter((x) => isServiceCode(x) && !isMigrationPath(x))
      .reduce(
        (n, x) =>
          n +
          count(x.text, /CREATE TABLE|schema_migrations|prisma migrate|drizzle-kit|migrate\(/gi),
        0,
      ),
    // W3: secret literals in project files (userinfo passwords and password/secret/token assignments, not ${...} or $VAR)
    W3: own
      .filter(
        (x) =>
          /\.(ya?ml|json|toml|conf|sh|star|ts|js)$|Dockerfile|Tiltfile/.test(x.rel) &&
          !/package\.json$/.test(x.rel),
      )
      .reduce(
        (n, x) =>
          n +
          count(x.text, /:\/\/[\w.-]+:(?![${])[^@\s$"'{}]+@/g) +
          count(
            x.text,
            /(?:password|secret|token|api_?key)["']?\s*[:=]\s*["']?(?![${<]|["']?\s*$)[A-Za-z0-9_.-]{3,}/gi,
          ),
        0,
      ),
    // W4: start order waits for the database and queue (lines)
    W4: config.reduce((n, x) => n + count(x.text, new RegExp(w.waitsOnHealthy, "g")), 0), // nosemgrep: javascript.lang.security.audit.detect-non-literal-regexp.detect-non-literal-regexp -- pattern from a reviewed bench.json
    // W5: health checks declared
    W5: config.reduce((n, x) => n + count(x.text, new RegExp(w.healthChecks, "gi")), 0), // nosemgrep: javascript.lang.security.audit.detect-non-literal-regexp.detect-non-literal-regexp -- pattern from a reviewed bench.json
    // W6: service-to-service URLs hardcoded in service code instead of injected
    W6: all
      .filter(isServiceCode)
      .reduce(
        (n, x) =>
          n +
          count(
            x.text.replace(/process\.env\.[A-Z_]+/g, ""),
            /["'`]https?:\/\/(?!localhost:\d+\/?["'`])[a-z][\w-]*(?::\d+)?/g,
          ),
        0,
      ),
    // W7: lines of run/infra config written (or generated and kept) in the tool's own files
    W7: config.reduce(
      (n, x) => n + x.text.split("\n").filter((l) => l.trim() && !l.trim().startsWith("#")).length,
      0,
    ),
    configFilesFound: config.map((x) => x.rel),
  };
}

const fmt = (v, unit = " s") => (v === null || v === undefined ? "–" : `${v}${unit}`);
const mark = (b) => (b === undefined ? "–" : b ? "✅" : "❌");

export function renderReport(doc) {
  const r = doc.runner;
  const L = [];
  L.push("## Shop benchmark (scripted, informational)", "");
  L.push(
    `> **Informational, not a gate.** One scripted run per tool, no LLM agent. Numbers come from a ${r.ci ? "CI runner" : "local machine"} (${r.os} ${r.arch}, ${r.cpus} CPUs, ${r.memGB} GB, Docker ${r.docker || "?"}) and are **not comparable** with the Colima Mac numbers in the agent bench doc (\`docs/benchmarks/agent-build-bench-2026-11-10.md\`). Image caches are whatever the machine had, so "first start" is a first start of this project, not always a cold cache. Commit \`${(doc.commit ?? "").slice(0, 10) || "?"}\`, ${doc.startedAt}.`,
    "",
  );
  L.push("### Timings", "");
  L.push(
    "| Tool | Version | Result | First start to healthy | Order to shipped | Stop | Restart to healthy |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const x of doc.results) {
    const p = x.phases;
    L.push(
      `| ${x.name} | ${x.version ?? "–"} | ${x.status === "ok" ? "✅ pass" : x.status === "skipped" ? "⏭️ skipped" : "❌ failed"} | ${fmt(p.firstStartSeconds)} | ${fmt(p.orderToShippedSeconds)} | ${fmt(p.stopSeconds)} | ${fmt(p.restartSeconds)} |`,
    );
  }
  L.push("", "### Outcome checks", "");
  L.push(
    "| Tool | Catalog | Order paid | Shipped | 1 payment | 1 notification | Web pages | Stop stops | Data kept |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const x of doc.results) {
    const c = x.checks;
    if (x.status === "skipped") continue;
    L.push(
      `| ${x.name} | ${mark(c.catalogLists)} | ${mark(c.orderPaid)} | ${mark(c.orderShipped)} | ${mark(c.onePayment)} | ${mark(c.oneNotification)} | ${mark(c.webPagesServed)} | ${mark(c.stopReallyStops)} | ${mark(c.dataKept)} |`,
    );
  }
  L.push("", "### Wiring (counts read from files)", "");
  L.push(
    "| Tool | W1 web→hardcoded host:port | W2 migration in API start | W3 secret literals | W4 start-order lines | W5 health checks | W6 hardcoded service URLs | W7 config lines |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  );
  for (const x of doc.results) {
    const w = x.wiring;
    if (!w) continue;
    L.push(`| ${x.name} | ${w.W1} | ${w.W2} | ${w.W3} | ${w.W4} | ${w.W5} | ${w.W6} | ${w.W7} |`);
  }
  L.push(
    "",
    "W4, W5 and W7 count the tool's own config files (`wiring.configFiles` in its `bench.json`), so they compare effort, not quality. The shop code is the same for every tool.",
  );
  const bad = doc.results.filter((x) => x.error);
  if (bad.length) {
    L.push("", "### Problems", "");
    for (const x of bad)
      L.push(
        `- **${x.name}** (${x.status}): ${[
          x.error.split("\n")[0],
          x.error.split("\n").filter(Boolean).pop(),
        ]
          .filter((v, i, a) => a.indexOf(v) === i)
          .join(" / ")
          .slice(0, 400)}`,
      );
  }
  L.push("");
  return L.join("\n");
}

/** Writes results.json and report.md. The runner calls it after every competitor, so a later hang keeps earlier results. */
export function writeResults(outDir, doc) {
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "results.json"), `${JSON.stringify(doc, null, 2)}\n`);
  fs.writeFileSync(path.join(outDir, "report.md"), renderReport(doc));
}
