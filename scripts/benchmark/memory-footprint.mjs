// Idle memory of a running Flisk stack (#2873): every container whose Compose project belongs to the project (its name,
// then "-"), sampled with `docker stats`, split into infrastructure (Postgres, Traefik, NATS, ...) and app services.
// Start the stack with the profiles to measure first (`flisk up`, or `flisk up --profile admin`), let it settle, then:
//
//   node scripts/benchmark/memory-footprint.mjs --project flisk-restaurant-example --profile default
//   node scripts/benchmark/memory-footprint.mjs --project shop --profile admin --samples 5 --interval 10
//
// It prints a table and writes docs/benchmarks/results/memory-footprint-<project>-<profile>-<date>.json (or --output).
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** "107.4MiB / 7.737GiB" -> bytes of the first figure. */
export function parseMemUsage(text) {
	const match = /^\s*([\d.]+)\s*([KMGT]?i?B)/i.exec(String(text));
	if (!match) return 0;
	const units = { B: 1, KB: 1e3, MB: 1e6, GB: 1e9, TB: 1e12, KIB: 1024, MIB: 1024 ** 2, GIB: 1024 ** 3, TIB: 1024 ** 4 };
	return Math.round(Number(match[1]) * (units[match[2].toUpperCase()] ?? 1));
}

/** Infrastructure is every Compose project of the stack that is not an app stack (`<project>-<stack>-autogenerated`). */
export function roleOf(composeProject) {
	return composeProject.endsWith("-autogenerated") ? "app" : "infra";
}

/** Containers of the project: [{ name, composeProject }]. */
export function projectContainers(project, ps = (args) => execFileSync("docker", args, { encoding: "utf-8" })) {
	const prefix = `${project.toLowerCase()}-`;
	return ps(["ps", "--format", '{{.Names}}\t{{.Label "com.docker.compose.project"}}'])
		.split("\n")
		.map((line) => line.split("\t"))
		.filter(([name, composeProject]) => name && composeProject && composeProject.startsWith(prefix))
		.map(([name, composeProject]) => ({ name, composeProject }));
}

function sample(names) {
	const out = execFileSync("docker", ["stats", "--no-stream", "--format", "{{json .}}", ...names], {
		encoding: "utf-8",
	});
	const usage = new Map();
	for (const line of out.split("\n").filter(Boolean)) {
		const row = JSON.parse(line);
		usage.set(row.Name, parseMemUsage(row.MemUsage));
	}
	return usage;
}

const mib = (bytes) => Math.round((bytes / 1024 ** 2) * 10) / 10;

export function summarize(containers, samples) {
	const median = (values) => {
		const sorted = [...values].sort((a, b) => a - b);
		return sorted[Math.floor(sorted.length / 2)] ?? 0;
	};
	const rows = containers.map(({ name, composeProject }) => ({
		name,
		role: roleOf(composeProject),
		memoryMiB: mib(median(samples.map((s) => s.get(name) ?? 0))),
	}));
	const total = (role) => Math.round(rows.filter((r) => !role || r.role === role).reduce((n, r) => n + r.memoryMiB, 0) * 10) / 10;
	return { containers: rows, infraMiB: total("infra"), appMiB: total("app"), totalMiB: total() };
}

async function main() {
	const args = process.argv.slice(2);
	const value = (flag, fallback) => {
		const i = args.indexOf(flag);
		return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
	};
	const project = value("--project");
	if (!project) {
		console.error("usage: memory-footprint.mjs --project <name> [--profile <label>] [--samples 3] [--interval 5] [--output <file>]");
		process.exit(2);
	}
	const profile = value("--profile", "default");
	const samplesWanted = Number(value("--samples", "3"));
	const intervalMs = Number(value("--interval", "5")) * 1000;
	const containers = projectContainers(project);
	if (containers.length === 0) {
		console.error(`No running containers for project "${project}". Start it with flisk up first.`);
		process.exit(1);
	}
	const samples = [];
	for (let i = 0; i < samplesWanted; i++) {
		if (i > 0) await new Promise((resolve) => setTimeout(resolve, intervalMs));
		samples.push(sample(containers.map((c) => c.name)));
	}
	const summary = summarize(containers, samples);
	const [memTotal, cpus, engine, os] = execFileSync("docker", ["info", "--format", "{{.MemTotal}}\t{{.NCPU}}\t{{.ServerVersion}}\t{{.OperatingSystem}}"], { encoding: "utf-8" })
		.trim()
		.split("\t");
	const result = {
		project,
		profile,
		measuredAt: new Date().toISOString(),
		samples: samplesWanted,
		intervalSeconds: intervalMs / 1000,
		docker: { memoryMiB: mib(Number(memTotal)), cpus: Number(cpus), engine, os },
		...summary,
	};
	for (const row of summary.containers) console.log(`${row.role.padEnd(5)}  ${String(row.memoryMiB).padStart(8)} MiB  ${row.name}`);
	console.log(`infra ${summary.infraMiB} MiB, apps ${summary.appMiB} MiB, total ${summary.totalMiB} MiB (${containers.length} containers, Docker has ${result.docker.memoryMiB} MiB)`);
	const date = result.measuredAt.slice(0, 10);
	const output = value("--output", path.join(repoRoot, "docs/benchmarks/results", `memory-footprint-${project}-${profile}-${date}.json`));
	mkdirSync(path.dirname(output), { recursive: true });
	writeFileSync(output, `${JSON.stringify(result, null, "\t")}\n`);
	console.log(`wrote ${path.relative(repoRoot, output)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	await main();
}
