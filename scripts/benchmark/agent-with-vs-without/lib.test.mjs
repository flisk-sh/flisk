import assert from "node:assert/strict";
import { test } from "node:test";
import { classifyInfraFiles, isInfraFile, parseStream, sanitize } from "./lib.mjs";

const tool = (id, name, input) => JSON.stringify({ type: "assistant", message: { content: [{ type: "tool_use", id, name, input }] } });
const res = (id, isError) => JSON.stringify({ type: "user", message: { content: [{ type: "tool_result", tool_use_id: id, is_error: isError, content: "x" }] } });

const lines = [
	JSON.stringify({ type: "system", subtype: "init", model: "claude-test", tools: ["Bash"], skills: ["flisk-build"], cwd: "/r" }),
	tool("1", "Skill", { skill: "flisk-build" }),
	res("1", false),
	tool("2", "Write", { file_path: "/r/Dockerfile", content: "FROM node" }),
	res("2", false),
	tool("3", "Bash", { command: "cat > docker-compose.yml <<EOF\nservices: {}\nEOF\necho ok > /dev/null 2>&1" }),
	res("3", true),
	tool("4", "Edit", { file_path: "/r/src/index.ts", old_string: "a", new_string: "b" }),
	res("4", false),
	tool("5", "Bash", { command: "docker compose up -d" }),
	res("5", true),
	JSON.stringify({
		type: "result",
		is_error: false,
		num_turns: 7,
		total_cost_usd: 0.5,
		modelUsage: { "claude-test": { inputTokens: 10, outputTokens: 20, cacheReadInputTokens: 300, cacheCreationInputTokens: 40, costUSD: 0.5 } },
	}),
];

test("parseStream counts tool calls, errors, retries, tokens and skills", () => {
	const p = parseStream(lines);
	assert.equal(p.init.model, "claude-test");
	assert.equal(p.toolCalls, 5);
	assert.equal(p.toolErrors, 2);
	assert.equal(p.retriesAfterError, 1, "the last error was not followed by another tool call");
	assert.equal(p.tokens.total, 370);
	assert.deepEqual(p.skillsInvoked, ["flisk-build"]);
});

test("classifyInfraFiles keeps only infrastructure files the agent wrote", () => {
	const p = parseStream(lines);
	const infra = classifyInfraFiles(p.writtenFiles, "/r");
	assert.deepEqual(infra, [
		{ path: "Dockerfile", via: ["Write"] },
		{ path: "docker-compose.yml", via: ["Bash"] },
	]);
});

test("isInfraFile", () => {
	for (const f of ["Dockerfile", "api/Dockerfile.dev", "compose.yaml", "Tiltfile", ".env", "nginx.conf", "start-all.sh", "services/a/.autogenerated/x.ts", "services/a/service.json"])
		assert.ok(isInfraFile(f), f);
	for (const f of ["src/index.ts", "package.json", "README.md", "schema.sql"]) assert.ok(!isInfraFile(f), f);
});

test("sanitize replaces the run folder", () => {
	const out = sanitize([JSON.stringify({ type: "x", path: "/r/a" })], "/r");
	assert.match(out[0], /<run>\/a/);
});
