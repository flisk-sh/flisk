import { homedir } from "node:os";
import { basename, isAbsolute, join, relative } from "node:path";

// Files that set up how the app runs rather than what it does. A file counts when the agent wrote or edited it itself
// (Write, Edit, MultiEdit, or a shell redirect or tee); files a tool such as `flisk resource` generated do not count.
const INFRA_PATTERNS = [
	/^(Dockerfile|Containerfile)(\..+)?$/i,
	/\.dockerfile$/i,
	/^\.dockerignore$/,
	/^(docker-)?compose(\.[\w-]+)?\.ya?ml$/i,
	/^Tiltfile$/,
	/\.star$/,
	/^nginx.*\.conf$/i,
	/^Caddyfile$/,
	/^traefik.*\.(ya?ml|toml)$/i,
	/^\.env(\..+)?$/,
	/^Procfile/,
	/^Makefile$/,
	/^ecosystem\.config\.(c?js|json)$/,
	/^supervisord\.conf$/,
	/^service\.json$/,
	/^(start|stop|run|dev|up|down|setup|launch|serve)([-_.\w]*)?\.sh$/i,
	/\.k8s\.ya?ml$/i,
];

export function isInfraFile(path) {
	if (path.split("/").includes(".autogenerated")) return true;
	return INFRA_PATTERNS.some((re) => re.test(basename(path)));
}

const REDIRECT = /(?:^|[\s;&|(])(?:>>?|tee(?:\s+-a)?)\s*["']?([^\s"';&|<>()]+)/g;

function bashWrites(command) {
	const files = [];
	for (const m of command.matchAll(REDIRECT)) {
		const f = m[1];
		if (!f || f.startsWith("/dev/") || f === "&1" || f === "&2" || /^\d$/.test(f)) continue;
		files.push(f);
	}
	return files;
}

export function parseStream(lines) {
	let init = null;
	let result = null;
	const toolUses = [];
	const errors = [];
	const writtenFiles = [];
	const skillsInvoked = [];
	let order = 0;
	for (const line of lines) {
		let ev;
		try {
			ev = JSON.parse(line);
		} catch {
			continue;
		}
		if (ev.type === "system" && ev.subtype === "init") init = ev;
		else if (ev.type === "result") result = ev;
		const content = ev.message?.content;
		if (!Array.isArray(content)) continue;
		for (const block of content) {
			if (ev.type === "assistant" && block.type === "tool_use") {
				order++;
				toolUses.push({ order, name: block.name, id: block.id });
				const input = block.input ?? {};
				if (["Write", "Edit", "MultiEdit", "NotebookEdit"].includes(block.name) && input.file_path)
					writtenFiles.push({ path: input.file_path, via: block.name });
				if (block.name === "Bash" && typeof input.command === "string")
					for (const f of bashWrites(input.command)) writtenFiles.push({ path: f, via: "Bash" });
				if (block.name === "Skill" && input.skill) skillsInvoked.push(input.skill);
			}
			if (ev.type === "user" && block.type === "tool_result" && block.is_error) errors.push({ order, id: block.tool_use_id });
		}
	}
	const lastCall = toolUses.length ? toolUses[toolUses.length - 1].order : 0;
	const retriesAfterError = errors.filter((e) => e.order < lastCall).length;
	const tokens = { input: 0, output: 0, cacheRead: 0, cacheCreation: 0, total: 0, byModel: {} };
	for (const [model, u] of Object.entries(result?.modelUsage ?? {})) {
		const t = {
			input: u.inputTokens ?? 0,
			output: u.outputTokens ?? 0,
			cacheRead: u.cacheReadInputTokens ?? 0,
			cacheCreation: u.cacheCreationInputTokens ?? 0,
			costUsd: u.costUSD ?? null,
		};
		tokens.byModel[model] = t;
		tokens.input += t.input;
		tokens.output += t.output;
		tokens.cacheRead += t.cacheRead;
		tokens.cacheCreation += t.cacheCreation;
	}
	tokens.total = tokens.input + tokens.output + tokens.cacheRead + tokens.cacheCreation;
	return {
		init: init && {
			model: init.model,
			tools: init.tools,
			skills: init.skills ?? null,
			slashCommands: init.slash_commands ?? null,
			cwd: init.cwd,
		},
		result,
		tokens,
		toolCalls: toolUses.length,
		toolErrors: errors.length,
		retriesAfterError,
		writtenFiles,
		skillsInvoked: [...new Set(skillsInvoked)],
	};
}

export function classifyInfraFiles(writtenFiles, runDir) {
	const seen = new Map();
	for (const { path, via } of writtenFiles) {
		const abs = isAbsolute(path) ? path : join(runDir, path);
		const rel = relative(runDir, abs);
		if (rel.startsWith("..") || rel === "HEALTH_URLS.txt") continue;
		if (!isInfraFile(rel)) continue;
		if (!seen.has(rel)) seen.set(rel, new Set());
		seen.get(rel).add(via);
	}
	return [...seen.entries()].sort().map(([path, via]) => ({ path, via: [...via].sort() }));
}

// The committed transcript: every event, with the home directory and run folder replaced and long tool output cut.
export function sanitize(lines, runDir) {
	const home = homedir();
	const cut = (s, n) => (typeof s === "string" && s.length > n ? `${s.slice(0, n)}… [${s.length - n} more chars]` : s);
	return lines.map((line) => {
		let ev;
		try {
			ev = JSON.parse(line);
		} catch {
			return JSON.stringify({ unparsed: cut(line, 200) });
		}
		if (ev.type === "system" && ev.subtype === "init") {
			ev = { type: ev.type, subtype: ev.subtype, model: ev.model, tools: ev.tools, skills: ev.skills, cwd: ev.cwd };
		}
		const content = ev.message?.content;
		if (Array.isArray(content))
			for (const block of content) {
				if (block.type === "tool_result") {
					if (typeof block.content === "string") block.content = cut(block.content, 1500);
					else if (Array.isArray(block.content))
						block.content = block.content.map((c) => (c.type === "text" ? { ...c, text: cut(c.text, 1500) } : { type: c.type }));
				}
				if (block.type === "tool_use" && block.input) {
					for (const k of ["content", "new_string", "old_string"]) if (block.input[k]) block.input[k] = cut(block.input[k], 4000);
				}
				if (block.type === "thinking") block.thinking = cut(block.thinking, 2000);
			}
		return JSON.stringify(ev).replaceAll(runDir, "<run>").replaceAll(home, "~");
	});
}
