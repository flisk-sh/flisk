// Unit tests for the memory footprint script (#2873): unit parsing, roles, which containers belong to a project, medians.
import assert from "node:assert/strict";
import { test } from "node:test";
import { parseMemUsage, projectContainers, roleOf, summarize } from "./memory-footprint.mjs";

test("reads the used figure of docker stats MemUsage in any unit", () => {
	assert.equal(parseMemUsage("107.4MiB / 7.737GiB"), Math.round(107.4 * 1024 ** 2));
	assert.equal(parseMemUsage("1.5GiB / 8GiB"), Math.round(1.5 * 1024 ** 3));
	assert.equal(parseMemUsage("512KiB / 1GiB"), 512 * 1024);
	assert.equal(parseMemUsage("--"), 0);
});

test("app stacks are <project>-<stack>-autogenerated, everything else is infrastructure", () => {
	assert.equal(roleOf("shop-orders-autogenerated"), "app");
	assert.equal(roleOf("shop-database-management"), "infra");
	assert.equal(roleOf("shop-traefik"), "infra");
});

test("takes only the containers whose Compose project belongs to the project", () => {
	const ps = () =>
		[
			"shop-orders-autogenerated-api-1\tshop-orders-autogenerated",
			"shop_postgres\tshop-database-management",
			"shopify-web-1\tshopify-web",
			"other_postgres\tother-database-management",
			"loose-container\t",
		].join("\n");
	assert.deepEqual(projectContainers("Shop", ps), [
		{ name: "shop-orders-autogenerated-api-1", composeProject: "shop-orders-autogenerated" },
		{ name: "shop_postgres", composeProject: "shop-database-management" },
	]);
});

test("reports the median of the samples per container, and the infra, app and total sums", () => {
	const containers = [
		{ name: "api", composeProject: "shop-orders-autogenerated" },
		{ name: "db", composeProject: "shop-database-management" },
	];
	const MiB = 1024 ** 2;
	const samples = [
		new Map([["api", 10 * MiB], ["db", 100 * MiB]]),
		new Map([["api", 30 * MiB], ["db", 100 * MiB]]),
		new Map([["api", 20 * MiB], ["db", 102 * MiB]]),
	];
	assert.deepEqual(summarize(containers, samples), {
		containers: [
			{ name: "api", role: "app", memoryMiB: 20 },
			{ name: "db", role: "infra", memoryMiB: 100 },
		],
		infraMiB: 100,
		appMiB: 20,
		totalMiB: 120,
	});
});
