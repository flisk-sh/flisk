# End-to-end check for one bring-your-own template repository (flisk-sh/flisk-template-<id>, #1965): register the
# template in a throwaway Flisk project, run a real `flisk up`, and expect HTTP 200 on its healthCheckPath through Traefik.
# The template's own `verify` job only runs the image alone; this is the check that it works under Flisk.
# Needs Docker, Tilt and the `flisk` CLI. Uses unique names and random alternate ports, and removes only the containers,
# networks and images carrying its own project name (it never calls `flisk down`).
#
# Usage: scripts/e2e/verify-byo-template.sh <template-dir>      (the directory holding Dockerfile and service.json)
set -euo pipefail

src="$(cd "${1:?usage: verify-byo-template.sh <template-dir>}" && pwd)"
[ -f "$src/Dockerfile" ] || { echo "no Dockerfile in $src" >&2; exit 2; }
[ -f "$src/service.json" ] || { echo "no service.json in $src" >&2; exit 2; }
read -r id health < <(python3 -c 'import json,sys; m=json.load(open(sys.argv[1])); print(m["template"]["id"], m.get("healthCheckPath", "/"))' "$src/service.json")

base="tpl${id//[^a-z0-9]/}"
pid="$$"
proj="${base:0:$((24 - ${#pid}))}$pid"
work="$(mktemp -d)/$proj"
mkdir -p "$work"
http_port=$((30000 + RANDOM % 2000))
flisk() { command "${FLISK_BIN:-flisk}" "$@"; }

cleanup() {
  pkill -f "tilt up.*$proj" >/dev/null 2>&1 || true
  docker ps -aq --filter "name=$proj" | xargs -r docker rm -f >/dev/null 2>&1 || true
  docker network ls --format '{{.Name}}' | grep "^${proj}" | xargs -r docker network rm >/dev/null 2>&1 || true
  docker images --format '{{.Repository}}:{{.Tag}}' | grep -E "^${proj}(_|-l[0-9]+)" | xargs -r docker rmi -f >/dev/null 2>&1 || true
}
trap cleanup EXIT

cd "$work"
git init -q .
flisk project --yes >/dev/null
printf '\nTDK_HTTP_PORT=%s\nTDK_HTTPS_PORT=%s\nTDK_POSTGRES_PORT=%s\n' \
  "$http_port" "$((32000 + RANDOM % 2000))" "$((34000 + RANDOM % 2000))" >> .env
mkdir -p "services/app/$proj"
# Copy the image inputs only: the template's service.json names its own app and stack, and `flisk resource` writes this project's.
cp -R "$src/." "services/app/$proj/"
rm -rf "services/app/$proj/.git" "services/app/$proj/.github" "services/app/$proj/service.json" "services/app/$proj/README.md"
(cd "services/app/$proj" && flisk resource "$proj" --type bring-your-own --stack app \
  --register-existing --dockerfile ./Dockerfile --health-path "$health" --yes >/dev/null)
nohup "${FLISK_BIN:-flisk}" up app >"$work/up.log" 2>&1 &

url="http://127.0.0.1:$http_port/api/$proj$health"
status=000
for _ in $(seq 1 "${VERIFY_WAIT_SECONDS:-600}"); do
  status="$(curl -s -o /dev/null -m 3 -w '%{http_code}' -H "Host: api.$proj.localhost" "$url" || true)"
  [ "$status" = "200" ] && break
  sleep 1
done

if [ "$status" = "200" ]; then
  echo "PASS $id: through flisk up and Traefik, GET /api/$proj$health -> 200"
else
  echo "FAIL $id: GET /api/$proj$health -> $status" >&2
  tail -40 "$work/up.log" >&2 || true
  docker logs "${proj}-app-autogenerated-$proj-1" 2>&1 | tail -20 >&2 || true
  [ -n "${EVIDENCE_DIR:-}" ] && mkdir -p "$EVIDENCE_DIR" && cp "$work/up.log" "$EVIDENCE_DIR/" 2>/dev/null || true
  exit 1
fi
