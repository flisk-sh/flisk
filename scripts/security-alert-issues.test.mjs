test("a range says whether a version falls inside it", () => {
	assert.equal(versionInRange("21.14.6", "<= 21.14.6"), true);
	assert.equal(versionInRange("21.14.7", "<= 21.14.6"), false);
	assert.equal(versionInRange("7.3.6", ">= 7.0.0, < 7.3.7"), true);
	assert.equal(versionInRange("7.3.7", ">= 7.0.0, < 7.3.7"), false);
	assert.equal(versionInRange("1.2.3", "^1.2.0"), true);
	assert.equal(versionInRange("2.0.0", "^1.2.0"), false);
	assert.equal(versionInRange("1.2.9", "~1.2.0"), true);
	assert.equal(versionInRange("1.3.0", "~1.2.0"), false);
	assert.equal(versionInRange("1.2.3", "1.0.0 || 1.2.3"), true);
	assert.equal(versionInRange("1.2.3", "not a range"), null);
	assert.equal(parseVersionRange(""), null);
});

