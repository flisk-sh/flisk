// Renders docs/competitors/MATRIX.md from the competitor data: feature areas as rows, competitors as columns, and the
// quick-win bar for the missing rows. The file is generated; edit docs/competitors/<id>.json and run
//   node scripts/competitor-matrix.mjs            write MATRIX.md
//   node scripts/competitor-matrix.mjs --check    exit 1 when the committed MATRIX.md is stale
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MIN_EASE, MIN_ICE } from "./competitor-gap-issues.mjs";
import { counts, coverage, iceScore, loadAll, passesBar } from "./competitors/lib.mjs";

export const OUT = "docs/competitors/MATRIX.md";

// One cell: what Flisk has against the in-scope rows of an area. ✅ all covered, ◐ some covered or partial, ✗ none, — no in-scope row.
export function cell(rows) {
	const inScope = rows.filter((r) => r.flisk?.scope === "in");
	if (!inScope.length) return rows.length ? "— (out of scope)" : "—";
	const done = inScope.filter((r) => r.flisk.status === "covered").length;
	const part = inScope.filter((r) => r.flisk.status === "partial").length;
	const mark = done === inScope.length ? "✅" : done + part > 0 ? "◐" : "✗";
	return `${mark} ${done}/${inScope.length}`;
}

export function render(root) {
	const { index, competitors } = loadAll(root);
	const all = competitors.flatMap((c) => c.rows);
	const dates = (c) => {
		const d = c.rows.map((r) => r.checked).sort();
		return d.length ? (d[0] === d.at(-1) ? d[0] : `${d[0]} to ${d.at(-1)}`) : "-";
	};
	const L = [
		"# Competitor feature matrix",
		"",
		"<!-- Generated by scripts/competitor-matrix.mjs from docs/competitors/*.json. Do not edit; run the script. -->",
		"",
		"> This is the maintainers' reading of public pages on the `checked` dates below. It is not an endorsement, a ranking or a benchmark, and the products change: re-read the cited source before relying on a row. A row Flisk deliberately does not do is a decision (out of scope), not a gap.",
		"",
		"Each cell is `Flisk covers / rows Flisk could reasonably do` for that competitor and area: ✅ all covered, ◐ some covered or partial, ✗ none, — nothing in scope. The last column adds up all competitors. Format and how to add a competitor: [README.md](README.md).",
		"",
		`| Area | ${competitors.map((c) => c.name).join(" | ")} | All |`,
		`| --- | ${competitors.map(() => "---").join(" | ")} | --- |`,
	];
	for (const area of index.areas)
		L.push(`| ${area} | ${competitors.map((c) => cell(c.rows.filter((r) => r.area === area))).join(" | ")} | ${cell(all.filter((r) => r.area === area))} |`);
	L.push("", "## Per competitor", "", "| Competitor | Category | Coverage | Covered | Partial | Missing | Out of scope | Checked |", "| --- | --- | --- | --- | --- | --- | --- | --- |");
	for (const c of competitors) {
		const n = counts(c.rows);
		const cov = coverage(c.rows);
		L.push(`| [${c.name}](${c.url}) | ${c.category} | ${cov ? `${cov.value}%` : "-"} | ${n.covered} | ${n.partial} | ${n.missing} | ${n["out-of-scope"]} | ${dates(c)} |`);
	}
	L.push("", "Why each is here:", "");
	for (const c of competitors) L.push(`- **${c.name}**: ${c.why}`);
	const missing = competitors.flatMap((c) => c.rows.filter((r) => r.flisk?.scope === "in" && r.flisk?.status === "missing").map((row) => ({ c, row })));
	const bar = { minIce: MIN_ICE, minEase: MIN_EASE };
	const table = (items) => [
		"| Competitor | Feature | Area | I / C / E | ICE | Source |",
		"| --- | --- | --- | --- | --- | --- |",
		...items.map(({ c, row }) => `| ${c.name} | ${row.name ?? row.id} | ${row.area} | ${row.ice.impact} / ${row.ice.confidence} / ${row.ice.ease} | ${iceScore(row.ice)?.toFixed(1)} | [source](${row.source}) |`),
	];
	const raised = missing.filter(({ row }) => passesBar(row, bar));
	L.push("", `## Raised as issues (ICE ${MIN_ICE.toFixed(1)} or more and ease ${MIN_EASE} or more)`, "");
	L.push(...(raised.length ? table(raised) : ["None today."]));
	L.push("", `## Not raised: below the ICE bar (${missing.length - raised.length})`, "", "These gaps are real but score under the bar, so they stay in this report and never become issues. ICE is the mean of impact, confidence and ease (1 to 10).", "");
	L.push(...table(missing.filter(({ row }) => !passesBar(row, bar))));
	return `${L.join("\n")}\n`;
}

function main(argv, root) {
	const text = render(root);
	const file = path.join(root, OUT);
	if (argv.includes("--check")) {
		let current = "";
		try {
			current = readFileSync(file, "utf8");
		} catch {}
		if (current !== text) {
			console.error(`${OUT} is stale: run node scripts/competitor-matrix.mjs`);
			return 1;
		}
		return 0;
	}
	writeFileSync(file, text);
	return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	process.exitCode = main(process.argv.slice(2), path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."));
}
