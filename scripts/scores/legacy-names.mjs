export function measure({ root }, intentional = INTENTIONAL) {
	const findings = [];
	const used = new Set();
	let files = 0;
	for (const rel of walk(root, ".")) {
		if (SKIPPED.some((s) => s.re.test(rel))) continue;
		files++;
		read(root, rel)
			.split("\n")
			.forEach((text, i) => {
				if (text.length > MAX_LINE || !LEGACY.test(text)) return;
				const known = intentional.filter((e) => e.file === rel && e.line.test(text));
				if (known.length) {
					for (const e of known) used.add(e);
					return;
				}
				findings.push(`${rel}:${i + 1} ${text.trim().slice(0, 160)}`);
			});
	}
	for (const e of intentional.filter((x) => !used.has(x)))
		findings.push(`${e.file} ${e.line}: INTENTIONAL entry no longer matches a line; remove it`);
	return {
		value: findings.length,
		summary: `${files} files scanned, ${findings.length} leftover old names`,
		findings,
	};
}
