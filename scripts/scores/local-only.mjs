// Flisk is local-only by default (AGENTS.md: "Do not add Deployment or cluster manifest generators without an agreed
// export scope"). This gate reads the code that generates a project — cli/src (not tests), cli/templates and the
// Starlark engine under runtime/ — for anything that deploys to a cluster: a Kubernetes object kind or apiVersion in a
// generated manifest, Tilt's cluster functions (k8s_yaml, k8s_resource, k8s_custom_deploy, helm, kustomize) in
// Starlark code, and kubectl apply/create. Starlark docstrings and comments are prose and are not read; Markdown is
// docs. An agreed export would be listed in ALLOWED with its reason, and an entry that matches nothing is a finding.
import { isTestFile, read, walk } from "./lib.mjs";
import { codeOnly } from "./starlark-loads.mjs";

export const meta = {
	id: "local-only",
	title: "No cluster deployment generated by default",
	source: "files",
	mode: "gate",
	target: 0,
	better: "lower",
	unit: "violations",
};

// Agreed exceptions: { file, reason }. None today.
export const ALLOWED = [];

const KIND = /\bkind:\s*["']?(Deployment|StatefulSet|DaemonSet|ReplicaSet|CronJob|Ingress|HelmRelease|Kustomization)\b/;
const API_VERSION = /\bapiVersion:\s*["']?(apps\/v1|batch\/v1|networking\.k8s\.io\/|helm\.toolkit\.fluxcd\.io\/|kustomize\.)/;
const TILT_CLUSTER = /(?<![\w.])(k8s_yaml|k8s_resource|k8s_custom_deploy|helm|kustomize)\s*\(/;
const KUBECTL = /\bkubectl\s+(apply|create)\b/;

const isStarlark = (rel) => /\.star$/.test(rel) || /(^|\/)Tiltfile(\.hbs)?$/.test(rel);
const isGeneratorSource = (rel) =>
	!rel.endsWith(".md") && !isTestFile(rel) && !/(^|\/)(__tests__|tests|test-support)\//.test(rel);

// The violations in one file: { line, what }.
export function scan(rel, text) {
	const lines = (isStarlark(rel) ? codeOnly(text) : text).split("\n");
	const out = [];
	lines.forEach((line, i) => {
		const hit =
			KIND.exec(line)?.[0] ??
			API_VERSION.exec(line)?.[0] ??
			(isStarlark(rel) ? TILT_CLUSTER.exec(line)?.[0] : undefined) ??
			KUBECTL.exec(line)?.[0];
		if (hit) out.push({ line: i + 1, what: hit.trim() });
	});
	return out;
}

export function measure({ root }, allowed = ALLOWED) {
	const files = [
		...walk(root, "cli/src", isGeneratorSource),
		...walk(root, "cli/templates", isGeneratorSource),
		...walk(root, "runtime", isGeneratorSource),
	];
	const findings = [];
	const used = new Set();
	for (const rel of files) {
		const hits = scan(rel, read(root, rel));
		if (!hits.length) continue;
		const ok = allowed.find((a) => a.file === rel);
		if (ok) {
			used.add(ok);
			continue;
		}
		for (const { line, what } of hits) findings.push(`${rel}:${line} ${what}: cluster deployment in a generator`);
	}
	for (const a of allowed) if (!used.has(a)) findings.push(`${a.file}: ALLOWED entry no longer matches anything; remove it`);
	return {
		value: findings.length,
		summary: `${files.length} generator, template and engine files, ${findings.length} cluster deployments`,
		findings,
	};
}
